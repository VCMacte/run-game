/* ───────────────── поддельный холст ─────────────────

   Порядок заливок и их геометрия — это и есть половина дефектов вида: кольцо
   поверх плиты, тень дальнего кольца поверх ближнего, обочина поверх стены.
   Проверять их можно только по НАСТОЯЩЕМУ вызову отрисовки, поэтому вместо
   Canvas подставляется вот это: оно не рисует, а записывает.

   Два среза одного и того же. `fills` — только цвета по порядку, им проверяют
   «что чем накрыто» и считают бюджет кадра. `shapes` — то же плюс рамка каждой
   фигуры, и этим отличают дальнее кольцо от ближнего: цвет у них один, разный
   только размер.

   Был он здесь в четырёх почти одинаковых копиях, и каждая умела чуть своё.
   Разные копии расходятся молча: проверка начинает мерить не то, что рисует
   соседняя, и спорят в итоге не код с кодом, а два теста между собой. */
function painter() {
  const fills = [];
  const shapes = [];
  const images = [];
  let style = null;
  let pts = [];
  const add = (x, y) => pts.push([x, y]);
  const done = () => {
    fills.push(style);
    const xs = pts.map((q) => q[0]);
    const ys = pts.map((q) => q[1]);
    shapes.push({
      style,
      minX: Math.min(...xs), maxX: Math.max(...xs),
      minY: Math.min(...ys), maxY: Math.max(...ys),
      w: Math.max(...xs) - Math.min(...xs),
      h: Math.max(...ys) - Math.min(...ys),
    });
  };
  const ctx = {
    get fillStyle() { return style; },
    set fillStyle(v) { style = v; },
    beginPath() { pts = []; },
    closePath() {},
    moveTo: add,
    lineTo: add,
    ellipse(x, y) { add(x, y); },
    quadraticCurveTo(x1, y1, x2, y2) { add(x1, y1); add(x2, y2); },
    drawImage(im) { images.push(im); },
    fill() { done(); },
    fillRect(x, y, w, h) { pts = [[x, y], [x + w, y + h]]; done(); },
  };
  return { canvas: { width: 0, height: 0, getContext: () => ctx }, fills, shapes, images };
}

/** Один кадр поддельным холстом. Умолчания — пустая сцена без ничего. */
function paintFrame(patch = {}) {
  const p = painter();
  createView(p.canvas, patch.backdrops ? { backdrops: patch.backdrops } : {})
    .render({
      u: 0, v: 0, travel: 0, elapsed: 0, stars: [], obstacles: [], decor: [], ...patch,
    });
  return p;
}

/* Случайность с посевом. Генераторы уровня, звёзд и декораций принимают rng
   снаружи именно для этого: тест прогоняет тысячу РАЗНЫХ уровней, а не один и
   тот же, и при этом каждый прогон повторяем. */
function seeded(seed) {
  let s = seed;
  return () => { s = (s * 1103515245 + 12345) & 0x7fffffff; return s / 0x7fffffff; };
}

// ───────────────────── синтетический скелет ─────────────────────

/* Стоящий человек в нормализованных координатах кадра: x вправо, y вниз.
   Параметрами двигаем то, что нас интересует: смещение вбок, присед, подход
   к камере, поворот боком. */
function pose({
  x = 0.5, y = 0.45, scale = 0.2, crouch = 0, profile = 1, vis = 0.9, lean = 0,
  aspect = 1,
} = {}) {
  const lm = new Float32Array(33 * 4);
  const put = (i, px, py, v = vis) => {
    lm[i * 4] = px; lm[i * 4 + 1] = py; lm[i * 4 + 2] = 0; lm[i * 4 + 3] = v;
  };
  /* Горизонтальные размеры делятся на отношение сторон, потому что MediaPipe
     нормирует x по ШИРИНЕ кадра: одна и та же ширина плеч в широком кадре
     занимает меньшую его долю. Без этого деления синтетика физически неверна
     при любом кадре кроме 1:1 — отношение плеч к торсу росло с формой кадра
     (1.10 при 1:1, 1.96 при 16:9), а geometry() умножает x на aspect и
     получал бы не те плечи. Та же договорённость, что в группе «единицы
     кадра»: строим в физических длинах, делим x на ширину кадра.

     Умолчание 1 оставлено нарочно: при нём синтетика ровно та же, что была,
     и ни одна прежняя проверка не меняет смысла. */
  const halfShoulder = 0.11 * scale / 0.2 * profile / aspect;
  const halfHip = 0.08 * scale / 0.2 * profile / aspect;
  /* Присед: плечи и бёдра идут вниз.

     `lean` отдельно укорачивает ПРОЕКЦИЮ торса, не трогая ширину плеч. Это не
     украшение синтетики, а то, что настоящий присед делает с кадром: ребёнок
     наклоняется вперёд, торс разворачивается к камере и в кадре становится
     короче, а ширина плеч при повороте вокруг горизонтальной оси сохраняется.
     Пока этого параметра здесь не было, синтетика утверждала обратное («торс
     не укорачивается»), и ни одна проверка не могла увидеть, что присед
     выбивает ребёнка в паузу по нижней границе. В журнале 7 октября торс
     ронялся с 0.30 до 0.11 на каждом из одиннадцати приседов. */
  const shoulderY = y + crouch * scale;
  const hipY = shoulderY + scale * (1 - lean);
  put(11, x - halfShoulder, shoulderY);
  put(12, x + halfShoulder, shoulderY);
  put(23, x - halfHip, hipY);
  put(24, x + halfHip, hipY);
  // Колени и ступни: в приседе колено сгибается.
  const kneeY = hipY + scale * (crouch > 0.2 ? 0.35 : 0.7);
  const kneeX = crouch > 0.2 ? 0.06 * scale / 0.2 : 0;
  put(25, x - halfHip - kneeX, kneeY);
  put(26, x + halfHip + kneeX, kneeY);
  put(27, x - halfHip, hipY + scale * 1.4);
  put(28, x + halfHip, hipY + scale * 1.4);
  return lm;
}

/** Прогнать серию поз через трекер с шагом dt мс. */
function run(tracker, frames, { dt = 50, t0 = 0 } = {}) {
  const out = [];
  let t = t0;
  for (const f of frames) {
    out.push(tracker.push({ lm: f, t }));
    t += dt;
  }
  return out;
}

const steady = (opts, n) => Array.from({ length: n }, () => pose(opts));

