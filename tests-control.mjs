// ──────────────────── препятствия и телеграф ────────────────────

group('уровень', () => {
  /* Проверяется не «похоже на правду», а инварианты, которые обязаны
     держаться на любом уровне. Непроходимый уровень на глаз не виден — он
     виден ребёнку, который не понимает, почему проиграл. Поэтому тысяча
     разных уровней, а не один. */
  const rng = seeded(12345);

  let minGap = Infinity;
  let sameSideRun = 0;
  let worstSameSide = 0;
  let total = 0;
  let ducks = 0;
  let firstTooEarly = 0;

  for (let i = 0; i < 1000; i++) {
    const level = makeLevel({ durationS: 180, crouch: true, rng });
    if (!level.length) continue;
    if (level[0].at < O.firstAtS) firstTooEarly++;

    let prevSide = 0;
    sameSideRun = 0;
    for (let k = 0; k < level.length; k++) {
      total++;
      if (level[k].kind === 'duck') ducks++;
      if (k > 0) minGap = Math.min(minGap, level[k].at - level[k - 1].at);
      if (level[k].kind === 'side') {
        sameSideRun = level[k].side === prevSide ? sameSideRun + 1 : 0;
        worstSameSide = Math.max(worstSameSide, sameSideRun);
        prevSide = level[k].side;
      }
    }
  }

  check('между препятствиями хватает места на телеграф', minGap >= O.minGapS - 1e-9,
    `самый тесный промежуток ${minGap.toFixed(2)} с при телеграфе ${O.signalS} с`);
  check('времени на решение хватает всегда', minGap >= O.minLeadS,
    'иначе ребёнок физически не успевает — и дело не в ловкости');
  check('разминка не прерывается', firstTooEarly === 0);
  check('подряд в одну сторону не больше двух', worstSameSide <= 2,
    `встретилось ${worstSameSide + 1} подряд; смысл игры в том, что ребёнок двигается`);
  check('приседания встречаются, но не преобладают',
    ducks / total > 0.1 && ducks / total < 0.5,
    `их доля ${(ducks / total * 100).toFixed(0)}%`);

  // Выключенные приседания должны убирать их совсем, а не «пореже».
  const flat = makeLevel({ durationS: 300, crouch: false, rng });
  check('без приседаний верхних препятствий нет', flat.every((o) => o.kind === 'side'),
    'настройка для взрослого обязана работать буквально');
});

/* ───────────── волны ─────────────

   Прежде интервал между препятствиями был равномерным 5.5–8.0 с — за пять
   минут это метроном без единой группировки: «три плотных подряд, потом пауза»
   не случалось почти никогда. Волна даёт забегу форму, которую слышно без
   часов.

   Делается она СВЕРХУ, и это не выбор, а единственная возможность: сгустить
   препятствия нельзя (`minGapS > signalS`, иначе два телеграфа звучат разом;
   `minGapS > 2 * starGuardS`, иначе сдвиг колец перестаёт сходиться), а верхней
   границы на разнос нет вовсе.

   Главное, что здесь проверяется, — что СЛОЖНОСТЬ НЕ ПОЕХАЛА: средний разнос и
   число препятствий за забег остались прежними. Иначе следующий журнал нельзя
   будет сравнить с седьмым октября, а менять сложность по журналу с дефектами
   в этом проекте запрещено. */
group('волны', () => {
  const ВЕРХ_СЕРИИ = O.minGapS + O.seriesJitterS;   // 6.1
  const СЕРИЙ = 400;

  const разносы = (L) => L.slice(1).map((o, i) => o.at - L[i].at);

  let мин = Infinity;
  let макс = 0;
  let всеРазносы = 0;
  let суммаРазносов = 0;
  let препятствий = 0;
  let междуПолос = 0;
  let пустых = 0;
  let безСерии = 0;
  let худшаяСерия = 0;

  /* Прежнее правило воспроизведено здесь ровно как было — `minGapS + rng()*2.5`
     — чтобы сравнение шло с ЗАМЕРОМ, а не с числом из комментария: число в
     комментарии однажды разойдётся с кодом, и проверка начнёт сверять правку
     саму с собой. */
  const прежнее = (durationS, rng) => {
    const out = [];
    let t = O.firstAtS;
    while (t < durationS) { out.push(t); t += O.minGapS + rng() * 2.5; }
    return out;
  };
  let прежнихПрепятствий = 0;

  for (let seed = 1; seed <= СЕРИЙ; seed++) {
    const L = makeLevel({ durationS: 300, rng: seeded(seed) });
    прежнихПрепятствий += прежнее(300, seeded(seed)).length;
    if (!L.length) { пустых++; continue; }
    препятствий += L.length;

    const g = разносы(L);
    for (const d of g) {
      мин = Math.min(мин, d);
      макс = Math.max(макс, d);
      суммаРазносов += d;
      всеРазносы++;
      // Разнос обязан лежать в одной из двух полос, а не между ними.
      if (d > ВЕРХ_СЕРИИ + 1e-9 && d < O.breatherS - 1e-9) междуПолос++;
    }
    /* Серия обязана случаться — и обязана укладываться в потолок. Считается
       она по ПРЕПЯТСТВИЯМ, а не по разносам: три препятствия подряд дают два
       плотных разноса, и путать одно с другим значило бы сдвинуть потолок на
       единицу. */
    let подряд = 1;
    let лучшая = 1;
    for (const d of g) {
      подряд = d <= ВЕРХ_СЕРИИ + 1e-9 ? подряд + 1 : 1;
      лучшая = Math.max(лучшая, подряд);
    }
    if (лучшая < O.seriesMin) безСерии++;
    худшаяСерия = Math.max(худшаяСерия, лучшая);
  }

  check('пустых уровней нет', пустых === 0, `${пустых} из ${СЕРИЙ}`);
  check('пол разноса соблюдён', мин >= O.minGapS - 1e-9, `минимум ${мин.toFixed(2)}`);
  check('и он не ниже длины телеграфа', O.minGapS > O.signalS,
    'иначе два телеграфа звучат разом и теряются оба');

  /* Полосы не пересекаются — это и есть «волну слышно без часов». Если
     разносы размазаны между 6.1 и 8.8, группировки на слух нет, и вся правка
     сводится к другому генератору случайных чисел. */
  check('каждый разнос попал в свою полосу', междуПолос === 0,
    `${междуПолос} разносов повисли между полосами (серия ≤ ${ВЕРХ_СЕРИИ}, передышка ≥ ${O.breatherS})`);
  check('передышка заметно длиннее серии', O.breatherS / ВЕРХ_СЕРИИ >= 1.4,
    `${(O.breatherS / ВЕРХ_СЕРИИ).toFixed(2)}× — при меньшем отношении волна не читается`);
  check('серия случается на каждом уровне', безСерии === 0, `${безСерии} уровней без серии`);

  /* И НЕ ДЛИННЕЕ заявленной. Проверялось только то, что серия случается, — а
     хвост забега рос мимо потолка: когда до финиша не влезала передышка,
     генератор продлевал серию по одному и делал это до самого конца. Замерено
     на четырёхстах посевах: 56 серий по шесть и 12 по семь при потолке пять.
     Конфиг этот случай прямо отвергает («шесть подряд без паузы — вопрос о
     выносливости семилетки»), то есть код противоречил своему же решению, и
     увидеть это было нечем. */
  check('серия не длиннее заявленного потолка', худшаяСерия <= O.seriesMax,
    `${худшаяСерия} подряд при потолке ${O.seriesMax} — хвост забега растёт мимо потолка`);
  check('передышка не длиннее заявленной', макс <= O.breatherS + O.breatherJitterS + 1e-9,
    `максимум ${макс.toFixed(2)}`);

  /* ─── сложность не поехала ───

     Два числа, и оба нужны: среднее разнесение говорит про ритм, число
     препятствий — про то, сколько решений ребёнок принял за забег. Именно по
     второму следующий журнал будет сравниваться с седьмым октября. */
  const средний = суммаРазносов / всеРазносы;
  const было = прежнихПрепятствий / СЕРИЙ;
  const стало = препятствий / СЕРИЙ;
  check('средний разнос остался прежним', Math.abs(средний - 6.75) / 6.75 < 0.03,
    `${средний.toFixed(2)} против 6.75`);
  check('число препятствий за забег осталось прежним', Math.abs(стало - было) / было < 0.03,
    `${стало.toFixed(2)} против ${было.toFixed(2)} у прежнего правила`);

  /* Короткий забег. Передышка не имеет права съесть его конец: ровно поэтому в
     генераторе остаток сравнивается с её длиной. */
  for (const durationS of [180, 300, 480, 720]) {
    const L = makeLevel({ durationS, rng: seeded(durationS) });
    check(`забег ${durationS} с не пустой`, L.length > 0);
    check(`забег ${durationS} с начинается с разминки`, L[0].at >= O.firstAtS,
      `первое на ${L[0].at}`);
    check(`в забеге ${durationS} с нет препятствий после конца`,
      L.every((o) => o.at < durationS), `последнее на ${L[L.length - 1].at}`);
  }
  // Отладочный забег на двадцать секунд — тоже забег, и пустым он быть не должен.
  check('отладочный забег на 20 с не пустой',
    makeLevel({ durationS: 20, rng: seeded(5) }).length > 0,
    'иначе ?run=20 перестаёт показывать препятствия вовсе');

  check('расписание строго по возрастанию', (() => {
    const L = makeLevel({ durationS: 300, rng: seeded(99) });
    return L.every((o, i) => i === 0 || o.at > L[i - 1].at);
  })(), 'stepObstacles делает ранний break: неупорядоченный список молча перестанет показываться');
});

group('телеграф', () => {
  // Порядок отметок — это и есть механика. Ошибка в нём не видна на глаз, но
  // ломает игру: ребёнок узнаёт о препятствии позже, чем может среагировать.
  const order = [O.signalS, O.visibleS, O.railS, O.lastCallS];
  check('отметки идут по убыванию', order.every((x, i) => i === 0 || x < order[i - 1]),
    JSON.stringify(order));
  check('сигнал раньше, чем препятствие видно', O.signalS > O.visibleS,
    'звук опережает картинку намеренно: у динамика телефона задержки нет');
  check('времени на решение не меньше заявленного', O.minLeadS <= O.visibleS);

  // Окно далёкой метки удлинено до двух секунд (signalS 5.0 против visibleS
  // 3.0) после жалобы «плохо видно предупреждение»: при метке в одну секунду
  // мерцание 1 Гц успевает показать один цикл, то есть не читается вовсе.
  const far = telegraph(6);
  check('за шесть секунд ещё ничего не показано', !far.signal && !far.visible);
  const sig = telegraph(4.5);
  check('за 4.5 с идёт только сигнал', sig.signal && !sig.visible && !sig.rail);
  const sig2 = telegraph(3.5);
  check('за 3.5 с сигнал ещё идёт — окно метки двухсекундное',
    sig2.signal && !sig2.visible, 'иначе медленному мерцанию негде показаться');
  check('метка не накладывается на соседнее препятствие', O.minGapS > O.signalS,
    `minGapS ${O.minGapS} против signalS ${O.signalS}`);
  const vis = telegraph(2.5);
  check('за 2.5 с препятствие видно, рельса ещё нет', vis.visible && !vis.rail);
  const rail = telegraph(1.5);
  check('за 1.5 с идёт рельс', rail.rail && !rail.lastCall);
  const last = telegraph(0.5);
  check('за полсекунды — последний зов', last.lastCall && !last.arrived);
  check('ноль — это приход', telegraph(0).arrived);

  // Пока открыто окно прощения, ребёнок ещё может уйти — и обязан видеть,
  // куда. Поэтому вплотную препятствие перестаёт рисоваться: иначе оно
  // закрывает проём именно в эти миллисекунды.
  const forgiveS = O.lateForgiveMs / 1000;
  check('препятствие исчезает не раньше окна прощения',
    O.drawNearM / VIEW.speed >= forgiveS - 1e-9,
    `исчезает за ${(O.drawNearM / VIEW.speed).toFixed(2)} с, окно ${forgiveS} с`);
  check('и не слишком рано', O.drawNearM / VIEW.speed < 1.0,
    'иначе препятствие пропадает, когда решение ещё не принято');
});

/* ───────────── перекраска не достаёт до игры ─────────────

   Препятствий два вида по ДЕЙСТВИЮ — шаг в сторону и присед, — и больше их не
   станет: у ребёнка ровно две оси управления. А вот внешностей теперь по две
   на каждое: `beam`/`ceiling` у приседа, `plate`/`gate` у бокового. Пять минут
   одного и того же силуэта приедаются, и это единственное, что перекраска
   лечит.

   Вся группа проверяет одно: что `look` не значит НИЧЕГО. Перекраска,
   дотянувшаяся до приговора, дала бы препятствие, которое выглядит как одно, а
   судится как другое, — дефект, невидимый на глаз и видимый только ребёнку,
   который не понял, почему проиграл. Поэтому проверяется не «нарисовалось
   красиво», а что приговор, метка телеграфа и звук от вида не зависят. */
group('перекраска не достаёт до игры', () => {
  const edge = obstacleEdge();

  // Приговор. Перебираются все внешности против всех положений тела.
  for (const kind of Object.keys(LOOKS)) {
    for (const side of kind === 'duck' ? [0] : [-1, 1]) {
      const verdicts = LOOKS[kind].map((look) => {
        const ob = { at: 10, kind, look, side };
        return [-1, -edge - 0.01, 0, edge + 0.01, 1]
          .flatMap((camX) => [true, false].map((crouching) => isSafe(ob, { camX, crouching })))
          .join(',');
      });
      check(`приговор у ${kind} одинаков при любой внешности`,
        new Set(verdicts).size === 1,
        LOOKS[kind].map((l, i) => `${l}: ${verdicts[i]}`).join(' | '));
    }
  }

  // Звук. Мотив сообщает, ЧТО делать, и перекраска не вправе его менять:
  // мотивы различаются числом нот, и новый мотив означал бы новое действие.
  for (const kind of Object.keys(LOOKS)) {
    const motifs = LOOKS[kind].map((look) => motifFor({ at: 10, kind, look, side: 1 }));
    check(`мотив у ${kind} одинаков при любой внешности`,
      new Set(motifs).size === 1, motifs.join(' / '));
  }

  // Расписание телеграфа — тоже по действию, а не по внешности.
  for (const kind of Object.keys(LOOKS)) {
    const plans = LOOKS[kind].map((look) => JSON.stringify(telegraph({ at: 10, kind, look, side: 1 }, 6)));
    check(`телеграф у ${kind} одинаков при любой внешности`, new Set(plans).size === 1);
  }

  /* Зубья висят ВНУТРИ щели, в которую ребёнок проходит приседая. Приговор от
     их длины не зависит (присед судится флагом), но ребёнок видит картинку, а
     не приговор: длинные зубья учили бы приседать глубже, чем просят. */
  check('зубья не съедают щель для приседа', O.teethM < O.duckHeight * 0.25,
    `зубья ${O.teethM} при щели ${O.duckHeight}`);

  // Генератор: внешности из таблицы, обе встречаются, полос нет.
  const level = makeLevel({ durationS: 300, rng: seeded(11) });
  check('внешность есть у каждого препятствия', level.every((o) => typeof o.look === 'string'));
  check('внешности только из таблицы',
    level.every((o) => LOOKS[o.kind].includes(o.look)),
    [...new Set(level.map((o) => `${o.kind}/${o.look}`))].join(', '));
  for (const kind of Object.keys(LOOKS)) {
    const seen = new Set(level.filter((o) => o.kind === kind).map((o) => o.look));
    check(`у ${kind} за забег встречаются обе внешности`, seen.size === 2,
      [...seen].join(', ') || '(ни одного препятствия этого вида)');
  }

  /* Подряд не больше двух одинаковых. Чистая случайность даёт полосы по
     пять-шесть штук, и перекраска внутри такой полосы не видна вовсе — то
     есть не делает того единственного, ради чего сделана. */
  let worstRun = 1;
  let runLen = 1;
  for (let i = 1; i < level.length; i++) {
    const same = level[i].kind === level[i - 1].kind && level[i].look === level[i - 1].look;
    runLen = same ? runLen + 1 : 1;
    worstRun = Math.max(worstRun, runLen);
  }
  check('подряд не больше двух одинаковых препятствий', worstRun <= 2, `${worstRun} подряд`);

  check('один посев даёт тот же набор внешностей',
    JSON.stringify(makeLevel({ durationS: 300, rng: seeded(11) }).map((o) => o.look))
    === JSON.stringify(level.map((o) => o.look)));

  /* И наконец — что перекраска вообще РИСУЕТСЯ по-другому. Без этой проверки
     все предыдущие выполнялись бы и у поля, которое никто не читает. */
  const recorder = painter;   // общий поддельный холст, см. выше
  const paint = (ob) => {
    const { canvas, fills } = recorder();
    createView(canvas).render({
      u: 0, v: 0, travel: 0, elapsed: 10 - 1.5, obstacles: [ob], stars: [],
    });
    return fills;
  };
  const C = THEME.greenHill;
  const teeth = (look) => paint({ at: 10, kind: 'duck', look, side: 0 })
    .filter((f) => f === C.spike).length;
  check('у внешности ceiling зубья есть', teeth('ceiling') > 0);
  check('а у beam их нет', teeth('beam') === 0,
    'иначе внешности не отличаются, и перекраска существует только в поле');

  const sidePaint = (look) => paint({ at: 10, kind: 'side', look, side: 1 });
  check('у внешности gate бадника нет', !sidePaint('gate').includes(C.badnik),
    'живое существо рядом с механической створкой читается как два препятствия');
  check('а у plate он есть', sidePaint('plate').includes(C.badnik));
});

/* ───────────── силуэт препятствия ─────────────

   Заказчик после забега 10 октября: «каждое препятствие залито красным, так и
   должно быть? бадник — мелкое существо, позади которого красная стена во всю
   высоту, и из-за неё самого препятствия почти не видно». Плюс: шипы
   недостаточно шипастые, а створка выглядит просто красной стеной.

   Жалоба верна, и ответ на неё — не «убрать красное». Красная область и есть
   приговор: по её краю судит `isSafe()`, её светлота против почти белого
   проёма — единственное, что переживает сжатие Miracast. Менять в ней нельзя
   ничего. А вот `look` — наклейка поверх приговора, он не значит ничего, и ему
   ничто не мешает вырасти до размера плиты.

   Поэтому здесь проверяется ровно эта развязка: приговор на месте (это
   соседняя группа), а внешность занимает плиту, а не висит на ней маркой.
   Доли нарочно грубые — вопрос «крупно или мелко», а не «красиво». */
group('силуэт препятствия', () => {
  const C = THEME.greenHill;
  const at = 10;
  const paint = (ob, dt = 1.5) => paintFrame({ elapsed: at - dt, obstacles: [ob] }).shapes;
  const plateOf = (shapes) => shapes.find((f) => f.style === C.block);
  const side = (look) => ({ at, kind: 'side', look, side: 1 });

  // ─── бадник занимает плиту, а не висит на ней ───
  {
    const shapes = paint(side('plate'));
    const plate = plateOf(shapes);
    const body = shapes.find((f) => f.style === C.badnik);
    check('плита нарисована', !!plate);
    check('бадник нарисован', !!body);
    const doleH = body ? body.h / plate.h : 0;
    const doleW = body ? body.w / plate.w : 0;
    check('бадник занимает больше половины высоты плиты', doleH > 0.5,
      `${(doleH * 100).toFixed(0)}% высоты — иначе из-за стены самого препятствия не видно`);
    check('и больше половины её ширины', doleW > 0.5, `${(doleW * 100).toFixed(0)}% ширины`);
    check('но не вылезает за плиту',
      body && body.minX >= plate.minX - 1 && body.maxX <= plate.maxX + 1,
      'приговор судит по краю плиты, и фигура не вправе обещать проход там, где его нет');
    check('у бадника есть рот', shapes.some((f) => f.style === C.badnikMouth),
      'заказчик описал его как существо с анимацией рта — её не было вовсе');

    /* ─── и светлое пятно на враге осталось пятном ───

       `badnikEye` светлее проёма (0.96 против 0.954) и не входит ни в один
       набор ролей — исключён нарочно, со словами «занимает несколько пикселей
       и на светлоту кадра не влияет». Когда тело выросло до размера плиты,
       глаз поехал вместе с ним, и условие исключения молча перестало
       выполняться: на плите появилось окно ярче проёма. Поймано глазами на
       первом же кадре закатной зоны, а не тестом, — поэтому тест теперь есть.

       Порог в долях площади ПЛИТЫ, а не в пикселях: пиксели зависят от
       глубины, а доля — нет. */
    const eye = shapes.find((f) => f.style === C.badnikEye);
    check('глаз бадника нарисован', !!eye);
    const доля = eye ? (eye.w * eye.h) / (plate.w * plate.h) : 1;
    check('но остаётся мелким пятном, а не окном', доля < 0.015,
      `${(доля * 100).toFixed(1)}% площади плиты, а он ярче проёма: `
      + 'именно поэтому он и не входит ни в один набор ролей');
  }

  // Рот живёт, и живёт функцией времени, без состояния: видно это из node.
  {
    const рты = [0, 0.2, 0.4, 0.6, 0.8].map((d) => {
      const m = paint(side('plate'), 2.4 - d).find((f) => f.style === C.badnikMouth);
      return m ? Math.round(m.h) : -1;
    });
    check('рот открывается и закрывается', new Set(рты).size > 1, рты.join(' / '));
  }

  /* ─── колёсико остаётся внутри корпуса ───

     Размах полоски подняли с 0.05 до 0.12 вместе с ростом тела, а высоту её
     оставили прежней — и на нижнем краю размаха светлая метка уходила в
     y = −0.02, то есть выезжала из колеса и ложилась на пол ПЕРЕД
     препятствием. Нашлось ревью, а не глазами: дефект живёт ровно в те кадры,
     когда синус на дне.

     Проверяется по всему обороту, а не в одной фазе: дефект фазовый, и
     единственный снимок его пропустил бы с вероятностью в девять десятых. */
  {
    for (const dt of [1.5, 1.6, 1.7, 1.8, 1.9, 2.0, 2.1, 2.2]) {
      const shapes = paint(side('plate'), dt);
      const plate = plateOf(shapes);
      // Полоска колеса — единственная светлая фигура НИЖЕ тела бадника.
      const body = shapes.find((f) => f.style === C.badnik);
      const колесо = shapes.filter((f) => f.style === C.spike && f.minY > body.maxY);
      check(`колёсико нарисовано (dt=${dt})`, колесо.length === 1, `${колесо.length} фигур`);
      if (!колесо.length) continue;
      check(`колёсико не выезжает ниже пола (dt=${dt})`, колесо[0].maxY <= plate.maxY + 0.5,
        `низ полоски ${колесо[0].maxY.toFixed(1)} при полу ${plate.maxY.toFixed(1)}`);
    }
  }

  /* ─── шипы переживают створку ───

     Шипы рисовались ДО внешности, а стойки створки идут от пола до самой
     кромки — и закрашивали корни крайних зубьев. Те два снова читались
     колпаками на кромке, то есть ровно тем, ради чего корни и уводили внутрь
     плиты. С бадником это не всплывало: его тело кончается ниже корней, и
     порядок случайно оказывался верным. */
  {
    /* Шип опознаётся формой, а не цветом: `spike` носят ещё полоска колеса и
       болты створки, и счёт по одному цвету сравнивал бы разные наборы фигур.
       Шип — единственная фигура, которая ТОРЧИТ выше кромки плиты и при этом
       уходит корнем ниже неё. */
    const корни = (look) => {
      const shapes = paint(side(look));
      const plate = plateOf(shapes);
      return shapes.filter((f) => f.style === C.spike
        && f.minY < plate.minY && f.maxY > plate.minY + 1).length;
    };
    check('корни шипов видны и у створки', корни('gate') === корни('plate'),
      `${корни('gate')} против ${корни('plate')} у бадника: стойки створки их закрашивали`);
  }

  // ─── створка тоже на всю плиту ───
  {
    const shapes = paint(side('gate'));
    const plate = plateOf(shapes);
    const детали = shapes.filter((f) => f.style === C.blockDeep);
    check('у створки есть детали', детали.length >= 5,
      `${детали.length} — три полоски посередине заказчик и назвал красной стеной`);
    /* И детали обязаны быть ВИДНЫ. В `blockDark` их не было видно вовсе:
       0.080 против 0.160 у лица плиты — после сжатия Miracast ноль. Разница
       вчетверо и больше переживёт и его. */
    check('детали заметно темнее лица плиты',
      luminance(C.block) / luminance(C.blockDeep) > 4,
      `${luminance(C.block).toFixed(3)} против ${luminance(C.blockDeep).toFixed(3)}`);
    check('но не светлее его', luminance(C.blockDeep) < luminance(C.block),
      'светлое пятно на лице плиты начинает спорить с проёмом');
    const высоко = детали.some((f) => f.minY < plate.minY + plate.h * 0.25);
    const низко = детали.some((f) => f.maxY > plate.minY + plate.h * 0.75);
    check('детали идут по всей высоте плиты', высоко && низко,
      'иначе верх и низ створки остаются той же заливкой');
    const широко = Math.max(...детали.map((f) => f.w)) / plate.w;
    check('и по всей её ширине', широко > 0.8, `${(широко * 100).toFixed(0)}% ширины`);
  }

  // ─── шипы по кромке плиты ───
  {
    const shapes = paint(side('plate'));
    const plate = plateOf(shapes);
    const spikes = shapes.filter((f) => f.style === C.spike && f.minY < plate.minY);
    check('шипов больше трёх', spikes.length > 3, `${spikes.length}`);
    const высоты = spikes.map((f) => f.h);
    check('шипы неровные', new Set(высоты.map((h) => Math.round(h))).size > 1,
      `высоты ${высоты.map((h) => h.toFixed(0)).join(', ')} — ровный гребень и был скучным`);
    check('шипы начинаются ВНУТРИ плиты', spikes.some((f) => f.maxY > plate.minY + 1),
      'корни за кромкой читаются как колпаки на крыше, а не как гребень');
  }

  /* Неровность обязана быть ФУНКЦИЕЙ, а не случайностью: дрожащий от кадра к
     кадру гребень — это рябь, а не шипы. По тому же правилу сделаны все
     анимации проекта. */
  {
    const гребень = (ob, dt) => paint(ob, dt).filter((f) => f.style === C.spike)
      .map((f) => f.h.toFixed(3)).join(',');
    check('гребень не дрожит от кадра к кадру',
      гребень(side('plate'), 1.5) === гребень(side('plate'), 1.5));
    check('а у соседнего препятствия он другой',
      гребень(side('plate'), 1.5)
      !== paintFrame({ elapsed: at + 0.7 - 1.5, obstacles: [{ at: at + 0.7, kind: 'side', look: 'plate', side: 1 }] })
        .shapes.filter((f) => f.style === C.spike).map((f) => f.h.toFixed(3)).join(','),
      'иначе все препятствия забега носят один и тот же гребень');
  }

  /* ─── зубья приседа: неровные, но НЕ длиннее ───

     Зубья висят внутри щели, в которую ребёнок проходит. Приговор от их длины
     не зависит — присед судится флагом, — но ребёнок видит картинку, а не
     приговор: длинные зубья учили бы приседать глубже, чем просят. Поэтому
     неровность им разрешена, а рост — нет, и потолок мерится в пикселях
     кадра, а не в доверии к формуле. */
  {
    const z = 1.5 * VIEW.speed;
    const cam = camera(0, 0);
    const потолок = Math.abs(project(0, O.duckHeight - O.teethM, z, cam).sy
      - project(0, O.duckHeight, z, cam).sy);
    const зубья = paint({ at, kind: 'duck', look: 'ceiling', side: 0 })
      .filter((f) => f.style === C.spike);
    check('зубьев больше прежних семи', зубья.length > 7, `${зубья.length}`);
    check('зубья неровные', new Set(зубья.map((f) => Math.round(f.h))).size > 1,
      зубья.map((f) => f.h.toFixed(0)).join(', '));
    const самый = Math.max(...зубья.map((f) => f.h));
    check('но ни один не длиннее teethM', самый <= потолок + 0.5,
      `самый длинный ${самый.toFixed(1)} px при потолке ${потолок.toFixed(1)}`);
  }
});

/* ───────────── большое кольцо видно, а не только слышно ─────────────

   Заказчик: «кольцо с большим количеством очков визуально не отличается от
   остальных, только другой звук». Это и значит, что о его ценности ребёнок
   узнаёт ПОСЛЕ сбора, то есть редкое событие перестаёт быть событием.

   Размером отличать больше нечем: рим большого кольца 0.256 м против окна
   сбора 0.26 — запас двенадцать миллиметров, и он уже выбран. Поэтому цвет, и
   цвет РЕШЕНИЯ: общий на все зоны, как и у обычного кольца, иначе зона
   перекрасила бы язык игры посреди забега. */
group('большое кольцо', () => {
  const C = THEME.greenHill;
  const ring = (worth) => paintFrame({ stars: [{ x: 0, z: 4, worth }] }).shapes;

  const обычное = ring(1);
  const большое = ring(3);
  check('обычное кольцо золотое', обычное.some((f) => f.style === C.star));
  check('большое кольцо другого цвета', большое.some((f) => f.style === C.starBig),
    'иначе о цене ребёнок узнаёт только задним числом, по звуку');
  check('и золотым оно не рисуется', !большое.some((f) => f.style === C.star),
    'два цвета на одном кольце читаются как два кольца');
  check('у обычного кольца нового цвета нет', !обычное.some((f) => f.style === C.starBig),
    'иначе отличать нечем снова');
  check('у большого есть лучи',
    большое.filter((f) => f.style === C.starBig).length
    > обычное.filter((f) => f.style === C.star).length,
    'один только цвет после сжатия Miracast различается хуже, чем цвет плюс форма');

  // Цвета большого кольца — решения, а не фона: общие на все зоны и под
  // проверкой светлоты. Неотнесённый цвет не проверяется ничем.
  check('starBig отнесён к цветам решения', DECISION_KEYS.includes('starBig'));
  check('starBigDim тоже', DECISION_KEYS.includes('starBigDim'));
  for (const z of ZONES) {
    check(`${z}: большое кольцо того же цвета, что в первой зоне`,
      THEME[z].starBig === THEME.greenHill.starBig
      && THEME[z].starBigDim === THEME.greenHill.starBigDim,
      'язык игры ребёнок учит в первые полминуты, и зона не вправе его перекрасить');
    check(`${z}: большое кольцо отличается от обычного по светлоте`,
      Math.abs(luminance(THEME[z].starBig) - luminance(THEME[z].star)) > 0.05,
      `${luminance(THEME[z].starBig).toFixed(3)} против ${luminance(THEME[z].star).toFixed(3)}: `
      + 'цветность Miracast режет сильнее светлоты, и отличие обязано быть в ней');
  }

  // Размер по-прежнему зажат окном сбора: нарисованное крупнее собираемого —
  // это обещание, которого игра не держит.
  check('рим большого кольца внутри окна сбора',
    VIEW.starDrawR * VIEW.bigStarScale < VIEW.starReach,
    `${(VIEW.starDrawR * VIEW.bigStarScale).toFixed(3)} против ${VIEW.starReach}`);
});

/* ───────────── небо меняется вместе с зоной ─────────────

   Заказчик после забега 10 октября: «смена цветового оформления во время
   забега работает хорошо, но небо и дальний план остаются без изменений».

   Так и было, и не по недосмотру, а по построению: растр один на весь забег и
   кладётся во ВЕСЬ кадр (1024×576 на 1280×720 даёт dy = 0, dh = 720 — это
   посчитано в соседней группе). То есть `COLORS.sky` зоны закрашивался
   картинкой целиком, и зона могла перекрасить всё, кроме верхней половины
   кадра, — ровно той, которая и называется «небо и дальний план».

   Проверяется здесь не красота картинок, а развязка: у каждой зоны свой
   растр, а зона без растра уходит на векторный путь СВОИХ цветов, не утаскивая
   за собой ни палитру, ни игру. */
group('небо меняется вместе с зоной', () => {
  const растр = (метка) => ({ width: 1024, height: 576, метка });
  const backdrops = {
    greenHill: растр('утро'),
    sunsetDunes: растр('закат'),
  };
  const кадр = (zone) => paintFrame({ zone, backdrops, travel: 30, elapsed: 30 });

  check('в первой зоне кладётся её растр',
    кадр('greenHill').images.every((i) => i.метка === 'утро'),
    кадр('greenHill').images.map((i) => i.метка).join(', ') || 'ни одного');
  check('во второй — её, а не первой',
    кадр('sunsetDunes').images.length > 0
    && кадр('sunsetDunes').images.every((i) => i.метка === 'закат'),
    'иначе всё оформление зоны меняется, кроме верхней половины кадра');

  /* Зона без растра: картинки нет, но игра идёт, и фон рисуется цветами
     ЭТОЙ зоны. Это и есть та независимость от арта, ради которой запасной
     путь вообще существует. */
  const ночь = кадр('nightHills');
  check('зона без растра обходится без него', ночь.images.length === 0);
  check('и рисуется в своих цветах, а не в чужих',
    ночь.fills.includes(THEME.nightHills.sky)
    && !ночь.fills.includes(THEME.greenHill.sky),
    'запасной путь красится палитрой кадра, и зона обязана доехать до него');

  /* Неизвестная зона не роняет растр. Без памяти о последней известной зоне
     палитра оставалась бы прежней, а небо прыгало бы с картинки на вектор —
     то есть кадр оказался бы наполовину в одной зоне, наполовину в другой. */
  const p = painter();
  const v = createView(p.canvas, { backdrops });
  v.render({ zone: 'sunsetDunes', travel: 30, elapsed: 30, stars: [], obstacles: [], decor: [] });
  const было = p.images.length;
  v.render({ zone: 'чего-то такого нет', travel: 30, elapsed: 30, stars: [], obstacles: [], decor: [] });
  check('неизвестная зона оставляет прежний растр, а не роняет его',
    p.images.length > было && p.images[p.images.length - 1].метка === 'закат');

  // Таблица зона → файл одна на проект: по ней грузит train.js и по ней же
  // собирается список офлайн-кэша.
  check('у каждой зоны назван файл неба',
    ZONES.every((z) => typeof SKY_FILES[z] === 'string' && SKY_FILES[z].endsWith('.webp')),
    JSON.stringify(SKY_FILES));
  check('файлы разные', new Set(Object.values(SKY_FILES)).size === ZONES.length,
    'один файл на две зоны вернул бы ровно ту жалобу, с которой всё началось');
});

group('уклонение', () => {
  const edge = obstacleEdge();
  const full = Math.abs(cameraX(1));

  // Уйти должно быть можно. Край препятствия выражен долей хода камеры именно
  // поэтому: развязать эти числа значит получить препятствие, от которого
  // нельзя уклониться в принципе, и заметить это только на ребёнке.
  check('от препятствия можно уйти', edge < full,
    `край на ${edge.toFixed(2)} м при ходе камеры ${full.toFixed(2)} м`);
  check('но уйти надо заметно, а не качнуться', edge > full * 0.2,
    'иначе достаточно стоять и чуть шевелиться');

  const right = { kind: 'side', side: 1 };
  check('закрыта правая — спасает левая', isSafe(right, { camX: -full }));
  check('стоять посередине не спасает', !isSafe(right, { camX: 0 }));
  check('уйти в закрытую сторону не спасает', !isSafe(right, { camX: full }));

  const left = { kind: 'side', side: -1 };
  check('и симметрично', isSafe(left, { camX: full }) && !isSafe(left, { camX: -full }));

  const duck = { kind: 'duck', side: 0 };
  check('верхнее проходится приседом', isSafe(duck, { camX: 0, crouching: true }));
  check('а смещением вбок — нет', !isSafe(duck, { camX: full, crouching: false }),
    'иначе присед можно было бы не делать вовсе');
});

group('звук', () => {
  // Мотивы различаются числом нот, а не только высотой: высоту съедает
  // телефонный динамик и комнатное эхо, а «два» и «три» слышно всегда.
  const m = describe();
  const need = ['left', 'right', 'duck', 'ready', 'warn', 'clear', 'star', 'hit', 'finish'];
  for (const name of need) check(`мотив «${name}» есть`, m[name]?.length > 0);

  check('присед отличается от боковых числом нот',
    m.duck.length !== m.left.length && m.duck.length !== m.right.length,
    `присед ${m.duck.length}, влево ${m.left.length}, вправо ${m.right.length}`);
  check('подтверждение короче предупреждения', m.ready.length < m.warn.length,
    'подтверждение звучит чаще и не должно надоедать');
  check('финиш — самый длинный',
    m.finish.length >= Math.max(...need.map((n) => m[n].length)));

  // Одинаковое число нот у «влево» и «вправо» — так и задумано, их различает
  // направление хода высоты. Но сами мотивы обязаны отличаться.
  check('влево и вправо — разные мотивы',
    JSON.stringify(m.left) !== JSON.stringify(m.right));
  check('влево идёт вниз', m.left[0][0] > m.left[1][0],
    `${m.left[0][0]} → ${m.left[1][0]}`);
  check('вправо идёт вверх', m.right[0][0] < m.right[1][0]);

  // Ноты не должны накладываться сами на себя: следующая начинается не
  // раньше, чем кончилась предыдущая, иначе мотив превращается в аккорд и
  // ритм, которым они и различаются, пропадает.
  for (const [name, notes] of Object.entries(m)) {
    for (let i = 1; i < notes.length; i++) {
      check(`«${name}»: ноты не наезжают`, notes[i][1] >= notes[i - 1][1],
        `нота ${i} начинается в ${notes[i][1]}, предыдущая в ${notes[i - 1][1]}`);
    }
  }

  check('для бокового справа звучит «влево»', motifFor({ kind: 'side', side: 1 }) === 'left',
    'закрыта правая сторона — уходить надо влево, и звук говорит именно это');
  check('для бокового слева звучит «вправо»', motifFor({ kind: 'side', side: -1 }) === 'right');
  check('для верхнего звучит присед', motifFor({ kind: 'duck', side: 0 }) === 'duck');
});

