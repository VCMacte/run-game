/* ───────────────── порядок маляра ─────────────────

   Кольцо просвечивало сквозь препятствие: кольца рисовались одним проходом
   после препятствий, а плита видна с 10 м при кольцах до 30 м. Заметил
   заказчик. Здесь проверяется и арифметика глубины, и настоящий порядок
   заливок — через поддельный контекст, потому что порядок и есть дефект. */
group('порядок маляра', () => {
  const ob = (at, extra = {}) => ({ at, kind: 'side', side: 1, ...extra });

  check('далёкое препятствие не рисуется', obstacleDepth(ob(10), 10 - O.signalS - 0.1) === null);
  check('пройденное не рисуется', obstacleDepth(ob(10, { passed: true }), 9) === null);
  check('уехавшее за спину не рисуется', obstacleDepth(ob(10), 10.5) === null,
    'у него отрицательная глубина, и проекция залила бы экран целиком');
  check('в окне телеграфа глубина — у самой дымки',
    Math.abs(obstacleDepth(ob(10), 10 - (O.signalS + O.visibleS) / 2) - VIEW.fogDistance * 0.92) < 1e-9);
  const close = obstacleDepth(ob(10), 10 - 1.5);
  check('ближе окна телеграфа глубина — это сама плита',
    Math.abs(close - 1.5 * VIEW.speed) < 1e-9, `глубина ${close}`);

  let prev = Infinity;
  let mono = true;
  for (let dt = O.visibleS; dt > 0.5; dt -= 0.1) {
    const d = obstacleDepth(ob(10), 10 - dt);
    if (d != null) { if (d > prev) mono = false; prev = d; }
  }
  check('глубина убывает по мере приближения', mono);

  check('разрез — по самому близкому', nearestObstacleDepth([ob(16), ob(10)], 9) === 2);
  check('без препятствий разреза нет', nearestObstacleDepth([], 9) === Infinity);

  // Настоящий порядок заливок. Контекст поддельный: нужен не рисунок, а
  // последовательность, в которой он кладётся.
  const recorder = painter;   // общий поддельный холст, см. выше

  const order = (starZ) => {
    const { canvas, fills } = recorder();
    const view = createView(canvas);
    view.render({
      u: 0, v: 0, travel: 0, elapsed: 0,
      obstacles: [ob(1.5)],            // плита на 3 м
      stars: [{ x: 0, z: starZ }],
    });
    return { ring: fills.indexOf(THEME.greenHill.star), plate: fills.indexOf(THEME.greenHill.block) };
  };

  const far = order(12);
  check('кольцо и плита вообще нарисованы', far.ring >= 0 && far.plate >= 0, JSON.stringify(far));
  check('кольцо ЗА плитой уходит под неё', far.ring < far.plate,
    `кольцо ${far.ring}, плита ${far.plate} — ровно этот дефект заметил заказчик`);

  const near = order(1.2);
  check('кольцо ПЕРЕД плитой остаётся поверх', near.ring > near.plate,
    `кольцо ${near.ring}, плита ${near.plate} — иначе кольцо теряется там, где важнее всего`);

  /* ─── пятно под кольцом ───

     Пятно лежит на полу и обязано ехать тем же проходом, что его кольцо.
     Нарисуй его вместе с полом — и препятствие, стоящее ДАЛЬШЕ ближнего
     кольца, накрыло бы пятно, которое должно быть перед ним. Это ровно тот
     класс дефекта, из-за которого проходов стало два. */
  const C = THEME.greenHill;
  const withShadow = (starZ, extra = {}) => {
    const { canvas, fills } = recorder();
    createView(canvas).render({
      u: 0, v: 0, travel: 0, elapsed: 0,
      obstacles: [ob(1.5)],
      stars: [{ x: 0, z: starZ, ...extra }],
    });
    return {
      fills,
      shadow: fills.indexOf(C.shadow),
      ring: fills.indexOf(C.star),
      plate: fills.indexOf(C.block),
    };
  };

  const sNear = withShadow(1.2);
  check('пятно под кольцом нарисовано', sNear.shadow >= 0, JSON.stringify(sNear.fills.length));
  check('пятно кладётся вплотную перед своим кольцом', sNear.ring - sNear.shadow === 1,
    `пятно ${sNear.shadow}, кольцо ${sNear.ring}`);
  check('у ближнего кольца пятно поверх плиты', sNear.shadow > sNear.plate,
    `пятно ${sNear.shadow}, плита ${sNear.plate}`);

  const sFar = withShadow(12);
  check('у дальнего кольца пятно уходит под плиту', sFar.shadow < sFar.plate,
    `пятно ${sFar.shadow}, плита ${sFar.plate}`);

  /* У собранного кольца пятна нет: оно подпрыгивает и исчезает, а пятно
     осталось бы висеть на полу сиротой. */
  const taken = withShadow(1.2, { taken: true, takenAtS: 0 });
  check('у собранного кольца пятна нет', taken.shadow === -1,
    'иначе на полу остаётся пятно без кольца');

  /* Светлота пятна проверяется не здесь, а в группе «тема»: она про палитру, а
     не про порядок, и обязана идти по КАЖДОЙ зоне. Здесь остаётся только
     порядок заливок. */

  /* Пятно — тень, а не площадка: заметно меньше того радиуса, в котором
     кольцо собирается. Иначе ребёнок станет вставать НА пятно вместо того,
     чтобы вести к кольцу взгляд. */
  check('пятно меньше радиуса сбора',
    VIEW.starShadowM < VIEW.starReach * VIEW.corridorWidth / 2,
    `${VIEW.starShadowM} против ${(VIEW.starReach * VIEW.corridorWidth / 2).toFixed(2)} м`);

  /* ─── три полосы глубины у пола ───

     Третья полоса не стоит ни одной лишней заливки: меняется только выбор
     цвета в том же цикле шахматки. Проверяется, что она действительно
     появляется в кадре и что светлота идёт лестницей — порядок тут важнее
     самих цветов, по нему и видно, что дальше. */
  check('средняя полоса пола в кадре есть', sFar.fills.includes(C.floorMid),
    'иначе полос по-прежнему две, и правка ничего не изменила');
  // Лестница светлоты — в группе «тема», по каждой зоне.
});

/* ───────────────── небо не красит невидимое ─────────────────

   Замерено на телефоне: до появления арта кадр шёл 46–47 fps, с артом — 38–39,
   обе полки ровные все 400 секунд. То есть арт стоит около 5 мс на кадр, а
   `draw50` при этом показывает 0 мс: он мерит время вызовов Canvas2D на CPU,
   то есть постановку работы в очередь, и растеризацию не видит вовсе.

   Куда уходили эти миллисекунды, видно из геометрии. Растр неба 1024×576 на
   кадре 1280×720 кладётся как dh = 720, dy = 0 — то есть РОВНО во весь кадр. А
   перед ним drawSky заливал весь кадр (1.00 экрана) и верхнюю полосу
   (0.30 экрана). Обе заливки растр закрывал целиком: 1.3 экранных заливки на
   каждом кадре красили пиксели, которых не видел никто.

   Поэтому заливка идёт по ФАКТИЧЕСКОЙ геометрии, а не по признаку «растр
   есть». Разница не косметическая: dy зависит от наклона взгляда, в приседе
   горизонт уезжает на pitchPx, и прореха там действительно появляется. */
/* ───────────────── бюджет кадра ─────────────────

   «Потянет телефон» до сих пор было словами: число заливок считали в браузере
   руками — 44 при потолке 150, — и ни одна правда об этом не держалась. Теперь
   держится, и держится в node: поддельный контекст считает заливки, а стадия
   кадра собирается как настоящая, с декорациями, кольцами и препятствием.

   Потолок 150 замерен на телефоне, а не выбран: это та граница, за которой
   кадр перестаёт укладываться в 38–40 fps. Запас между 44 и 150 и есть
   единственное, чем оправданы новые украшения — поэтому и считается он, а не
   «на глаз красиво».

   Проверяется ХУДШИЙ кадр прогона, а не средний: именно он и роняет fps.
   Прежние «44 заливки» из CLAUDE.md — это типичный кадр, посчитанный руками в
   браузере; худший вдвое тяжелее.

   Чего этот счётчик НЕ видит, и об этом надо помнить, читая его число.
   Во-первых, он считает ВЫЗОВЫ, а не площадь, — а на телефоне кадр роняет
   именно площадь: замерено, что арт стоит около 5 мс при `draw50 = 0`.
   Во-вторых, в node нет растра неба, поэтому drawSky идёт запасным путём и
   выдаёт около дюжины заливок на холмы и облака; на телефоне вместо них два
   drawImage — вызовов меньше, площади больше. То есть число годится для
   сравнения «до и после правки», а не как предсказание fps. */
group('бюджет кадра', () => {
  const CEILING = 150;

  const recorder = painter;   // общий поддельный холст, см. выше

  /* По нескольким посевам, а не по одному. Худший кадр зависит от того, как
     встали декорации и кольца, и разброс между посевами — десяток заливок:
     один посев дал бы случайное число и однажды пропустил бы перебор. */
  let worst = 0;
  let worstAt = 0;
  let worstSeed = 0;
  for (const seed of [1, 7, 13, 29]) {
    const rng = seeded(seed);
    const obstacles = makeLevel({ durationS: 300, rng });
    const stars = makeStars({ durationS: 300, obstacles, rng });
    const decor = makeDecor({ durationS: 300, rng });

    const { canvas, fills } = recorder();
    const view = createView(canvas);

    // Шаг 0.25 с по всему забегу: кадры между ними отличаются сдвигом камеры,
    // а не составом, и на число заливок это не влияет.
    for (let t = 0; t < 300; t += 0.25) {
      fills.length = 0;
      view.render({
        u: t % 2 < 1 ? 1 : -1, v: 0, travel: t * VIEW.speed, elapsed: t,
        obstacles, stars, decor, speed: 0.5,
        // Зона — та же, что была бы в игре: формы обочины у зон свои, и считать
        // бюджет по одной зоне значило бы не проверить остальные.
        zone: zoneAt(t, 300),
        finishIn: 300 - t, safe: true, pulse: 0.5,
      });
      if (fills.length > worst) { worst = fills.length; worstAt = t; worstSeed = seed; }
    }
  }

  console.log(`  худший кадр: ${worst} заливок при потолке ${CEILING}`
    + ` (посев ${worstSeed}, ${worstAt.toFixed(1)} с)`);
  check(`худший кадр укладывается в потолок ${CEILING}`, worst <= CEILING,
    `${worst} заливок на ${worstAt.toFixed(1)} с`);
  check('и запас ещё остаётся', worst <= CEILING * 0.8,
    `${worst} из ${CEILING} — добавлять дальше уже нельзя без замера на телефоне`);
  // Обратная сторона: кадр не должен внезапно опустеть. Ноль заливок означал
  // бы, что render упал молча или стадия собралась пустой.
  check('кадр не пустой', worst > 20, `${worst} заливок`);
});

