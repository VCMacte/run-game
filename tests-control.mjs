group('тема', () => {
  /* Эта группа существует из-за одного риска. Тема «зелёные холмы» делает мир
     светлым и зелёным, а до неё коридор был тёмно-синим, и контраст «плита /
     проём» получался сам. Теперь он сам не получается, а именно он сообщает
     ребёнку, куда уходить. Проверять его глазами нельзя: после Miracast кадр
     выглядит иначе, чем на машине разработки.

     Поэтому правило выражено числом: ФОРМА СООБЩАЕТ ТЕМУ, СВЕТЛОТА СООБЩАЕТ
     РЕШЕНИЕ.

     И проверяется оно по КАЖДОЙ теме, а не по первой. Раньше здесь стояло
     `const t = THEME.greenHill`, и перебора не было нигде: вторая зона не
     получила бы ни одной из этих проверок — то есть ровно так в палитру и
     попала бы белая декорация, спорящая с «иди сюда». Цикл поставлен ДО того,
     как появились зоны: с одной темой он не меняет ничего, а со второй он
     единственное, что держит читаемость. */
  const L = luminance;
  // Порог взят замером прежней палитры, а не выдуман: столько контраста уже
  // было, и терять его при покраске нельзя ни в каком случае.
  const baseline = L('#4fd6a0') - L('#c2415a');
  const classified = new Set([...DECISION_KEYS, ...BACKGROUND_KEYS, 'badnikEye', 'id', 'name', 'decor']);

  check('темы вообще есть', Object.keys(THEME).length > 0);

  for (const t of Object.values(THEME)) {
    const z = t.id || '?';

    check(`${z}: контраст «плита / проём» не ниже прежнего`,
      L(t.gap) - L(t.block) >= baseline,
      `было ${baseline.toFixed(3)}, стало ${(L(t.gap) - L(t.block)).toFixed(3)}`);

    check(`${z}: проём светлее всего фона`,
      BACKGROUND_KEYS.every((k) => L(t[k]) < L(t.gap)),
      'иначе «куда идти» перестанет быть самым заметным местом кадра');

    for (const k of BACKGROUND_KEYS) {
      check(`${z}: фон «${k}» не лезет в канал решения`,
        Math.abs(L(t[k]) - L(t.gap)) >= GAP_GUARD,
        `${t[k]}: разница ${Math.abs(L(t[k]) - L(t.gap)).toFixed(3)} при пороге ${GAP_GUARD}`);
    }

    /* Цвет, не отнесённый ни к решению, ни к фону, не проверяется ничем — и
       именно так в палитру и попадёт однажды белая декорация. Единственное
       исключение названо в theme.js: глаз бадника в несколько пикселей. */
    check(`${z}: каждый цвет палитры отнесён к роли`,
      Object.keys(t).every((k) => classified.has(k)),
      `без роли: ${Object.keys(t).filter((k) => !classified.has(k)).join(', ')}`);

    // И наоборот: в палитре зоны обязан быть КАЖДЫЙ ключ, который где-то
    // рисуется. Забытый ключ даёт `undefined` в fillStyle — Canvas молча
    // оставляет прежний цвет, то есть кадр красится цветом соседней фигуры.
    for (const k of [...DECISION_KEYS, ...BACKGROUND_KEYS, 'badnikEye']) {
      check(`${z}: цвет «${k}» задан`, typeof t[k] === 'string' && /^#[0-9a-f]{6}$/i.test(t[k]),
        `${k} = ${t[k]}`);
    }

    check(`${z}: левый и правый обрыв различаются по светлоте`,
      Math.abs(L(t.earthL) - L(t.earthR)) > 0.02,
      'разница светлоты подсказывает, в какую сторону уехал взгляд');

    check(`${z}: шахматка пола различима`,
      Math.abs(L(t.floorA) - L(t.floorB)) > 0.1,
      'без этого пол сливается и скорость перестаёт читаться');

    /* Эти три переехали сюда из группы «порядок маляра»: они про палитру, а не
       про порядок, и обязаны идти по каждой зоне. Пятно под кольцом зажато с
       двух сторон — темнее самой тёмной клетки пола (иначе не видно) и светлее
       глубины обрыва (иначе читается дыркой в полу); полосы пола идут
       лестницей, и порядок тут важнее самих цветов. */
    check(`${z}: пятно темнее самой тёмной клетки пола`, L(t.shadow) < L(t.floorB),
      `${L(t.shadow).toFixed(3)} против ${L(t.floorB).toFixed(3)}`);
    check(`${z}: но светлее глубины обрыва`, L(t.shadow) > L(t.earthDeep),
      'тень в цвет обрыва читается дыркой в полу');
    check(`${z}: светлота полос пола идёт лестницей вниз`,
      L(t.floorA) > L(t.floorMid) && L(t.floorMid) > L(t.floorFar),
      [t.floorA, t.floorMid, t.floorFar].map((h) => L(h).toFixed(3)).join(' → '));
  }
});

/* ───────────── зоны ─────────────

   Забег идёт пять минут, и всё это время он был одной сцены. Зоны — то, чем
   это лечится: для семилетки видимое продвижение и есть награда за долгий
   забег, а полоса прогресса в углу — нет.

   Цена замысла — ноль заливок: меняются цвета и виды обочины, а не состав
   кадра. Проверяется здесь именно это, а не красота.

   Решающие цвета (проём, плита, предупреждение, кольцо) в зонах ОБЩИЕ, и это
   главное правило: язык игры ребёнок выучивает в первые полминуты, и зона,
   перекрасившая проём, заставила бы учиться заново посреди забега. */
group('зоны', () => {
  const L = luminance;

  check('зон больше одной', ZONES.length > 1);
  check('все зоны есть в палитре', ZONES.every((z) => THEME[z]), ZONES.join(', '));
  check('и лишних тем не осталось', Object.keys(THEME).length === ZONES.length,
    'тема вне ZONES не покажется никогда, то есть не проверится ни глазами, ни забегом');

  /* Решающие цвета совпадают во всех зонах — побайтово. Это не стиль, а
     запрет: ребёнок читает «куда идти» светлотой проёма, и менять её посреди
     забега нельзя. */
  for (const k of DECISION_KEYS) {
    const значения = new Set(ZONES.map((z) => THEME[z][k]));
    check(`цвет решения «${k}» одинаков во всех зонах`, значения.size === 1,
      [...значения].join(' / '));
  }

  /* А фон обязан различаться, иначе зоны не зоны. Проверяется по небу и полу:
     это самые большие площади кадра, и если они совпали, смену зоны не
     увидит никто. */
  for (const k of ['sky', 'floorA']) {
    check(`фоновый «${k}» различается между зонами`,
      new Set(ZONES.map((z) => THEME[z][k])).size === ZONES.length,
      ZONES.map((z) => THEME[z][k]).join(' / '));
  }

  /* Границы по долям забега. Отладочный забег на минуту обязан показать все
     три зоны: иначе та единственная проверка, которой зоны смотрят глазами,
     перестала бы работать. */
  for (const durationS of [60, 180, 300]) {
    const увиденные = new Set();
    for (let t = 0; t < durationS; t += 0.25) увиденные.add(zoneAt(t, durationS));
    check(`за забег ${durationS} с видны все зоны`, увиденные.size === ZONES.length,
      [...увиденные].join(', '));
  }
  check('забег начинается первой зоной', zoneAt(0, 300) === ZONES[0]);
  check('и кончается последней', zoneAt(299.9, 300) === ZONES[ZONES.length - 1]);
  check('зоны идут по порядку, без возвратов', (() => {
    let i = 0;
    for (let t = 0; t < 300; t += 0.25) {
      const j = ZONES.indexOf(zoneAt(t, 300));
      if (j < i) return false;
      i = j;
    }
    return true;
  })(), 'возврат в прошлую зону читался бы как «забег пошёл назад»');

  /* Вырожденные входы. `zoneAt` зовётся и из расстановки декораций, и из кадра:
     вернуть `undefined` она не имеет права нигде — это `THEME[undefined]`, то
     есть кадр без палитры. */
  for (const [e, d] of [[0, 0], [10, 0], [-5, 300], [1e9, 300], [NaN, 300], [10, NaN]]) {
    check(`zoneAt(${e}, ${d}) отдаёт существующую зону`, ZONES.includes(zoneAt(e, d)),
      String(zoneAt(e, d)));
  }

  // ── палитра кадра действительно меняется ──
  const recorder = painter;   // общий поддельный холст, см. выше
  const кадр = (zone) => {
    const { canvas, fills } = recorder();
    createView(canvas).render({ u: 0, v: 0, travel: 0, elapsed: 0, zone });
    return fills;
  };

  for (const z of ZONES) {
    const f = кадр(z);
    check(`кадр зоны ${z} красится её полом`, f.includes(THEME[z].floorA),
      'иначе зона пришла полем, но до заливок не дошла');
  }
  check('кадр другой зоны не красится полом первой',
    !кадр(ZONES[1]).includes(THEME[ZONES[0]].floorA),
    'палитра защёлкнулась один раз, и смена зоны не работает');
  /* Неизвестная зона не обнуляет палитру: лучше цвета соседней зоны, чем
     `undefined` в fillStyle — на него Canvas молча оставляет прежний цвет, и
     кадр красится цветом соседней фигуры. */
  check('неизвестная зона не ломает кадр', кадр('нет такой').length > 20);

  // ── формы обочины: не дороже пальмы ──
  /* Бюджет кадра — 150 заливок при худших 108, и декорации уже самая большая
     статья. Поэтому зона имеет право на свои формы, но не на более дорогие:
     одновременно активна одна зона, и если каждая её форма не дороже пальмы,
     кадр не может стать тяжелее сегодняшнего. Проверяется, а не обещается. */
  const формы = new Map();
  for (const z of ZONES) {
    for (const k of THEME[z].decor.kinds) {
      if (!формы.has(k.kind)) формы.set(k.kind, { zone: z, height: k.height, out: k.out ?? DECOR.outM });
    }
  }
  const заливок = (zone, kind, height, out = DECOR.outM) => {
    const { canvas, fills } = recorder();
    createView(canvas).render({
      u: 0, v: 0, travel: 0, elapsed: 0, zone,
      /* Отступ от кромки — тот, что у ВИДА, а не общий: обрыв скрывает низ
         декорации, и при чужом отступе низкий вид не нарисовался бы вовсе.
         Разбор — у `decorYMask` и в группе «что чем перекрыто». */
      decor: [{ kind, zone, side: 1, x: CORRIDOR_HALF + out, y: CLIFF_TOP, h: height, z: 4, at: 1, phase: 0.3 }],
    });
    const пусто = кадр(zone).length;
    return fills.length - пусто;
  };
  const пальма = заливок('greenHill', 'palm', 2.2);
  check('пальма вообще рисуется', пальма > 0, `${пальма} заливок`);
  for (const [kind, { zone, height, out }] of формы) {
    const n = заливок(zone, kind, height, out);
    check(`форма «${kind}» рисуется`, n > 0, `${n} заливок`);
    check(`форма «${kind}» не дороже пальмы`, n <= пальма,
      `${n} против ${пальма} у пальмы — кадр станет тяжелее сегодняшнего`);
  }

  /* Незнакомый вид не рисуется НИЧЕМ. Раньше последняя ветка drawDecor была
     `else`, то есть любой новый вид молча становился тотемом с подмигивающим
     глазом; с зонами это ловушка под ногами. */
  check('незнакомый вид не рисуется вовсе',
    заливок('greenHill', 'нетакого', 1.5) === 0,
    'молчаливая подмена вида — дефект, который виден только на телефоне');
});

