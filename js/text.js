/**
 * Склонение существительного при числительном.
 * Формы: [1 сессия, 2 сессии, 5 сессий].
 *
 * Нужно потому, что «1 сессий» на экране, который читает взрослый, подрывает
 * доверие к остальным показанным там числам — а числа на этом экране и есть
 * весь его смысл.
 */
export function plural(n, [one, few, many]) {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b > 1 && b < 5) return few;
  return b === 1 ? one : many;
}

/** «3 сессии» — число вместе с правильной формой слова. */
export const count = (n, forms) => `${n} ${plural(n, forms)}`;

