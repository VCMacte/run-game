/* ──────────────────────────── светлота ────────────────────────────
   Относительная светлота по WCAG. Нужна не для красоты: Miracast режет
   цветность сильнее светлоты, поэтому все различия, которые ребёнок обязан
   увидеть, выражены светлотой. Этой же функцией их проверяют тесты — одна
   формула на палитру и на проверку, иначе проверка начнёт мерить не то, что
   рисуется. */
export function luminance(hex) {
  const n = parseInt(hex.slice(1), 16);
  const ch = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2];
}

