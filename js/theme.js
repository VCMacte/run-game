/** Цвет темы с прозрачностью. Для затемнения: оно кладётся поверх кадра. */
export function rgba(hex, alpha) {
  const n = parseInt(hex.slice(1), 16);
  return `rgba(${(n >> 16) & 255},${(n >> 8) & 255},${n & 255},${alpha})`;
}

/* Полоса вокруг светлоты проёма, в которую фону входить нельзя.

   badnikEye в список фона не входит намеренно: глаз занимает несколько
   пикселей и на светлоту кадра не влияет, а светлым он должен быть, иначе
   врага не видно вовсе. */
export const GAP_GUARD = 0.25;

/* Потолок светлоты для фонового РАСТРА, по зонам.

   Нужен при сборке арта: нейросеть рисует облака чисто белыми, светлота 1.0
   при проёме 0.95, и фон начинает спорить с каналом решения — с сообщением
   «иди сюда». Зажим делает `toWebp(..., clampTo)` в `tools/frame.html`, один
   раз, при сборке файла: проверка светлоты в тестах растр увидеть не может,
   декодировщика картинок там нет.

   Число живёт ЗДЕСЬ, а не в строке запуска. Вписанное руками, оно было копией
   без владельца: `GAP_GUARD` изменился бы, а конвейер арта молча остался бы
   на старом зажиме — и разошлись бы они ровно так же, как разошёлся худший
   кадр кадра между корнем и счётчиком.

   Дневным зонам потолок ВЫВОДИТСЯ: это граница `GAP_GUARD` от проёма, то
   есть ровно то же правило, по которому проверяется палитра.

   Ночной задан отдельно и меньше, и это не придирка: при общем потолке её
   облака оказались бы многократно светлее самого светлого цвета её же
   палитры — небо перестало бы быть ночным. Вывести это число из палитры
   нельзя: такого правила проект не формулировал, и выдуманная формула была бы
   хуже честного исключения. Поэтому исключение названо исключением.

   Проверяется в группе «небо» (`tests-control.mjs`): дневной обязан
   следовать за `GAP_GUARD`, ночной — оставаться ниже дневного. */

export function skyClamp(zone) {
  const свой = THEME[zone]?.skyClampTo;
  return typeof свой === 'number' ? свой : luminance(THEME[zone].gap) - GAP_GUARD;
}

