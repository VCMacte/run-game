/** Собран ли арт этого мира. Открытый, но несобранный мир показывает «скоро». */
export function worldReady(world) {
  const zones = WORLDS[world]?.zones;
  /* Не только «три штуки», но и «все три существуют в палитре». Без второй
     половины мир с опечаткой в имени зоны считался бы собранным, и `zonesOf`
     отдал бы его список как есть — а `undefined` в палитре кадра Canvas
     проглатывает молча, оставляя цвет соседней фигуры. */
  return Array.isArray(zones) && zones.length === 3 && zones.every((z) => !!THEME[z]);
}

/** Зоны мира. Неизвестный, мусорный и несобранный мир отдают первый — молча:
    отрисовка кадра не вправе получить undefined вместо имени зоны. */
export function zonesOf(world) {
  return worldReady(world) ? WORLDS[world].zones : WORLDS.hills.zones;
}

/* Состав видов обочины для зоны — с учётом открытых призов. Единственный
   владелец: `makeDecor` берёт виды только отсюда.

   Приз правит ВЕС, а не список: второй список («цветущий состав») разъехался
   бы с основным молча, и зона получила бы кактус там, где его нарисовать
   нечем. Поэтому у вида есть необязательное поле `bloomWeight` — вес при
   открытом призе «цветущая обочина», — и необязательное `needs`: имя приза,
   без которого вида в составе нет вовсе.

   Безусловный вид в зоне обязан остаться хотя бы один: `pickFrom` делит на
   сумму весов, и при нуле отдаёт последний вид списка — то есть обочина из
   одного вида, без всякого отказа. Это проверяется тестом по каждой зоне и
   каждому набору призов. */
export function kindsFor(zone, prizes = {}) {
  const kinds = THEME[zone]?.decor?.kinds || THEME[WORLDS.hills.zones[0]].decor.kinds;
  const out = [];
  for (const k of kinds) {
    if (k.needs && !prizes[k.needs]) continue;
    const weight = prizes.bloom && k.bloomWeight != null ? k.bloomWeight : k.weight;
    if (!(weight > 0)) continue;
    out.push({ ...k, weight });
  }
  /* Пустой состав невозможен. Зона, у которой ВСЕ виды условны или обнулены,
     отдаёт свои же виды с положительным весом: `pickFrom` в `makeDecor` делит
     на сумму весов и на пустом списке возвращает `undefined`, а дальше —
     TypeError, то есть забег НЕ НАЧИНАЕТСЯ.

     Здесь (и в двух темах) было написано, что пустой список «не падает, а
     врёт»: даёт NaN и обочину из одного вида. Это было правдой, пока строкой
     выше не появился отсев нулевых весов. Поймано ревью. Тест на инвариант
     остаётся, но теперь он сторожит не единственную защиту. */
  if (out.length === 0) {
    return kinds.map((k) => ({ ...k, weight: k.weight > 0 ? k.weight : 1 }));
  }
  return out;
}

