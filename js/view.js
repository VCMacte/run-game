// Коридор от первого лица на Canvas2D.
//
// Персонажа на экране нет, поэтому понять «где я» ребёнку больше нечем, кроме
// самой панорамы: она едет вбок вместе с телом непрерывно и без задержки. Это
// и обратная связь, и то, что маскирует задержку трансляции — воспринимаемая
// задержка определяется первым видимым изменением, а не моментом, когда вид
// доехал.
//
// Три правила отрисовки, и все три — не вкусовые:
//   * фиксированный буфер 1280×720 и никакого DPR. Miracast всё равно
//     пережимает в 720p, рисовать выше — чистый нагрев GPU, который уже делят
//     распознавание и кодировщик;
//   * никаких теней, фильтров и градиентов в покадровом пути: на Adreno 619
//     это самые дорогие операции, а сжатие их всё равно съест;
//   * ощущение скорости несут поперечные линии пола. В первом лице с
//     минимумом текстур смотреть больше не на что, и без них кажется, что
//     стоишь на месте.

// FIN, а не F: F здесь уже занято фокусным расстоянием.
import { VIEW, OBSTACLES as O, FINISH as FIN, SIGNALS as S } from './config.js';
import { clamp } from './util.js';
import { THEME, DECOR, MOTION, ZONES, zoneAt, motionScale, rgba } from './theme.js';

const EYE = 1.2;          // высота глаз ребёнка, условных метров
const WALL = 2.6;         // высота стен
const HALF = VIEW.corridorWidth / 2;
const NEAR = 0.7;

/* Откуда начинается та геометрия, которая обязана доходить до края кадра.

   Пол и обрывы — плоскости при постоянном x, и панорама их не растягивает, а
   двигает: точка схода стоит на месте (yawPx = 0), едет мир. Поэтому ближний
   угол правого обрыва при полном смещении вправо уезжает ВНУТРЬ кадра, и
   справа от него не нарисовано ничего — остаётся небо, которым залит буфер
   перед всем остальным.

   Посчитано: при NEAR = 0.7 угол доходит до края кадра только пока
   cam.x < 0.663 м, а полный ход — 0.72 м. На максимуме справа оставалась
   полоса 68 px, пятая часть сотни, сплошного skyLow ниже горизонта. Выглядит
   как дырка в мире; пожаловался заказчик.

   Лечится не рамкой и не запасом по ширине, а тем, что плоскость начинается у
   глаза: тогда её ближний угол проецируется в тысячи пикселей за кадр при
   любом сдвиге. Между глазом и NEAR всё равно ничего не рисуется, так что
   лишней работы это не добавляет — те же четыре точки. */
const NEAR_DRAW = 0.08;

const FOV = 75 * Math.PI / 180;

/* Палитра переехала в js/theme.js: там она проверяется по светлоте, и там же
   объяснено, почему проём почти белый, а облака подсинённые.

   Здесь стояло `const COLORS = THEME.greenHill` с объяснением, что второй темы
   не существует и протаскивать её через восемь функций отрисовки ради будущей
   не надо. Теперь зон три, и посылка того объяснения кончилась — но вывод
   остался верным: тема по-прежнему НЕ протаскивается через функции. Вместо
   этого зона приходит полем кадра и защёлкивается на этот кадр в одной
   переменной.

   Почему так, а не параметром: функций отрисовки десять плюс две вложенные, и
   у каждой свой набор аргументов. Лишний параметр в каждой — двенадцать мест,
   где его однажды забудут передать, и забытый даст `undefined` в fillStyle, на
   что Canvas молча оставляет прежний цвет. Одна переменная на кадр такого
   класса ошибок не создаёт вовсе.

   `let`, а не `const`, и меняется ровно в одном месте — в начале render(). */
let COLORS = THEME.greenHill;


/* Границы коридора наружу. Декорации и их проверки обязаны брать эти числа
   здесь, а не повторять у себя: разошедшиеся копии — это пальма, выросшая
   посреди игровой полосы, и заметно это станет на ребёнке. */
export const CORRIDOR_HALF = HALF;
export const CLIFF_TOP = WALL;

const W = VIEW.width;
const H = VIEW.height;
const F = (W / 2) / Math.tan(FOV / 2);
const HORIZON = H * 0.46;

/**
 * Положение взгляда при таком состоянии тела.
 *
 * `x`, `y` — где находятся глаза; `yaw`, `pitch` — куда они смотрят.
 *
 * Поворот взгляда отключён (`VIEW.yawPx = 0`): движение несёт один только
 * боковой сдвиг, то есть параллакс — стены и пол едут мимо, а точка схода
 * стоит на месте. От поступательного движения укачивает слабее, чем от
 * поворота, и для ребёнка на 55 дюймах это решающее соображение.
 *
 * Механизм поворота оставлен: он сделан сдвигом центра проекции, а не
 * вращением сцены, и поэтому горизонт остаётся строго горизонтальным по
 * построению, а не по аккуратности. Крен запрещён в любом случае.
 */
export function camera(u = 0, v = 0) {
  // Мёртвая зона: в покое распознавание всё равно дрожит на сотые доли, и без
  // неё стены мелко шевелятся даже у неподвижного ребёнка.
  const dead = VIEW.viewDeadband;
  const squelch = (x) => (Math.abs(x) < dead ? 0 : x - Math.sign(x) * dead);
  const un = clamp(squelch(u), -1.5, 1.5);
  const vn = clamp(v, 0, 0.6);
  return {
    x: un * VIEW.panGain * HALF,
    y: EYE * (1 - vn * VIEW.pitchGain),
    yaw: -un * VIEW.yawPx,
    pitch: (vn / 0.6) * VIEW.pitchPx,
  };
}

/** Проекция точки мира на экран. Чистая арифметика — проверяется в node. */
export function project(x, y, z, cam) {
  const d = Math.max(z, 0.05);
  return {
    sx: W / 2 + cam.yaw + (x - cam.x) * F / d,
    sy: HORIZON + cam.pitch + (cam.y - y) * F / d,
    scale: F / d,
  };
}

/** Куда уехала точка схода и где оказался горизонт. Для проверок и диагностики. */
export const vanishX = (cam) => W / 2 + cam.yaw;
export const horizonY = (cam) => HORIZON + cam.pitch;

export function createView(canvas, { backdrop = null } = {}) {
  const ctx = canvas.getContext('2d', { alpha: false, desynchronized: true });
  canvas.width = VIEW.width;
  canvas.height = VIEW.height;

  /* «Меньше движения» спрашивается один раз на весь забег, а не каждый кадр:
     matchMedia в кадре — это обращение к стилям двадцать раз в секунду.
     Амплитуда сжимается почти в ноль, но код остаётся один: нулевой путь,
     который никто не исполняет, отдельно гниёт. */
  const reduced = typeof matchMedia === 'function'
    && matchMedia('(prefers-reduced-motion: reduce)').matches;
  const mscale = motionScale(reduced);

  function quad(p1, p2, p3, p4, fill) {
    ctx.fillStyle = fill;
    ctx.beginPath();
    ctx.moveTo(p1.sx, p1.sy);
    ctx.lineTo(p2.sx, p2.sy);
    ctx.lineTo(p3.sx, p3.sy);
    ctx.lineTo(p4.sx, p4.sy);
    ctx.closePath();
    ctx.fill();
  }

  return {
    get element() { return canvas; },

    /**
     * Один кадр.
     * `u` — боковое смещение тела в долях торса, `v` — присед, оба уже
     * сглажены и предсказаны: сюда приходит то, что надо показать сейчас.
     */
    render({ u = 0, v = 0, travel = 0, stars = [], dim = 0, obstacles = [],
             elapsed = 0, safe = true, pulse = 0, finishIn = null, decor = [],
             speed = 0, zone = ZONES[0] }) {
      /* Палитра кадра. Приходит ПОЛЕМ, а решает её train.js — там же, где
         живут стадии, пауза и отсчёт: вид остаётся глупым, и это то же
         разделение, по которому вид не знает ни про камеру, ни про калибровку.

         Неизвестная зона не обнуляет палитру, а оставляет прежнюю: лучше
         нарисовать кадр в цветах соседней зоны, чем в `undefined`. */
      COLORS = THEME[zone] || COLORS;

      const cam = camera(u, v);

      const far = VIEW.fogDistance;

      // ── небо, дальние холмы, облака ──
      // В экранных координатах, а не через проекцию: они на бесконечности, и
      // проекция дала бы им нулевой размер. Параллакс здесь — разная скорость
      // слоёв, ровно как в комиксе того же автора.
      drawSky(ctx, cam, travel, elapsed, backdrop, mscale);

      // ── пол: шахматка ──
      drawFloor(ctx, cam, travel, { project, quad, far });

      // ── обрывы вместо стен ──
      // Геометрия та же, что была у стен, и трогать её нельзя: параллакс
      // ближнего поля — единственная обратная связь управления в игре.
      drawCliffs(cam, { project, quad, far });

      // ── декорации над кромкой ──
      drawDecor(ctx, cam, decor, travel, elapsed, { project, quad, far, mscale });

      // ── финиш ──
      // Рисуется до препятствий: ворота стоят дальше них и не должны лезть
      // поверх того, что ближе.
      if (finishIn != null && finishIn <= FIN.visibleS) {
        drawFinish(ctx, cam, Math.max(finishIn, 0) * VIEW.speed, { project, quad, pulse });
      }

      /* ── кольца и препятствия: порядок маляра ──

         Кольца рисуются двумя проходами, а препятствие — между ними. Замысел
         прежний: кольцо ПЕРЕД препятствием обязано быть видно поверх него,
         иначе оно теряется ровно там, где важнее всего. Но условия «перед» в
         коде не было вовсе: кольца шли одним проходом после препятствий, а
         плита видна с 10 м при кольцах до 30 м — то есть за плитой почти
         всегда есть кольцо, и оно просвечивало сквозь неё. Заметил заказчик.

         Разрез — глубина самого близкого нарисованного препятствия. Линия по
         полу и последний зов остаются в конце: они у самого глаза и ниже
         колец (starY 0.55), спорить им не с чем. */
      const zCut = nearestObstacleDepth(obstacles, elapsed, far);
      drawStars(stars, zCut, far);

      /* «Стоит на месте» нужно бадникам: они икают, пока ребёнок не двигается.

         Считается по СКОРОСТИ, а не по положению. Через положение было
         наоборот: ребёнок, припарковавшийся в боковой трети, — ровно тот, кого
         икота должна расшевелить, — не видел её никогда, а пробегающий через
         центр видел. Порог берётся тот же, которым сигналы отличают дрейф от
         движения, чтобы «не двигается» значило одно и то же во всей игре. */
      const still = Math.abs(speed) < S.driftSpeedMax;
      drawObstacles(ctx, cam, obstacles, elapsed, { project, quad, far, safe, pulse, still, mscale });

      // Кольца ближе препятствия — поверх него, как и было задумано.
      drawStars(stars, 0, zCut);

      /**
       * Кольца в полосе глубин [zFrom, zTo).
       *
       * Кольцо вместо звезды: ромб золота с тёмной серединой. Середина именно
       * заливкой, а не вырезом: тонкая рамка после сжатия исчезает, а тёмный
       * ромб внутри светлого читается как дырка и переживает Miracast.
       *
       * Полоса видимости (NEAR..far) проверяется здесь и только здесь, а
       * границы прохода — отдельной строкой: кольцо ровно на разрезе уходит в
       * ДАЛЬНИЙ проход, то есть при равной глубине прячется за плитой, а не
       * просвечивает сквозь неё.
       */
      function drawStars(list, zFrom, zTo) {
      for (const s of list) {
        const z = s.z - travel;
        if (z < NEAR || z > far) continue;
        if (z < zFrom || z >= zTo) continue;
        const p = project(s.x, VIEW.starY, z, cam);
        // Большое кольцо и выглядит большим: иначе его ценность сообщал бы
        // только звук, то есть ребёнок узнавал бы о ней ПОСЛЕ сбора.
        const крупно = (s.worth ?? 1) > 1;
        const r = Math.max(3, p.scale * VIEW.starDrawR * (крупно ? VIEW.bigStarScale : 1));

        // Собранное кольцо подпрыгивает и исчезает — короткой функцией от
        // времени, без хранения состояния.
        let lift = 0;
        if (s.taken) {
          const age = elapsed - (s.takenAtS ?? -9);
          if (age < 0 || age > 0.45) continue;
          lift = Math.sin((age / 0.45) * Math.PI) * r * 2.2 * mscale;
        }

        /* Пятно на полу под кольцом.

           Самая большая отдача на пиксель во всём уровне, и она не про
           красоту: кольцо висит в воздухе (starY 0.55), а глубину в коридоре
           с плоской покраской сообщают только размер объекта и шахматка пола.
           Пятно говорит прямо, НАД КАКИМ местом пола кольцо висит, — а ловят
           его именно по этому.

           Рисуется ровно здесь, внутри прохода, а не вместе с полом: проходов
           два, и порядок маляра держится на том, что дальние кольца уходят до
           препятствия, а ближние — после. Нарисуй тень вместе с полом, и
           препятствие, стоящее ДАЛЬШЕ ближнего кольца, накрыло бы её.

           У собранного кольца тени нет: оно подпрыгивает и исчезает, а пятно
           под ним осталось бы висеть на полу сиротой. */
        if (!s.taken) {
          const rm = VIEW.starShadowM;
          quad(
            project(s.x - rm, 0, z - rm * 0.6, cam), project(s.x + rm, 0, z - rm * 0.6, cam),
            project(s.x + rm, 0, z + rm * 0.6, cam), project(s.x - rm, 0, z + rm * 0.6, cam),
            COLORS.shadow,
          );
        }

        // Вращение: сжатие по горизонтали. В профиль кольцо не исчезает —
        // это цель, а не украшение.
        const w = r * ringSquash(elapsed, s.z, mscale);
        const cy = p.sy - lift;
        const ring = (rx, ry, fill) => {
          ctx.fillStyle = fill;
          ctx.beginPath();
          ctx.moveTo(p.sx, cy - ry);
          ctx.lineTo(p.sx + rx, cy);
          ctx.lineTo(p.sx, cy + ry);
          ctx.lineTo(p.sx - rx, cy);
          ctx.closePath();
          ctx.fill();
        };
        ring(w, r, COLORS.star);
        if (w > 2.5) ring(w * 0.42, r * 0.42, COLORS.starDim);
      }
      }

      // Затемнение на паузе. Сплошной прямоугольник поверх — дешевле любого
      // фильтра и переживает сжатие.
      if (dim > 0) {
        ctx.fillStyle = rgba(COLORS.shade, clamp(dim, 0, 1));
        ctx.fillRect(0, 0, W, H);
      }
    },
  };
}

/* ─────────────────────── слои фона ───────────────────────

   Небо и дальние холмы — единственное место, где уместен растр: мягкие
   градиенты и дымку вектором не нарисовать. Он необязателен — без него
   рисуются плоские полосы и силуэт холмов, и игра остаётся играбельной.
   Это важнее, чем кажется: арт собирается отдельным прогоном Easy Diffusion,
   и игра не должна от него зависеть.

   Контракт растра: ГОРИЗОНТ НА 46% ВЫСОТЫ картинки, потому что ровно там он у
   нашей проекции (HORIZON = H * 0.46). Фон с горизонтом в другом месте не
   сойдётся с полом, и стык будет виден сразу. */
/**
 * Куда ляжет растр неба и какие полосы кадра он НЕ закроет.
 *
 * Отдельной функцией — потому что от этих чисел зависит, что заливать, а
 * заливка здесь главная статья расхода кадра.
 *
 * Замерено на телефоне: до арта кадр шёл 46–47 fps, с артом 38–39, обе полки
 * ровные все 400 секунд, то есть арт стоит около 5 мс на кадр. При этом
 * `draw50` показывает 0 мс — он мерит время вызовов Canvas2D на CPU, то есть
 * постановку работы в очередь, и растеризацию не видит. «Отрисовка 0 мс» не
 * значит «арт бесплатен».
 *
 * Куда уходили эти миллисекунды, видно отсюда: растр 1024×576 на кадре
 * 1280×720 даёт dh = 720 и dy = 0, то есть ложится РОВНО во весь кадр. А
 * заливка перед ним красила весь кадр плюс верхнюю полосу — 1.3 экранных
 * заливки, которых не видел никто.
 *
 * Считать надо именно геометрию, а не признак «растр есть»: `dy` зависит от
 * наклона взгляда, в приседе горизонт уезжает на pitchPx, и прореха там
 * настоящая. Форма растра тоже не гарантирована — контракт обещает горизонт на
 * 46% высоты, а не отношение сторон.
 */
export function skyGaps(hy, backdrop) {
  if (!backdrop || !backdrop.width) return null;
  const dh = W * backdrop.height / backdrop.width;
  const dy = hy - dh * 0.46;
  return {
    dy,
    dh,
    top: Math.max(0, Math.min(H, dy)),
    bottom: Math.max(0, Math.min(H, H - (dy + dh))),
  };
}

function drawSky(ctx, cam, travel, elapsed, backdrop, mscale) {
  const hy = HORIZON + cam.pitch;
  const gaps = skyGaps(hy, backdrop);

  if (gaps) {
    /* Заливаем ТОЛЬКО прорехи. Полноэкранная заливка служила заодно страховкой
       от «дырки в мире» — полосы неба у края обрыва, — и страховка остаётся: при
       растре во весь кадр он сам и есть сплошная непрозрачная подложка, причём
       лучшая, чем плоский цвет: в прорехе окажется небо с картинки, а не ровная
       синева, которая и выглядела дыркой.

       Нижнюю половину растра перекрывает пол — это ещё около половины экрана
       впустую. Обрезать его по горизонту здесь намеренно не стали: ровно там
       жила та самая полоса 68 пикселей у правого обрыва, и обрезка вернула бы
       риск, только вместо неба в прорехе был бы мусор. */
    if (gaps.top > 0) {
      ctx.fillStyle = COLORS.sky;
      ctx.fillRect(0, 0, W, gaps.top);
    }
    if (gaps.bottom > 0) {
      ctx.fillStyle = COLORS.skyLow;
      ctx.fillRect(0, H - gaps.bottom, W, gaps.bottom);
    }
    // Растр тянется по ширине кадра и кладётся дважды: при боковом уходе
    // взгляда и своём параллаксе он иначе оторвался бы от края.
    /* Сдвиг округляется до целого пикселя. Пара копий кроет [0, W] ровно, но
       при дробном сдвиге на их стыке остаётся волосок субпиксельной
       интерполяции — а полноэкранной заливки под ним больше нет, и в волоске
       проглянул бы предыдущий кадр. Округление снимает весь этот класс
       целиком; движение фона от целого пикселя не страдает — у него свой
       медленный параллакс.

       Второе условие той же страховки: растр обязан быть НЕПРОЗРАЧНЫМ. Наш
       `assets/sky.webp` такой (VP8 без альфы), и собирается он `toWebp()` из
       `tools/frame.html`; растр с альфой пустил бы предыдущий кадр наружу
       по всей площади. */
    const shift = Math.round(-(travel * MOTION.farParallax * 40 + cam.x * 30) % W);
    ctx.drawImage(backdrop, shift, gaps.dy, W, gaps.dh);
    ctx.drawImage(backdrop, shift + (shift > 0 ? -W : W), gaps.dy, W, gaps.dh);
    return;
  }

  ctx.fillStyle = COLORS.skyLow;
  ctx.fillRect(0, 0, W, H);
  ctx.fillStyle = COLORS.sky;
  ctx.fillRect(0, 0, W, Math.max(0, hy - H * 0.16));

  // Запасной путь: силуэт холмов. Крупными горбами — мелкий рельеф после
  // сжатия всё равно превратится в кашу.
  ctx.fillStyle = COLORS.hills;
  const drift = travel * MOTION.farParallax * 18 + cam.x * 24;
  for (let i = -1; i < 7; i++) {
    const cx = ((i * 0.22 * W - drift) % (W * 1.6) + W * 1.6) % (W * 1.6) - W * 0.3;
    const rw = W * (0.17 + 0.05 * ((i + 7) % 3));
    const rh = H * (0.05 + 0.022 * ((i + 7) % 3));
    ctx.beginPath();
    ctx.moveTo(cx - rw, hy);
    ctx.quadraticCurveTo(cx, hy - rh * 2.2, cx + rw, hy);
    ctx.closePath();
    ctx.fill();
  }

  // Облака: своя скорость и свой дрейф. Подсинённые, а не белые — белое
  // облако у горизонта спорит по светлоте с проёмом.
  ctx.fillStyle = COLORS.cloud;
  const cd = travel * MOTION.cloudParallax * 22 + elapsed * MOTION.cloudDriftHz * 60 * mscale;
  for (let i = 0; i < 4; i++) {
    const cx = ((i * 0.31 * W - cd) % (W * 1.3) + W * 1.3) % (W * 1.3) - W * 0.15;
    const cy = hy - H * (0.2 + 0.07 * (i % 3));
    const rw = W * 0.085;
    const rh = H * 0.028;
    ctx.beginPath();
    ctx.ellipse(cx, cy, rw, rh, 0, 0, Math.PI * 2);
    ctx.ellipse(cx + rw * 0.7, cy + rh * 0.3, rw * 0.6, rh * 0.75, 0, 0, Math.PI * 2);
    ctx.fill();
  }
}

/* Пол шахматкой.

   Шаг тот же, что был у поперечных линий (floorLineStep), и это не мелочь:
   линии несли скорость и ритм, по которому ребёнок ждёт препятствие. Сменить
   шаг значило бы сменить ритм, то есть залезть в гейм-плей.

   Клетки привязаны к мировой сетке (z + travel), а не к фазе: привязанные к
   фазе они дёргались бы на каждом обороте остатка.

   Защита от мерцания у горизонта сохранена: то, что мельче lineMinGapPx, не
   рисуется вовсе. Это чистая резь в глазах без крупицы пользы. */
function drawFloor(ctx, cam, travel, { project, quad, far }) {
  const step = VIEW.floorLineStep;
  const NX = 4;                      // столбцов на ширину коридора
  const cw = (HALF * 2) / NX;

  // Основа одним четырёхугольником: половину клеток рисовать не надо.
  // От NEAR_DRAW, а не от NEAR: при полном смещении камеры край пола иначе
  // уезжает внутрь кадра и сбоку остаётся небо. Шахматка поверх может
  // начинаться где угодно — под ней уже закрашено.
  quad(
    project(-HALF, 0, NEAR_DRAW, cam), project(HALF, 0, NEAR_DRAW, cam),
    project(HALF, 0, far, cam), project(-HALF, 0, far, cam),
    COLORS.floorB,
  );

  const zStart = Math.ceil((NEAR + travel) / step) * step - travel;
  for (let zb = zStart; zb < far; zb += step) {
    if (F * step / (zb * zb) < VIEW.lineMinGapPx) break;
    const iz = Math.round((zb + travel) / step);
    const zf = Math.min(zb + step, far);
    /* Дальние клетки бледнее, но не прозрачнее: прозрачность стоит дорого, а
       разница в светлоте переживает сжатие лучше.

       Полос три, а не две, и это не стоит ни одной лишней заливки — меняется
       только выбор цвета в том же цикле. Светлота идёт лестницей вниз
       (0.399 → 0.328 → 0.283), и расстояние по трём ступеням читается заметно
       лучше, чем по двум: в коридоре с плоской покраской глубину сообщают
       только размер объекта и эта шахматка. */
    const fill = zb > far * 0.65 ? COLORS.floorFar
      : zb > far * 0.33 ? COLORS.floorMid
        : COLORS.floorA;
    for (let ix = 0; ix < NX; ix++) {
      if ((iz + ix) % 2) continue;
      const x0 = -HALF + ix * cw;
      const x1 = x0 + cw;
      quad(
        project(x0, 0, zb, cam), project(x1, 0, zb, cam),
        project(x1, 0, zf, cam), project(x0, 0, zf, cam),
        fill,
      );
    }
  }
}

/* Обрывы по сторонам — те же вертикальные плоскости, что были стенами.

   Светлота левого и правого различается, как и раньше: при боковом уходе
   взгляда разница подсказывает направление даже после сжатия, когда цвет уже
   размыт. Поверх — полоса травы по кромке и тёмная полоса глубже: именно они
   делают из стены обрыв. */
function drawCliffs(cam, { project, quad, far }) {
  // Все четыре полосы — от NEAR_DRAW, а не от NEAR: обрыв обязан доходить до
  // края кадра при любом смещении камеры, иначе сбоку видно небо.
  const cliff = (x, earth) => {
    quad(
      project(x, 0, NEAR_DRAW, cam), project(x, WALL, NEAR_DRAW, cam),
      project(x, WALL, far, cam), project(x, 0, far, cam),
      earth,
    );
    // Тёмная полоса у основания: глубина обрыва.
    quad(
      project(x, 0, NEAR_DRAW, cam), project(x, 0.5, NEAR_DRAW, cam),
      project(x, 0.5, far, cam), project(x, 0, far, cam),
      COLORS.earthDeep,
    );
    // Кромка травы. Две полосы — светлая сверху, тёмная под ней: один тон
    // после сжатия сливается с землёй.
    quad(
      project(x, WALL - 0.34, NEAR_DRAW, cam), project(x, WALL, NEAR_DRAW, cam),
      project(x, WALL, far, cam), project(x, WALL - 0.34, far, cam),
      COLORS.grassDark,
    );
    quad(
      project(x, WALL - 0.14, NEAR_DRAW, cam), project(x, WALL, NEAR_DRAW, cam),
      project(x, WALL, far, cam), project(x, WALL - 0.14, far, cam),
      COLORS.grass,
    );
  };
  cliff(-HALF, COLORS.earthL);
  cliff(HALF, COLORS.earthR);
}

/* Декорации.

   Рисуются после обрывов и только выше кромки: ниже их всё равно не видно,
   стены закрывают всё за собой.

   Потолок на число нарисованных — не перестраховка, а бюджет кадра:
   Snapdragon 695 уже отдаёт 62 мс медианы на инференс при цели 20 Гц, и кадр
   здесь дешевле не станет. Ближние важнее дальних, список упорядочен по
   глубине, поэтому достаточно прекратить на потолке. */
/* Сколько декораций рисуется за кадр. Это ЗАПАС, а не рабочее ограничение.

   Поднимая его с 12 вместе с плотностью, я написал здесь, что старый потолок
   обрезал обочину на середине коридора. Это оказалось неправдой: в окне
   отрисовки (`NEAR` … `far * 0.75`) при нынешней плотности помещается самое
   большее одиннадцать декораций — замерено по четырём посевам на всём забеге.
   То есть и прежний потолок не связывал ни разу, и поднятие ничего не
   изменило.

   Оставлен поднятым осознанно: одиннадцать против двенадцати — это запас в
   одну штуку, и следующая же правка плотности начала бы молча резать обочину.
   Восемнадцать дают настоящий запас. Но называть это починкой нельзя: число в
   конфиге, разошедшееся с поведением, хуже отсутствующего. */
const DECOR_MAX = 18;

function drawDecor(ctx, cam, decor, travel, elapsed, { project, quad, far, mscale }) {
  /* Сначала отбираем ближние — на них бюджет, — а рисуем в обратном порядке,
     от дальних к ближним. Список от `makeDecor` идёт по возрастанию глубины,
     и рисование прямо по нему клало дальнюю пальму поверх ближней: тёмный
     ствол дальней перекрывал зелёную крону ближней. Две пальмы одной стороны
     на трёх и пяти метрах перекрываются на экране — видно сразу. */
  const near = [];
  for (const d of decor) {
    if (near.length >= DECOR_MAX) break;
    const z = d.z - travel;
    if (z < NEAR || z > far * 0.75) continue;
    near.push([d, z]);
  }

  for (let i = near.length - 1; i >= 0; i--) {
    const [d, z] = near[i];

    const base = d.y;                        // кромка обрыва
    const top = base + d.h;
    const sway = palmSway(elapsed, d.phase, mscale);
    /* Цвета — ЗОНЫ ЭЛЕМЕНТА, а не кадра. На границе зон обочина следующей уже
       видна (декорации рисуются на 22 метра вперёд), и в палитре предыдущей
       она выглядела бы ошибкой. Запасной вариант — палитра кадра: у записи от
       прошлой версии поля `zone` нет. */
    const C = THEME[d.zone] || COLORS;

    if (d.kind === 'palm') {
      const w = 0.09;
      quad(
        project(d.x - w, base, z, cam), project(d.x + w, base, z, cam),
        project(d.x + w + sway, top, z, cam), project(d.x - w + sway, top, z, cam),
        C.palmTrunk,
      );
      /* Крона: два боковых пера и одно вверх. Средним пером тут был тот же
         цикл по [-1, 0, 1], и при нуле все четыре угла схлопывались в одну
         точку — перо с нулевой площадью, которого никто никогда не видел.
         Вертикальное перо приходится задавать отдельно: у него своя ширина,
         а не нулевой размах. */
      const cx = d.x + sway;
      for (const dir of [-1, 1]) {
        quad(
          project(cx, top - 0.1, z, cam), project(cx + dir * 0.52, top + 0.1, z, cam),
          project(cx + dir * 0.58, top + 0.28, z, cam), project(cx, top + 0.22, z, cam),
          C.palmLeaf,
        );
      }
      quad(
        project(cx - 0.12, top - 0.05, z, cam), project(cx + 0.12, top - 0.05, z, cam),
        project(cx + 0.16, top + 0.34, z, cam), project(cx - 0.16, top + 0.34, z, cam),
        C.palmLeaf,
      );
    } else if (d.kind === 'bush') {
      quad(
        project(d.x - 0.34, base, z, cam), project(d.x + 0.34, base, z, cam),
        project(d.x + 0.26, top, z, cam), project(d.x - 0.26, top, z, cam),
        C.palmLeaf,
      );
      quad(
        project(d.x - 0.18, top - 0.08, z, cam), project(d.x + 0.18, top - 0.08, z, cam),
        project(d.x + 0.12, top + 0.12, z, cam), project(d.x - 0.12, top + 0.12, z, cam),
        C.grass,
      );
    } else if (d.kind === 'flower') {
      quad(
        project(d.x - 0.03, base, z, cam), project(d.x + 0.03, base, z, cam),
        project(d.x + 0.03, top, z, cam), project(d.x - 0.03, top, z, cam),
        C.grassDark,
      );
      /* Цветок поворачивается вслед проходящему. Поворот — функция близости, а
         не времени: он должен провожать именно того, кто бежит. */
      const turn = clamp(1 - z / 6, 0, 1) * MOTION.flowerTurnM * mscale * -Math.sign(d.x);
      quad(
        project(d.x - 0.14 + turn, top, z, cam), project(d.x + 0.14 + turn, top, z, cam),
        project(d.x + 0.14 + turn, top + 0.28, z, cam), project(d.x - 0.14 + turn, top + 0.28, z, cam),
        C.flower,
      );
    } else if (d.kind === 'cactus') {
      /* Кактус: ствол и две лапы. Три заливки — дешевле пальмы, у которой
         четыре, то есть зона дюн кадр не утяжеляет. */
      const w = 0.13;
      quad(
        project(d.x - w, base, z, cam), project(d.x + w, base, z, cam),
        project(d.x + w, top, z, cam), project(d.x - w, top, z, cam),
        C.cactus,
      );
      for (const dir of [-1, 1]) {
        const y0 = base + d.h * (dir < 0 ? 0.42 : 0.58);
        quad(
          project(d.x + dir * w, y0, z, cam), project(d.x + dir * 0.34, y0, z, cam),
          project(d.x + dir * 0.34, y0 + 0.42, z, cam), project(d.x + dir * w, y0 + 0.2, z, cam),
          C.cactus,
        );
      }
    } else if (d.kind === 'rock') {
      // Камень: одна трапеция. Самая дешёвая форма в игре — одна заливка.
      quad(
        project(d.x - 0.3, base, z, cam), project(d.x + 0.3, base, z, cam),
        project(d.x + 0.16, top, z, cam), project(d.x - 0.2, top, z, cam),
        C.rock,
      );
    } else if (d.kind === 'spruce') {
      /* Ель: ствол и два яруса. Ярусы треугольниками через четырёхугольник с
         совпадающими верхними углами — тем же приёмом, что зубья на потолке. */
      quad(
        project(d.x - 0.06, base, z, cam), project(d.x + 0.06, base, z, cam),
        project(d.x + 0.06, base + d.h * 0.3, z, cam), project(d.x - 0.06, base + d.h * 0.3, z, cam),
        C.palmTrunk,
      );
      for (const [y0, w] of [[0.25, 0.42], [0.58, 0.3]]) {
        const yb = base + d.h * y0;
        quad(
          project(d.x - w, yb, z, cam), project(d.x + w, yb, z, cam),
          project(d.x, yb + d.h * 0.42, z, cam), project(d.x, yb + d.h * 0.42, z, cam),
          C.spruce,
        );
      }
    } else if (d.kind === 'post') {
      /* Столб у обочины. Высокий и узкий, то есть почти целиком из пустых
         пикселей, — а мимо глаза проходит заметно. Ради этого и поставлен:
         шахматка пола даёт поток только в нижней половине кадра, а скорость
         читается периферией.

         Не качается, в отличие от пальмы: столб — это ритм, и дрожащий ритм
         хуже ровного. */
      const w = 0.08;
      quad(
        project(d.x - w, base, z, cam), project(d.x + w, base, z, cam),
        project(d.x + w, top, z, cam), project(d.x - w, top, z, cam),
        C.post,
      );
      // Поясок под верхушкой: по нему столб и опознаётся как метка, а не как
      // палка. Светлее тела, но мелкий — на светлоту кадра не влияет.
      quad(
        project(d.x - w * 1.6, top - 0.34, z, cam), project(d.x + w * 1.6, top - 0.34, z, cam),
        project(d.x + w * 1.6, top - 0.08, z, cam), project(d.x - w * 1.6, top - 0.08, z, cam),
        C.postMark,
      );
    } else if (d.kind === 'totem') {
      // Тотем. Подмигивает, когда проходишь вплотную — одна из четырёх шуток
      // уровня, и единственная, которую можно не заметить.
      quad(
        project(d.x - 0.22, base, z, cam), project(d.x + 0.22, base, z, cam),
        project(d.x + 0.22, top, z, cam), project(d.x - 0.22, top, z, cam),
        C.totem,
      );
      /* Порог 3.6 м, а не «вплотную». Декорации стоят за кромкой, на
         x = ±1.75, и ближе ~2.3 м тотем уже за краем кадра: шутка, которую
         нельзя увидеть, — это не шутка, а мёртвый код. */
      const wink = z < 3.6 && Math.sin(elapsed * 6 + d.phase * 9) > 0.4;
      const eyeH = wink ? 0.03 : 0.12;
      quad(
        project(d.x - 0.1, top - 0.3, z, cam), project(d.x + 0.1, top - 0.3, z, cam),
        project(d.x + 0.1, top - 0.3 + eyeH, z, cam), project(d.x - 0.1, top - 0.3 + eyeH, z, cam),
        C.badnikEye,
      );
    }
  }
}

/**
 * Препятствия и четыре отметки телеграфа.
 *
 * Порядок отметок и их смысл — в config.OBSTACLES. Коротко: за четыре секунды
 * в глубине коридора загорается полоса на той стороне, которая будет закрыта;
 * за три проявляется само препятствие; за две по полу идёт линия, которая
 * дойдёт до игрока ровно вместе с ним; за секунду проём пульсирует, а
 * неверное положение подсвечивается.
 *
 * Самая важная из них — линия по полу. Семилетка плохо оценивает «сколько
 * осталось до того столба», но прекрасно ждёт, пока линия доедет до него:
 * задача оценки расстояния подменяется задачей ожидания ритма, а ритм в этом
 * возрасте уже освоен.
 */
function drawObstacles(ctx, cam, obstacles, elapsed, { project, quad, far, safe, pulse, still, mscale }) {
  const edge = obstacleEdge();
  for (const ob of obstacles) {
    /* Глубина берётся из obstacleDepth, а не считается здесь: по ней же
       режется проход по кольцам, и две копии разошлись бы — кольцо снова
       начало бы просвечивать сквозь плиту. Отсечения («прошли», «дальше
       телеграфа», «уехало за спину») живут там же. */
    const depth = obstacleDepth(ob, elapsed, far);
    if (depth == null) continue;
    const dt = ob.at - elapsed;          // секунд до прихода
    const zRaw = dt * VIEW.speed;
    const z = depth;

    /* Метка в глубине коридора: крупная заливка, а не рамка. Тонкий контур на
       дальнем плане сжатие уничтожает первым.

       Красная и мерцающая, а не оранжевая и ровная. Заказчик пожаловался, что
       предупреждение о будущем препятствии плохо видно, и причин было три
       сразу: оранжевый сидел между цветом финиша и цветом звезды, метка
       занимала половину высоты обрыва, а жила ровно секунду. Теперь цвет
       свой, высота полная, окно две секунды (signalS 5.0 против visibleS 3.0),
       и медленное мерцание 1 Гц отличает «это будет» от «это уже здесь».

       Фаза своя у каждого препятствия: две метки подряд не должны мигать в
       унисон, иначе мерцание читается как общая рябь кадра, а не как метка. */
    if (dt > O.visibleS) {
      const zf = depth;
      const h = 0.9;
      const hot = warnBlink(elapsed, ob.at * 2, mscale) > 0.5;
      const fill = hot ? COLORS.warn : COLORS.warnDim;
      if (ob.kind === 'duck') {
        quad(
          project(-HALF, WALL, zf, cam), project(HALF, WALL, zf, cam),
          project(HALF, WALL - h * 1.6, zf, cam), project(-HALF, WALL - h * 1.6, zf, cam),
          fill,
        );
      } else {
        const x0 = ob.side > 0 ? edge : -HALF;
        const x1 = ob.side > 0 ? HALF : -edge;
        quad(
          project(x0, 0, zf, cam), project(x1, 0, zf, cam),
          project(x1, WALL, zf, cam), project(x0, WALL, zf, cam),
          fill,
        );
      }
      // Метка и плита — взаимоисключающие стадии одного препятствия: пока
      // идёт телеграф, самой плиты ещё не видно.
      continue;
    }

    const zBack = Math.max(zRaw + O.thickness, O.drawNearM + 0.02);

    // Проём заливается ярким: ребёнку надо показать, куда идти, а не только
    // куда нельзя.
    if (ob.kind === 'duck') {
      quad(
        project(-HALF, WALL, z, cam), project(HALF, WALL, z, cam),
        project(HALF, O.duckHeight, z, cam), project(-HALF, O.duckHeight, z, cam),
        COLORS.block,
      );
      quad(
        project(-HALF, WALL, zBack, cam), project(HALF, WALL, zBack, cam),
        project(HALF, O.duckHeight, zBack, cam), project(-HALF, O.duckHeight, zBack, cam),
        COLORS.blockDark,
      );
      quad(
        project(-HALF, 0.02, z, cam), project(HALF, 0.02, z, cam),
        project(HALF, 0.02, zBack, cam), project(-HALF, 0.02, zBack, cam),
        COLORS.gap,
      );
      /* Цепей здесь нет, хотя по замыслу бревно должно было висеть на них.
         Вешать не на что: плита и так занимает всё от `duckHeight` до кромки
         обрыва, промежутка нет. Нарисованные цепи ложились прямо на её лицо
         двумя тёмными полосами поверх цвета, который сообщает решение, —
         шума больше, чем смысла. */

      // Шипы вниз по нижней кромке — вторая внешность того же приседа.
      if (ob.look === 'ceiling') {
        drawTeeth(z, cam, { project, quad });
      }
    } else {
      const x0 = ob.side > 0 ? edge : -HALF;
      const x1 = ob.side > 0 ? HALF : -edge;
      quad(
        project(x0, 0, z, cam), project(x1, 0, z, cam),
        project(x1, WALL, z, cam), project(x0, WALL, z, cam),
        COLORS.block,
      );
      quad(
        project(x0, 0, zBack, cam), project(x1, 0, zBack, cam),
        project(x1, WALL, zBack, cam), project(x0, WALL, zBack, cam),
        COLORS.blockDark,
      );
      // Пол в проёме.
      const g0 = ob.side > 0 ? -HALF : edge;
      const g1 = ob.side > 0 ? -edge : HALF;
      quad(
        project(g0, 0.02, z, cam), project(g1, 0.02, z, cam),
        project(g1, 0.02, zBack, cam), project(g0, 0.02, zBack, cam),
        COLORS.gap,
      );

      /* Шипы по кромке плиты и бадник на закрытой стороне.

         Форма сообщает тему, светлота сообщает решение: плита осталась ровно
         той же по светлоте, проём — самым светлым местом кадра, а шипы и враг
         добавлены поверх. Нарушить этот порядок значит сделать красивый
         уровень, в котором непонятно, куда уходить. */
      drawSpikes(ob, z, cam, { project, quad, x0, x1 });
      /* Бадник или створка — ровно одно из двух, и это не экономия, а смысл:
         две внешности одного препятствия должны отличаться с первого взгляда,
         а живое существо рядом с механической створкой читается как два разных
         препятствия сразу. Попутно створка стоит дешевле бадника по заливкам,
         так что перекраска не съела бюджет кадра. */
      if (ob.look === 'gate') {
        drawGate(z, cam, { project, quad, x0, x1 });
      } else {
        drawBadnik(ob, dt, z, cam, elapsed, { project, quad, x0, x1, safe, still, mscale });
      }
    }

    // Линия по полу, которая дойдёт вместе с препятствием.
    if (dt <= O.railS && dt > 0 && zRaw > NEAR) {
      quad(
        project(-HALF, 0.03, Math.max(zRaw - 0.12, NEAR), cam), project(HALF, 0.03, Math.max(zRaw - 0.12, NEAR), cam),
        project(HALF, 0.03, Math.max(zRaw, NEAR), cam), project(-HALF, 0.03, Math.max(zRaw, NEAR), cam),
        COLORS.rail,
      );
    }

    // Последний зов: если ребёнок не там, закрытая сторона наливается цветом.
    // Подтверждение правильного положения не менее важно, чем предупреждение:
    // в первом лице нет персонажа, по которому видно, достаточно ли ты ушёл.
    if (dt <= O.lastCallS && dt > 0 && pulse > 0.5) {
      const warn = safe ? COLORS.gap : COLORS.block;
      quad(
        project(-HALF, 0, 0.75, cam), project(HALF, 0, 0.75, cam),
        project(HALF, 0.08, 0.75, cam), project(-HALF, 0.08, 0.75, cam),
        warn,
      );
    }
  }
}

/* Шипы по верхней кромке плиты.

   Треугольниками, но крупными: мелкий зубец после сжатия превращается в
   неровную линию. Цвет металла светлее плиты и темнее проёма — он не
   участвует в решении и не имеет права спорить с ним по светлоте. */
/* Шипы на потолке: зубья вниз по нижней кромке верхней плиты.

   Это ВТОРАЯ ВНЕШНОСТЬ приседа, а не второе препятствие. Действие то же,
   метка телеграфа та же, мотив тот же — меняется только силуэт, и меняется он
   ради пяти минут, которые ребёнок смотрит в один и тот же коридор.

   Плита при этом остаётся на месте целиком. Заменить её зубьями было бы
   красивее и неправильно: светлота плиты сообщает «сюда нельзя», а между
   зубьями просвечивал бы проём, то есть самое светлое место кадра оказалось
   бы там, куда идти как раз не надо. Форма сообщает тему, светлота сообщает
   решение — здесь это ровно тот же порядок, что у боковых шипов ниже. */
function drawTeeth(z, cam, { project, quad }) {
  const N = 7;
  const w = (HALF * 2) / N;
  const h = O.teethM;
  for (let i = 0; i < N; i++) {
    const xa = -HALF + i * w;
    // Треугольник четырёхугольником: два верхних угла врозь, нижние — вместе.
    quad(
      project(xa, O.duckHeight, z, cam), project(xa + w, O.duckHeight, z, cam),
      project(xa + w * 0.5, O.duckHeight - h, z, cam), project(xa + w * 0.5, O.duckHeight - h, z, cam),
      COLORS.spike,
    );
  }
}

/* Створка: та же плита, но с поперечными полосами и утолщённым низом.

   Вторая внешность бокового препятствия. Полосы — `blockDark`, тем же цветом
   нарисована задняя грань плиты: новый цвет здесь не нужен и был бы вреден —
   на лице плиты, которое сообщает решение, любая светлая полоса начала бы
   спорить с проёмом. */
function drawGate(z, cam, { project, quad, x0, x1 }) {
  for (const y of [0.7, 1.4, 2.1]) {
    quad(
      project(x0, y, z, cam), project(x1, y, z, cam),
      project(x1, y + 0.12, z, cam), project(x0, y + 0.12, z, cam),
      COLORS.blockDark,
    );
  }
}

function drawSpikes(ob, z, cam, { project, quad, x0, x1 }) {
  const n = 3;
  const w = (x1 - x0) / n;
  for (let i = 0; i < n; i++) {
    const a = x0 + i * w;
    const apex = project(a + w / 2, WALL + 0.26, z, cam);
    quad(
      project(a, WALL, z, cam), project(a + w, WALL, z, cam),
      apex, apex,
      COLORS.spike,
    );
  }
}

/* Бадник — жук на колёсике, сидит на закрытой стороне.

   Тело тёмное: враг обязан быть заметным, но не светлым, иначе он начнёт
   соперничать с проёмом, то есть с сообщением «иди сюда».

   Две шутки уровня живут здесь, и обе — функции времени, без состояния:

   1. Икает, пока ребёнок стоит на месте. Нужна не для смеха: неподвижность —
      это ровно то, чего игра не хочет, и дёргающийся враг тянет взгляд.
   2. На последней отметке телеграфа, если ребёнок уже в безопасном месте,
      бадник вскрывается и из него выскакивает зверёк. Это награда, и она
      приходит ДО столкновения, а не после: в момент прохода бадник уже за
      спиной, и там его не видно вовсе — проверено построением проекции.
*/
function drawBadnik(ob, dt, z, cam, elapsed, { project, quad, x0, x1, safe, still, mscale }) {
  const cx = (x0 + x1) / 2;
  const opened = dt <= O.lastCallS && safe;

  // Икота: короткий подскок, и только когда ребёнок не двигается.
  const hic = still && !opened
    ? Math.max(0, Math.sin(elapsed * (2 * Math.PI / MOTION.badnikHiccupS) * 3)) ** 8 * 0.1 * mscale
    : 0;

  const bodyY = 0.14 + hic;
  const bodyH = 0.3;

  if (opened) {
    // Вскрылся: две половинки разъехались. Чем ближе, тем шире — функция dt,
    // а не накопленное время.
    const open = clamp(1 - dt / O.lastCallS, 0, 1);
    for (const dir of [-1, 1]) {
      const hx = cx + dir * (0.1 + open * 0.22);
      quad(
        project(hx - 0.1, bodyY, z, cam), project(hx + 0.1, bodyY, z, cam),
        project(hx + 0.1, bodyY + bodyH * 0.7, z, cam), project(hx - 0.1, bodyY + bodyH * 0.7, z, cam),
        COLORS.badnik,
      );
    }
    /* Зверёк: выскакивает и убегает по кромке обрыва, спотыкаясь. Спотыкание
       — просадка в середине пути, тоже функция `open`. */
    const run = open;
    const sx = cx + Math.sign(ob.side || 1) * run * 0.5;
    const trip = Math.abs(run - 0.55) < 0.08 ? -0.08 : 0;
    const sy = bodyY + bodyH + run * 0.5 + Math.abs(Math.sin(run * 9)) * 0.1 + trip;
    quad(
      project(sx - 0.09, sy, z, cam), project(sx + 0.09, sy, z, cam),
      project(sx + 0.09, sy + 0.18, z, cam), project(sx - 0.09, sy + 0.18, z, cam),
      COLORS.critter,
    );
    return;
  }

  // Тело.
  quad(
    project(cx - 0.24, bodyY, z, cam), project(cx + 0.24, bodyY, z, cam),
    project(cx + 0.24, bodyY + bodyH, z, cam), project(cx - 0.24, bodyY + bodyH, z, cam),
    COLORS.badnik,
  );
  // Колёсико: крутится. Видно по полоске, которая ходит вверх-вниз, — сплошной
  // круг вращения не показывает вовсе.
  const spin = Math.sin(elapsed * 2 * Math.PI * MOTION.badnikWheelHz * mscale) * 0.05;
  quad(
    project(cx - 0.14, 0.02, z, cam), project(cx + 0.14, 0.02, z, cam),
    project(cx + 0.14, bodyY, z, cam), project(cx - 0.14, bodyY, z, cam),
    COLORS.earthDeep,
  );
  quad(
    project(cx - 0.08, 0.06 + spin, z, cam), project(cx + 0.08, 0.06 + spin, z, cam),
    project(cx + 0.08, 0.1 + spin, z, cam), project(cx - 0.08, 0.1 + spin, z, cam),
    COLORS.spike,
  );
  // Глаз. Маленький и светлый: на светлоту кадра не влияет, но без него враг
  // не читается как живой.
  quad(
    project(cx - 0.07, bodyY + bodyH * 0.55, z, cam), project(cx + 0.07, bodyY + bodyH * 0.55, z, cam),
    project(cx + 0.07, bodyY + bodyH * 0.85, z, cam), project(cx - 0.07, bodyY + bodyH * 0.85, z, cam),
    COLORS.badnikEye,
  );
}

/**
 * Ворота финиша.
 *
 * Две стойки и перекладина, жёлтым — цветом звёзд, а не проёма: проём значит
 * «сюда можно», а ворота значат «всё, добежал», и путать эти два сообщения
 * нельзя. На подходе перекладина мигает: это единственное место в игре, где
 * мигание уместно — оно обещает конец, а не требует реакции.
 */
function drawFinish(ctx, cam, z, { project, quad, pulse }) {
  if (z < 0.4) return;
  const w = FIN.postWidth;
  const h = FIN.gateHeight;
  const post = (x0, x1) => quad(
    project(x0, 0, z, cam), project(x1, 0, z, cam),
    project(x1, h, z, cam), project(x0, h, z, cam),
    COLORS.finishDark,
  );
  post(-HALF, -HALF + w);
  post(HALF - w, HALF);
  quad(
    project(-HALF, h, z, cam), project(HALF, h, z, cam),
    project(HALF, h - w, z, cam), project(-HALF, h - w, z, cam),
    z < 10 && pulse > 0.5 ? COLORS.finish : COLORS.finishDark,
  );

  /* Табличка-указатель: самая заметная шутка уровня и прямая цитата из той
     игры, по которой уровень сделан. Крутится, а вплотную шлёпается лицом
     вверх.

     Сжатие по горизонтали, а не поворот сцены: поворот обошёлся бы матрицей,
     а сжатие — это та же функция, что крутит кольца.

     Стоит У КРАЯ, а не посередине. Посередине она закрывала проход сплошной
     заливкой того же цвета, что и ворота, и всё вместе читалось как жёлтая
     стена поперёк коридора — проверено на кадре через tools/frame.html.
     Вплотную не рисуется вовсе: на метре она занимает весь экран. */
  if (z < 1.2) return;

  const sx = HALF * 0.62;
  const flop = z < 2.2;
  const spin = flop ? 1 : Math.abs(Math.cos(2 * Math.PI * z * MOTION.signSpinHz / VIEW.speed));
  const bw = 0.26 * Math.max(0.14, spin);
  const by = flop ? 0.14 : 0.78;
  const bh = flop ? 0.12 : 0.44;
  // Столбик.
  quad(
    project(sx - 0.04, 0, z, cam), project(sx + 0.04, 0, z, cam),
    project(sx + 0.04, by + bh * 0.4, z, cam), project(sx - 0.04, by + bh * 0.4, z, cam),
    COLORS.finishDark,
  );
  // Рамка и поле таблички: без рамки она сливается с перекладиной ворот,
  // потому что цвет у них один и тот же — цвет финиша.
  quad(
    project(sx - bw, by, z, cam), project(sx + bw, by, z, cam),
    project(sx + bw, by + bh, z, cam), project(sx - bw, by + bh, z, cam),
    COLORS.finishDark,
  );
  quad(
    project(sx - bw * 0.78, by + bh * 0.14, z, cam), project(sx + bw * 0.78, by + bh * 0.14, z, cam),
    project(sx + bw * 0.78, by + bh * 0.86, z, cam), project(sx - bw * 0.78, by + bh * 0.86, z, cam),
    COLORS.finish,
  );
}

/* ─────────────────────── анимации ───────────────────────

   Все до единой — функции времени. Ни одна не копит состояние, и это не
   стилистическое предпочтение: источник поз идёт на 20 Гц, кадры проседают, и
   накопительная анимация расходится с картинкой тем сильнее, чем дольше
   забег. Функция от времени не расходится никогда.

   Побочная выгода: их видно из node. Проверка «анимации» в tests-control.mjs
   прогоняет их без браузера и канваса, как и всю остальную математику. */

/**
 * Сжатие кольца по горизонтали: оно крутится.
 *
 * `t` — секунды от старта забега, `phase` — своя фаза кольца, чтобы весь ряд
 * не крутился в унисон. Пол 0.12 важен: кольцо, повернувшееся строго в
 * профиль, исчезло бы, а это цель, а не украшение — ребёнок должен видеть,
 * куда тянуться.
 */
export function ringSquash(t, phase = 0, scale = 1) {
  const spin = Math.max(0.12, Math.abs(Math.cos(2 * Math.PI * (t * MOTION.ringSpinHz + phase))));
  // Сжатие уменьшается вместе с амплитудой: при «меньше движения» кольцо
  // почти не вращается, но тот же код продолжает работать.
  return 1 - scale * (1 - spin);
}

/** Качание пальмовой кроны, условных метров в сторону. Вокруг своего места. */
export function palmSway(t, phase = 0, scale = 1) {
  return MOTION.palmSwayM * scale * Math.sin(2 * Math.PI * (t * MOTION.palmSwayHz + phase));
}

/**
 * Мерцание далёкого предупреждения: 1 — ярко, 0 — приглушённо.
 *
 * Потолок, а не пол, в отличие от ringSquash: при «меньше движения» значение
 * прижимается к ЕДИНИЦЕ, то есть метка остаётся ровно яркой. Это не
 * украшение, а сообщение о решении — системная настройка не имеет права его
 * погасить, и погасить её не может по построению, а не по аккуратности.
 */
export function warnBlink(t, phase = 0, scale = 1) {
  const wave = 0.5 * (1 + Math.sin(2 * Math.PI * MOTION.warnBlinkHz * t + phase));
  return 1 - scale * wave;
}

/**
 * Декорации по сторонам коридора.
 *
 * Стоят ЗА кромкой обрыва и выше неё. Иначе никак: стены рисуются сплошными
 * четырёхугольниками до тумана и всё за собой закрывают.
 *
 * Расставляются по времени, а не через равные метры: при смене скорости бега
 * уровень должен выглядеть так же густо, а метры этого не дают.
 *
 * Ни одна декорация не участвует в игре — не меняет `isSafe`, не попадает в
 * игровую полосу, не даёт очков. Проверяется группой «декорации».
 */
export function makeDecor({ durationS = 300, rng = Math.random } = {}) {
  /* Виды берутся из ЗОНЫ, в которую элемент попадает по времени, а зона — из
     той же `zoneAt`, по которой выбирается палитра кадра. Один источник: две
     копии расписания разошлись бы, и кактус оказался бы в зелёной зоне. */
  const pickFrom = (kinds, r) => {
    const total = kinds.reduce((sum, k) => sum + k.weight, 0);
    let acc = 0;
    for (const k of kinds) {
      acc += k.weight / total;
      if (r < acc) return k;
    }
    return kinds[kinds.length - 1];
  };

  const out = [];
  let t = DECOR.firstS;
  while (t < durationS) {
    const side = rng() < 0.5 ? -1 : 1;
    const zone = zoneAt(t, durationS);
    const k = pickFrom(THEME[zone].decor.kinds, rng());
    out.push({
      kind: k.kind,
      /* Зона хранится у элемента, и рисуется он ЕЙ, а не палитрой кадра.

         Иначе на границе зон пять секунд видно обочину следующей зоны в цветах
         предыдущей: декорации видны до `far * 0.75`, то есть на 22 метра
         вперёд. С полем всё наоборот и лучше — следующая зона видна
         приближающейся, и это ровно то продвижение, ради которого зоны и
         сделаны. */
      zone,
      side,
      x: side * (HALF + DECOR.outM),
      y: WALL,                 // основание — ровно кромка обрыва
      h: k.height,
      z: t * VIEW.speed,
      at: t,
      phase: rng(),
    });
    // Разброс, но без провалов: равные промежутки превращают обочину в
    // штакетник, а слишком редкие — в пустое ущелье.
    t += DECOR.gapS * (0.75 + rng() * 0.5);
  }
  return out;
}

/** Где кончается препятствие и начинается проём. Связано с ходом камеры. */
export const obstacleEdge = () => Math.abs(camera(1, 0).x) * O.blockFrac;

/**
 * Глубина, на которой препятствие будет нарисовано, или `null` — не рисуется.
 *
 * Существует по той же причине, что `obstacleEdge`: число нужно в двух местах
 * сразу — отрисовке препятствия и разрезу прохода по кольцам, — и две копии
 * разошлись бы. Разошлись бы не абстрактно: кольцо начало бы просвечивать
 * сквозь плиту, то есть вернулся бы ровно тот дефект, из-за которого функция
 * и появилась.
 *
 * Заслоняющих поверхностей у препятствия две, и они взаимоисключающие по
 * времени: пока идёт телеграф (dt между visibleS и signalS) — метка у самой
 * дымки, дальше — лицо плиты. Линия по полу и последний зов сюда не входят:
 * они у самого глаза и ниже колец.
 *
 * Отсечение по ближней плоскости — не перестраховка: препятствие, уехавшее за
 * спину, проецируется с зажатой отрицательной глубиной и растягивается на
 * весь экран. Логика столкновения при этом продолжает работать, она смотрит
 * на время, а не на пиксели.
 */
export function obstacleDepth(ob, elapsed, far = VIEW.fogDistance) {
  if (!ob || ob.passed) return null;
  const dt = ob.at - elapsed;
  if (dt > O.signalS) return null;
  const zRaw = dt * VIEW.speed;
  if (zRaw + O.thickness < O.drawNearM) return null;
  return dt > O.visibleS ? far * 0.92 : Math.max(zRaw, O.drawNearM);
}

/** Глубина самого близкого нарисованного препятствия; Infinity — ни одного. */
export function nearestObstacleDepth(obstacles = [], elapsed = 0, far = VIEW.fogDistance) {
  let cut = Infinity;
  for (const ob of obstacles) {
    const d = obstacleDepth(ob, elapsed, far);
    if (d != null && d < cut) cut = d;
  }
  return cut;
}

/**
 * Где находятся глаза при таком смещении тела.
 *
 * Отдаётся наружу, чтобы сбор звёзд считался по тому же числу, по которому
 * рисуется картинка: две копии этой формулы разошлись бы, и звёзды начали бы
 * собираться не там, где их видно.
 */
export const cameraX = (u) => camera(u, 0).x;

/**
 * Экранный x ближайшего нарисованного угла обрыва при таком смещении тела.
 *
 * Существует ради одной проверки: при любом смещении левый обрыв обязан
 * доходить до x ≤ 0, правый — до x ≥ width. Иначе сбоку остаётся небо, и
 * выглядит это дыркой в мире. Числом это ловится, глазами — только на
 * телевизоре и только в крайнем положении, то есть почти никогда.
 */
export const wallNearEdgeX = (u, side = 1) =>
  project(side * HALF, 0, NEAR_DRAW, camera(u, 0)).sx;

/**
 * Дотянется ли ребёнок до звезды при таком смещении.
 *
 * Отдельной функцией, потому что это игровое правило, а не деталь
 * отрисовки: оно решает, надо ли вообще двигаться, чтобы собирать звёзды.
 * Проверяется в node.
 */
export const canReach = (starX, u) => Math.abs(starX - cameraX(u)) < VIEW.starReach;

/* Запас при сдвиге кольца за край запретного окна.

   Пятьдесят миллисекунд физического смысла не несут. Они нужны потому, что
   сложение секунд в double не даёт точного равенства: сдвиг на ровно
   starGuardS давал 1.5999999999999996 вместо 1.6, кольцо попадало ровно в
   точку, которую сдвиг и должен был покинуть, и правило нарушалось — тихо и
   на каждом уровне. Поймано тестом на сотне сеяных уровней. */
const STAR_SHIFT_EPS = 0.05;

/**
 * Можно ли поставить кольцо в секунду `t` на сторону `side`.
 *
 * Правило появилось после первого полного забега: расписания колец и
 * препятствий строились независимо, и одиннадцать колец оказались ближе
 * 0.35 с к препятствию, пять — ближе 0.1 с. Худший случай из журнала —
 * кольцо на u = −0.89 в 0.07 с от приседа: присед и боковой наклон
 * одновременно физически невозможны, то есть кольцо было не трудным, а
 * недостижимым. Ребёнок при таком выборе либо теряет кольцо, либо бьётся.
 *
 * Внутри запретного окна:
 *   duck — нельзя ничего. Под верхнее препятствие уходят приседом, а присед
 *          не совмещается ни с наклоном, ни с возвратом в центр;
 *   side — можно только кольцо на ОТКРЫТОЙ стороне. Там уклонение и сбор
 *          совпадают, и кольцо становится наградой за правильный уход, а не
 *          вторым, противоречащим заданием. Центральное тоже нельзя: в
 *          уклонении до него не дотянуться (это и есть смысл starReach).
 *
 * `isSafe` в js/level.js говорит, что side > 0 закрывает +x — значит открыта
 * сторона −ob.side, и именно её мы и разрешаем.
 */
export function starAllowed(t, side, obstacles) {
  for (const ob of obstacles) {
    if (Math.abs(t - ob.at) > VIEW.starGuardS) continue;
    if (ob.kind === 'duck') return false;
    if (side !== -ob.side) return false;
  }
  return true;
}

/**
 * Раскладка звёзд.
 *
 * Висят в боковых третях коридора: главная ценность игры в том, что ребёнок
 * двигается, и собирать их, стоя посередине, не должно получаться.
 *
 * Расставляются по ВРЕМЕНИ, а не через равные метры. Расстояние ничего не
 * говорит о том, успеет ли ребёнок: на переход из левого положения в правое
 * нужны секунды, и нужны они одни и те же при любой скорости бега. Поэтому
 * промежуток перед звездой на другой стороне больше — ровно на цену перехода.
 *
 * Три подряд на одной стороне не ставим: смысл игры в том, что ребёнок
 * двигается, а не стоит, подобрав удобное положение.
 *
 * `obstacles` обязателен для настоящего уровня: без него кольца снова встанут
 * вплотную к препятствиям. Умолчание — пустой список — существует для тестов
 * и для сравнения «сколько колец было бы без развязки».
 */
export function makeStars({ durationS = 300, obstacles = [], rng = Math.random } = {}) {
  /* Стороны набираются ФРАЗАМИ, а не броском на каждое кольцо.

     Зачем. Независимые броски дают ряд без замысла: собирать приходится то,
     что попалось. Фраза — это узнаваемый ход («двойка на одной стороне»,
     «слалом», «через середину»), и ряд начинает читаться как сделанный, а не
     высыпанный.

     Чего фраза НЕ делает, и это важнее: она не меняет ни геометрию, ни
     плотность. Узор, который хотелось нарисовать сначала — дуга, цепочка через
     коридор, — физически невозможен, и границы здесь не наши:
       • смена стороны стоит `starSwitchS` 3.0 с — это ИЗМЕРЕННОЕ время
         перехода ребёнка через коридор, а не настройка;
       • положений по x ровно три (±HALF*starX и 0): промежуточное может
         оказаться достижимым стоя, и ровно из-за этого `starX` с `starReach`
         однажды пересчитывали;
       • глубина жёстко связана со временем (`z === at * speed`), так что гнуть
         узор можно только по x.
     Поэтому фраза живёт на той же решётке: те же три положения, те же два
     промежутка. Меняется порядок, а не физика.

     Согласование с волнами препятствий — здесь и живёт ощущение ритма. В серии
     препятствий идут спокойные фразы, в передышке — беговые: ребёнок и так
     занят уклонением, и давать ему слалом поверх серии значило бы требовать
     двух дел сразу. `obstacles` для этого уже есть — тот же список, по которому
     работает запретное окно. */

  // Местный разнос препятствий вокруг секунды t: по нему видно, серия сейчас
  // или передышка. Края забега считаем передышкой — там препятствий нет.
  const вПередышке = (t) => {
    if (!obstacles.length) return true;
    let prev = null;
    for (const ob of obstacles) {
      if (ob.at > t) return prev === null ? true : ob.at - prev >= O.breatherS;
      prev = ob.at;
    }
    return true;
  };

  /* Словарь фраз. Каждая — последовательность сторон; промежутки из неё
     выводятся ниже сами, по тому же правилу «смена стороны стоит дороже».
     `s` — ведущая сторона фразы. */
  const СПОКОЙНЫЕ = [
    (s) => [s, s],        // двойка на одной стороне
    () => [0, 0],         // две по середине — передышка для ног
    (s) => [s, 0],        // сторона и возврат в середину
  ];
  const БЕГОВЫЕ = [
    (s) => [s, -s, s],    // слалом
    (s) => [s, 0, -s],    // через середину
    (s) => [s, -s],       // простой перекид
  ];

  const sides = [];
  const n = Math.ceil(durationS / VIEW.starGapS) + 2;
  let ведущая = rng() < 0.5 ? -1 : 1;
  let tФразы = VIEW.starFirstS;
  while (sides.length < n) {
    const набор = вПередышке(tФразы) ? БЕГОВЫЕ : СПОКОЙНЫЕ;
    const фраза = набор[Math.floor(rng() * набор.length)](ведущая);
    for (const side of фраза) sides.push(side);
    // Следующая фраза ведёт в другую сторону: иначе двойка за двойкой дала бы
    // четыре кольца на одном боку, то есть ребёнка, стоящего на месте.
    ведущая = -ведущая;
    // Оценка времени фразы — грубая и нужна только чтобы спросить «серия или
    // передышка»: точное время считается ниже, при расстановке.
    tФразы += фраза.length * VIEW.starSwitchS;
  }

  /* Правило «не больше двух подряд на одной стороне» применяется к ГОТОВОМУ
     ряду, а не внутри фраз. Так оно держится при любом словаре: фразы
     предлагают замысел, а инвариант остаётся инвариантом. Ровно тот же фильтр
     стоял здесь и до фраз. */
  let sameRun = 0;
  for (let i = 0; i < sides.length; i++) {
    if (sides[i] !== 0 && sides[i] === sides[i - 1] && sameRun >= 1) sides[i] = -sides[i];
    sameRun = sides[i] !== 0 && sides[i] === sides[i - 1] ? sameRun + 1 : 0;
  }

  const stars = [];
  let t = VIEW.starFirstS;
  // Когда можно будет поставить следующее большое кольцо. Первое не раньше
  // периода: забег начинается с обычных, иначе редкое событие открывает забег.
  let следующееБольшое = VIEW.starFirstS + VIEW.bigStarEveryS * (0.75 + rng() * 0.5);
  for (let i = 0; i < sides.length && t < durationS; i++) {
    /* Конфликт с препятствием — СДВИГ, а не выброс: ряд колец не должен
       редеть там, где и без того напряжённо.

       Одного сдвига достаточно всегда, и это не удача: препятствия идут не
       чаще minGapS (5.5 с), а окно двустороннее и шириной 2 × starGuardS
       (3.2 с), так что за концом одного окна следующее ещё не начинается.
       Связь minGapS > 2 × starGuardS проверяется тестом — развязать эти числа
       значит получить бесконечный сдвиг и пустой ряд колец. */
    if (!starAllowed(t, sides[i], obstacles)) {
      // За конец самого позднего из мешающих окон: с одним их и не бывает,
      // но брать максимум дешевле, чем полагаться на инвариант молча.
      t = obstacles
        .filter((ob) => Math.abs(t - ob.at) <= VIEW.starGuardS)
        .reduce((max, ob) => Math.max(max, ob.at + VIEW.starGuardS + STAR_SHIFT_EPS), t);
      if (t >= durationS) break;
    }
    /* Большое кольцо — по ПРОШЕДШЕМУ ВРЕМЕНИ, а не броском на каждое кольцо.

       Сначала здесь стояла вероятность, выведенная из плотности ряда
       (`starGapS / bigStarEveryS`), и она врала: заявленные 45 секунд давали
       фактические сто. Плотность ряда не равна `starGapS` — смена стороны
       стоит дороже, да и обстановка сдвигает кольца от препятствий, — а треть
       колец центральные и большими не становятся вовсе. Число в конфиге,
       разошедшееся с поведением втрое, хуже отсутствующего.

       Поэтому период стал периодом: большое кольцо ставится, когда с прошлого
       прошло не меньше `bigStarEveryS` с разбросом. Разброс обязателен — ровно
       по 45 секунд было бы метрономом, то есть той же бедой, от которой
       избавлялись у препятствий.

       Центральное большим не делается: большое обязано требовать полного
       размаха, иначе его ценность достаётся тому, кто стоит в середине. */
    const большое = sides[i] !== 0 && t - следующееБольшое >= 0;
    if (большое) следующееБольшое = t + VIEW.bigStarEveryS * (0.75 + rng() * 0.5);
    stars.push({
      x: sides[i] * HALF * VIEW.starX,
      z: t * VIEW.speed,
      side: sides[i],
      at: t,
      taken: false,
      // Вес есть всегда: `undefined` ушёл бы делителем в счёт очков.
      worth: большое ? VIEW.bigStarWorth : 1,
    });
    const next = sides[i + 1];
    const переход = next !== undefined && next !== 0 && sides[i] !== 0 && next !== sides[i];
    t += переход ? VIEW.starSwitchS : VIEW.starGapS;
  }
  return stars;
}
