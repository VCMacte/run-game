// Коридор от первого лица на Canvas2D.
//
// Персонажа на экране нет, поэтому понять «где я» ребёнку больше нечем, кроме
// самой панорамы: она едет вбок вместе с телом непрерывно и без задержки. Это
// и обратная связь, и то, что маскирует задержку трансляции — воспринимаемая
// задержка определяется первым видимым изменением, а не моментом, когда вид
// доехал.
//
// Три правила отрисовки, и все три — не вкусовые:
//   * фиксированный буфер 1280×720 и никакого DPR. Miracast всё равно
//     пережимает в 720p, рисовать выше — чистый нагрев GPU, который уже делят
//     распознавание и кодировщик;
//   * никаких теней, фильтров и градиентов в покадровом пути: на Adreno 619
//     это самые дорогие операции, а сжатие их всё равно съест;
//   * ощущение скорости несут поперечные линии пола. В первом лице с
//     минимумом текстур смотреть больше не на что, и без них кажется, что
//     стоишь на месте.
//
// Разбор: docs/difficulty.md, docs/identity-and-icons.md, docs/obstacle-looks.md, docs/obstacles.md, docs/prizes-and-cost.md, docs/rings.md, docs/sky-and-art.md, docs/trophy-and-worlds.md, docs/view-and-zones.md

// FIN, а не F: F здесь уже занято фокусным расстоянием.
import { VIEW, OBSTACLES as O, FINISH as FIN, SIGNALS as S } from './config.js';
import { clamp } from './util.js';
import {
  THEME, DECOR, MOTION, zonesOf, zoneAt, kindsFor, motionScale, rgba, luminance,
} from './theme.js';

const EYE = 1.2;          // высота глаз ребёнка, условных метров
const WALL = 2.6;         // высота стен
const HALF = VIEW.corridorWidth / 2;
const NEAR = 0.7;

/* Откуда начинается та геометрия, которая обязана доходить до края кадра.

   Пол и обрывы — плоскости при постоянном x, и панорама их не растягивает, а
   двигает: точка схода стоит на месте (yawPx = 0), едет мир. Поэтому ближний
   угол правого обрыва при полном смещении вправо уезжает ВНУТРЬ кадра, и
   справа от него не нарисовано ничего — остаётся небо, которым залит буфер
   перед всем остальным.

   Посчитано: при NEAR = 0.7 угол доходит до края кадра только пока
   cam.x < 0.663 м, а полный ход — 0.72 м. На максимуме справа оставалась
   полоса 68 px, пятая часть сотни, сплошного skyLow ниже горизонта. Выглядит
   как дырка в мире; пожаловался заказчик.

   Лечится не рамкой и не запасом по ширине, а тем, что плоскость начинается у
   глаза: тогда её ближний угол проецируется в тысячи пикселей за кадр при
   любом сдвиге. Между глазом и NEAR всё равно ничего не рисуется, так что
   лишней работы это не добавляет — те же четыре точки. */
const NEAR_DRAW = 0.08;

const FOV = 75 * Math.PI / 180;

/* Палитра переехала в js/theme.js: там она проверяется по светлоте, и там же
   объяснено, почему проём почти белый, а облака подсинённые.

   Здесь стояло `const COLORS = THEME.greenHill` с объяснением, что второй темы
   не существует и протаскивать её через восемь функций отрисовки ради будущей
   не надо. Теперь зон три, и посылка того объяснения кончилась — но вывод
   остался верным: тема по-прежнему НЕ протаскивается через функции. Вместо
   этого зона приходит полем кадра и защёлкивается на этот кадр в одной
   переменной.

   Почему так, а не параметром: функций отрисовки десять плюс две вложенные, и
   у каждой свой набор аргументов. Лишний параметр в каждой — двенадцать мест,
   где его однажды забудут передать, и забытый даст `undefined` в fillStyle, на
   что Canvas молча оставляет прежний цвет. Одна переменная на кадр такого
   класса ошибок не создаёт вовсе.

   `let`, а не `const`, и меняется ровно в одном месте — в начале render(). */
let COLORS = THEME.greenHill;


/* Границы коридора наружу. Декорации и их проверки обязаны брать эти числа
   здесь, а не повторять у себя: разошедшиеся копии — это пальма, выросшая
   посреди игровой полосы, и заметно это станет на ребёнке. */
export const CORRIDOR_HALF = HALF;
export const CLIFF_TOP = WALL;

const W = VIEW.width;
const H = VIEW.height;
const F = (W / 2) / Math.tan(FOV / 2);
const HORIZON = H * 0.46;

/* Докуда рисуются пол и обрывы. Это ДАЛЬНИЙ близнец NEAR_DRAW, и дефект у них
   один.

   Пол кончался на `fogDistance` (30 м), а горизонт — на бесконечности: между
   дальним краем пола и горизонтом оставался клин чистого неба шириной ровно в
   коридор на тридцати метрах (65 px) и высотой 33 px. Он был там при ЛЮБОМ
   смещении, но в середине кадра читается как даль, а при крайнем уезжает вбок
   от точки схода — и тогда виден как пустота сбоку от дальнего плана.
   Заметил заказчик; найдено пересчётом пикселей в браузере.

   Число не на глаз: дальний край пола отстоит от горизонта на `cam.y · F / z`
   пикселей, и дальше этой глубины он тоньше пикселя. Глаза опускаются при
   приседе, так что берётся самое высокое их положение (EYE) и запас в пятую
   часть. Заливок это не добавляет ни одной: меняется дальняя кромка тех же
   четырёхугольников. */
const FAR_DRAW = EYE * F * 1.2;

/**
 * Положение взгляда при таком состоянии тела.
 *
 * `x`, `y` — где находятся глаза; `yaw`, `pitch` — куда они смотрят.
 *
 * Поворот взгляда отключён (`VIEW.yawPx = 0`): движение несёт один только
 * боковой сдвиг, то есть параллакс — стены и пол едут мимо, а точка схода
 * стоит на месте. От поступательного движения укачивает слабее, чем от
 * поворота, и для ребёнка на 55 дюймах это решающее соображение.
 *
 * Механизм поворота оставлен: он сделан сдвигом центра проекции, а не
 * вращением сцены, и поэтому горизонт остаётся строго горизонтальным по
 * построению, а не по аккуратности. Крен запрещён в любом случае.
 */
export function camera(u = 0, v = 0) {
  // Мёртвая зона: в покое распознавание всё равно дрожит на сотые доли, и без
  // неё стены мелко шевелятся даже у неподвижного ребёнка.
  const dead = VIEW.viewDeadband;
  const squelch = (x) => (Math.abs(x) < dead ? 0 : x - Math.sign(x) * dead);
  const un = clamp(squelch(u), -1.5, 1.5);
  const vn = clamp(v, 0, 0.6);
  return {
    x: un * VIEW.panGain * HALF,
    y: EYE * (1 - vn * VIEW.pitchGain),
    yaw: -un * VIEW.yawPx,
    pitch: (vn / 0.6) * VIEW.pitchPx,
  };
}

/** Проекция точки мира на экран. Чистая арифметика — проверяется в node. */
export function project(x, y, z, cam) {
  const d = Math.max(z, 0.05);
  return {
    sx: W / 2 + cam.yaw + (x - cam.x) * F / d,
    sy: HORIZON + cam.pitch + (cam.y - y) * F / d,
    scale: F / d,
  };
}

/** Куда уехала точка схода и где оказался горизонт. Для проверок и диагностики. */
export const vanishX = (cam) => W / 2 + cam.yaw;
export const horizonY = (cam) => HORIZON + cam.pitch;

/**
 * Вид коридора.
 *
 * `backdrops` — растры неба ПО ЗОНАМ, картой `{ зона: Image }`. Карта, а не
 * одна картинка, потому что заказчик после забега 10 октября заметил: смена
 * оформления по зонам работает, «но небо и дальний план остаются без
 * изменений». Так и было по построению — растр кладётся во весь кадр, и
 * цветов зоны из-под него не видно вовсе.
 *
 * Зона без растра рисуется запасным, векторным путём, и он уже красится
 * цветами СВОЕЙ зоны. То есть недостающая картинка роняет качество фона, но
 * не ломает ни зоны, ни игру — ровно как и задумано про `assets/sky.webp` с
 * самого начала: арт собирается отдельным прогоном, и забег не имеет права от
 * него зависеть.
 */
export function createView(canvas, { backdrops = null, speed = VIEW.speed } = {}) {
  /* СКОРОСТЬ ЗАБЕГА приходит снаружи, а не берётся из `VIEW.speed`.

     Причина — уровень сложности: с 18 октября скорость растёт на третьем и
     пятом. Жить ей в модуле нельзя было бы, будь это накопительное
     состояние, но это не оно: число приходит один раз при создании вида и
     больше не меняется — тот же приём, которым сюда приходит `backdrops`.

     Умолчание `VIEW.speed` оставлено нарочно: все прежние вызовы (и тесты, и
     `tools/replay.mjs`) продолжают значить ровно то же, что значили. */
  const РЕЙС = speed > 0 ? speed : VIEW.speed;
  const ctx = canvas.getContext('2d', { alpha: false, desynchronized: true });
  canvas.width = VIEW.width;
  canvas.height = VIEW.height;

  /* «Меньше движения» спрашивается один раз на весь забег, а не каждый кадр:
     matchMedia в кадре — это обращение к стилям двадцать раз в секунду.
     Амплитуда сжимается почти в ноль, но код остаётся один: нулевой путь,
     который никто не исполняет, отдельно гниёт. */
  const reduced = typeof matchMedia === 'function'
    && matchMedia('(prefers-reduced-motion: reduce)').matches;
  const mscale = motionScale(reduced);

  /* Последняя ИЗВЕСТНАЯ зона. Неизвестная оставляет и палитру, и растр
     прежними: лучше нарисовать кадр в цветах соседней зоны, чем половину его
     в одних, а половину в других. Без этой памяти неизвестная зона оставляла
     бы палитру, но роняла растр — то есть небо прыгало бы с картинки на
     вектор, а всё остальное нет. */
  let zoneNow = zonesOf()[0];

  function quad(p1, p2, p3, p4, fill) {
    ctx.fillStyle = fill;
    ctx.beginPath();
    ctx.moveTo(p1.sx, p1.sy);
    ctx.lineTo(p2.sx, p2.sy);
    ctx.lineTo(p3.sx, p3.sy);
    ctx.lineTo(p4.sx, p4.sy);
    ctx.closePath();
    ctx.fill();
  }

  return {
    get element() { return canvas; },

    /**
     * Один кадр.
     * `u` — боковое смещение тела в долях торса, `v` — присед, оба уже
     * сглажены и предсказаны: сюда приходит то, что надо показать сейчас.
     */
    render({ u = 0, v = 0, travel = 0, stars = [], dim = 0, obstacles = [],
             elapsed = 0, safe = true, pulse = 0, finishIn = null, decor = [],
             speed = 0, zone = zonesOf()[0], prizes = {} }) {
      /* Палитра кадра. Приходит ПОЛЕМ, а решает её train.js — там же, где
         живут стадии, пауза и отсчёт: вид остаётся глупым, и это то же
         разделение, по которому вид не знает ни про камеру, ни про калибровку.

         Неизвестная зона не обнуляет палитру, а оставляет прежнюю: лучше
         нарисовать кадр в цветах соседней зоны, чем в `undefined`. */
      if (THEME[zone]) { COLORS = THEME[zone]; zoneNow = zone; }

      /* Цвета колец считаются ОДИН раз на кадр, а не на каждое кольцо.

         Радуга вершины (`rainbowOf`) зависит только от базового цвета, времени
         и сжатия — все три за кадр постоянны, — а внутри у неё двадцать четыре
         шага двоичного поиска по светлоте. В окне видимости бывает до девяти
         колец, то есть восемнадцать вызовов там, где хватает четырёх.
         Счётчик заливок этого не видит по построению: он считает ВЫЗОВЫ
         отрисовки, а не вычисления, — и просадка проявилась бы только как fps
         на телевизоре. Поймано ревью. */
      const цветаКолец = prizes.gold ? {
        small: rainbowOf(COLORS.star, elapsed, mscale),
        smallDim: rainbowOf(COLORS.starDim, elapsed, mscale),
        big: rainbowOf(COLORS.starBig, elapsed, mscale),
        bigDim: rainbowOf(COLORS.starBigDim, elapsed, mscale),
      } : {
        small: COLORS.star, smallDim: COLORS.starDim,
        big: COLORS.starBig, bigDim: COLORS.starBigDim,
      };

      const cam = camera(u, v);

      const far = VIEW.fogDistance;

      // ── небо, дальние холмы, облака ──
      // В экранных координатах, а не через проекцию: они на бесконечности, и
      // проекция дала бы им нулевой размер. Параллакс здесь — разная скорость
      // слоёв, ровно как в комиксе того же автора.
      drawSky(ctx, cam, travel, elapsed, backdrops?.[zoneNow] ?? null, mscale);

      /* Спутник — приз десятого уровня: птица, летящая рядом. Две заливки:
         тело и крыло, и крыло машет функцией времени с фазой — состояния не
         копит, как все анимации проекта.

         Летит она ВЫСОКО и у середины кадра — там, где небо открыто при любом
         уходе взгляда. Не сбоку: сбоку её режет обрыв, и это проверено дважды
         (сперва ноль пикселей, потом мигание при полном уходе). Высоко —
         чтобы не спорить с препятствием: приз не вправе соперничать с
         решением. Рисуется сразу за небом — всё остальное её закрывает, и это
         верно: она дальше обочины.

         Оплачена порогом у пятна под кольцом (две заливки), и плата внесена
         до покупки, как требует правило. */
      if (prizes.buddy) {
        const { x: bx, y: by } = buddyPos(elapsed, mscale);
        const крыло = buddyFlap(elapsed, mscale);
        const bs = W * 0.012;
        ctx.fillStyle = COLORS.buddy;
        ctx.beginPath();
        ctx.moveTo(bx - bs, by);
        ctx.lineTo(bx + bs, by);
        ctx.lineTo(bx, by + bs * 0.5);
        ctx.closePath();
        ctx.fill();
        ctx.beginPath();
        ctx.moveTo(bx - bs * 0.3, by);
        ctx.lineTo(bx + bs * 0.3, by);
        ctx.lineTo(bx, by - bs * (0.3 + 1.1 * крыло));
        ctx.closePath();
        ctx.fill();
      }

      // ── пол: шахматка ──
      drawFloor(ctx, cam, travel, { project, quad, far });

      // ── обрывы вместо стен ──
      // Геометрия та же, что была у стен, и трогать её нельзя: параллакс
      // ближнего поля — единственная обратная связь управления в игре.
      drawCliffs(cam, { project, quad });

      // ── декорации над кромкой ──
      drawDecor(ctx, cam, decor, travel, elapsed, { project, quad, far, mscale });

      // ── финиш ──
      // Рисуется до препятствий: ворота стоят дальше них и не должны лезть
      // поверх того, что ближе.
      if (finishIn != null && finishIn <= FIN.visibleS) {
        drawFinish(ctx, cam, Math.max(finishIn, 0) * РЕЙС, { project, quad, pulse, speed: РЕЙС });
      }

      /* ── кольца и препятствия: порядок маляра ──

         Кольца рисуются двумя проходами, а препятствие — между ними. Замысел
         прежний: кольцо ПЕРЕД препятствием обязано быть видно поверх него,
         иначе оно теряется ровно там, где важнее всего. Но условия «перед» в
         коде не было вовсе: кольца шли одним проходом после препятствий, а
         плита видна с 10 м при кольцах до 30 м — то есть за плитой почти
         всегда есть кольцо, и оно просвечивало сквозь неё. Заметил заказчик.

         Разрез — глубина самого близкого нарисованного препятствия. Линия по
         полу и последний зов остаются в конце: они у самого глаза и ниже
         колец (starY 0.55), спорить им не с чем. */
      const zCut = nearestObstacleDepth(obstacles, elapsed, far, РЕЙС);
      drawStars(stars, zCut, far);

      /* «Стоит на месте» нужно бадникам: они икают, пока ребёнок не двигается.

         Считается по СКОРОСТИ, а не по положению. Через положение было
         наоборот: ребёнок, припарковавшийся в боковой трети, — ровно тот, кого
         икота должна расшевелить, — не видел её никогда, а пробегающий через
         центр видел. Порог берётся тот же, которым сигналы отличают дрейф от
         движения, чтобы «не двигается» значило одно и то же во всей игре. */
      const still = Math.abs(speed) < S.driftSpeedMax;
      drawObstacles(ctx, cam, obstacles, elapsed,
        { project, quad, far, safe, pulse, still, mscale, speed: РЕЙС });

      // Кольца ближе препятствия — поверх него, как и было задумано.
      drawStars(stars, 0, zCut);

      /**
       * Кольца в полосе глубин [zFrom, zTo).
       *
       * Кольцо вместо звезды: ромб золота с тёмной серединой. Середина именно
       * заливкой, а не вырезом: тонкая рамка после сжатия исчезает, а тёмный
       * ромб внутри светлого читается как дырка и переживает Miracast.
       *
       * Полоса видимости (NEAR..far) проверяется здесь и только здесь, а
       * границы прохода — отдельной строкой: кольцо ровно на разрезе уходит в
       * ДАЛЬНИЙ проход, то есть при равной глубине прячется за плитой, а не
       * просвечивает сквозь неё.
       */
      function drawStars(list, zFrom, zTo) {
      /* Обход с КОНЦА, то есть от дальнего кольца к ближнему.

         Список идёт по возрастанию z, и прямой обход клал дальнее кольцо
         поверх ближнего: его пятно на полу просвечивало сквозь ближний
         предмет. Заметил заказчик. Разрез между проходами тут не помогает
         вовсе — оба кольца лежат в одном проходе, и порядок внутри прохода
         задаётся только этим циклом. Тот же дефект и та же починка, что у
         пальмы поверх пальмы в `drawDecor`. */
      for (let i = list.length - 1; i >= 0; i--) {
        const s = list[i];
        const z = s.z - travel;
        if (z < NEAR || z > far) continue;
        if (z < zFrom || z >= zTo) continue;
        const p = project(s.x, VIEW.starY, z, cam);
        // Большое кольцо и выглядит большим: иначе его ценность сообщал бы
        // только звук, то есть ребёнок узнавал бы о ней ПОСЛЕ сбора.
        const крупно = (s.worth ?? 1) > 1;
        /* Цвет большого кольца — свой, и это теперь главное его отличие.
           Размером отличать нечем: рим 0.256 м против окна сбора 0.26, запас
           двенадцать миллиметров, и он уже выбран. Заказчик сказал об этом
           прямо: «визуально не отличается, только другой звук», — то есть о
           цене ребёнок узнавал ПОСЛЕ сбора. */
        const colr = крупно ? цветаКолец.big : цветаКолец.small;
        const colDim = крупно ? цветаКолец.bigDim : цветаКолец.smallDim;
        const r = Math.max(3, p.scale * VIEW.starDrawR * (крупно ? VIEW.bigStarScale : 1));

        // Собранное кольцо подпрыгивает и исчезает — короткой функцией от
        // времени, без хранения состояния.
        let lift = 0;
        if (s.taken) {
          const age = elapsed - (s.takenAtS ?? -9);
          if (age < 0 || age > 0.45) continue;
          lift = Math.sin((age / 0.45) * Math.PI) * r * 2.2 * mscale;

          /* Искры — приз первого уровня. Функция времени с фазой, состояния не
             копят: `age` уже посчитан выше, и этого хватает.

             Рисуются ТОЛЬКО у собранного кольца и только 0.45 с: горящие весь
             забег, они платили бы за себя каждым кадром, а не одним.

             Цвет — `starDim`, уже стоящий в контракте светлоты: собственного
             цвета искрам не нужно, и свободного им всё равно не положено. */
          if (prizes.sparks) {
            const ф = age / 0.45;
            const разлёт = r * 2.4 * ф;
            const полу = r * 0.34 * (1 - ф);
            for (let k = 0; k < 4; k++) {
              const a = (k / 4) * Math.PI * 2 + 0.6;
              ctx.fillStyle = colDim;
              ctx.fillRect(
                p.x + Math.cos(a) * разлёт - полу,
                p.y - lift + Math.sin(a) * разлёт - полу,
                полу * 2, полу * 2,
              );
            }
          }
        }

        /* Пятно на полу под кольцом.

           Самая большая отдача на пиксель во всём уровне, и она не про
           красоту: кольцо висит в воздухе (starY 0.55), а глубину в коридоре
           с плоской покраской сообщают только размер объекта и шахматка пола.
           Пятно говорит прямо, НАД КАКИМ местом пола кольцо висит, — а ловят
           его именно по этому.

           Рисуется ровно здесь, внутри прохода, а не вместе с полом: проходов
           два, и порядок маляра держится на том, что дальние кольца уходят до
           препятствия, а ближние — после. Нарисуй тень вместе с полом, и
           препятствие, стоящее ДАЛЬШЕ ближнего кольца, накрыло бы её.

           У собранного кольца тени нет: оно подпрыгивает и исчезает, а пятно
           под ним осталось бы висеть на полу сиротой. */
        /* Пятно рисуется только у кольца, которое уже близко: порог тот же по
           смыслу, что у ободка, и считается по той же вертикальной полуоси —
           горизонтальная сжимается вращением, и ворота на ней мигали бы.
           Разбор и цена — docs/rings.md. */
        if (!s.taken && r > MOTION.shadowMinR) {
          const rm = VIEW.starShadowM;
          quad(
            project(s.x - rm, 0, z - rm * 0.6, cam), project(s.x + rm, 0, z - rm * 0.6, cam),
            project(s.x + rm, 0, z + rm * 0.6, cam), project(s.x - rm, 0, z + rm * 0.6, cam),
            COLORS.shadow,
          );
        }

        // Вращение: сжатие по горизонтали. В профиль кольцо не исчезает —
        // это цель, а не украшение.
        const w = r * ringSquash(elapsed, s.z, mscale);
        const cy = p.sy - lift;
        const ring = (rx, ry, fill) => {
          ctx.fillStyle = fill;
          ctx.beginPath();
          ctx.moveTo(p.sx, cy - ry);
          ctx.lineTo(p.sx + rx, cy);
          ctx.lineTo(p.sx, cy + ry);
          ctx.lineTo(p.sx - rx, cy);
          ctx.closePath();
          ctx.fill();
        };
        /* Лучи у большого кольца. Цвета мало: цветность Miracast режет
           сильнее светлоты, а форма переживает сжатие лучше всего. Четыре
           коротких клина по диагоналям — и кольцо читается как награда уже на
           подходе, а не в момент сбора.

           Рисуются ДО кольца: это сияние за ним, а не накладка поверх. */
        if (крупно) {
          for (const [dx, dy] of [[1, 1], [1, -1], [-1, 1], [-1, -1]]) {
            const bx = p.sx + dx * w * 0.5;
            const by = cy + dy * r * 0.5;
            ctx.fillStyle = colr;
            ctx.beginPath();
            ctx.moveTo(bx + dy * w * 0.18, by - dx * r * 0.18);
            ctx.lineTo(bx - dy * w * 0.18, by + dx * r * 0.18);
            ctx.lineTo(p.sx + dx * w * 1.25, cy + dy * r * 1.25);
            ctx.closePath();
            ctx.fill();
          }
        }
        /* Ободок — приз пятого уровня: тёмная КАЙМА снаружи кольца, под ней
           тело обычного цвета, внутри прежнее отверстие.

           Первая версия клала третий контур МЕЖДУ телом и отверстием, тем же
           тёмным цветом, — и это была ошибка, видимая только глазами: ободок и
           отверстие одного цвета, они сливались в одно тёмное пятно, то есть
           приз лишь сужал жёлтую полосу и платил за это заливкой. Поймано на
           кадре в браузере; из node такое не видно — счётчик заливок считает
           вызовы, а не картинку.

           Снаружи, а не внутри, ещё и потому, что так это и называется:
           ободок — кайма по краю. Отверстие при этом остаётся, и кольцо
           остаётся кольцом — словом, которым его зовёт ребёнок.

           Цвет — тот же `starDim`: собственного цвета кольцу не положено, оно
           в контракте светлоты как цвет РЕШЕНИЯ.

           Оплачен цветущей обочиной (приз уровня 2): она вернула две заливки,
           сместив вес с пальмы в три на цветок и куст в две. Порядок
           обязателен — сначала плата, потом покупка. */
        /* Шлейф — приз одиннадцатого уровня: полоса, уходящая от кольца НАЗАД,
           к ребёнку. Одна заливка, рисуется ДО тела кольца — она за ним, а не
           поверх.

           Спек обещал «0, замена» — неверно, как было неверно у ободка:
           заменять у кольца нечего, тело и отверстие оба нужны.

           Порог свой и строже, чем у пятна: полоса тоньше самого кольца, и
           дальше 7.4 метра она тоньше пикселя. У СОБРАННОГО кольца шлейфа
           нет — оно исчезает за 0.45 с, а полоса пережила бы его и осталась
           висеть сиротой, ровно как осталось бы пятно. */
        if (prizes.trail && !s.taken && r > MOTION.trailMinR) {
          const длина = r * 0.9;
          const полу = Math.max(1, w * 0.10);
          ctx.fillStyle = colDim;
          ctx.beginPath();
          ctx.moveTo(p.sx - полу, cy);
          ctx.lineTo(p.sx + полу, cy);
          ctx.lineTo(p.sx + полу * 0.3, cy + длина);
          ctx.lineTo(p.sx - полу * 0.3, cy + длина);
          ctx.closePath();
          ctx.fill();
        }

        const сОбодком = prizes.rim && r > MOTION.rimMinR;
        if (сОбодком) {
          ring(w, r, colDim);
          ring(w * 0.82, r * 0.82, colr);
        } else {
          ring(w, r, colr);
        }
        if (w > 2.5) ring(w * 0.42, r * 0.42, colDim);
      }
      }

      // Затемнение на паузе. Сплошной прямоугольник поверх — дешевле любого
      // фильтра и переживает сжатие.
      if (dim > 0) {
        ctx.fillStyle = rgba(COLORS.shade, clamp(dim, 0, 1));
        ctx.fillRect(0, 0, W, H);
      }
    },
  };
}

/* ─────────────────────── слои фона ───────────────────────

   Небо и дальние холмы — единственное место, где уместен растр: мягкие
   градиенты и дымку вектором не нарисовать. Он необязателен — без него
   рисуются плоские полосы и силуэт холмов, и игра остаётся играбельной.
   Это важнее, чем кажется: арт собирается отдельным прогоном Easy Diffusion,
   и игра не должна от него зависеть.

   Контракт растра: ГОРИЗОНТ НА 46% ВЫСОТЫ картинки, потому что ровно там он у
   нашей проекции (HORIZON = H * 0.46). Фон с горизонтом в другом месте не
   сойдётся с полом, и стык будет виден сразу. */
/**
 * Куда ляжет растр неба и какие полосы кадра он НЕ закроет.
 *
 * Отдельной функцией — потому что от этих чисел зависит, что заливать, а
 * заливка здесь главная статья расхода кадра.
 *
 * Замерено на телефоне: до арта кадр шёл 46–47 fps, с артом 38–39, обе полки
 * ровные все 400 секунд, то есть арт стоит около 5 мс на кадр. При этом
 * `draw50` показывает 0 мс — он мерит время вызовов Canvas2D на CPU, то есть
 * постановку работы в очередь, и растеризацию не видит. «Отрисовка 0 мс» не
 * значит «арт бесплатен».
 *
 * Куда уходили эти миллисекунды, видно отсюда: растр 1024×576 на кадре
 * 1280×720 даёт dh = 720 и dy = 0, то есть ложится РОВНО во весь кадр. А
 * заливка перед ним красила весь кадр плюс верхнюю полосу — 1.3 экранных
 * заливки, которых не видел никто.
 *
 * Считать надо именно геометрию, а не признак «растр есть»: `dy` зависит от
 * наклона взгляда, в приседе горизонт уезжает на pitchPx, и прореха там
 * настоящая. Форма растра тоже не гарантирована — контракт обещает горизонт на
 * 46% высоты, а не отношение сторон.
 */
export function skyGaps(hy, backdrop) {
  if (!backdrop || !backdrop.width) return null;
  const dh = W * backdrop.height / backdrop.width;
  const dy = hy - dh * 0.46;
  return {
    dy,
    dh,
    top: Math.max(0, Math.min(H, dy)),
    bottom: Math.max(0, Math.min(H, H - (dy + dh))),
  };
}

function drawSky(ctx, cam, travel, elapsed, backdrop, mscale) {
  const hy = HORIZON + cam.pitch;
  const gaps = skyGaps(hy, backdrop);

  if (gaps) {
    /* Заливаем ТОЛЬКО прорехи. Полноэкранная заливка служила заодно страховкой
       от «дырки в мире» — полосы неба у края обрыва, — и страховка остаётся: при
       растре во весь кадр он сам и есть сплошная непрозрачная подложка, причём
       лучшая, чем плоский цвет: в прорехе окажется небо с картинки, а не ровная
       синева, которая и выглядела дыркой.

       Нижнюю половину растра перекрывает пол — это ещё около половины экрана
       впустую. Обрезать его по горизонту здесь намеренно не стали: ровно там
       жила та самая полоса 68 пикселей у правого обрыва, и обрезка вернула бы
       риск, только вместо неба в прорехе был бы мусор. */
    if (gaps.top > 0) {
      ctx.fillStyle = COLORS.sky;
      ctx.fillRect(0, 0, W, gaps.top);
    }
    if (gaps.bottom > 0) {
      ctx.fillStyle = COLORS.skyLow;
      ctx.fillRect(0, H - gaps.bottom, W, gaps.bottom);
    }
    // Растр тянется по ширине кадра и кладётся дважды: при боковом уходе
    // взгляда и своём параллаксе он иначе оторвался бы от края.
    /* Сдвиг округляется до целого пикселя. Пара копий кроет [0, W] ровно, но
       при дробном сдвиге на их стыке остаётся волосок субпиксельной
       интерполяции — а полноэкранной заливки под ним больше нет, и в волоске
       проглянул бы предыдущий кадр. Округление снимает весь этот класс
       целиком; движение фона от целого пикселя не страдает — у него свой
       медленный параллакс.

       Второе условие той же страховки: растр обязан быть НЕПРОЗРАЧНЫМ. Наш
       `assets/sky.webp` такой (VP8 без альфы), и собирается он `toWebp()` из
       `tools/frame.html`; растр с альфой пустил бы предыдущий кадр наружу
       по всей площади. */
    /* Вторая копия кладётся ЗЕРКАЛЬНО, и это исправление того, что заказчик
       описал как «чёткая граница в месте наслоения».

       Две копии подряд предполагают, что растр замощается по горизонтали. Ни
       одна наша картинка не замощается, и мерить это можно: невязка левого и
       правого столбца у ночного неба в среднем 23.5 из 255, а на строке
       горизонта — 211, то есть светлый пиксель хребта встаёт вплотную к
       тёмному. Это и есть шов. У дневных он того же порядка (380 и 247) и
       просто читается текстурой на светлом арте — то есть ждёт своего часа.

       Зеркало делает шов невозможным ПО ПОСТРОЕНИЮ: на общей кромке сходятся
       два одинаковых края картинки, левый с левым или правый с правым, при
       любом содержимом и в любой зоне. Починка на стороне арта потребовала бы
       замощаемости от каждой новой картинки, а её нечем проверить — в node нет
       декодировщика.

       Заливок не добавляется, `drawImage` по-прежнему два. */
    const shift = Math.round(-(travel * MOTION.farParallax * 40 + cam.x * 30) % W);
    ctx.drawImage(backdrop, shift, gaps.dy, W, gaps.dh);
    const x2 = shift + (shift > 0 ? -W : W);
    ctx.save();
    ctx.translate(x2 + W, 0);
    ctx.scale(-1, 1);
    ctx.drawImage(backdrop, 0, gaps.dy, W, gaps.dh);
    ctx.restore();
    return;
  }

  ctx.fillStyle = COLORS.skyLow;
  ctx.fillRect(0, 0, W, H);
  ctx.fillStyle = COLORS.sky;
  ctx.fillRect(0, 0, W, Math.max(0, hy - H * 0.16));

  // Запасной путь: силуэт холмов. Крупными горбами — мелкий рельеф после
  // сжатия всё равно превратится в кашу.
  ctx.fillStyle = COLORS.hills;
  const drift = travel * MOTION.farParallax * 18 + cam.x * 24;
  for (let i = -1; i < 7; i++) {
    const cx = ((i * 0.22 * W - drift) % (W * 1.6) + W * 1.6) % (W * 1.6) - W * 0.3;
    const rw = W * (0.17 + 0.05 * ((i + 7) % 3));
    const rh = H * (0.05 + 0.022 * ((i + 7) % 3));
    ctx.beginPath();
    ctx.moveTo(cx - rw, hy);
    ctx.quadraticCurveTo(cx, hy - rh * 2.2, cx + rw, hy);
    ctx.closePath();
    ctx.fill();
  }

  /* Ночью облаков нет, вместо них звёзды — решение заказчика, и оно же
     физически вернее: облака в ночном небе читались серыми кляксами, а
     единственное, что сообщает «это ночь», — звёзды.

     Звёзды — функция МЕСТА, а не времени. Мигание было бы украшением, а правило
     проекта требует от каждой анимации смысла; к тому же мерцающая точка под
     сжатием Miracast просто исчезает через кадр. Дрейф у них свой, самый
     медленный: они дальше холмов. */
  if (COLORS.skyStars) {
    ctx.fillStyle = COLORS.starSky;
    const sd = travel * MOTION.farParallax * 6 + cam.x * 8;
    for (let i = 0; i < 8; i++) {
      const cx = ((wobble(i, 11) * W * 1.4 - sd) % (W * 1.4) + W * 1.4) % (W * 1.4) - W * 0.2;
      const cy = (hy - H * 0.3) * (0.08 + 0.86 * wobble(i, 29));
      const s = H * (0.006 + 0.005 * wobble(i, 47));
      ctx.fillRect(cx, cy, s, s);
    }
    return;
  }

  // Облака: своя скорость и свой дрейф. Подсинённые, а не белые — белое
  // облако у горизонта спорит по светлоте с проёмом.
  ctx.fillStyle = COLORS.cloud;
  const cd = travel * MOTION.cloudParallax * 22 + elapsed * MOTION.cloudDriftHz * 60 * mscale;
  for (let i = 0; i < 4; i++) {
    const cx = ((i * 0.31 * W - cd) % (W * 1.3) + W * 1.3) % (W * 1.3) - W * 0.15;
    const cy = hy - H * (0.2 + 0.07 * (i % 3));
    const rw = W * 0.085;
    const rh = H * 0.028;
    ctx.beginPath();
    ctx.ellipse(cx, cy, rw, rh, 0, 0, Math.PI * 2);
    ctx.ellipse(cx + rw * 0.7, cy + rh * 0.3, rw * 0.6, rh * 0.75, 0, 0, Math.PI * 2);
    ctx.fill();
  }
}

/* Пол шахматкой.

   Шаг тот же, что был у поперечных линий (floorLineStep), и это не мелочь:
   линии несли скорость и ритм, по которому ребёнок ждёт препятствие. Сменить
   шаг значило бы сменить ритм, то есть залезть в гейм-плей.

   Клетки привязаны к мировой сетке (z + travel), а не к фазе: привязанные к
   фазе они дёргались бы на каждом обороте остатка.

   Защита от мерцания у горизонта сохранена: то, что мельче lineMinGapPx, не
   рисуется вовсе. Это чистая резь в глазах без крупицы пользы. */
function drawFloor(ctx, cam, travel, { project, quad, far }) {
  const step = VIEW.floorLineStep;
  const NX = 4;                      // столбцов на ширину коридора
  const cw = (HALF * 2) / NX;

  // Основа одним четырёхугольником: половину клеток рисовать не надо.
  // От NEAR_DRAW, а не от NEAR: при полном смещении камеры край пола иначе
  // уезжает внутрь кадра и сбоку остаётся небо. Шахматка поверх может
  // начинаться где угодно — под ней уже закрашено.
  quad(
    project(-HALF, 0, NEAR_DRAW, cam), project(HALF, 0, NEAR_DRAW, cam),
    project(HALF, 0, FAR_DRAW, cam), project(-HALF, 0, FAR_DRAW, cam),
    COLORS.floorB,
  );

  /* Хвост за дымкой — самой бледной полосой, а не самой тёмной.

     Основа пола красится `floorB`, то есть цветом тёмной клетки шахматки, и
     дотянутая до горизонта она дала бы у самого горизонта тёмную черту —
     ровно там, где лестница светлоты обязана кончаться самым бледным.
     Одна заливка на кадр, и она же закрывает тот клин, ради которого
     FAR_DRAW и появился. */
  quad(
    project(-HALF, 0, far, cam), project(HALF, 0, far, cam),
    project(HALF, 0, FAR_DRAW, cam), project(-HALF, 0, FAR_DRAW, cam),
    COLORS.floorFar,
  );

  const zStart = Math.ceil((NEAR + travel) / step) * step - travel;
  for (let zb = zStart; zb < far; zb += step) {
    if (F * step / (zb * zb) < VIEW.lineMinGapPx) break;
    const iz = Math.round((zb + travel) / step);
    const zf = Math.min(zb + step, far);
    /* Дальние клетки бледнее, но не прозрачнее: прозрачность стоит дорого, а
       разница в светлоте переживает сжатие лучше.

       Полос три, а не две, и это не стоит ни одной лишней заливки — меняется
       только выбор цвета в том же цикле. Светлота идёт лестницей вниз
       (0.399 → 0.328 → 0.283), и расстояние по трём ступеням читается заметно
       лучше, чем по двум: в коридоре с плоской покраской глубину сообщают
       только размер объекта и эта шахматка. */
    const fill = zb > far * 0.65 ? COLORS.floorFar
      : zb > far * 0.33 ? COLORS.floorMid
        : COLORS.floorA;
    for (let ix = 0; ix < NX; ix++) {
      if ((iz + ix) % 2) continue;
      const x0 = -HALF + ix * cw;
      const x1 = x0 + cw;
      quad(
        project(x0, 0, zb, cam), project(x1, 0, zb, cam),
        project(x1, 0, zf, cam), project(x0, 0, zf, cam),
        fill,
      );
    }
  }
}

/* Обрывы по сторонам — те же вертикальные плоскости, что были стенами.

   Светлота левого и правого различается, как и раньше: при боковом уходе
   взгляда разница подсказывает направление даже после сжатия, когда цвет уже
   размыт. Поверх — полоса травы по кромке и тёмная полоса глубже: именно они
   делают из стены обрыв. */
function drawCliffs(cam, { project, quad }) {
  // Все четыре полосы — от NEAR_DRAW, а не от NEAR: обрыв обязан доходить до
  // края кадра при любом смещении камеры, иначе сбоку видно небо.
  const cliff = (x, earth) => {
    quad(
      project(x, 0, NEAR_DRAW, cam), project(x, WALL, NEAR_DRAW, cam),
      project(x, WALL, FAR_DRAW, cam), project(x, 0, FAR_DRAW, cam),
      earth,
    );
    // Тёмная полоса у основания: глубина обрыва.
    quad(
      project(x, 0, NEAR_DRAW, cam), project(x, 0.5, NEAR_DRAW, cam),
      project(x, 0.5, FAR_DRAW, cam), project(x, 0, FAR_DRAW, cam),
      COLORS.earthDeep,
    );
    // Кромка травы. Две полосы — светлая сверху, тёмная под ней: один тон
    // после сжатия сливается с землёй.
    quad(
      project(x, WALL - 0.34, NEAR_DRAW, cam), project(x, WALL, NEAR_DRAW, cam),
      project(x, WALL, FAR_DRAW, cam), project(x, WALL - 0.34, FAR_DRAW, cam),
      COLORS.grassDark,
    );
    quad(
      project(x, WALL - 0.14, NEAR_DRAW, cam), project(x, WALL, NEAR_DRAW, cam),
      project(x, WALL, FAR_DRAW, cam), project(x, WALL - 0.14, FAR_DRAW, cam),
      COLORS.grass,
    );
  };
  cliff(-HALF, COLORS.earthL);
  cliff(HALF, COLORS.earthR);
}

/**
 * Ниже какой высоты точка обочины спрятана за обрывом.
 *
 * Декорации стоят ЗА плоскостью обрыва (`x = ±(HALF + out)`), а рисовались
 * одним проходом после него — то есть не перекрывались им ни разу, и обочина
 * висела поверх стены. Заметил заказчик.
 *
 * Перекрытие здесь выходит точным и почти бесплатным, и причина в самой
 * проекции: `sy` не зависит от `x` вовсе. Значит кромка обрыва — линия
 * (`x = ±HALF`, `y = WALL`) — проецируется в ПРЯМУЮ, проходящую через точку
 * схода, и условие «точка за обрывом» сводится к неравенству, из которого
 * глубина сокращается начисто:
 *
 *     видно  ⇔  y > cam.y + (WALL − cam.y) · |x − cam.x| / |side·HALF − cam.x|
 *
 * Поэтому ни `clip`, ни второго прохода обрыва не нужно: достаточно поднять
 * каждую вершину декорации до этой высоты. Нижняя кромка фигуры при этом
 * ложится ровно по линии перекрытия, а не по горизонтали, — то есть так, как
 * её и обрезал бы обрыв.
 *
 * Три следствия, и все три проверены в группе «что чем перекрыто»: доля
 * скрытого НЕ зависит от глубины; уход взгляда в сторону перекрывает свою
 * обочину сильнее, а противоположную слабее; при нейтрали скрыто ровно
 * `(WALL − EYE) / HALF × out` метра. Последнее и есть причина, по которой у
 * низких видов обочины свой, меньший отступ от кромки: при общем 0.55 скрыто
 * 0.64 м, и куст с цветком исчезли бы из игры целиком.
 */
export function decorYMask(x, cam, side) {
  // Расстояние от глаза до плоскости обрыва по горизонтали. В ноль не
  // обращается: ход камеры 0.72 м при полуширине коридора 1.2 — но делить на
  // него всё равно нельзя без оговорки, а не с запасом «вроде хватает».
  const a = Math.abs(side * HALF - cam.x);
  if (a < 1e-6) return Infinity;
  return cam.y + (WALL - cam.y) * Math.abs(x - cam.x) / a;
}

/* Декорации.

   Рисуются после обрывов и только выше кромки: ниже их всё равно не видно,
   стены закрывают всё за собой.

   Потолок на число нарисованных — не перестраховка, а бюджет кадра:
   Snapdragon 695 уже отдаёт 62 мс медианы на инференс при цели 20 Гц, и кадр
   здесь дешевле не станет. Ближние важнее дальних, список упорядочен по
   глубине, поэтому достаточно прекратить на потолке. */
/* Сколько декораций рисуется за кадр. Это ЗАПАС, а не рабочее ограничение.

   Поднимая его с 12 вместе с плотностью, я написал здесь, что старый потолок
   обрезал обочину на середине коридора. Это оказалось неправдой: в окне
   отрисовки (`NEAR` … `far * 0.75`) при нынешней плотности помещается самое
   большее одиннадцать декораций — замерено по четырём посевам на всём забеге.
   То есть и прежний потолок не связывал ни разу, и поднятие ничего не
   изменило.

   Оставлен поднятым осознанно: одиннадцать против двенадцати — это запас в
   одну штуку, и следующая же правка плотности начала бы молча резать обочину.
   Восемнадцать дают настоящий запас. Но называть это починкой нельзя: число в
   конфиге, разошедшееся с поведением, хуже отсутствующего. */
const DECOR_MAX = 18;

function drawDecor(ctx, cam, decor, travel, elapsed, { project, quad, far, mscale }) {
  /* Сначала отбираем ближние — на них бюджет, — а рисуем в обратном порядке,
     от дальних к ближним. Список от `makeDecor` идёт по возрастанию глубины,
     и рисование прямо по нему клало дальнюю пальму поверх ближней: тёмный
     ствол дальней перекрывал зелёную крону ближней. Две пальмы одной стороны
     на трёх и пяти метрах перекрываются на экране — видно сразу. */
  const near = [];
  for (const d of decor) {
    if (near.length >= DECOR_MAX) break;
    const z = d.z - travel;
    if (z < NEAR || z > far * 0.75) continue;
    near.push([d, z]);
  }

  for (let i = near.length - 1; i >= 0; i--) {
    const [d, z] = near[i];

    const base = d.y;                        // кромка обрыва
    const top = base + d.h;

    /* Обрыв перекрывает низ декорации, и дальше вся фигура рисуется через
       `pr`, а не через `project`: вершина ниже кромки поднимается до неё.
       Разбор — у `decorYMask`. Считается маска по вершине, а не по фигуре:
       перья пальмы разъезжаются на полметра, и у них своя высота кромки. */
    const side = d.side || Math.sign(d.x) || 1;
    // Целиком скрытая декорация не рисуется вовсе: вырожденные
    // четырёхугольники нулевой площади — это заливки в пользу никому.
    if (top <= decorYMask(d.x, cam, side)) continue;
    const pr = (x, y, zz) => project(x, Math.max(y, decorYMask(x, cam, side)), zz, cam);

    const sway = palmSway(elapsed, d.phase, mscale);
    /* Цвета — ЗОНЫ ЭЛЕМЕНТА, а не кадра. На границе зон обочина следующей уже
       видна (декорации рисуются на 22 метра вперёд), и в палитре предыдущей
       она выглядела бы ошибкой. Запасной вариант — палитра кадра: у записи от
       прошлой версии поля `zone` нет. */
    const C = THEME[d.zone] || COLORS;

    if (d.kind === 'palm') {
      const w = 0.09;
      quad(
        pr(d.x - w, base, z), pr(d.x + w, base, z),
        pr(d.x + w + sway, top, z), pr(d.x - w + sway, top, z),
        C.palmTrunk,
      );
      /* Крона: два боковых пера и одно вверх. Средним пером тут был тот же
         цикл по [-1, 0, 1], и при нуле все четыре угла схлопывались в одну
         точку — перо с нулевой площадью, которого никто никогда не видел.
         Вертикальное перо приходится задавать отдельно: у него своя ширина,
         а не нулевой размах. */
      const cx = d.x + sway;
      for (const dir of [-1, 1]) {
        quad(
          pr(cx, top - 0.1, z), pr(cx + dir * 0.52, top + 0.1, z),
          pr(cx + dir * 0.58, top + 0.28, z), pr(cx, top + 0.22, z),
          C.palmLeaf,
        );
      }
      quad(
        pr(cx - 0.12, top - 0.05, z), pr(cx + 0.12, top - 0.05, z),
        pr(cx + 0.16, top + 0.34, z), pr(cx - 0.16, top + 0.34, z),
        C.palmLeaf,
      );
    } else if (d.kind === 'bush') {
      quad(
        pr(d.x - 0.34, base, z), pr(d.x + 0.34, base, z),
        pr(d.x + 0.26, top, z), pr(d.x - 0.26, top, z),
        C.palmLeaf,
      );
      quad(
        pr(d.x - 0.18, top - 0.08, z), pr(d.x + 0.18, top - 0.08, z),
        pr(d.x + 0.12, top + 0.12, z), pr(d.x - 0.12, top + 0.12, z),
        C.grass,
      );
    } else if (d.kind === 'flower') {
      quad(
        pr(d.x - 0.03, base, z), pr(d.x + 0.03, base, z),
        pr(d.x + 0.03, top, z), pr(d.x - 0.03, top, z),
        C.grassDark,
      );
      /* Цветок поворачивается вслед проходящему. Поворот — функция близости, а
         не времени: он должен провожать именно того, кто бежит. */
      const turn = clamp(1 - z / 6, 0, 1) * MOTION.flowerTurnM * mscale * -Math.sign(d.x);

      /* Поворот упирается в край коридора, а не проходит сквозь него.

         Цветок — самый низкий вид обочины, и отступ от кромки у него самый
         маленький (0.08): иначе обрыв скрыл бы его целиком. Но лепесток
         шириной 0.28 шире этого отступа сам по себе, а поворот добавляет ещё
         0.18 внутрь — и у самого глаза лепесток оказывался НАД игровой
         полосой, в полуметре от края. Спрятать его там нечем: внутри
         коридора маска обрыва не работает по построению.

         Поэтому не отступ больше (он зажат видимостью с другой стороны), а
         упор: лепесток доезжает до стены и дальше не идёт. Выглядит это
         правдоподобнее поворота в пустоту, а проверяется тем, что ни одна
         заливка обочины не попадает между кромками коридора. */
      const s = Math.sign(d.x) || 1;
      const cxf = d.x + turn;
      const push = Math.max(0, HALF - (Math.abs(cxf) - 0.14));
      const fx = cxf + s * push;
      quad(
        pr(fx - 0.14, top, z), pr(fx + 0.14, top, z),
        pr(fx + 0.14, top + 0.28, z), pr(fx - 0.14, top + 0.28, z),
        C.flower,
      );
    } else if (d.kind === 'cactus') {
      /* Кактус: ствол и две лапы. Три заливки — дешевле пальмы, у которой
         четыре, то есть зона дюн кадр не утяжеляет. */
      const w = 0.13;
      quad(
        pr(d.x - w, base, z), pr(d.x + w, base, z),
        pr(d.x + w, top, z), pr(d.x - w, top, z),
        C.cactus,
      );
      for (const dir of [-1, 1]) {
        const y0 = base + d.h * (dir < 0 ? 0.42 : 0.58);
        quad(
          pr(d.x + dir * w, y0, z), pr(d.x + dir * 0.34, y0, z),
          pr(d.x + dir * 0.34, y0 + 0.42, z), pr(d.x + dir * w, y0 + 0.2, z),
          C.cactus,
        );
      }
    } else if (d.kind === 'rock') {
      // Камень: одна трапеция. Самая дешёвая форма в игре — одна заливка.
      quad(
        pr(d.x - 0.3, base, z), pr(d.x + 0.3, base, z),
        pr(d.x + 0.16, top, z), pr(d.x - 0.2, top, z),
        C.rock,
      );
    } else if (d.kind === 'firefly') {
      /* Светлячок: один ромб, висящий в воздухе. Самая дешёвая форма в игре
         наравне с камнем — одна заливка, — и вес он у камня и забирает, так
         что приз кадру ничего не стоит.

         Мерцание — функция времени с фазой, как все анимации проекта:
         состояния не копит, иначе разошлось бы с картинкой тем сильнее, чем
         дольше забег. Фаза берётся у самого элемента (`d.phase` — та же,
         которой качается пальма), чтобы светлячки не мигали строем: второй
         источник фазы был бы второй копией одного понятия.

         Мерцает он РАЗМЕРОМ, а не цветом: цветность Miracast режет сильнее
         светлоты, и мерцание цветом на телевизоре пропало бы. */
      /* Полуразмер 0.08 м — вдвое меньше радиуса кольца (0.16), и это
         НАМЕРЕННО: светлячок не должен читаться как кольцо. Пульс уводит его
         почти в ноль — светлячки мигают, в этом они и есть.

         Здесь стояло 0.17 «потому что из браузера светлячков не видно». Это
         была ошибка ЗАМЕРА, а не кода: декорации рисуются до `far * 0.75`,
         то есть до 22.5 м, а мерил я окно в 30 м — единственный светлячок в
         нём стоял на 24.45 и был срезан окном по построению. Камень на том же
         месте не рисовался тоже. */
      const пульс = 0.6 + 0.4 * Math.sin(
        elapsed * MOTION.fireflyHz * 2 * Math.PI + d.phase * Math.PI * 2) * mscale;
      const rf = 0.08 * пульс;
      quad(
        pr(d.x, top - rf, z), pr(d.x + rf, top, z),
        pr(d.x, top + rf, z), pr(d.x - rf, top, z),
        C.firefly,
      );
    } else if (d.kind === 'spruce') {
      /* Ель: ствол и два яруса. Ярусы треугольниками через четырёхугольник с
         совпадающими верхними углами — тем же приёмом, что зубья на потолке. */
      quad(
        pr(d.x - 0.06, base, z), pr(d.x + 0.06, base, z),
        pr(d.x + 0.06, base + d.h * 0.3, z), pr(d.x - 0.06, base + d.h * 0.3, z),
        C.palmTrunk,
      );
      for (const [y0, w] of [[0.25, 0.42], [0.58, 0.3]]) {
        const yb = base + d.h * y0;
        quad(
          pr(d.x - w, yb, z), pr(d.x + w, yb, z),
          pr(d.x, yb + d.h * 0.42, z), pr(d.x, yb + d.h * 0.42, z),
          C.spruce,
        );
      }
    } else if (d.kind === 'post') {
      /* Столб у обочины. Высокий и узкий, то есть почти целиком из пустых
         пикселей, — а мимо глаза проходит заметно. Ради этого и поставлен:
         шахматка пола даёт поток только в нижней половине кадра, а скорость
         читается периферией.

         Не качается, в отличие от пальмы: столб — это ритм, и дрожащий ритм
         хуже ровного. */
      const w = 0.08;
      quad(
        pr(d.x - w, base, z), pr(d.x + w, base, z),
        pr(d.x + w, top, z), pr(d.x - w, top, z),
        C.post,
      );
      // Поясок под верхушкой: по нему столб и опознаётся как метка, а не как
      // палка. Светлее тела, но мелкий — на светлоту кадра не влияет.
      quad(
        pr(d.x - w * 1.6, top - 0.34, z), pr(d.x + w * 1.6, top - 0.34, z),
        pr(d.x + w * 1.6, top - 0.08, z), pr(d.x - w * 1.6, top - 0.08, z),
        C.postMark,
      );
    } else if (d.kind === 'totem') {
      // Тотем. Подмигивает, когда проходишь вплотную — одна из четырёх шуток
      // уровня, и единственная, которую можно не заметить.
      quad(
        pr(d.x - 0.22, base, z), pr(d.x + 0.22, base, z),
        pr(d.x + 0.22, top, z), pr(d.x - 0.22, top, z),
        C.totem,
      );
      /* Порог 3.6 м, а не «вплотную». Декорации стоят за кромкой, на
         x = ±1.75, и ближе ~2.3 м тотем уже за краем кадра: шутка, которую
         нельзя увидеть, — это не шутка, а мёртвый код. */
      const wink = z < 3.6 && Math.sin(elapsed * 6 + d.phase * 9) > 0.4;
      const eyeH = wink ? 0.03 : 0.12;
      quad(
        pr(d.x - 0.1, top - 0.3, z), pr(d.x + 0.1, top - 0.3, z),
        pr(d.x + 0.1, top - 0.3 + eyeH, z), pr(d.x - 0.1, top - 0.3 + eyeH, z),
        C.badnikEye,
      );

    /* ── Формы новых миров ──

       Семь форм, по две-три на мир, и каждая встаёт НА МЕСТО прежней, не
       рядом с ней: ель стояла в семи зонах из двенадцати, в том числе под
       водой и в туманности, и заказчик 18 октября сказал об этом прямо.
       Размен идёт только вниз по заливкам (ель 3 → шпиль, коралл, кристалл 2;
       цветок 2 → обломок 1), поэтому отдельной платы `DECOR.gapS` покупка не
       требует: плата и покупка здесь — одно и то же движение.

       Второй тон у шести из семи — существующий `grassDark` или `rock`: он
       уже задан во всех двенадцати зонах и уже под контрактом светлоты, а
       различать заливкой, а не тонкой рамкой, требует Miracast. Семь новых
       ключей вместо четырнадцати.

       Качание берут готовый `palmSway` — второй источник фазы был бы второй
       копией понятия. */
    } else if (d.kind === 'kelp') {
      /* Водоросль: две ленты от дна, обе качаются. Верх уже низа и уведён
         течением — стебель «стелется», а не стоит столбом. Две заливки, то
         есть дешевле ели, которую она заменяет. */
      for (const [dx, w, len] of [[-0.10, 0.09, 1.0], [0.10, 0.07, 0.78]]) {
        const bx = d.x + dx;
        const tp = base + d.h * len;
        quad(
          pr(bx - w, base, z), pr(bx + w, base, z),
          pr(bx + w * 0.4 + sway * 1.6, tp, z), pr(bx - w * 0.4 + sway * 1.6, tp, z),
          dx < 0 ? C.kelp : C.grassDark,
        );
      }
    } else if (d.kind === 'coral') {
      // Коралл: каменное основание и веер над ним. Веер широкий и плоский —
      // тонкие ветви Miracast съел бы целиком.
      quad(
        pr(d.x - 0.16, base, z), pr(d.x + 0.16, base, z),
        pr(d.x + 0.1, base + d.h * 0.3, z), pr(d.x - 0.1, base + d.h * 0.3, z),
        C.rock,
      );
      /* Веер узкий. Широкий (полуразмах 0.34) читался розовым флагом — самой
         громкой фигурой кадра в тёмной зоне, где всё остальное приглушено. */
      quad(
        pr(d.x - 0.09, base + d.h * 0.25, z), pr(d.x + 0.09, base + d.h * 0.25, z),
        pr(d.x + 0.2, base + d.h * 0.85, z), pr(d.x - 0.2, base + d.h * 0.85, z),
        C.coral,
      );
    } else if (d.kind === 'anemone') {
      // Актиния: столбик и венчик, венчик колышется.
      quad(
        pr(d.x - 0.06, base, z), pr(d.x + 0.06, base, z),
        pr(d.x + 0.05, base + d.h * 0.55, z), pr(d.x - 0.05, base + d.h * 0.55, z),
        C.grassDark,
      );
      const cxa = d.x + sway * 0.8;
      quad(
        pr(cxa - 0.1, base + d.h * 0.5, z), pr(cxa + 0.1, base + d.h * 0.5, z),
        pr(cxa + 0.2, top, z), pr(cxa - 0.2, top, z),
        C.anemone,
      );
    } else if (d.kind === 'spire') {
      /* Ледяной шпиль: освещённая грань и теневая. Треугольник собирается
         четырёхугольником со слипшимися верхними углами — приём елового
         яруса. Две заливки против трёх у ели. */
      quad(
        pr(d.x - 0.26, base, z), pr(d.x, base, z),
        pr(d.x - 0.02, top, z), pr(d.x - 0.02, top, z),
        C.spire,
      );
      quad(
        pr(d.x, base, z), pr(d.x + 0.2, base, z),
        pr(d.x - 0.02, top, z), pr(d.x - 0.02, top, z),
        C.grassDark,
      );
    } else if (d.kind === 'drift') {
      // Сугроб: тело и светлая шапка. Низкий и широкий — у самой кромки.
      quad(
        pr(d.x - 0.42, base, z), pr(d.x + 0.42, base, z),
        pr(d.x + 0.24, base + d.h * 0.7, z), pr(d.x - 0.28, base + d.h * 0.7, z),
        C.grassDark,
      );
      quad(
        pr(d.x - 0.28, base + d.h * 0.6, z), pr(d.x + 0.24, base + d.h * 0.6, z),
        pr(d.x + 0.14, top, z), pr(d.x - 0.16, top, z),
        C.drift,
      );
    } else if (d.kind === 'crystal') {
      // Кристалл: две пирамиды, сросшиеся основаниями. Висит над кромкой —
      // ему это к лицу, он не растёт из земли.
      const mid = base + d.h * 0.55;
      quad(
        pr(d.x - 0.18, mid, z), pr(d.x + 0.18, mid, z),
        pr(d.x, top, z), pr(d.x, top, z),
        C.crystal,
      );
      quad(
        pr(d.x - 0.18, mid, z), pr(d.x + 0.18, mid, z),
        pr(d.x, base + d.h * 0.1, z), pr(d.x, base + d.h * 0.1, z),
        C.grassDark,
      );
    } else if (d.kind === 'shard') {
      // Обломок: одна скошенная трапеция. Самая дешёвая форма наравне с
      // камнем и светлячком — и вес она у камня и забирает.
      quad(
        pr(d.x - 0.26, base, z), pr(d.x + 0.22, base, z),
        pr(d.x + 0.08, top, z), pr(d.x - 0.18, top, z),
        C.shard,
      );
    }
  }
}

/**
 * Препятствия и четыре отметки телеграфа.
 *
 * Порядок отметок и их смысл — в config.OBSTACLES. Коротко: за четыре секунды
 * в глубине коридора загорается полоса на той стороне, которая будет закрыта;
 * за три проявляется само препятствие; за две по полу идёт линия, которая
 * дойдёт до игрока ровно вместе с ним; за секунду проём пульсирует, а
 * неверное положение подсвечивается.
 *
 * Самая важная из них — линия по полу. Семилетка плохо оценивает «сколько
 * осталось до того столба», но прекрасно ждёт, пока линия доедет до него:
 * задача оценки расстояния подменяется задачей ожидания ритма, а ритм в этом
 * возрасте уже освоен.
 */
function drawObstacles(ctx, cam, obstacles, elapsed,
  { project, quad, far, safe, pulse, still, mscale, speed = VIEW.speed }) {
  for (const ob of obstacles) {
    /* Край берётся У САМОГО препятствия: с тихой адаптацией сложности он
       зависит от ступени, на которой построен уровень, а не от текущего
       конфига. Запасной путь нужен для препятствий, собранных руками в
       тестах и в tools/frame.html. */
    const edge = ob.edge ?? obstacleEdge();
    /* Глубина берётся из obstacleDepth, а не считается здесь: по ней же
       режется проход по кольцам, и две копии разошлись бы — кольцо снова
       начало бы просвечивать сквозь плиту. Отсечения («прошли», «дальше
       телеграфа», «уехало за спину») живут там же. */
    const depth = obstacleDepth(ob, elapsed, far, speed);
    if (depth == null) continue;
    const dt = ob.at - elapsed;          // секунд до прихода
    const zRaw = dt * speed;
    const z = depth;

    /* Метка в глубине коридора: крупная заливка, а не рамка. Тонкий контур на
       дальнем плане сжатие уничтожает первым.

       Красная и мерцающая, а не оранжевая и ровная. Заказчик пожаловался, что
       предупреждение о будущем препятствии плохо видно, и причин было три
       сразу: оранжевый сидел между цветом финиша и цветом звезды, метка
       занимала половину высоты обрыва, а жила ровно секунду. Теперь цвет
       свой, высота полная, окно две секунды (signalS 5.0 против visibleS 3.0),
       и медленное мерцание 1 Гц отличает «это будет» от «это уже здесь».

       Фаза своя у каждого препятствия: две метки подряд не должны мигать в
       унисон, иначе мерцание читается как общая рябь кадра, а не как метка. */
    if (dt > O.visibleS) {
      const zf = depth;
      const h = 0.9;
      const hot = warnBlink(elapsed, ob.at * 2, mscale) > 0.5;
      const fill = hot ? COLORS.warn : COLORS.warnDim;
      if (ob.kind === 'duck') {
        quad(
          project(-HALF, WALL, zf, cam), project(HALF, WALL, zf, cam),
          project(HALF, WALL - h * 1.6, zf, cam), project(-HALF, WALL - h * 1.6, zf, cam),
          fill,
        );
      } else {
        const x0 = ob.side > 0 ? edge : -HALF;
        const x1 = ob.side > 0 ? HALF : -edge;
        quad(
          project(x0, 0, zf, cam), project(x1, 0, zf, cam),
          project(x1, WALL, zf, cam), project(x0, WALL, zf, cam),
          fill,
        );
      }
      // Метка и плита — взаимоисключающие стадии одного препятствия: пока
      // идёт телеграф, самой плиты ещё не видно.
      continue;
    }

    const zBack = Math.max(zRaw + O.thickness, drawNear(speed) + 0.02);

    // Проём заливается ярким: ребёнку надо показать, куда идти, а не только
    // куда нельзя.
    if (ob.kind === 'duck') {
      quad(
        project(-HALF, WALL, z, cam), project(HALF, WALL, z, cam),
        project(HALF, O.duckHeight, z, cam), project(-HALF, O.duckHeight, z, cam),
        COLORS.block,
      );
      quad(
        project(-HALF, WALL, zBack, cam), project(HALF, WALL, zBack, cam),
        project(HALF, O.duckHeight, zBack, cam), project(-HALF, O.duckHeight, zBack, cam),
        COLORS.blockDark,
      );
      quad(
        project(-HALF, 0.02, z, cam), project(HALF, 0.02, z, cam),
        project(HALF, 0.02, zBack, cam), project(-HALF, 0.02, zBack, cam),
        COLORS.gap,
      );
      /* Цепей здесь нет, хотя по замыслу бревно должно было висеть на них.
         Вешать не на что: плита и так занимает всё от `duckHeight` до кромки
         обрыва, промежутка нет. Нарисованные цепи ложились прямо на её лицо
         двумя тёмными полосами поверх цвета, который сообщает решение, —
         шума больше, чем смысла. */

      // Шипы вниз по нижней кромке — одна внешность приседа, висящий зверь —
      // другая. Явные ветки, а не `else`: незнакомая внешность не рисуется
      // ничем, по тому же правилу, что у декораций.
      if (ob.look === 'ceiling') {
        drawTeeth(ob, z, cam, { project, quad });
      } else if (ob.look === 'bat') {
        drawBat(ob, z, cam, elapsed, { project, quad, mscale });
      } else if (ob.look === 'icicles') {
        drawIcicles(ob, z, cam, { project, quad });
      } else if (ob.look === 'ribs') {
        drawRibs(ob, z, cam, { project, quad });
      } else if (ob.look === 'comet') {
        // Имя внешности историческое, фигура — метеорный дождь; разбор в
        // шапке `drawMeteors`.
        drawMeteors(ob, z, cam, elapsed, { project, quad, mscale });
      }
    } else {
      const x0 = ob.side > 0 ? edge : -HALF;
      const x1 = ob.side > 0 ? HALF : -edge;
      quad(
        project(x0, 0, z, cam), project(x1, 0, z, cam),
        project(x1, WALL, z, cam), project(x0, WALL, z, cam),
        COLORS.block,
      );
      quad(
        project(x0, 0, zBack, cam), project(x1, 0, zBack, cam),
        project(x1, WALL, zBack, cam), project(x0, WALL, zBack, cam),
        COLORS.blockDark,
      );
      // Пол в проёме.
      const g0 = ob.side > 0 ? -HALF : edge;
      const g1 = ob.side > 0 ? -edge : HALF;
      quad(
        project(g0, 0.02, z, cam), project(g1, 0.02, z, cam),
        project(g1, 0.02, zBack, cam), project(g0, 0.02, zBack, cam),
        COLORS.gap,
      );

      /* Шипы по кромке плиты и бадник на закрытой стороне.

         Форма сообщает тему, светлота сообщает решение: плита осталась ровно
         той же по светлоте, проём — самым светлым местом кадра, а шипы и враг
         добавлены поверх. Нарушить этот порядок значит сделать красивый
         уровень, в котором непонятно, куда уходить. */
      /* Бадник или створка — ровно одно из двух, и это не экономия, а смысл:
         две внешности одного препятствия должны отличаться с первого взгляда,
         а живое существо рядом с механической створкой читается как два разных
         препятствия сразу. Попутно створка стоит дешевле бадника по заливкам,
         так что перекраска не съела бюджет кадра. */
      if (ob.look === 'gate') {
        drawGate(z, cam, { project, quad, x0, x1 });
        /* Шипы — ПОСЛЕ внешности, и порядок тут содержательный: стойки створки
           идут от пола до самой кромки и, нарисованные вторыми, закрашивали
           корни крайних зубьев — те читались колпаками на кромке, ровно тем,
           ради чего `spikeRootM` и появился.

           Теперь шипы ЕСТЬ ТОЛЬКО У СТВОРКИ, и это решение заказчика от
           11 октября: у бадника они смотрели в центр поля и съедали ту самую
           плиту, на которой существо живёт. Поэтому вызов стоит внутри ветки
           `gate`, а не после развилки — и порядок внутри неё остаётся
           единственным, который приходится держать руками. */
        drawSpikes(ob, z, cam, { project, quad, x0, x1 });
      } else if (ob.look === 'plate') {
        drawBadnik(ob, dt, z, cam, elapsed, { project, quad, x0, x1, safe, still, mscale });
      } else if (ob.look === 'jelly') {
        drawJelly(ob, z, cam, elapsed, { project, quad, x0, x1, mscale });
      } else if (ob.look === 'floe') {
        drawFloe(ob, z, cam, elapsed, { project, quad, x0, x1, mscale });
      } else if (ob.look === 'asteroid') {
        // Имя историческое, фигура — ракета на старте; разбор в шапке
        // `drawRocket`.
        drawRocket(ob, z, cam, elapsed, { project, quad, x0, x1, mscale });
      }
      /* Ветки ЯВНЫЕ, без `else`, и здесь он стоял: плита со зверем была
         «всё остальное». Пока внешностей было две, разницы не было никакой, а
         с шестью `else` означал бы, что опечатка в имени рисует зверя под
         водой и в космосе — то есть молчаливо и неотличимо от замысла. Правило
         то же, что у декораций: незнакомый вид не рисуется НИЧЕМ, и снятая
         `beam` из старых журналов это проверяет. */
    }

    // Линия по полу, которая дойдёт вместе с препятствием.
    if (dt <= O.railS && dt > 0 && zRaw > NEAR) {
      quad(
        project(-HALF, 0.03, Math.max(zRaw - 0.12, NEAR), cam), project(HALF, 0.03, Math.max(zRaw - 0.12, NEAR), cam),
        project(HALF, 0.03, Math.max(zRaw, NEAR), cam), project(-HALF, 0.03, Math.max(zRaw, NEAR), cam),
        COLORS.rail,
      );
    }

    // Последний зов: если ребёнок не там, закрытая сторона наливается цветом.
    // Подтверждение правильного положения не менее важно, чем предупреждение:
    // в первом лице нет персонажа, по которому видно, достаточно ли ты ушёл.
    if (dt <= O.lastCallS && dt > 0 && pulse > 0.5) {
      const warn = safe ? COLORS.gap : COLORS.block;
      quad(
        project(-HALF, 0, 0.75, cam), project(HALF, 0, 0.75, cam),
        project(HALF, 0.08, 0.75, cam), project(-HALF, 0.08, 0.75, cam),
        warn,
      );
    }
  }
}

/* Шипы по верхней кромке плиты.

   Треугольниками, но крупными: мелкий зубец после сжатия превращается в
   неровную линию. Цвет металла светлее плиты и темнее проёма — он не
   участвует в решении и не имеет права спорить с ним по светлоте. */
/* Шипы на потолке: зубья вниз по нижней кромке верхней плиты.

   Это ВТОРАЯ ВНЕШНОСТЬ приседа, а не второе препятствие. Действие то же,
   метка телеграфа та же, мотив тот же — меняется только силуэт, и меняется он
   ради пяти минут, которые ребёнок смотрит в один и тот же коридор.

   Плита при этом остаётся на месте целиком. Заменить её зубьями было бы
   красивее и неправильно: светлота плиты сообщает «сюда нельзя», а между
   зубьями просвечивал бы проём, то есть самое светлое место кадра оказалось
   бы там, куда идти как раз не надо. Форма сообщает тему, светлота сообщает
   решение — здесь это ровно тот же порядок, что у боковых шипов ниже. */
function drawTeeth(ob, z, cam, { project, quad }) {
  const N = O.teethN;
  const w = (HALF * 2) / N;
  for (let i = 0; i < N; i++) {
    const xa = -HALF + i * w;
    /* Разброс идёт ВНИЗ от `teethM`, а не вверх. Это не стилистика: зубья
       висят внутри щели, в которую ребёнок проходит приседая, и потолок их
       длины связан с `duckHeight` проверкой. Неровность им разрешена, рост —
       нет; проверяется в группе «силуэт препятствия», в пикселях кадра. */
    const h = O.teethM * (0.45 + 0.55 * wobble(ob.at, i));
    // Остриё смещено внутри своей доли — иначе гребень остаётся регулярным,
    // даже когда зубья разной длины.
    const tip = xa + w * (0.3 + 0.4 * wobble(ob.at, i + 97));
    // Треугольник четырёхугольником: два верхних угла врозь, нижние — вместе.
    quad(
      project(xa, O.duckHeight, z, cam), project(xa + w, O.duckHeight, z, cam),
      project(tip, O.duckHeight - h, z, cam), project(tip, O.duckHeight - h, z, cam),
      COLORS.spike,
    );
  }
}

/* Висящий зверь — вторая внешность приседа, на месте голой плиты.

   `beam` была плита и ничего больше: четыре заливки, ровное красное поле. Так
   её и назвал заказчик 10 октября — «простая и скучная красная стена», — и
   заменить её он попросил прямо.

   Зверь висит вниз головой и машет крыльями. Выбран он не ради зоологии:
   верхнее препятствие и боковое — это два разных действия, и живое существо
   сверху даёт паре смысл, которого у «плиты с зубьями» и «плиты с бадником» не
   было. Внизу прыгает, сверху висит.

   Доли — от ПЛИТЫ (её высота `WALL − duckHeight`), не метры: ширина коридора и
   высота щели приседа — числа гейм-плея, и фигура в метрах при их правке
   однажды вылезла бы за край плиты, то есть нарисовалась бы в проёме.

   Глаза светлые, и они попадают под то же ограничение, что глаз бадника:
   `badnikEye` ярче проёма и в наборы ролей не входит ИМЕННО потому, что занимает
   несколько пикселей. На этом уже обожглись однажды — когда тело бадника
   выросло, глаз поехал вместе с ним и условие исключения молча перестало
   выполняться. Поэтому доли глаз подобраны отдельно от тела, а площадь
   проверяется тестом.

   Крылья — `blockDeep`, тем же цветом и по той же причине, что детали створки:
   впятеро темнее лица плиты, и это единственное, что переживает сжатие
   Miracast. Светлее делать нельзя — спорило бы с проёмом. */
function drawBat(ob, z, cam, elapsed, { project, quad, mscale }) {
  const top = WALL;
  const bottom = O.duckHeight;
  const ph = top - bottom;

  // Крюк-зацеп: зверь обязан на чём-то висеть, иначе он просто парит в плите.
  quad(
    project(-0.06, top - ph * 0.06, z, cam), project(0.06, top - ph * 0.06, z, cam),
    project(0.06, top, z, cam), project(-0.06, top, z, cam),
    COLORS.badnikMouth,
  );

  const bodyW = HALF * 0.22;
  const bodyTop = top - ph * 0.10;
  const bodyBot = bodyTop - ph * 0.46;
  quad(
    project(-bodyW, bodyBot, z, cam), project(bodyW, bodyBot, z, cam),
    project(bodyW, bodyTop, z, cam), project(-bodyW, bodyTop, z, cam),
    COLORS.badnik,
  );

  /* Взмах — функция времени с фазой от метки препятствия, как у всех анимаций
     проекта: накопленное состояние разошлось бы с картинкой тем сильнее, чем
     дольше забег, а два зверя в кадре махали бы в унисон. Амплитуду жмёт
     `mscale`, но не в ноль — неисполняемый путь гниёт отдельно. */
  const flap = 0.5 + 0.5 * Math.sin(2 * Math.PI * (elapsed * MOTION.batFlapHz + ob.at));
  const span = HALF * 0.80;
  const tipY = bodyTop - ph * (0.10 + 0.34 * flap * mscale);
  for (const dir of [-1, 1]) {
    quad(
      project(dir * bodyW, bodyTop, z, cam), project(dir * bodyW, bodyBot + ph * 0.08, z, cam),
      project(dir * span, tipY, z, cam), project(dir * span, tipY, z, cam),
      COLORS.blockDeep,
    );
  }

  // Глаза. Два, и мелкие: светлое на плите — это заём у проёма.
  const eyeY = bodyBot + ph * 0.06;
  const eyeW = bodyW * 0.22;
  const eyeH = ph * 0.05;
  for (const dir of [-1, 1]) {
    const ex = dir * bodyW * 0.45;
    quad(
      project(ex - eyeW, eyeY, z, cam), project(ex + eyeW, eyeY, z, cam),
      project(ex + eyeW, eyeY + eyeH, z, cam), project(ex - eyeW, eyeY + eyeH, z, cam),
      COLORS.badnikEye,
    );
  }
}

/* ─────────────── свои внешности миров: присед ───────────────

   Все три — ПРОДОЛЖЕНИЕ `drawTeeth`, а не новое препятствие: плита остаётся на
   месте целиком, фигура рисуется на её лице, светлота решения не меняется ни
   на пиксель. Форма сообщает мир, светлота сообщает решение.

   И все три — НЕПОДВИЖНЫЕ навесы сверху, кроме дыхания хвоста кометы. Это
   правило, а не совпадение: своё боковое препятствие в каждом мире живое или
   движется, своё верхнее — висит. Ребёнок учит один признак на четыре мира.

   Доли берутся от высоты плиты (`WALL − duckHeight`), как у зверя, а не метры:
   высота щели приседа — число гейм-плея, и фигура в метрах при его правке
   вылезла бы в проём, то есть в самое светлое место кадра. */

/* Сосульки — лёд. Шесть ТОНКИХ игл против тринадцати широких зубьев.

   Отличает их от зубьев ширина, а не число, и это выяснилось кадром. Первая
   версия ставила пять треугольников во всю свою долю: на экране вышла та же
   пила, только с пропусками, — с полутора метров не отличить. Глубина у обоих
   одна и та же и расти не вправе: потолок связан с `duckHeight` проверкой,
   потому что ребёнок видит картинку, а не приговор, и длинная бахрома учила бы
   приседать глубже, чем просят. Значит остаётся ширина — и игла в треть своей
   доли читается льдом, а не челюстью.

   Блика здесь НЕТ, и его отсутствие намеренное. Он был — одна светлая заливка,
   ползущая по кромке, — и на кадре оказался белым прямоугольником поперёк той
   самой линии, по которой судит `isSafe`: светлое пятно размером с кольцо на
   границе «можно / нельзя». Правило проекта светлое на плите разрешает только
   в несколько пикселей, и здесь оно нарушалось не чуть-чуть. Блик остался
   у тороса, где ему есть по чему ползти. */
function drawIcicles(ob, z, cam, { project, quad }) {
  const N = 6;
  const w = (HALF * 2) / N;
  for (let i = 0; i < N; i++) {
    const xa = -HALF + i * w;
    // Разброс идёт ВНИЗ от `teethM`, как у зубьев: неровность разрешена, рост нет.
    const h = O.teethM * (0.62 + 0.38 * wobble(ob.at, i + 31));
    const base = w * 0.17;                 // треть доли на всю иглу, не больше
    const cx = xa + w * (0.35 + 0.3 * wobble(ob.at, i + 61));
    quad(
      project(cx - base, O.duckHeight, z, cam), project(cx + base, O.duckHeight, z, cam),
      project(cx, O.duckHeight - h, z, cam), project(cx, O.duckHeight - h, z, cam),
      COLORS.spike,
    );
  }
}

/* Рёбра затонувшего кита — вода. Хребет вдоль плиты и пять рёбер вниз.
   Неподвижны: кость не шевелится, и в этом вся разница с медузой на той же
   глубине. */
function drawRibs(ob, z, cam, { project, quad }) {
  const top = WALL;
  const bottom = O.duckHeight;
  const ph = top - bottom;
  /* Вся фигура живёт в НИЖНЕЙ половине плиты, и это не композиция, а
     видимость: верх плиты в кадре срезан — она уходит за верхнюю кромку
     экрана. Первая версия вешала хребет под самый потолок, и на кадре его не
     было вовсе: оставались пять тёмных клиньев сверху, то есть те же зубья,
     только толще. Поймано кадром в браузере; числом это не ловится — заливки
     нарисованы, габариты внутри плиты, всё «сошлось». */
  const spine = bottom + ph * 0.62;
  // Хребет: без него рёбра висят поодиночке и читаются теми же зубьями.
  quad(
    project(-HALF * 0.86, spine, z, cam), project(HALF * 0.86, spine, z, cam),
    project(HALF * 0.86, spine + ph * 0.09, z, cam),
    project(-HALF * 0.86, spine + ph * 0.09, z, cam),
    COLORS.badnikMouth,
  );
  const N = 5;
  for (let i = 0; i < N; i++) {
    const x = -HALF * 0.74 + (HALF * 1.48) * (i / (N - 1));
    // Ребро сужается вниз: верх шире низа, поэтому четырёхугольник не
    // вырождается в треугольник и кость читается костью.
    const w = HALF * 0.07;
    const len = ph * (0.34 + 0.16 * wobble(ob.at, i + 17));
    quad(
      project(x - w, spine, z, cam), project(x + w, spine, z, cam),
      project(x + w * 0.35, spine - len, z, cam),
      project(x - w * 0.35, spine - len, z, cam),
      COLORS.blockDeep,
    );
  }
}

/* Метеорный дождь — звёздная дорога, внешность ПРИСЕДА. Имя внешности в коде
   осталось `comet`: оно стоит в каждом снятом журнале, в офлайн-кэше и в
   тестах, и переименование обрубило бы сравнимость со всем, что проект про
   себя знает. Рисуется при этом дождь, и расхождение имени с фигурой здесь
   осознанное — ровно по тому же правилу, по которому `js/train.js` остался
   дирижёром забега, а не тренировкой.

   ЭТО РАЗВОРОТ ПРЕЖНЕГО РЕШЕНИЯ, и отменяемый текст стоял здесь же: «Комета —
   звёздная дорога. Ядро у одного края, хвост тянется к другому. Висит
   неподвижно, как и положено верхнему препятствию; дышит только ДЛИНА
   хвоста». Опровергнут он заказчиком 19 октября, после трёх забегов: «верхнее
   препятствие нарисовано двигающимся в бок».

   Он прав, и дефект здесь не косметический. Горизонтальная фигура, у которой
   вдобавок дышала ДЛИНА, читается как «летит вбок» — то есть подсказывает ШАГ
   В СТОРОНУ. А висит она над щелью, в которую надо ПРИСЕСТЬ. Подсказка одного
   действия на препятствии другого — соседний случай того же худшего класса
   дефекта, что приговор за непоказанное: ребёнок делает ровно то, что увидел,
   и проигрывает, не понимая, за что. Сторона вдобавок выбиралась фазой, то
   есть половина комет смотрела влево, половина вправо, и не значило это
   ничего.

   Теперь вся семья приседа смотрит ВНИЗ: зубья, сосульки, рёбра, висящий
   зверь — и дождь. Проверяется это не на глаз, а группой «звёздная дорога
   читается»: каждая фигура внешности обязана быть выше, чем шире.

   Светлого нет вовсе. Искра у ядра была и снята по жалобе заказчика — «что за
   белый квадрат в метеоритном дожде»: светлота в этой игре сообщает решение,
   самое светлое место кадра — щель под плитой, и белое пятно на лице плиты
   тянуло взгляд туда, куда идти нельзя. */
function drawMeteors(ob, z, cam, elapsed, { project, quad, mscale }) {
  const top = WALL;
  const bottom = O.duckHeight;
  const ph = top - bottom;
  const N = 4;
  const pitch = (HALF * 2) / N;
  // Фазы разнесены поровну долей `i / N`: метеоры, падающие в ногу, читаются
  // решёткой, а не дождём.
  const t = elapsed * MOTION.meteorFallHz + ob.at;
  for (let i = 0; i < N; i++) {
    const x = -HALF + pitch * (i + 0.5);
    const w = pitch * (0.11 + 0.04 * wobble(ob.at, i + 31));
    const frac = ((t + i / N) % 1 + 1) % 1;
    /* МЕТЕОР ВЫРАСТАЕТ ИЗ НИЧЕГО И СХОДИТ В НИЧТО, и это не украшение, а
       единственный способ сделать падение без разрыва.

       Падение задано пилой, то есть у неё ЕСТЬ момент возврата. Пока размер
       был постоянным, возврат приходился на середину плиты: ядро прыгало
       вверх на четверть её высоты, и при четырёх метеорах со сдвигом фаз такой
       прыжок случался трижды в секунду. Это ровно то мерцание, ради запрета
       которого частоты мира держат в полосе до 1.6 Гц, — и оно стояло бы НА
       ЛИЦЕ ПРЕПЯТСТВИЯ, где мерцанием говорит телеграф. Поймано ревью;
       проверки этого не видели, потому что мерят один кадр, а дефект живёт на
       стыке двух.

       `k` обнуляет и длину, и ширину разом: на возврате фигура — точка, а
       точка, перескочившая вверх, на экране не видна. Делить на «ширину» и
       «длину» нельзя: от этого поехало бы отношение сторон, а им проверяется
       вертикальность. */
    const k = 1 - (1 - Math.sin(Math.PI * frac)) * mscale;
    const wk = w * k;
    /* Ход — доля ВЫСОТЫ ПЛИТЫ, и жмётся он через `motionScale`, как у медузы.
       При нулевой амплитуде `k` остаётся единицей, а метеоры замирают на
       РАЗНОЙ высоте: разброс даёт `wobble`, а не движение, так что
       неисполняемый путь остаётся дождём, а не рядом одинаковых штрихов.

       Числа выбраны так, чтобы зажима не понадобилось НИ В ОДНОЙ фазе: при
       нулевой амплитуде верх шлейфа встаёт на 0.98 высоты плиты, при полной —
       не выше 0.82, а остриё не опускается ниже нуля, то есть не достаёт до
       кромки приговора: за неё свисают только зубья. Прежде это было написано
       и НЕВЕРНО — зажим `Math.min` срабатывал, и один шлейф выходил короче
       прочих. Теперь это не обещание в комментарии, а проверка «дождь не
       достаёт до кромок плиты ни в одной фазе». */
    const tipU = 0.42 - 0.08 * wobble(ob.at, i + 53) - 0.34 * frac * mscale;
    const tip = bottom + ph * tipU;
    const headTop = tip + ph * 0.20 * k;
    const tailTop = headTop + ph * 0.36 * k;
    // Шлейф — ВВЕРХ от ядра и сужается к нему: широкий конец там, откуда
    // метеор пришёл.
    quad(
      project(x - wk, tailTop, z, cam), project(x + wk, tailTop, z, cam),
      project(x + wk * 0.45, headTop, z, cam), project(x - wk * 0.45, headTop, z, cam),
      COLORS.blockDeep,
    );
    /* Ядро — клин ОСТРИЁМ ВНИЗ, четырёхугольником с совпавшими углами: тот же
       приём, которым нарисованы зубья.

       Читается оно СИЛУЭТОМ, а не цветом, и это стоит знать. В палитрах
       звёздной дороги `badnik` и `blockDeep` — соседи по светлоте (0.046,
       0.030 и 0.027 против 0.024), то есть границы между шлейфом и ядром на
       экране нет вовсе. Работает другое: шлейф к ядру СУЖАЕТСЯ, ядро снова
       расширяется до полной ширины и сходит в остриё — излом контура виден и
       после сжатия. Цвет оставлен разным на будущее: поднимется `badnik` в
       палитре — ядро отделится и цветом. Померено ревью. */
    quad(
      project(x - wk, headTop, z, cam), project(x + wk, headTop, z, cam),
      project(x, tip, z, cam), project(x, tip, z, cam),
      COLORS.badnik,
    );
  }
}

/* ─────────────── свои внешности миров: шаг в сторону ───────────────

   Эти три, наоборот, ЖИВЫЕ или движутся, и рисуются они на закрытой плите
   вместо зверя. Доли — от самой плиты (`x0`…`x1`), как у створки: ширина плиты
   меняется со ступенью (`blockFrac`), и фигура в метрах на узкой плите вылезла
   бы в проём. Проверяется это по ВСЕМУ циклу анимации, а не в одной фазе. */

/* Медуза — вода. Купол, щупальца и два пятна свечения; плавает вверх-вниз.
   Ровно то, что просил заказчик, и движение здесь несёт смысл: боковое
   препятствие в каждом мире шевелится, верхнее — висит. */
function drawJelly(ob, z, cam, elapsed, { project, quad, x0, x1, mscale }) {
  const w = x1 - x0;
  const cx = x0 + w * 0.5;
  const bob = Math.sin(2 * Math.PI * (elapsed * MOTION.jellyBobHz + ob.at));
  /* Середина купола гуляет внутри плиты. Запас сверху и снизу взят так, чтобы
     при полной амплитуде фигура осталась внутри `0…WALL`: это и проверяется. */
  const cy = WALL * (0.52 + MOTION.jellyBobAmp * bob * mscale);
  const bellW = w * 0.40;
  const bellH = WALL * 0.17;

  /* Купол: широкий по НИЖНЕЙ кромке, сужается кверху — это и есть форма
     медузы, и ошибиться тут легко. Первая версия была трапецией наоборот,
     широкой сверху, и вместе с двумя светлыми пятнами читалась лицом с
     глазами, а не медузой. Поймано кадром в браузере, тестами — нет: число
     заливок и габариты у обеих трапеций одинаковые. */
  quad(
    project(cx - bellW, cy, z, cam), project(cx + bellW, cy, z, cam),
    project(cx + bellW * 0.58, cy + bellH, z, cam),
    project(cx - bellW * 0.58, cy + bellH, z, cam),
    COLORS.badnik,
  );
  // Щупальца. Три, разной длины: ряд одинаковых читается бахромой.
  for (const [k, scale] of [[-0.55, 0.9], [0, 1.0], [0.55, 0.8]]) {
    const tx = cx + bellW * k;
    const len = WALL * 0.26 * scale;
    quad(
      project(tx - w * 0.045, cy - len, z, cam), project(tx + w * 0.045, cy - len, z, cam),
      project(tx + w * 0.055, cy, z, cam), project(tx - w * 0.055, cy, z, cam),
      COLORS.blockDeep,
    );
  }
  /* Свечение по КРОМКЕ купола, двумя точками. Крупные пятна посреди купола
     вместе с трапецией читались парой глаз — то есть мордой, которой у медузы
     нет; на кромке они читаются свечением. Размер тот же, что у глаза бадника,
     и по той же причине: светлое на плите — заём у проёма, и площадь его
     проверяется тестом. */
  const gw = bellW * 0.11;
  const gh = bellH * 0.15;
  for (const dir of [-1, 1]) {
    const gx = cx + dir * bellW * 0.62;
    quad(
      project(gx - gw, cy + bellH * 0.10, z, cam), project(gx + gw, cy + bellH * 0.10, z, cam),
      project(gx + gw, cy + bellH * 0.10 + gh, z, cam),
      project(gx - gw, cy + bellH * 0.10 + gh, z, cam),
      COLORS.badnikEye,
    );
  }
}

/* Торос — лёд. Глыба в две грани, трещина и блик, который идёт по грани.
   Не живая, но ДВИЖЕТСЯ светом — то есть попадает в то же правило «шевелится
   — обходи», не притворяясь при этом зверем. */
function drawFloe(ob, z, cam, elapsed, { project, quad, x0, x1, mscale }) {
  const w = x1 - x0;
  const cx = x0 + w * 0.5;
  const top = WALL * 0.78;
  // Две грани, разной высоты: одна глыба читалась бы просто прямоугольником.
  quad(
    project(x0 + w * 0.08, 0, z, cam), project(cx, 0, z, cam),
    project(cx, top, z, cam), project(x0 + w * 0.22, top * 0.86, z, cam),
    COLORS.badnik,
  );
  quad(
    project(cx, 0, z, cam), project(x1 - w * 0.08, 0, z, cam),
    project(x1 - w * 0.20, top * 0.70, z, cam), project(cx, top, z, cam),
    COLORS.blockDeep,
  );
  // Трещина по стыку граней: тонкая, тёмная, от пола до вершины.
  quad(
    project(cx - w * 0.035, 0, z, cam), project(cx + w * 0.035, 0, z, cam),
    project(cx + w * 0.02, top * 0.92, z, cam), project(cx - w * 0.02, top * 0.92, z, cam),
    COLORS.badnikMouth,
  );
  // Блик ползёт по грани — единственное светлое, и оно в несколько пикселей.
  const slide = 0.5 + 0.5 * Math.sin(2 * Math.PI * (elapsed * MOTION.iceShineHz + ob.at));
  const sy = top * (0.22 + 0.5 * slide * mscale);
  quad(
    project(cx - w * 0.14, sy, z, cam), project(cx - w * 0.04, sy, z, cam),
    project(cx - w * 0.04, sy + WALL * 0.05, z, cam),
    project(cx - w * 0.14, sy + WALL * 0.05, z, cam),
    COLORS.badnikEye,
  );
}

/* Ракета на старте — звёздная дорога, внешность ШАГА В СТОРОНУ. Имя внешности
   в коде осталось `asteroid`, по той же причине, что у дождя выше: оно стоит
   в журналах, и несовпадение фигуры с именем переименованию не повод.

   ЭТО РАЗВОРОТ ПРЕЖНЕГО РЕШЕНИЯ. Отменяемый текст стоял здесь: «Астероид —
   камень с кратерами, и он ПОВОРАЧИВАЕТСЯ: кратеры едут по телу, само тело
   стоит». Опровергнут он заказчиком 19 октября: «статичная тёмная
   бесформенная клякса с тремя пятнами».

   Все три слова жалобы указывают на одну причину, и причина эта — светлота.
   Тело было `badnik`, кратеры `blockDeep`: два ТЁМНЫХ цвета рядом, разница
   светлоты между ними мизерная, и Miracast съедал её целиком — оставалась
   ровная тёмная заливка. Поворот по той же причине был невидим: он сообщался
   только движением кратеров, которых не видно. А силуэт собирался из двух
   ВЫПУКЛЫХ четырёхугольников, то есть углов, по которым узнаётся камень, в нём
   не было вовсе.

   Ракета отвечает на всё это сразу: вытянутый силуэт самым тёмным цветом,
   стабилизаторы, дающие углы, и ОДНА светлая точка — иллюминатор. Точка и есть
   то, чего кляксе не хватало: тёмная фигура становится предметом от одного
   светлого пятна, по тому же правилу, по которому у створки светлые ровно два
   болта, а у зверя ровно глаз. Сторожит это группа «звёздная дорога читается».

   Факел ТЁМНЫЙ, и это не стилистика. Светлота в этой игре сообщает решение:
   самое светлое место кадра — проём, куда уходить. Яркий огонь на ЗАКРЫТОЙ
   плите тянул бы взгляд туда, куда идти нельзя, то есть врал бы ребёнку о
   решении. Светлого в ракете поэтому ровно иллюминатор, и он на корпусе, а не
   в пустоте: нижняя искра у сопла была и снята по жалобе заказчика о белых
   квадратах.

   Ракета НИКУДА НЕ ЛЕТИТ, и это тоже решение, а не экономия: движение вверх
   подсказывало бы прыжок, которого в словаре управления нет — у ребёнка две
   оси, шаг в сторону и присед. Угроза здесь в том, что ракета вот-вот
   стартует, и стоять рядом нельзя.

   Частоты — в той же полосе, что у остальных своих внешностей мира (не
   медленнее прыжка бадника, не быстрее взмаха крыльев). Настоящая дрожь
   двигателя в неё не влезает, и правило тут сильнее замысла: на десяти метрах
   всё, что чаще, читается мерцанием, а мерцание в этой игре занято
   телеграфом. */
function drawRocket(ob, z, cam, elapsed, { project, quad, x0, x1, mscale }) {
  const w = x1 - x0;
  // Дрожь — доля ШИРИНЫ ПЛИТЫ, не метры: плита меняется со ступенью.
  const shake = Math.sin(2 * Math.PI * (elapsed * MOTION.rocketShakeHz + ob.at))
    * w * MOTION.rocketShakeAmp * mscale;
  const cx = x0 + w * 0.5 + shake;
  const base = WALL * 0.30;        // срез сопла
  const shoulder = WALL * 0.72;    // плечо: где цилиндр переходит в конус
  const nose = WALL * 0.94;        // острие
  const half = w * 0.115;

  /* Факел пульсирует ДЛИНОЙ, а не яркостью: яркостью в этой игре говорит
     телеграф. Доли от `WALL`, и обе длины выбраны так, чтобы при полной
     амплитуде пламя не достало до пола: 0.30 − 0.24 = 0.06 высоты стены.

     Два клина разного цвета нужны не ради контраста между собой — в палитрах
     этого мира `badnik` и `blockDeep` почти не различаются, — а ради ДЛИНЫ:
     внутренний уходит ниже внешнего, и язык пламени получает остриё. Оба
     при этом втрое-вшестеро темнее лица плиты, по которому и читаются. */
  const k = 0.6 + 0.4 * (0.5 + 0.5
    * Math.sin(2 * Math.PI * (elapsed * MOTION.rocketFlameHz + ob.at))) * mscale;
  quad(
    project(cx - half * 0.9, base, z, cam), project(cx + half * 0.9, base, z, cam),
    project(cx + half * 0.35, base - WALL * 0.19 * k, z, cam),
    project(cx - half * 0.35, base - WALL * 0.19 * k, z, cam),
    COLORS.badnik,
  );
  quad(
    project(cx - half * 0.5, base, z, cam), project(cx + half * 0.5, base, z, cam),
    project(cx, base - WALL * 0.24 * k, z, cam),
    project(cx, base - WALL * 0.24 * k, z, cam),
    COLORS.blockDeep,
  );
  // Стабилизаторы. Они и дают силуэту углы, которых не было у кляксы; доли от
  // плиты, так что на узкой плите верхней ступени в проём не вылезут.
  for (const dir of [-1, 1]) {
    quad(
      project(cx + dir * half, WALL * 0.46, z, cam),
      project(cx + dir * half, base, z, cam),
      project(cx + dir * w * 0.22, WALL * 0.20, z, cam),
      project(cx + dir * w * 0.22, WALL * 0.20, z, cam),
      COLORS.blockDeep,
    );
  }
  /* Корпус и нос — ДВЕ фигуры, и вторая стоит своей заливки. Одной выходил
     шип: `quad` берёт ровно четыре точки, то есть сужение от среза сопла прямо
     к острию даёт треугольник во всю высоту, и на кадре он читался иглой, а не
     ракетой. Поймано кадром в браузере через `tools/frame.html`; набор был
     зелёным — число заливок, габариты и подпись у обеих версий в порядке.

     Ровно тот же случай, что у астероида, которому второй кусок ломал
     выпуклость, и у медузы, читавшейся лицом. Цилиндр и конус — это две формы,
     и экономия на второй покупает не заливку, а непонятную фигуру. */
  quad(
    project(cx - half, base, z, cam), project(cx + half, base, z, cam),
    project(cx + half, shoulder, z, cam), project(cx - half, shoulder, z, cam),
    COLORS.blockDeep,
  );
  quad(
    project(cx - half, shoulder, z, cam), project(cx + half, shoulder, z, cam),
    project(cx + half * 0.16, nose, z, cam), project(cx - half * 0.16, nose, z, cam),
    COLORS.blockDeep,
  );
  /* ШВА ПО КОРПУСУ ЗДЕСЬ НЕТ, и это снятая заливка, а не забытая. Он был —
     `badnik` поперёк корпуса `blockDeep` со словами «без него корпус остаётся
     ровной тёмной полосой», — и слова эти опровергнуты замером: в трёх
     палитрах звёздной дороги, где эта фигура только и появляется, светлота
     `badnik` равна 0.046, 0.030 и 0.027 против 0.024 у `blockDeep`. Это
     отношение от 1.1 до 1.9, а в этой теме записано, что и двукратное (0.080
     на 0.160) «не читалось ВООБЩЕ». То есть шов чинил бы ровную тёмную полосу
     ровной тёмной полосой — и был бы третьим случаем того самого дефекта,
     который шапка этой функции ставит астероиду в вину. Поймано ревью. */
  // Иллюминатор — единственное светлое, и он мелкий: на светлоту кадра
  // несколько пикселей не влияют, а предмет читается только по нему. Стоит
  // НИЖЕ плеча, то есть на цилиндре: в конусе он оказался бы шире самого носа.
  const eye = half * 0.34;
  quad(
    project(cx - eye, WALL * 0.57, z, cam), project(cx + eye, WALL * 0.57, z, cam),
    project(cx + eye, WALL * 0.62, z, cam), project(cx - eye, WALL * 0.62, z, cam),
    COLORS.badnikEye,
  );
}

/* Створка во всю плиту: рама по краям, поперечины по всей высоте, два болта.

   Было три полоски посередине, и заказчик назвал это ровно так — «просто
   красная стена, скучнее, чем было». Он прав: три полоски на двух с половиной
   метрах заливки не делают силуэта, а только слегка пачкают его.

   Правило при этом не меняется ни на пиксель: ЛИЦО плиты сообщает решение, и
   всё, что на нём рисуется, обязано быть темнее его. Деталям поэтому дан свой
   цвет, `blockDeep`: в `blockDark` они не читались вовсе — разница светлоты
   0.080 против 0.160, и на кадре створка оставалась ровной заливкой. Новый
   цвет темнее лица впятеро, то есть переживёт и сжатие. Болты — единственное
   светлое, и они мелкие: на
   светлоту кадра несколько пикселей не влияют, а металл читается только по
   ним. Тот же порядок, по которому у бадника светлый ровно глаз. */
function drawGate(z, cam, { project, quad, x0, x1 }) {
  const w = x1 - x0;
  const stile = w * 0.09;
  // Стойки во всю высоту: без них поперечины висят в воздухе, и створка
  // читается полосатой стеной, а не рамой.
  for (const sx of [x0, x1 - stile]) {
    quad(
      project(sx, 0, z, cam), project(sx + stile, 0, z, cam),
      project(sx + stile, WALL, z, cam), project(sx, WALL, z, cam),
      COLORS.blockDeep,
    );
  }
  // Поперечины по всей высоте, а не только по середине.
  for (const y of [0.2, 0.84, 1.48, 2.12]) {
    quad(
      project(x0, y, z, cam), project(x1, y, z, cam),
      project(x1, y + 0.2, z, cam), project(x0, y + 0.2, z, cam),
      COLORS.blockDeep,
    );
  }
  // Болты. Два, а не ряд: каждая лишняя заливка здесь умножается на число
  // препятствий в кадре, а характер металла дают уже эти два.
  for (const y of [0.86, 2.14]) {
    const bx = x0 + w * 0.5;
    quad(
      project(bx - w * 0.05, y + 0.02, z, cam), project(bx + w * 0.05, y + 0.02, z, cam),
      project(bx + w * 0.05, y + 0.14, z, cam), project(bx - w * 0.05, y + 0.14, z, cam),
      COLORS.spike,
    );
  }
}

/* Шипы боковой плиты — с ВНУТРЕННЕЙ кромки в сторону центра коридора.

   Росли они с верхней кромки вверх, и заказчик 10 октября сказал про это
   прямо: шипы должны смотреть туда, куда бежит ребёнок. Жалоба точная, и к
   внешности она отношения не имеет — `drawSpikes` зовётся безусловно для
   КАЖДОГО бокового препятствия, то есть гребень был одинаков и у бадника, и у
   створки.

   Сторону берём из `x0`/`x1`: правая плита занимает `[edge, HALF]`, значит её
   внутренняя кромка — `x0`, и зубья смотрят в минус; у левой `[-HALF, -edge]`
   внутренняя кромка `x1`, и смотрят в плюс. Знак отсюда и выводится, `ob.side`
   для этого не нужен — две копии одного решения разошлись бы.

   ВЕРШИНА ДОХОДИТ РОВНО ДО КРОМКИ И НЕ ПЕРЕХОДИТ ЕЁ. Это не вкус: по этой
   линии судит `isSafe()` через `obstacleEdge()`, и зуб, вылезший в проём,
   пообещал бы проход уже, чем приговор, — тот же класс дефекта, из-за которого
   край препятствия берётся из одного места, а не считается заново. Вверх шипы
   вылезали безнаказанно только потому, что выше `WALL` не судится ничего.
   Поэтому длина меряется ВНУТРЬ плиты: корень на `spikeM` от кромки, остриё на
   кромке.

   Корень при этом всё равно уходит внутрь (`spikeRootM`) — смысл тот же, что
   был у вертикальных: плита кончается зубьями, а не сидит под колпаками.

   Разнобой — `wobble` от метки препятствия, то есть функция, а не случайность:
   иначе гребень менялся бы каждый кадр, и это была бы рябь. */
function drawSpikes(ob, z, cam, { project, quad, x0, x1 }) {
  const n = O.spikeN;
  const h = WALL / n;
  // Внутренняя кромка и направление внутрь плиты.
  const inner = x1 >= HALF ? x0 : x1;
  const dir = x1 >= HALF ? 1 : -1;
  // Длина — доля ШИРИНЫ ПЛИТЫ: в метрах зубья закрывали бадника целиком, и
  // при правке `blockFrac` однажды вылезли бы в проём.
  const pw = Math.abs(x1 - x0);
  for (let i = 0; i < n; i++) {
    const y = i * h;
    const len = pw * O.spikeM * (0.45 + 0.55 * wobble(ob.at, i));
    const tip = y + h * (0.25 + 0.5 * wobble(ob.at, i + 53));
    const apex = project(inner, tip, z, cam);
    const base = inner + dir * (len + pw * O.spikeRootM);
    quad(
      project(base, y, z, cam), project(base, y + h, z, cam),
      apex, apex,
      COLORS.spike,
    );
  }
}

/* Бадник — мелкий зверёк, прыгающий на месте на закрытой стороне.

   Тело тёмное: враг обязан быть заметным, но не светлым, иначе он начнёт
   соперничать с проёмом, то есть с сообщением «иди сюда».

   Три шутки уровня живут здесь, и все — функции времени, без состояния
   (прыжок разобран ниже, у самих пропорций):

   1. Икает, пока ребёнок стоит на месте. Нужна не для смеха: неподвижность —
      это ровно то, чего игра не хочет, и дёргающийся враг тянет взгляд.
   2. На последней отметке телеграфа, если ребёнок уже в безопасном месте,
      бадник вскрывается и из него выскакивает зверёк. Это награда, и она
      приходит ДО столкновения, а не после: в момент прохода бадник уже за
      спиной, и там его не видно вовсе — проверено построением проекции.
*/
function drawBadnik(ob, dt, z, cam, elapsed, { project, quad, x0, x1, safe, still, mscale }) {
  const pw = Math.abs(x1 - x0);
  /* Бадник сидит ПО ЦЕНТРУ плиты — с 11 октября, когда шипы с его внешности
     убрали вовсе. До этого он уходил к дальней от коридора кромке, потому что
     внутреннюю занимали зубья и по центру существо скрывалось за ними целиком;
     без зубьев смещение осталось бы перекосом без причины. */
  const cx = (x0 + x1) / 2;
  const opened = dt <= O.lastCallS && safe;

  // Икота: короткий подскок, и только когда ребёнок не двигается.
  const hic = still && !opened
    ? Math.max(0, Math.sin(elapsed * (2 * Math.PI / MOTION.badnikHiccupS) * 3)) ** 8 * 0.1 * mscale
    : 0;

  /* Размеры тела — ДОЛИ плиты, а не метры.

     По высоте тело осталось мелким (15% плиты), а по ШИРИНЕ занимает её почти
     целиком: 92%. Это заказ от 11 октября — «растянуть монстра на всю ширину
     красного поля, чтобы не было пустоты после того как уберём шипы». Жалобы
     10 октября («растянутый по высоте монстр выглядит плохо») это не отменяет:
     растянут он вдоль плиты, а не вверх, и плиту по высоте по-прежнему занимает
     прыжок, а не тело.

     Полуширина берётся долей ПЛИТЫ, потому что ширина плиты зависит от
     `blockFrac`, то есть от гейм-плея: тело, заданное в метрах, при правке
     этого числа однажды вылезло бы за край и пообещало проход там, где его
     нет. Проверяется это в группе «силуэт препятствия».

     Восемь процентов не отданы запасом «на всякий случай»: по кромке плиты
     судит `isSafe()`, и фигура, дошедшая до неё вплотную, читается как
     продолжение плиты — то есть приговор и картинка снова начинают спорить,
     только в другую сторону. */
  const bw = pw * 0.46;
  const bodyH = WALL * 0.15;
  /* Прыжок. Верх тела в апогее доходит до `badnikJumpTop` высоты плиты, то
     есть существо само остаётся мелким, а ПЛИТУ занимает его движение.

     Так и было заказано — и это ровно обратное решению от 10 октября, когда
     тело растили до размера плиты. Разворот осознанный: «растянутый по высоте
     монстр выглядит плохо». Красную область это не трогает ничем — она и есть
     приговор, — а пустоту за мелким телом занимают дорожка и пыль ниже. */
  const ground = 0.14;
  const apex = Math.max(ground, O.badnikJumpTop * WALL - bodyH);
  /* Вскрывшийся бадник НЕ прыгает, и ждать от прыжка нужной фазы нечего:
     половинки с зверьком считаются от земли. Иначе награда за правильное
     положение выдаётся в точке, где существо случайно оказалось, — а зверёк,
     который «убегает по кромке обрыва», убегал бы по воздуху в полутора
     метрах над ней. */
  const lift = opened ? 0 : badnikJump(elapsed, ob.at, mscale) * (apex - ground);
  const bodyY = ground + lift + hic;

  if (opened) {
    // Вскрылся: две половинки разъехались. Чем ближе, тем шире — функция dt,
    // а не накопленное время. Половинки выросли вместе с телом: они и есть
    // оно, разъехавшееся надвое.
    const open = clamp(1 - dt / O.lastCallS, 0, 1);
    /* Половинки и их разъезд считаются от ШИРИНЫ ТЕЛА так, чтобы ОБА конца
       раскрытия сходились с цельным телом:

         open = 0 — половинки стоят вплотную и вместе занимают ровно `2·bw`,
                    то есть ширину тела. Иначе вскрытие начиналось бы рывком:
                    существо на один кадр сжималось бы вдвое и только потом
                    расходилось — глаз читает это поломкой, а не наградой;
         open = 1 — внешняя кромка приходится ровно на край тела, то есть
                    остаётся внутри плиты. Пока тело было узким (23% плиты),
                    разъезд на целую ширину умещался сам; у тела во всю плиту
                    он вылез бы в проём и пообещал проход там, где его нет.

       Отсюда и сужение половинок по ходу раскрытия: `hw + spread + hw = bw`
       при любом `open`. Оба конца проверяются тестом — верхний по кромке
       плиты, нижний по тому, что ширина в момент вскрытия не прыгает. */
    const hw = bw * (0.5 - 0.25 * open);
    for (const dir of [-1, 1]) {
      const hx = cx + dir * (hw + open * bw * 0.5);
      quad(
        project(hx - hw, bodyY, z, cam), project(hx + hw, bodyY, z, cam),
        project(hx + hw, bodyY + bodyH * 0.7, z, cam), project(hx - hw, bodyY + bodyH * 0.7, z, cam),
        COLORS.badnik,
      );
    }
    /* Зверёк: выскакивает и убегает по кромке обрыва, спотыкаясь. Спотыкание
       — просадка в середине пути, тоже функция `open`. */
    const run = open;
    const sx = cx + Math.sign(ob.side || 1) * run * 0.5;
    const trip = Math.abs(run - 0.55) < 0.08 ? -0.08 : 0;
    const sy = bodyY + bodyH + run * 0.5 + Math.abs(Math.sin(run * 9)) * 0.1 + trip;
    quad(
      project(sx - 0.09, sy, z, cam), project(sx + 0.09, sy, z, cam),
      project(sx + 0.09, sy + 0.18, z, cam), project(sx - 0.09, sy + 0.18, z, cam),
      COLORS.critter,
    );
    /* Уши и глаза. Зверёк — ТАЛИСМАН игры, его мордочка стоит на иконке
       приложения и в меню; безликий квадрат в самой игре означал бы, что имя
       «Шустрик» ни к чему в кадре не относится.

       Это третье место, где он нарисован, и синхронизировать три среды —
       байтовый PNG, SVG в разметке и четырёхугольники здесь — нечем. Цвета
       общие (`critter`, `badnikMouth` из js/theme.js), форму держим руками:
       правило записано в docs/identity-and-icons.md. */
    for (const d of [-1, 1]) {
      quad(
        project(sx + d * 0.085, sy + 0.15, z, cam), project(sx + d * 0.035, sy + 0.15, z, cam),
        project(sx + d * 0.035, sy + 0.22, z, cam), project(sx + d * 0.085, sy + 0.22, z, cam),
        COLORS.critter,
      );
      quad(
        project(sx + d * 0.055, sy + 0.09, z, cam), project(sx + d * 0.02, sy + 0.09, z, cam),
        project(sx + d * 0.02, sy + 0.13, z, cam), project(sx + d * 0.055, sy + 0.13, z, cam),
        COLORS.badnikMouth,
      );
    }
    return;
  }

  // Тело.
  quad(
    project(cx - bw, bodyY, z, cam), project(cx + bw, bodyY, z, cam),
    project(cx + bw, bodyY + bodyH, z, cam), project(cx - bw, bodyY + bodyH, z, cam),
    COLORS.badnik,
  );
  /* Дорожка и пыль — то, чем занята плита, пока тело снова стало мелким.

     Решение заказчика, и у него есть цена, которую надо называть: 10 октября
     жалоба была ОБРАТНОЙ — «мелкое существо, позади которого красная стена во
     всю высоту». Убрать красное нельзя, это приговор. Значит пустоту обязано
     занять что-то другое, и занимают её движение тела плюс две статичные
     детали: тёмная дорожка по низу плиты во всю её ширину и два облачка пыли в
     месте отрыва.

     Пыль — функция той же фазы прыжка, без своего состояния: у земли облачка
     широкие, в апогее сжимаются почти в ничто. Рисуются они ВСЕГДА, а не по
     условию, и это нарочно: условная заливка делает бюджет кадра зависящим от
     фазы, а бюджет здесь выбран до одной заливки и мерится худшим кадром.

     Колёсико ушло вместе с катанием: прыгающее существо не катится, а
     статичный корпус у подвижного тела от него отрывается. */
  quad(
    project(x0, 0.02, z, cam), project(x1, 0.02, z, cam),
    project(x1, 0.10, z, cam), project(x0, 0.10, z, cam),
    COLORS.earthDeep,
  );
  const puff = (1 - badnikJump(elapsed, ob.at, mscale)) ** 2;
  /* Облачка стоят под нижними углами тела, а не рядом с ним: тело теперь во всю
     плиту, и «рядом» означало бы «за кромкой». Доли подобраны так, чтобы при
     самом широком облачке (`puff = 1`) его край не доходил до края плиты:
     0.75 · 0.46 + 0.22 · 0.46 ≈ 0.45 полуширины.

     А по ВЫСОТЕ они целиком ниже тела (`ground` 0.14), и это не мелочь: пыль
     рисуется после тела, и стоило ей подняться выше — две тёмные выемки
     ложились прямо на нижние углы существа ровно в момент отрыва, когда
     облачко самое широкое. То есть в единственный момент, ради которого пыль
     и нарисована, она переставала быть пылью. Поймано ревью. Место под телом
     занято дорожкой (`earthDeep`, 0.02…0.10), и пыль лежит на ней — там, где
     ей и положено. */
  for (const dir of [-1, 1]) {
    const px = cx + dir * bw * 0.75;
    const half = bw * 0.22 * puff;
    quad(
      project(px - half, 0.02, z, cam), project(px + half, 0.02, z, cam),
      project(px + half, 0.02 + 0.11 * puff, z, cam),
      project(px - half, 0.02 + 0.11 * puff, z, cam),
      COLORS.shade,
    );
  }
  /* Глаз. Светлый — и единственное светлое на враге.

     Доли у него СВОИ, подобранные отдельно от пропорций тела, и это важнее,
     чем кажется. `badnikEye`
     (светлота 0.96) ярче проёма (0.954) и в наборы ролей не входит вовсе —
     исключён нарочно, со словами «занимает несколько пикселей и на светлоту
     кадра не влияет». Когда тело выросло до размера плиты, глаз поехал вместе
     с ним и это условие перестало выполняться: на плите появилось светлое
     пятно, спорящее с «иди сюда». Поймано глазами на первом же кадре закатной
     зоны.

     Поэтому доли подобраны так, чтобы пятно осталось пятном, а не окном, и
     его площадь проверяется тестом — иначе следующая правка пропорций тихо
     вернёт то же самое. Честная оговорка: доли всё равно СВЯЗАНЫ с телом, и
     следующая правка пропорций снова их подвинет. Держит здесь не формула, а
     потолок площади в тесте, и порог у него с запасом — 1.5% при нынешнем
     1.07%, а не впритык. */
  /* Доля уменьшена ровно во столько раз, во сколько выросло тело (0.20 → 0.10
     при 0.23 → 0.46 полуширины): глаз обязан остаться пятном ТОГО ЖЕ размера в
     долях плиты. Это и есть та ловушка, из-за которой проверка площади здесь
     появилась — 10 октября тело выросло, доли остались, и на плите возникло
     светлое окно ярче проёма. Снаружи это спор с «иди сюда». */
  const eyeW = bw * 0.10;
  const eyeH = bodyH * 0.22;
  const eyeY = bodyY + bodyH * 0.52;
  /* Глаза ДВА. Один широкий давал на мелком теле не существо, а щель в
     коробке: прямоугольник со светлой полосой и тёмной полосой читается
     телевизором. Пара глаз — единственное, что делает квадрат лицом, и стоит
     она одну заливку. */
  for (const dir of [-1, 1]) {
    const ex = cx + dir * bw * 0.42;
    quad(
      project(ex - eyeW, eyeY, z, cam), project(ex + eyeW, eyeY, z, cam),
      project(ex + eyeW, eyeY + eyeH, z, cam), project(ex - eyeW, eyeY + eyeH, z, cam),
      COLORS.badnikEye,
    );
  }
  /* Рот. Жуёт — функцией времени, без состояния, как и всё движение в игре.

     Сам по себе он украшение, но украшение нужное: тело во всю плиту без рта
     читается тёмным прямоугольником, а не существом, — то есть ровно тем, на
     что заказчик и жаловался, только тёмным вместо красного. Амплитуду жмёт
     `motionScale`, но не в ноль: неисполняемый путь гниёт отдельно. */
  const chew = (0.5 + 0.5 * Math.sin(elapsed * 2 * Math.PI * MOTION.badnikChewHz)) * mscale;
  const mouthY = bodyY + bodyH * 0.14;
  const mouthH = bodyH * (0.08 + 0.16 * chew);
  quad(
    project(cx - bw * 0.42, mouthY, z, cam), project(cx + bw * 0.42, mouthY, z, cam),
    project(cx + bw * 0.42, mouthY + mouthH, z, cam), project(cx - bw * 0.42, mouthY + mouthH, z, cam),
    COLORS.badnikMouth,
  );
}

/**
 * Ворота финиша.
 *
 * Две стойки и перекладина, жёлтым — цветом звёзд, а не проёма: проём значит
 * «сюда можно», а ворота значат «всё, добежал», и путать эти два сообщения
 * нельзя. На подходе перекладина мигает: это единственное место в игре, где
 * мигание уместно — оно обещает конец, а не требует реакции.
 */
function drawFinish(ctx, cam, z, { project, quad, pulse, speed = VIEW.speed }) {
  if (z < 0.4) return;
  const w = FIN.postWidth;
  const h = FIN.gateHeight;
  const post = (x0, x1) => quad(
    project(x0, 0, z, cam), project(x1, 0, z, cam),
    project(x1, h, z, cam), project(x0, h, z, cam),
    COLORS.finishDark,
  );
  post(-HALF, -HALF + w);
  post(HALF - w, HALF);
  quad(
    project(-HALF, h, z, cam), project(HALF, h, z, cam),
    project(HALF, h - w, z, cam), project(-HALF, h - w, z, cam),
    z < 10 && pulse > 0.5 ? COLORS.finish : COLORS.finishDark,
  );

  /* Табличка-указатель: самая заметная шутка уровня и прямая цитата из той
     игры, по которой уровень сделан. Крутится, а вплотную шлёпается лицом
     вверх.

     Сжатие по горизонтали, а не поворот сцены: поворот обошёлся бы матрицей,
     а сжатие — это та же функция, что крутит кольца.

     Стоит У КРАЯ, а не посередине. Посередине она закрывала проход сплошной
     заливкой того же цвета, что и ворота, и всё вместе читалось как жёлтая
     стена поперёк коридора — проверено на кадре через tools/frame.html.
     Вплотную не рисуется вовсе: на метре она занимает весь экран. */
  if (z < 1.2) return;

  const sx = HALF * 0.62;
  const flop = z < 2.2;
  const spin = flop ? 1 : Math.abs(Math.cos(2 * Math.PI * z * MOTION.signSpinHz / speed));
  const bw = 0.26 * Math.max(0.14, spin);
  const by = flop ? 0.14 : 0.78;
  const bh = flop ? 0.12 : 0.44;
  // Столбик.
  quad(
    project(sx - 0.04, 0, z, cam), project(sx + 0.04, 0, z, cam),
    project(sx + 0.04, by + bh * 0.4, z, cam), project(sx - 0.04, by + bh * 0.4, z, cam),
    COLORS.finishDark,
  );
  // Рамка и поле таблички: без рамки она сливается с перекладиной ворот,
  // потому что цвет у них один и тот же — цвет финиша.
  quad(
    project(sx - bw, by, z, cam), project(sx + bw, by, z, cam),
    project(sx + bw, by + bh, z, cam), project(sx - bw, by + bh, z, cam),
    COLORS.finishDark,
  );
  quad(
    project(sx - bw * 0.78, by + bh * 0.14, z, cam), project(sx + bw * 0.78, by + bh * 0.14, z, cam),
    project(sx + bw * 0.78, by + bh * 0.86, z, cam), project(sx - bw * 0.78, by + bh * 0.86, z, cam),
    COLORS.finish,
  );
}

/* ─────────────────────── анимации ───────────────────────

   Все до единой — функции времени. Ни одна не копит состояние, и это не
   стилистическое предпочтение: источник поз идёт на 20 Гц, кадры проседают, и
   накопительная анимация расходится с картинкой тем сильнее, чем дольше
   забег. Функция от времени не расходится никогда.

   Побочная выгода: их видно из node. Проверка «анимации» в tests-control.mjs
   прогоняет их без браузера и канваса, как и всю остальную математику. */

/**
 * Неровность, которая не дрожит.
 *
 * Шипам и зубьям нужен разнобой — ровный гребень читается как пила на
 * картинке, а не как угроза, — но случайность тут запрещена: `Math.random()` в
 * отрисовке дал бы новый гребень КАЖДЫЙ кадр, то есть рябь вместо шипов. По
 * тому же правилу в проекте сделаны все анимации: функция от времени, без
 * накопленного состояния.
 *
 * Поэтому разнобой берётся хешем от двух чисел — метки препятствия и номера
 * зуба. Одно препятствие носит один гребень весь забег, соседнее — другой, и
 * проверяется это из node, без браузера.
 */
function wobble(a, b) {
  const x = Math.sin(a * 12.9898 + b * 78.233) * 43758.5453;
  return x - Math.floor(x);
}

/**
 * Сжатие кольца по горизонтали: оно крутится.
 *
 * `t` — секунды от старта забега, `phase` — своя фаза кольца, чтобы весь ряд
 * не крутился в унисон. Пол 0.12 важен: кольцо, повернувшееся строго в
 * профиль, исчезло бы, а это цель, а не украшение — ребёнок должен видеть,
 * куда тянуться.
 */
export function ringSquash(t, phase = 0, scale = 1) {
  const spin = Math.max(0.12, Math.abs(Math.cos(2 * Math.PI * (t * MOTION.ringSpinHz + phase))));
  // Сжатие уменьшается вместе с амплитудой: при «меньше движения» кольцо
  // почти не вращается, но тот же код продолжает работать.
  return 1 - scale * (1 - spin);
}

/** Качание пальмовой кроны, условных метров в сторону. Вокруг своего места. */
/** Где на экране спутник. Отдельной функцией — и это не украшение кода: при
    `x = 0.78 W` птица давала РОВНО НОЛЬ пикселей, её целиком закрывал обрыв,
    а счётчик заливок исправно насчитывал две. Поймано кадром в браузере.

    Небо открыто клином вокруг точки схода, и клин этот СУЖАЕТСЯ с уходом
    взгляда. Первая починка держала размах 0.09 W — вдвое больше настоящего
    предела, — и спутник снова резался: при полном уходе (`u = ±1.5`, кламп)
    он пропадал пятую часть времени, а счётчик показывал стабильные две
    заливки. Поймано ревью. Размах 0.035 W вместе с полушириной птицы
    укладывается в худший зазор (0.068 W на высоте 0.13 H), и проверка в
    группе «кубок» выводит границу из геометрии обрыва, а не из числа.

    `scale` — то же сжатие «меньше движения», что у крыла: горизонтальный
    размах БОЛЬШЕ взмаха, и оставить его недожатым значило бы исполнить
    правило наполовину. Не в ноль: неисполняемый путь гниёт отдельно. */
export function buddyPos(t, scale = 1) {
  const фаза = t * MOTION.buddyHz * 2 * Math.PI;
  return {
    x: W * (0.5 + 0.035 * Math.sin(фаза * 0.3) * scale),
    y: H * (0.11 + 0.025 * Math.sin(фаза * 0.23) * scale),
  };
}

/** Тот же цвет с ПОВЁРНУТЫМ тоном и ТОЙ ЖЕ светлотой. Радуга вершины красит
    кольцо, но кольцо — цвет РЕШЕНИЯ, и контракт светлоты на него
    распространяется в любой фазе: свободного цвета ему не положено ни в каком
    призе. Поэтому поворачивается ТОН (через HSL), а светлота возвращается на
    место подбором множителя.

    Замерено на `#ffd34d`: максимальное отклонение светлоты за оборот 0.0048
    при допуске 0.02, двенадцать различимых цветов за период. */
export function rainbowOf(base, t, scale = 1) {
  const r = parseInt(base.slice(1, 3), 16) / 255;
  const g = parseInt(base.slice(3, 5), 16) / 255;
  const b = parseInt(base.slice(5, 7), 16) / 255;
  const max = Math.max(r, g, b); const min = Math.min(r, g, b);
  const l = (max + min) / 2;
  let h = 0; let sat = 0;
  if (max !== min) {
    const d = max - min;
    sat = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    h = max === r ? ((g - b) / d + (g < b ? 6 : 0))
      : max === g ? ((b - r) / d + 2) : ((r - g) / d + 4);
    h /= 6;
  }
  h = (h + (t * MOTION.rainbowHz * scale) % 1 + 1) % 1;
  const тон = (p, q, x) => {
    let v = x; if (v < 0) v += 1; if (v > 1) v -= 1;
    if (v < 1 / 6) return p + (q - p) * 6 * v;
    if (v < 1 / 2) return q;
    if (v < 2 / 3) return p + (q - p) * (2 / 3 - v) * 6;
    return p;
  };
  const q = l < 0.5 ? l * (1 + sat) : l + sat - l * sat;
  const p = 2 * l - q;
  const к = [тон(p, q, h + 1 / 3), тон(p, q, h), тон(p, q, h - 1 / 3)];
  const hex = (a) => '#' + a
    .map((v) => Math.max(0, Math.min(255, Math.round(v * 255))).toString(16).padStart(2, '0'))
    .join('');
  /* Светлота возвращается на место двоичным поиском множителя: поворот тона
     её сдвигает, а контракт этого не прощает. Двадцать четыре шага дают
     точность заведомо выше допуска. */
  const цель = luminance(base);
  let lo = 0; let hi = 3;
  for (let i = 0; i < 24; i++) {
    const m = (lo + hi) / 2;
    if (luminance(hex(к.map((v) => v * m))) < цель) lo = m; else hi = m;
  }
  return hex(к.map((v) => v * (lo + hi) / 2));
}

/** Взмах крыла спутника: 0…1, функция времени с фазой. Амплитуда жмётся
    `motionScale`, но НЕ в ноль — неисполняемый путь гниёт отдельно, а приз,
    исчезающий от системной настройки «меньше движения», это отказ, которого
    никто с настройкой не свяжет. */
export const buddyFlap = (t, scale = 1) =>
  0.5 + 0.5 * Math.sin(t * MOTION.buddyHz * 2 * Math.PI) * scale;

export function palmSway(t, phase = 0, scale = 1) {
  return MOTION.palmSwayM * scale * Math.sin(2 * Math.PI * (t * MOTION.palmSwayHz + phase));
}

/**
 * Мерцание далёкого предупреждения: 1 — ярко, 0 — приглушённо.
 *
 * Потолок, а не пол, в отличие от ringSquash: при «меньше движения» значение
 * прижимается к ЕДИНИЦЕ, то есть метка остаётся ровно яркой. Это не
 * украшение, а сообщение о решении — системная настройка не имеет права его
 * погасить, и погасить её не может по построению, а не по аккуратности.
 */
export function warnBlink(t, phase = 0, scale = 1) {
  const wave = 0.5 * (1 + Math.sin(2 * Math.PI * MOTION.warnBlinkHz * t + phase));
  return 1 - scale * wave;
}

/**
 * Прыжок бадника: доля полного размаха, от 0 (на земле) до 1 (в апогее).
 *
 * Форма — не синус. Синус половину времени держал бы существо ниже середины и
 * ни разу не дал бы ему постоять на земле, а прыжок читается именно паузой
 * между прыжками: отрицательную половину срезаем нулём, положительную поднимаем
 * степенью 0.65, и получается дуга с отдыхом внизу.
 *
 * Фаза обязана приходить от препятствия (`ob.at`), иначе все бадники в кадре
 * прыгают в унисон — и это читается не как живность, а как рябь кадра.
 *
 * `scale` жмёт АМПЛИТУДУ, а не частоту, и это не придирка: при «меньше
 * движения» бадник обязан прыгать ниже, а не медленнее. Колёсико жало частоту,
 * но оно и крутилось — у прыжка медленнее значит «висит в воздухе дольше».
 */
export function badnikJump(t, phase = 0, scale = 1) {
  const wave = Math.sin(2 * Math.PI * (t * MOTION.badnikJumpHz + phase));
  return scale * Math.max(0, wave) ** 0.65;
}

/**
 * Декорации по сторонам коридора.
 *
 * Стоят ЗА кромкой обрыва и выше неё. Иначе никак: стены рисуются сплошными
 * четырёхугольниками до тумана и всё за собой закрывают.
 *
 * Расставляются по времени, а не через равные метры: при смене скорости бега
 * уровень должен выглядеть так же густо, а метры этого не дают.
 *
 * Ни одна декорация не участвует в игре — не меняет `isSafe`, не попадает в
 * игровую полосу, не даёт очков. Проверяется группой «декорации».
 */
export function makeDecor({ durationS = 300, rng = Math.random, world = 'hills',
                            prizes = {}, speed = VIEW.speed } = {}) {
  /* Виды берутся из ЗОНЫ, в которую элемент попадает по времени, а зона — из
     той же `zoneAt`, по которой выбирается палитра кадра. Один источник: две
     копии расписания разошлись бы, и кактус оказался бы в зелёной зоне. */
  const pickFrom = (kinds, r) => {
    const total = kinds.reduce((sum, k) => sum + k.weight, 0);
    let acc = 0;
    for (const k of kinds) {
      acc += k.weight / total;
      if (r < acc) return k;
    }
    return kinds[kinds.length - 1];
  };

  const out = [];
  let t = DECOR.firstS;
  while (t < durationS) {
    const side = rng() < 0.5 ? -1 : 1;
    const zone = zoneAt(t, durationS, world);
    const k = pickFrom(kindsFor(zone, prizes), rng());
    out.push({
      kind: k.kind,
      /* Зона хранится у элемента, и рисуется он ЕЙ, а не палитрой кадра.

         Иначе на границе зон пять секунд видно обочину следующей зоны в цветах
         предыдущей: декорации видны до `far * 0.75`, то есть на 22 метра
         вперёд. С полем всё наоборот и лучше — следующая зона видна
         приближающейся, и это ровно то продвижение, ради которого зоны и
         сделаны. */
      zone,
      side,
      /* Отступ от кромки — свой у вида, общий как умолчание. Низкие виды
         стоят у самой кромки, иначе обрыв скрывает их целиком: разбор — у
         `decorYMask` и у `DECOR.outM`. */
      x: side * (HALF + (k.out ?? DECOR.outM)),
      y: WALL,                 // основание — ровно кромка обрыва
      h: k.height,
      /* Глубина = время × скорость забега. Расписание обочины задано в
         СЕКУНДАХ, поэтому её ритм на быстрых уровнях не меняется ни на
         секунду — меняется только шаг в метрах. */
      z: t * speed,
      at: t,
      phase: rng(),
    });
    // Разброс, но без провалов: равные промежутки превращают обочину в
    // штакетник, а слишком редкие — в пустое ущелье.
    t += DECOR.gapS * (0.75 + rng() * 0.5);
  }
  return out;
}

/** Где кончается препятствие и начинается проём. Связано с ходом камеры. */
export const obstacleEdge = (blockFrac = O.blockFrac) => Math.abs(camera(1, 0).x) * blockFrac;

/**
 * Глубина, на которой препятствие будет нарисовано, или `null` — не рисуется.
 *
 * Существует по той же причине, что `obstacleEdge`: число нужно в двух местах
 * сразу — отрисовке препятствия и разрезу прохода по кольцам, — и две копии
 * разошлись бы. Разошлись бы не абстрактно: кольцо начало бы просвечивать
 * сквозь плиту, то есть вернулся бы ровно тот дефект, из-за которого функция
 * и появилась.
 *
 * Заслоняющих поверхностей у препятствия две, и они взаимоисключающие по
 * времени: пока идёт телеграф (dt между visibleS и signalS) — метка у самой
 * дымки, дальше — лицо плиты. Линия по полу и последний зов сюда не входят:
 * они у самого глаза и ниже колец.
 *
 * Отсечение по ближней плоскости — не перестраховка: препятствие, уехавшее за
 * спину, проецируется с зажатой отрицательной глубиной и растягивается на
 * весь экран. Логика столкновения при этом продолжает работать, она смотрит
 * на время, а не на пиксели.
 */
/** Метры, ближе которых препятствие не рисуется. Выводятся из времени: при
    скорости 2.0 м/с это прежние 1.4 м. Единственный владелец — здесь. */
export function drawNear(speed = VIEW.speed) {
  return O.thickness + O.drawNearS * speed;
}

export function obstacleDepth(ob, elapsed, far = VIEW.fogDistance, speed = VIEW.speed) {
  if (!ob || ob.passed) return null;
  const dt = ob.at - elapsed;
  if (dt > O.signalS) return null;
  const zRaw = dt * speed;
  const ближе = drawNear(speed);
  if (zRaw + O.thickness < ближе) return null;
  return dt > O.visibleS ? far * 0.92 : Math.max(zRaw, ближе);
}

/** Глубина самого близкого нарисованного препятствия; Infinity — ни одного. */
export function nearestObstacleDepth(obstacles = [], elapsed = 0, far = VIEW.fogDistance,
  speed = VIEW.speed) {
  let cut = Infinity;
  for (const ob of obstacles) {
    const d = obstacleDepth(ob, elapsed, far, speed);
    if (d != null && d < cut) cut = d;
  }
  return cut;
}

/**
 * Где находятся глаза при таком смещении тела.
 *
 * Отдаётся наружу, чтобы сбор звёзд считался по тому же числу, по которому
 * рисуется картинка: две копии этой формулы разошлись бы, и звёзды начали бы
 * собираться не там, где их видно.
 */
export const cameraX = (u) => camera(u, 0).x;

/**
 * Экранный x ближайшего нарисованного угла обрыва при таком смещении тела.
 *
 * Существует ради одной проверки: при любом смещении левый обрыв обязан
 * доходить до x ≤ 0, правый — до x ≥ width. Иначе сбоку остаётся небо, и
 * выглядит это дыркой в мире. Числом это ловится, глазами — только на
 * телевизоре и только в крайнем положении, то есть почти никогда.
 */
export const wallNearEdgeX = (u, side = 1) =>
  project(side * HALF, 0, NEAR_DRAW, camera(u, 0)).sx;

/**
 * Дотянется ли ребёнок до звезды при таком смещении.
 *
 * Отдельной функцией, потому что это игровое правило, а не деталь
 * отрисовки: оно решает, надо ли вообще двигаться, чтобы собирать звёзды.
 * Проверяется в node.
 */
export const canReach = (starX, u) => Math.abs(starX - cameraX(u)) < VIEW.starReach;

/* Запас при сдвиге кольца за край запретного окна.

   Пятьдесят миллисекунд физического смысла не несут. Они нужны потому, что
   сложение секунд в double не даёт точного равенства: сдвиг на ровно
   starGuardS давал 1.5999999999999996 вместо 1.6, кольцо попадало ровно в
   точку, которую сдвиг и должен был покинуть, и правило нарушалось — тихо и
   на каждом уровне. Поймано тестом на сотне сеяных уровней. */
const STAR_SHIFT_EPS = 0.05;

/* Потолок сдвигов одного кольца. Четыре — это серия из четырёх препятствий
   одной стороны подряд, после которой кольцо той стороны пропускается, а не
   уезжает в конец забега. Число не из воздуха: длина серии препятствий 3–5
   (`seriesMin`/`seriesMax`), а стороны внутри серии не согласованы, так что
   четыре односторонних подряд — это уже редкий хвост распределения. */
const STAR_SHIFT_TRIES = 4;

/* Умолчания ступени для ряда колец.

   Четыре поля, и четвёртое — `breatherS` — приходит не из `VIEW`, а из
   `OBSTACLES`: передышка это свойство волны препятствий, а у ступеней 3 и 4 она
   ВЫВЕДЕНА из длины серии (`breatherFor`), не задана. Отдельный объект нужен
   вызовам без ступени — тестам и отладке. В игре `tune` всегда приходит из
   `tuneFor`, и забыть его там нельзя: тогда ступень 0 получила бы ряд ступеней
   1…4, то есть ровно то, что правка 11 октября и убирает. */
const STAR_TUNE = {
  starBesideObstacle: VIEW.starBesideObstacle,
  starSwitchScale: VIEW.starSwitchScale,
  starGapS: VIEW.starGapS,
  breatherS: O.breatherS,
  /* Словарь фраз ВНУТРИ серии. Прежде его выбирал `starBesideObstacle` —
     тот же флаг, что управляет запретным окном открытой стороны. Два разных
     решения на одном булеве нельзя было разложить по пяти уровням: третьему
     нужно кольцо у препятствия и спокойный ряд, пятому — беговой. */
  ringsInSeries: 'calm',
};

/**
 * Полуширина запретного окна для кольца на стороне `side` у препятствия `ob`.
 *
 * Одна функция на оба использования — и на приговор `starAllowed`, и на сдвиг
 * в `makeStars`. Две копии разошлись бы, и сдвиг ставил бы кольцо ровно в то
 * место, которое должен был покинуть: ровно так дефект и выглядел.
 *
 * Окон ТРИ, и разной ширины, потому что они про разные вещи:
 *
 *   duck, `starGuardS` — нельзя ничего. Под верхнее препятствие уходят
 *     приседом, а присед не совмещается ни с наклоном, ни с возвратом в центр.
 *
 *   открытая сторона (`−ob.side`), окна НЕТ вовсе — там уклонение и сбор
 *     совпадают, и кольцо становится наградой за правильный уход.
 *
 *   центр у бокового, `starGuardS` — в уклонении до него не дотянуться, это и
 *     есть смысл `starReach`.
 *
 *   ЗАКРЫТАЯ сторона (`ob.side`), `starSwitchS` — и это главное число здесь.
 *     Кольцо там требует не уклонения, а ПЕРЕХОДА через поле: препятствие
 *     согнало ребёнка на дорожку −1, кольцо висит на +2, это три дорожки.
 *     Раньше окно было `starGuardS`, и сдвиг ставил кольцо на его кромку —
 *     1.65 с, то есть вдвое меньше измеренного времени перехода (`starSwitchS`
 *     3.0 с на полный размах, около 0.75 с на дорожку). Между двумя кольцами
 *     на разных боках `makeStars` отводит честные 3.0 с, а после препятствия
 *     отводил 1.65: два числа про одно и то же, вдвое разные, в одном файле.
 *
 * Чем это обошлось. Заказчик 11 октября: «препятствия по бокам снова стали
 * накладываться на призовые предметы… физически времени может не хватить,
 * чтобы собрать кольцо и не врезаться». По журналу того дня — 21 кольцо из 145
 * требовало невозможного перехода, и ровно это дало ОБА задетых препятствия
 * за сессию: за первым стояло кольцо закрытой стороны в 1.04–1.64 с, и ребёнок
 * уже шёл за ним, когда получил удар. Это же объясняет и перебег за край поля:
 * чтобы успеть, он разгонялся до предела и проезжал дорожку ±2 по инерции.
 *
 * `isSafe` в js/level.js говорит, что side > 0 закрывает +x — значит открыта
 * сторона −ob.side.
 */
export function starWindow(side, ob, tune = STAR_TUNE) {
  if (ob.kind === 'duck') return VIEW.starGuardS;
  /* Открытая сторона: на ступени 0 она тоже под запретом, и это требование
     заказчика от 11 октября — «не должно быть резких обходов препятствий,
     совмещённых со сбором кольца до препятствия или сразу после него».

     Награда за правильный уход — хорошая мысль, но она требует делать две
     вещи сразу, а ступень 0 это первая игра ребёнка. На ступенях выше кольцо
     открытой стороны остаётся наградой, как и было. */
  if (side === -ob.side) return tune.starBesideObstacle ? 0 : VIEW.starGuardS;
  if (side === 0) return VIEW.starGuardS;
  return VIEW.starSwitchS;
}

/** Можно ли поставить кольцо в секунду `t` на сторону `side`. */
export function starAllowed(t, side, obstacles, tune = STAR_TUNE) {
  for (const ob of obstacles) {
    const окно = starWindow(side, ob, tune);
    if (окно > 0 && Math.abs(t - ob.at) <= окно) return false;
  }
  return true;
}

/**
 * Раскладка звёзд.
 *
 * Висят в боковых третях коридора: главная ценность игры в том, что ребёнок
 * двигается, и собирать их, стоя посередине, не должно получаться.
 *
 * Расставляются по ВРЕМЕНИ, а не через равные метры. Расстояние ничего не
 * говорит о том, успеет ли ребёнок: на переход из левого положения в правое
 * нужны секунды, и нужны они одни и те же при любой скорости бега. Поэтому
 * промежуток перед звездой на другой стороне больше — ровно на цену перехода.
 *
 * Три подряд на одной стороне не ставим: смысл игры в том, что ребёнок
 * двигается, а не стоит, подобрав удобное положение.
 *
 * `obstacles` обязателен для настоящего уровня: без него кольца снова встанут
 * вплотную к препятствиям. Умолчание — пустой список — существует для тестов
 * и для сравнения «сколько колец было бы без развязки».
 */
export function makeStars({ durationS = 300, obstacles = [], rng = Math.random,
                            tune = STAR_TUNE, speed = tune.speed || VIEW.speed } = {}) {
  /* Стороны набираются ФРАЗАМИ, а не броском на каждое кольцо.

     Зачем. Независимые броски дают ряд без замысла: собирать приходится то,
     что попалось. Фраза — это узнаваемый ход («двойка на одной стороне»,
     «слалом», «через середину»), и ряд начинает читаться как сделанный, а не
     высыпанный.

     Чего фраза НЕ делает, и это важнее: она не меняет ни геометрию, ни
     плотность. Узор, который хотелось нарисовать сначала — дуга, цепочка через
     коридор, — физически невозможен, и границы здесь не наши:
       • смена стороны стоит `starSwitchS` 3.0 с — это ИЗМЕРЕННОЕ время
         перехода ребёнка через коридор, а не настройка;
       • положений по x ровно три (±HALF*starX и 0): промежуточное может
         оказаться достижимым стоя, и ровно из-за этого `starX` с `starReach`
         однажды пересчитывали;
       • глубина жёстко связана со временем (`z === at * speed`), так что гнуть
         узор можно только по x.
     Поэтому фраза живёт на той же решётке: те же три положения, те же два
     промежутка. Меняется порядок, а не физика.

     Согласование с волнами препятствий — здесь и живёт ощущение ритма. В серии
     препятствий идут спокойные фразы, в передышке — беговые: ребёнок и так
     занят уклонением, и давать ему слалом поверх серии значило бы требовать
     двух дел сразу. `obstacles` для этого уже есть — тот же список, по которому
     работает запретное окно. */

  // Местный разнос препятствий вокруг секунды t: по нему видно, серия сейчас
  // или передышка. Края забега считаем передышкой — там препятствий нет.
  const вПередышке = (t) => {
    if (!obstacles.length) return true;
    let prev = null;
    for (const ob of obstacles) {
      // Передышка берётся у СТУПЕНИ, а не из конфига: у ступеней 3 и 4 серия
      // длиннее, и передышка выведена из неё (`breatherFor`). С конфигурационным
      // числом волны этих ступеней читались бы неверно.
      if (ob.at > t) return prev === null ? true : ob.at - prev >= tune.breatherS;
      prev = ob.at;
    }
    return true;
  };

  /* Словарь фраз. Каждая — последовательность сторон; промежутки из неё
     выводятся ниже сами, по тому же правилу «смена стороны стоит дороже».
     `s` — ведущая сторона фразы. */
  const СПОКОЙНЫЕ = [
    (s) => [s, s],        // двойка на одной стороне
    () => [0, 0],         // две по середине — передышка для ног
    (s) => [s, 0],        // сторона и возврат в середину
  ];
  /* Ступень 0, внутри серии препятствий — только середина. Требование
     заказчика «никаких обходов препятствия, совмещённых со сбором кольца»
     внутри серии означает ровно это: боковому кольцу там попросту негде
     встать, препятствия идут через 5.5–6.1 с, а запретные окна занимают 3.2 с
     вокруг каждого. Ритм выходит простой и читаемый — уйти, вернуться в
     середину, забрать кольцо, уйти снова. */
  const В_СЕРИИ = [
    () => [0, 0],
  ];
  const БЕГОВЫЕ = [
    (s) => [s, -s, s],    // слалом
    (s) => [s, 0, -s],    // через середину
    (s) => [s, -s],       // простой перекид
  ];

  /* Фразы набираются ПО ХОДУ расстановки, а не заранее в массив, и это
     разворот прежнего устройства.

     Прежде ряд сторон строился целиком, а «серия сейчас или передышка»
     спрашивалось по ОЦЕНКЕ времени (`длина фразы × starSwitchS`). Оценка
     держалась, пока сдвиг от препятствия был маленьким — окно было одно и
     узкое, 1.65 с. С широким окном закрытой стороны сдвиги выросли втрое, и
     часы выбора фразы разошлись с часами расстановки: фраза выбиралась для
     одной секунды, а кольца ложились в совсем другую. Снаружи это ровно то,
     что согласование фраз с волнами и обещает не допускать — замерено: смен
     стороны стало БОЛЬШЕ в серии (30%), чем в передышке (21%), то есть ребёнку
     давали слалом поверх уклонения.

     Ленивая выдача убирает расхождение по построению: фраза спрашивается в тот
     момент, когда её первое кольцо уже знает своё место. Запас в две стороны
     нужен для промежутка — цена шага зависит от того, меняется ли сторона у
     СЛЕДУЮЩЕГО кольца. */
  let ведущая = rng() < 0.5 ? -1 : 1;
  const очередь = [];

  /* Состояние ряда: последняя ПОСТАВЛЕННАЯ сторона и длина её серии. Правило
     «не больше двух подряд на одной стороне» применяется при выдаче в очередь,
     а не при снятии с неё, и это не вкусовщина: цена промежутка зависит от
     того, меняется ли сторона у СЛЕДУЮЩЕГО кольца, то есть решение читает
     `очередь[0]`. Правь сторону после — и промежуток окажется посчитан для
     одной стороны, а кольцо встанет другой; замерено 79 таких пар на ступенях
     1…4 и 164 на нулевой. Прежний код этой ошибки не допускал случайно: он
     правил весь массив ДО расстановки.

     Хвост очереди поэтому ведётся отдельно от поставленного и при опустевшей
     очереди берётся у него — иначе брошенная фраза (см. ниже) теряла бы счёт,
     и три кольца подряд на одном боку проскочили бы. */
  let последняя = null;
  let подрядПоставленных = 0;
  let хвост = null;
  let подрядХвоста = 0;
  let фразаВПередышке = null;

  const долить = (t) => {
    if (!очередь.length) { хвост = последняя; подрядХвоста = подрядПоставленных; }
    while (!очередь.length) {
      фразаВПередышке = вПередышке(t);
      const вСерии = tune.ringsInSeries ?? 'calm';
      const набор = фразаВПередышке || вСерии === 'run' ? БЕГОВЫЕ
        : (вСерии === 'calm' ? СПОКОЙНЫЕ : В_СЕРИИ);
      for (let side of набор[Math.floor(rng() * набор.length)](ведущая)) {
        if (side !== 0 && side === хвост && подрядХвоста >= 2) side = -side;
        подрядХвоста = side !== 0 && side === хвост ? подрядХвоста + 1 : 1;
        хвост = side;
        очередь.push(side);
      }
      // Следующая фраза ведёт в другую сторону: иначе двойка за двойкой дала бы
      // четыре кольца на одном боку, то есть ребёнка, стоящего на месте.
      ведущая = -ведущая;
    }
  };

  /* ВОЛНА СИЛЬНЕЕ ФРАЗЫ: фраза, выбранная для другой полосы волны, бросается.

     Фраза длиной 2–3 кольца занимает до девяти секунд (переход на ступени 0
     стоит 4.5 с), а полосы — серия 5.5 и передышка 8.8–10.1 с. То есть фраза
     НЕИЗБЕЖНО переливается через край полосы, и переливается в обе стороны:
     беговая приносит слалом в серию, спокойная уносит середину в передышку.
     Замерено на сотне сеяных уровней — сначала смен в серии оказалось 21%
     против 7% в передышке (ровно наоборот замыслу), а после запрета только
     одной из двух протечек передышка осела до 1.1%.

     Признак один и тот же в обе стороны: полоса, для которой фраза выбрана, не
     совпала с полосой, в которую кольцо ложится. Замысел предлагает фраза, а
     решает волна. */
  const переспросить = (t) => {
    долить(t);
    if (фразаВПередышке === вПередышке(t)) return;
    очередь.length = 0;
    долить(t);
  };

  /* Годится ли МЕСТО этой стороне. Два условия, и второе — только ступени 0.

     Запретные окна (`starAllowed`) — про препятствие рядом. Полоса волны — про
     то, что боковое кольцо внутри серии на нулевой ступени не ставится вовсе:
     требование заказчика звучит как «никаких обходов, совмещённых со сбором»,
     а внутри серии любое место рядом с препятствием.

     Проверять это после сдвига ОБЯЗАТЕЛЬНО, а не только при выборе стороны:
     сторона выбирается для одной секунды, а сдвиг от окна уносит кольцо на три
     секунды вперёд — замерено, что так в серию попадало 15.3% боковых колец
     при заявленном нуле. */
  const годится = (t, side) => starAllowed(t, side, obstacles, tune)
    && ((tune.ringsInSeries ?? 'calm') !== 'centre' || side === 0 || вПередышке(t));

  /* Отодвинуть кольцо от запретных окон. СДВИГ, а не выброс: ряд колец не
     должен редеть там, где и без того напряжённо.

     Сдвигов может понадобиться несколько, и это следствие широкого окна
     закрытой стороны. Прежде окно было одно (2 × starGuardS = 3.2 с),
     препятствия идут не чаще minGapS 5.5 с, и за концом одного окна следующее
     ещё не начиналось — отсюда и прежнее «одного сдвига достаточно всегда». У
     закрытой стороны окно 2 × starSwitchS = 6.0 с, то есть ШИРЕ разноса
     препятствий: два препятствия одной стороны подряд перекрывают свои окна, и
     кольцо той стороны между ними не поместится никуда.

     Поэтому цикл с потолком. Потолок обязателен: без него серия односторонних
     препятствий выталкивала бы кольцо до конца забега шагами по три секунды,
     то есть ряд вырождался бы молча. Связь minGapS > 2 × starGuardS при этом
     остаётся — она держит окна приседа и центра, где прежнее «за один шаг»
     по-прежнему верно. */
  const отодвинуть = (t0, side) => {
    let t = t0;
    let сдвигов = 0;
    while (!starAllowed(t, side, obstacles, tune) && сдвигов < STAR_SHIFT_TRIES) {
      // За конец самого позднего из мешающих окон. Окно берётся у той же
      // функции, что и приговор: иначе сдвиг целил бы не туда, откуда уходит.
      t = obstacles.reduce((max, ob) => {
        const окно = starWindow(side, ob, tune);
        return окно > 0 && Math.abs(t - ob.at) <= окно
          ? Math.max(max, ob.at + окно + STAR_SHIFT_EPS) : max;
      }, t);
      сдвигов++;
    }
    return t;
  };

  const stars = [];
  let t = VIEW.starFirstS;

  // Когда можно будет поставить следующее большое кольцо. Первое не раньше
  // периода: забег начинается с обычных, иначе редкое событие открывает забег.
  let следующееБольшое = VIEW.starFirstS + VIEW.bigStarEveryS * (0.75 + rng() * 0.5);
  let предыдущее = null;
  while (t < durationS) {
    /* Промежуток отрабатывается ПЕРЕД кольцом, а не после предыдущего, и цена
       считается по ФАКТИЧЕСКИМ сторонам. Прежде цена бралась по догадке о
       следующей стороне (`очередь[0]`), а догадку потом мог отменить
       пересмотр фразы — и промежуток оказывался посчитан для одной стороны, а
       кольцо вставало другой. Замерено 258 таких пар на сотне уровней.
       Зависимость тут круговая по природе — цена зависит от стороны, сторона
       от времени, время от цены, — и разрывается она так: сперва минимальная
       цена, по ней выбирается сторона, и только потом доплата за переход. */
    let side = null;
    let попыток = 0;
    for (;;) {
      if (предыдущее !== null) t = Math.max(t, предыдущее.t + tune.starGapS);
      переспросить(t);
      side = очередь[0];
      if (предыдущее !== null && side !== 0 && предыдущее.side !== 0 && side !== предыдущее.side) {
        t = Math.max(t, предыдущее.t + VIEW.starSwitchS * tune.starSwitchScale);
      }
      t = отодвинуть(t, side);
      if (t >= durationS || годится(t, side) || ++попыток >= 2) break;
      // Сторона выбрана не для этого места — выбрать заново ЗДЕСЬ. Двух
      // попыток хватает: второй выбор идёт по той полосе, куда кольцо уже
      // сдвинуто, а в серии словарь отдаёт середину, которой волна не мешает.
      очередь.length = 0;
    }
    if (t >= durationS) break;
    /* Место так и не подошло — кольцо ПРОПУСКАЕТСЯ, но время обязано уехать
       вперёд, и это не перестраховка. Сторона остаётся в очереди (её ещё
       предстоит поставить), `предыдущее` не менялось, а `Math.max` с его
       временем ничего не прибавит — то есть без явного шага цикл повторил бы
       ту же секунду навсегда. Генерация расписания идёт в начале забега, так
       что ценой была бы не просадка кадра, а экран, который не придёт никогда:
       тот же класс отказа, что калибровка без результата. На сотне сеяных
       уровней эта ветка не срабатывает ни разу, и именно поэтому её нельзя
       оставлять без гарантии — проверить её журналом не выйдет. */
    if (!годится(t, side)) { t += tune.starGapS; continue; }
    очередь.shift();
    /* Большое кольцо — по ПРОШЕДШЕМУ ВРЕМЕНИ, а не броском на каждое кольцо.

       Сначала здесь стояла вероятность, выведенная из плотности ряда
       (`starGapS / bigStarEveryS`), и она врала: заявленные 45 секунд давали
       фактические сто. Плотность ряда не равна `starGapS` — смена стороны
       стоит дороже, да и обстановка сдвигает кольца от препятствий, — а треть
       колец центральные и большими не становятся вовсе. Число в конфиге,
       разошедшееся с поведением втрое, хуже отсутствующего.

       Поэтому период стал периодом: большое кольцо ставится, когда с прошлого
       прошло не меньше `bigStarEveryS` с разбросом. Разброс обязателен — ровно
       по 45 секунд было бы метрономом, то есть той же бедой, от которой
       избавлялись у препятствий.

       Центральное большим не делается: большое обязано требовать полного
       размаха, иначе его ценность достаётся тому, кто стоит в середине. */
    const большое = side !== 0 && t - следующееБольшое >= 0;
    /* Срок следующего отсчитывается от СРОКА предыдущего, а не от места, где
       большое кольцо удалось поставить. Разница в том, копится ли ожидание.

       Большое не бывает центральным, значит оно ждёт бокового кольца, а на
       ступени 0 боковые живут только в передышках — ожидание выходит до десяти
       секунд. При отсчёте от места каждое такое ожидание прибавлялось к
       следующему сроку, и заявленные 45 с превращались в замеренные 55.5.
       Расписание же их не копит: опоздавшее кольцо не сдвигает всё расписание
       вперёд. `Math.max(…, t)` нужен на случай, когда опоздание переросло целый
       период: тогда следующее большое берёт первое же подходящее кольцо, а не
       назначается в прошлое. */
    if (большое) {
      /* Пол разброса считается от МЕСТА, а не от срока: расписание не должно
         копить ожидание, но и ставить два больших кольца вплотную оно не
         вправе. Без этого пола догонявшее расписание сводило их до 25.7 с при
         заявленном минимуме 45 × 0.75 — поймано проверкой. */
      следующееБольшое = Math.max(
        следующееБольшое + VIEW.bigStarEveryS * (0.75 + rng() * 0.5),
        t + VIEW.bigStarEveryS * 0.75,
      );
    }
    stars.push({
      x: side * HALF * VIEW.starX,
      z: t * speed,
      side,
      at: t,
      taken: false,
      // Вес есть всегда: `undefined` ушёл бы делителем в счёт очков.
      worth: большое ? VIEW.bigStarWorth : 1,
    });
    подрядПоставленных = side !== 0 && side === последняя ? подрядПоставленных + 1 : 1;
    последняя = side;
    предыдущее = { t, side };
  }
  return stars;
}
