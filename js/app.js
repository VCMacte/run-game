/* Запуск забега. Общий для кнопки меню и для «ещё раз» на финише: две
   копии разошлись бы, и повторный забег однажды поехал бы с другими
   настройками, чем первый.

   Через стадию установки штатива проходят ОБА пути, хотя у train.start есть
   skipSetup. Это не недосмотр: skipSetup уходит сразу в забег, минуя next(),
   то есть минуя isStale, — а между двумя забегами ребёнок как раз ходит к
   телефону и обратно, и штатив сбивают именно там. */
async function startRun() {
  // Новый забег — новый результат: прошлая запись в таблицу не должна
  // блокировать запись следующей.
  recorded = false;
  recordError = false;
  const { wantedSource } = await import('./pose.js');
  const want = wantedSource();

  if (want.source === 'camera') {
    // Комплект проверяется до запуска. Наполовину закэшированная модель не
    // даёт ошибки сети — она даёт молчаливый abort внутри wasm, и по симптому
    // это неотличимо от дефекта кода.
    const { checkVendor } = await import('./vendor.js');
    const v = await checkVendor();
    log.event('offline.check', {
      /* `caches`, а не `cache`: проверка перестала выбирать кэш по имени и
         смотрит все сразу, а имя поля осталось прежним — и в журнал
         записывался `null` при каждом запуске. Ровно та строка, которая нужна
         теперь, когда кэша два и разбирается гипотеза про вытеснение. */
      ok: v.ok, skipped: v.skipped || null, caches: v.caches || null,
      missing: v.missing || [], gone: v.gone === true,
    });
    /* Пропажа всего комплекта забег НЕ отменяет, и это не снисходительность.
       Страница только что загрузилась, значит сеть есть и распознавание
       поедет из неё; экран отказа здесь означал бы потерянный забег вместо
       починки. Добирает комплект repairOffline() — в меню, где ничего другого
       не работает, а не посреди открытия камеры и прогрева модели. */
    if (!v.ok && !v.gone) {
      // Перечисляем, чего именно не хватает: «что-то не скачалось» — ответ,
      // с которым нельзя ничего сделать, а имена файлов попадут и в журнал.
      showSoon('Нужен интернет один раз',
        'Не хватает файлов распознавания движений: ' + v.missing.join(', ')
        + '. Подключитесь к сети, откройте приложение один раз и дождитесь загрузки — '
        + 'дальше оно работает без сети.');
      return;
    }
  }

  const { createTraining } = await import('./train.js');
  await training?.stop();
  show('run');
  runsInRow++;
  /* Мир выбирается в меню, но решение «можно ли в него» принимается здесь, в
     момент старта: между выбором и забегом могла измениться копилка (сменили
     игрока, сбросили профиль), а запирать ребёнка в недоступном мире нельзя.
     Молча: приговор не вправе наказывать за то, чего игра не показала.

     Набор призов фиксируется тем же разом и едет параметром. Ни вид, ни звук
     не знают про хранилище и не должны: ровно поэтому их можно считать из
     node, а tools/replay.mjs — подать любой набор. */
  const bankNow = players.bank();
  const хочет = players.world();
  const world = worldsAt(bankNow).includes(хочет) && worldReady(хочет) ? хочет : 'hills';

  training = createTraining({
    canvas: $('runCanvas'),
    video: $('runVideo'),
    skeleton: $('runSkeleton'),
    field: $('runField'),
    fieldMark: $('runFieldMark'),
    onHud: renderRunHud,
    world,
    level: levelAt(bankNow),
    prizes: unlockedAt(bankNow),
  });
  renderRunHud({ stage: 'setup', score: 0 });
  await training.start({ source: want.source, script: want.script });
}

