/* Добор вытесненного офлайн-комплекта.

   Чинит то, что описано в sw.js у `prime`: кэш вытеснен, регистрация жива,
   `install` на неизменных байтах не повторится. Просьба идёт активному
   воркеру через MessageChannel, потому что нужен ИСХОД — просьба без
   последствия в журнале неотличима от «добрали» и от «сеть кончилась».

   Три решения, и каждое платит за себя:

   • зовётся из пути загрузки, то есть в МЕНЮ. Докачка 17.5 МБ посреди забега —
     это кадры ребёнка, а правило проекта «игра важнее»;
   • срок 60 секунд: по телефонной связи 8.6 МБ в сжатом виде столько и едут.
     `withTimeout` обязателен по тому же правилу, что у разрешений — любое
     обещание может не завершиться никогда;
   • спрашиваем состояние сами, а не доверяем воркеру решать: `prime` атомарен
     и дорог, и звать его на каждом открытии приложения значило бы условный
     запрос к GitHub Pages по всем 36 файлам без повода.

   Спрашиваем при этом `checkVendor()`, а не наличие имени `run-*`, и это не
   придирка. Имя кэша появляется в `caches.open()` ДО того, как в него что-то
   положили, поэтому оборванная посреди докачки установка оставляет пустой
   `run-vendor-…` — тот самый случай «сеть кончилась МЕЖДУ двумя addAll», ради
   которого `checkVendor` и написан. По имени он выглядел бы как здоровый, и
   починка не состоялась бы: ребёнок остался бы на экране «нужен интернет один
   раз» до следующей сборки, хотя одно сообщение воркеру всё чинит. */
async function repairOffline() {
  // Кэшей тут нет вовсе (localhost, запрет данных) — чинить нечего, но
  // занятое место спросить всё равно надо: без него журнал молчит о хранилище.
  if (!self.caches || !navigator.serviceWorker) { logStorageUsage(); return; }
  const { checkVendor } = await import('./vendor.js');
  /* Отказ проверки гасится ЗДЕСЬ, до `.then`, а не хвостовым `.catch`. Иначе
     замер занятого места пришлось бы звать в двух местах — и любая ошибка
     ПОСЛЕ него писала бы в журнал второе событие `storage` с другим числом.
     Разбор берёт последнее, так что сессия молча получила бы не тот замер. */
  Promise.resolve(checkVendor()).catch(() => ({ ok: false, unknown: true })).then(async (v) => {
    /* Занятое место — здесь, и `v.ok` это ровно то знание, которого не хватало
       замеру на 11-й миллисекунде: комплект цел, значит ноль невозможен.
       Упавшая проверка даёт `ok: false`, то есть без перечитывания нуля — про
       хранилище спросить всё равно надо, а утверждать нечего. */
    logStorageUsage(v.ok);
    if (v.ok) return;
    // Проверка упала — чинить по её молчанию нельзя: `prime` атомарен и дорог.
    if (v.unknown) return;

    const reg = await withTimeout(navigator.serviceWorker.ready, 5000, 'sw.ready').catch(() => null);
    const worker = reg?.active || navigator.serviceWorker.controller;
    // Воркера нет вовсе — значит это и правда первое открытие: кэш наполнит
    // `install`, и просить некого.
    if (!worker) {
      log.event('offline.repair', { asked: false, ok: null, missing: [], ms: 0 });
      return;
    }

    const t0 = performance.now();
    const answer = new Promise((done) => {
      const ch = new MessageChannel();
      ch.port1.onmessage = (e) => done(e.data);
      worker.postMessage({ type: 'prime' }, [ch.port2]);
    });
    // Без `why`: исход пишется событием `offline.repair` ниже.
    withTimeout(answer, 60000)
      .then((r) => log.event('offline.repair', {
        asked: true,
        ok: r?.ok === true,
        missing: r?.missing || [],
        ms: Math.round(performance.now() - t0),
      }))
      .catch(() => log.event('offline.repair', {
        asked: true, ok: null, missing: [], ms: Math.round(performance.now() - t0),
      }));
  // Хвостовой `.catch` МОЛЧИТ нарочно: отказ проверки уже обработан выше, а
  // здесь остаётся только то, что упало после замера хранилища.
  }).catch(() => {});
}

