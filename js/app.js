/* Просьба не вытеснять наши данные.

   Повод: заказчик заметил, что игрок и рекорды сбрасываются между сеансами.
   Наш код их не чистит — в js/players.js нет ни `removeItem`, ни `clear`, — а
   постоянное хранилище не запрашивалось нигде. При этом приложение занимает
   порядка 42 МБ: 17.5 МБ офлайн-кэша плюс потолок журнала 25 МБ. Хранилище,
   не помеченное постоянным, браузер вправе вытеснить ЦЕЛИКОМ, одним origin, —
   и вместе с кэшем уедет `localStorage`, то есть рекорды и калибровка. Та же
   причина объяснила бы и «игра опять долго грузится»: после вытеснения
   MediaPipe качается заново.

   Это гипотеза, и подтверждать её будет журнал (см. logStorageState и
   logStorageUsage ниже), а не рассуждение. Но сама просьба безусловно полезна
   и ничего не стоит.

   Стоит она здесь, в обработчике нажатия, рядом с полным экраном и ориентацией,
   по той же причине: привилегированные вызовы делаются одним жестом. Диалога
   пользователю не будет — Chrome на Android решает сам, по установке и
   вовлечённости, и молча отказывает, если не считает нужным.

   `withTimeout` обязателен: правило проекта — любое обещание разрешений может
   не завершиться никогда, и без него приложение зависало на экране загрузки. */
function askPersistentStorage() {
  const ask = navigator.storage?.persist?.();
  if (!ask) return;
  // Без `why`: исход пишется следующей же строкой, своим событием.
  withTimeout(ask, 3000)
    .then((granted) => log.event('storage.persist', { granted: granted === true }))
    .catch(() => log.event('storage.persist', { granted: null }));
}

/* Вытесняемы ли мы — в журнал, один раз за сессию и ДО первого нажатия.

   Без этого числа «рекорды пропали» остаётся догадкой. Череда сессий с
   `persisted:false` будет значить, что вытеснение и есть причина, и тогда
   резать надо потолок журнала; обратное — что причину надо искать в другом
   месте, а потолок трогать незачем.

   Спрашивается раньше просьбы из обработчика старта намеренно: нас интересует,
   каким хранилище пришло с прошлого сеанса, а просьба это состояние меняет.

   Тихо при любой ошибке: журнал не имеет права ронять игру, тем более на
   старте. */
function logStorageState() {
  navigator.storage?.persisted?.()
    .then((on) => log.event('storage.state', { persisted: on === true }))
    .catch(() => {});
}

/* А сколько ЗАНЯТО — отдельным событием и отдельным временем, и это разворот.

   Стояло оно рядом с `persisted`, то есть на 11-й миллисекунде жизни
   страницы, и 11 октября соврало ровно про то, ради чего написано: сказало
   «занято 0 МБ из 10240», а через три минуты `offline.check` в той же сессии
   нашёл оба кэша на месте, причём десятью минутами раньше, на том же
   устройстве и той же сборке, занято было 23 МБ. Вытеснения между ними не
   было — сборка та же, отпечаток vendor тот же. Квота выдаёт обман с головой:
   10240 вместо 10263, то есть ровно на те 23 МБ меньше.

   Снаружи это читается как подтверждение гипотезы о вытеснении, которого не
   случилось, — худший вид ошибки в журнале, потому что он не ломает игру и
   уводит разбор в сторону.

   Поэтому два изменения. Замер идёт ПОСЛЕ того, как выяснено состояние
   офлайн-комплекта (единственный момент сеанса, когда про хранилище вообще
   есть что сказать). И ноль, противоречащий живому комплекту, перечитывается:
   в одном MediaPipe 17.5 МБ, так что «комплект цел и занято 0» — это не
   вытеснение, а ответ, снятый слишком рано. Сколько попыток ушло, едет в
   журнал полем `tries`: без него починка неотличима от того, что всё
   получилось с первого раза.

   Отличать «цел» от «первого запуска» умеет только `checkVendor` — по тому же
   признаку, по которому он отличает вытеснение от первого открытия. Поэтому
   решение приходит сюда параметром, а не выясняется здесь заново. */
const USAGE_TRIES = 4;
const USAGE_STEP_MS = 500;

function logStorageUsage(kitPresent = false) {
  if (!navigator.storage?.estimate) return;
  const read = (n) => navigator.storage.estimate().then((e) => {
    const usage = e?.usage ?? null;
    const quota = e?.quota ?? null;
    if (kitPresent && !usage && n < USAGE_TRIES) {
      return new Promise((go) => setTimeout(go, USAGE_STEP_MS)).then(() => read(n + 1));
    }
    log.event('storage', {
      usageMb: usage == null ? null : Math.round(usage / 1048576),
      quotaMb: quota == null ? null : Math.round(quota / 1048576),
      pct: usage == null || !quota ? null : Math.round((usage / quota) * 100),
      tries: n,
    });
  });
  read(1).catch(() => {});
}

