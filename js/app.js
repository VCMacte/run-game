const BACK = {};

/* Подтверждение вторым нажатием.

   Нужно там, где одно касание уносит то, чего не вернуть: пятиминутный забег и
   экран результата с ещё не записанным рекордом. Ключ отдельный у каждого
   случая — иначе нажатие на одном экране засчиталось бы за первое на другом.

   Начальное значение −Infinity, а не 0: `performance.now()` отсчитывается от
   загрузки страницы, и ноль — это настоящая отметка в первые две секунды
   жизни. С нулём первое же нажатие на калитке считалось бы вторым. */
const CONFIRM_MS = 2000;
let confirmKey = null;
let confirmAt = -Infinity;

function confirmTwice(key) {
  const now = performance.now();
  const twice = key === confirmKey && now - confirmAt < CONFIRM_MS;
  confirmKey = twice ? null : key;
  confirmAt = twice ? -Infinity : now;
  return twice;
}

/* Кнопка «Назад» телефона: одна запись-ловушка в истории, и всё.

   Приложение одностраничное, адрес не меняется, и своей истории у него нет
   вовсе — поэтому до сих пор «Назад» уводил из игры на прошлый адрес вкладки.
   Самих экранов в историю складывать не стали: переходы между ними бывают
   условными и возвратными, и история начала бы расходиться с деревом экранов —
   «Назад» то открывал бы заново только что закрытое, то пропускал бы шаг.

   Поэтому история используется не как память, а как СИГНАЛ. Сверху лежит одна
   лишняя запись; «Назад» её съедает, мы спрашиваем у экрана его собственный
   выход и кладём ловушку обратно. Глубина истории постоянная, а куда вести —
   решает `BACK`, то есть то же самое, что и кнопка на экране.

   Ловушка возвращается ВСЕГДА и первым делом, даже на корне. Иначе она
   однажды кончается и больше не возвращается: во вкладке, открытой с нуля,
   уходить некуда, `history.back()` с корня не делает ничего — а ловушка уже
   съедена, и «Назад» мёртв до перезагрузки на ВСЕХ экранах. Поймано на
   разборе этой же правки.

   Уход из приложения — два нажатия на корне. И он получается только во
   вкладке браузера: у установленного приложения история начинается с нашей же
   страницы, уходить некуда, и `history.go(-2)` браузер просто не исполнит.
   Там «Назад» на главном меню не делает ничего — закрыть установленное
   приложение из своего же кода нечем, такого API нет. */
function keepBackButton() {
  history.pushState({ nav: 'trap' }, '');
  addEventListener('popstate', () => {
    const act = BACK[currentScreen];
    log.event('nav.back', { from: currentScreen, handled: !!act });
    // Первым делом и безусловно: что бы ни случилось ниже, «Назад» остаётся
    // живым. Уход из приложения перешагнёт эту запись сам.
    history.pushState({ nav: 'trap' }, '');
    if (act) { act(); return; }
    // Через ловушку и через саму страницу — то есть на прошлый адрес вкладки.
    if (confirmTwice('root')) history.go(-2);
  });
}

function show(name) {
  currentScreen = name;
  for (const id of SCREENS) $(id).hidden = id !== name;
  if (!ADULT.has(name)) previous = name;
  /* Полный экран запрашивается перед блокировкой ориентации, а не параллельно:
     на Android lock() без полноэкранного режима просто отказывает, и забег
     открывается горизонтальной вёрсткой внутри вертикального экрана. Если
     откажет и так — вместо игры покажется подсказка повернуть телефон, она на
     CSS и от успеха блокировки не зависит. */
  /* `.catch` обязателен, и не ради тишины в консоли. «Назад» телефона не даёт
     жеста пользователя, а без жеста `requestFullscreen()` отклоняется — и
     вместе с ним не исполнялся бы `.then`, то есть блокировка ориентации. Это
     ровно та беда, про которую написано выше: возврат на забег кнопкой
     «Назад» открывал бы его ВЕРТИКАЛЬНОЙ вёрсткой. Поэтому ориентация
     запрашивается в любом случае — у установленного приложения полный экран и
     не нужен, там это режим окна. */
  requestFullscreen()
    .catch(() => {})
    .then(() => lockOrientation(ORIENTATION[name] || 'portrait'))
    .catch(() => {});
  log.event('screen', { name });
  // Возврат в игру из родительского меню: показать то, что настроили.
  if (name === 'run') refreshHud();
  // Ушли с экрана забега — экран телефона снова нужен: меню держат в руке.
  if (name !== 'run') applyScreenPolicy(false);
}

