// Тихая адаптация сложности: ступень игрока и правило перехода.
//
// Чистая арифметика, как и всё, что можно проверить без браузера. Хранилище
// живёт в js/players.js, игра — в js/train.js; здесь только два решения:
// какими числами играть на ступени N и куда ступень поедет после забега.
//
// Почему ручек ровно три и почему остальные заперты — разобрано в js/config.js
// рядом с таблицей STEPS. Здесь — то, чего в таблице не видно.

import { OBSTACLES as O, DIFFICULTY as D, STEPS } from './config.js';

export const STEP_MAX = STEPS.length - 1;

export const clampStep = (n) => (Number.isInteger(n) ? Math.min(STEP_MAX, Math.max(0, n)) : 0);

/**
 * Передышка между сериями, выведенная из требования сохранить средний разнос.
 *
 * Это и есть то, что делает контраст волны законной ручкой сложности. Серия из
 * `n` препятствий содержит `n − 1` внутрисерийных промежутков (по `minGapS`
 * плюс половина джиттера в среднем) и одну передышку. Чтобы среднее по всем
 * промежуткам осталось прежним — `targetMeanGapS`, то есть замером прежнего
 * правила, — передышка обязана добрать разницу:
 *
 *     n · target = (n − 1) · (minGapS + jitter/2) + (breather + bjitter/2)
 *
 * Отсюда и формула. Подбирать это число руками было бы той же ошибкой, что
 * вторая копия края препятствия: связь важнее значения, и при правке `minGapS`
 * или длины серии подобранное вручную молча разъехалось бы с замером.
 */
export function breatherFor(seriesMin, seriesMax) {
  /* При ИСХОДНОЙ длине серии отдаём ровно то число, что стоит в конфиге.
     Не потому, что формула тут не работает — она даёт 8.95 против 8.80, то
     есть сходится с точностью до 0.15 с, — а потому, что 8.80 и есть то
     значение, НА КОТОРОМ снят замер среднего разноса. Ступень 0 обязана быть
     сегодняшней игрой побайтово, иначе журнал будет говорить «ступень 0», а
     значить другую игру. */
  if (seriesMin === O.seriesMin && seriesMax === O.seriesMax) return O.breatherS;
  const n = (seriesMin + seriesMax) / 2;
  const inner = O.minGapS + O.seriesJitterS / 2;
  return n * D.targetMeanGapS - (n - 1) * inner - O.breatherJitterS / 2;
}

/**
 * Числа игры для ступени.
 *
 * Ступень 0 отдаёт ровно сегодняшние числа — не копией, а тем, что строка
 * таблицы ссылается на `OBSTACLES`. Копия разошлась бы с источником при первой
 * правке конфига, и сравнимость со всеми замерами до 11 октября исчезла бы
 * молча: журнал говорил бы «ступень 0», а значил другую игру.
 *
 * Отдаёт ТОЛЬКО то, что ступени разрешено трогать. Это не экономия полей:
 * структура ответа и есть граница, и тест проверяет её по именам ключей —
 * появление здесь `signalS` или `speed` сломает проверку раньше, чем ребёнка.
 */
export function tuneFor(step) {
  const s = STEPS[clampStep(step)];
  return {
    blockFrac: s.blockFrac,
    duckShare: s.duckShare,
    seriesMin: s.seriesMin,
    seriesMax: s.seriesMax,
    breatherS: breatherFor(s.seriesMin, s.seriesMax),
  };
}

/**
 * Куда ступень поедет после забега.
 *
 * ```
 * outcome = { finished, faced, late, pauses, ringPct }
 *   faced   — препятствий, дошедших до приговора
 *   late    — «не успел»: задетые плюс прощённые
 *   pauses  — эпизодов паузы внутри забега
 *   ringPct — процент собранных колец
 * ```
 *
 * ВВЕРХ — только по безупречному забегу. ВНИЗ — по любому, включая брошенный.
 * Асимметрия намеренная, и снимать её нельзя: данных «ребёнку трудно» у
 * проекта нет вовсе (единственное задетое препятствие за всю историю
 * объясняется ложной паузой), а цена ошибки несимметрична. Слишком легко —
 * скучно; слишком трудно — «ребёнок не понял, почему проиграл», и это здесь
 * худший класс дефекта.
 *
 * Пороги — из журналов, а не из вкуса:
 *
 * • `late === 0` — наблюдённое состояние «легко»: 105 препятствий подряд без
 *   единого задетого. Прошедшее в окне прощения приравнено к задетому
 *   нарочно: ребёнок не ушёл к моменту прихода и успел только в те 350 мс,
 *   что ему прощают, — для счёта это такой же непройденный случай. Сколько
 *   таких было в прошлых журналах, НЕИЗВЕСТНО: до 11 октября расход окна не
 *   мерился вовсе (разбор — в `makeTally`), так что порог опирается на ноль
 *   задетых, а прощённые добавлены к нему вперёд их первого измерения;
 * • `faced ≥ 24` — законные забеги дают 26, 26, 26, 27 и 43 препятствия. Ниже
 *   этого только `?run=20` и отладочный режим; синтетический источник отсечён
 *   отдельно, в `train.js`, — порога ему мало, вниз он уезжал свободно;
 * • `pauses === 0` — это запрет «усложнять по журналу с дефектами», записанный
 *   числом. Порог достижим (11 октября — первая сессия без единой паузы за
 *   803 с) и необходим: 7 октября единственное задетое препятствие объясняется
 *   ложной паузой, а 9 октября восемь пауз сделали забег несуществующим;
 * • `ringPct ≥ 85` — наблюдённый ряд 81, 88, 93, 94, 98. Порог отрезает ровно
 *   холодный забег: 81% дал первый забег сразу после калибровки, 98% — второй,
 *   разогретый, через десять минут на том же коде. Потерял пятую часть колец —
 *   значит был занят, а не скучал;
 * • вниз — три, а не один: один промах из 26 это шум одного неудачного шага,
 *   три — уже больше десятой части серии.
 *
 * Мусор на входе ступень не двигает вовсе: решение принимается только по
 * числам, которые есть.
 */
export function nextStep(step, outcome = {}) {
  const now = clampStep(step);
  const { finished, faced, late, pauses, ringPct } = outcome;
  if (![faced, late, pauses, ringPct].every(Number.isFinite)) return now;

  if (faced >= D.minFacedDown && late >= D.lateDown) return clampStep(now - 1);
  if (finished === true && faced >= D.minFacedUp && late === 0 && pauses === 0
    && ringPct >= D.ringPctUp) return clampStep(now + 1);
  return now;
}

/** Почему ступень поехала (или не поехала) — одним словом, для журнала. */
export function whyStep(from, to) {
  if (to > from) return 'easy';
  if (to < from) return 'hard';
  return 'held';
}
