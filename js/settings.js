// Умолчания заданы явно, а не «вторым вариантом списка»: у приседаний вторым
// идёт «выключены», и выведенное правило молча выключало бы половину игры.
const DEFAULTS = {
  runLength: 300,
  speed: 1.0,
  crouch: true,
  sound: 0.8,
  preview: 'on',
  screenRun: 'awake',
  debug: 'off',
  cache: 'on',
  camera: 'user',
};

function read() {
  try {
    return { ...DEFAULTS, ...JSON.parse(localStorage.getItem(KEY) || '{}') };
  } catch {
    return { ...DEFAULTS };
  }
}

let current = read();

export const settings = {
  get: (name) => current[name],

  label(name) {
    const found = OPTIONS[name].find((o) => o.value === current[name]);
    return found ? found.label : String(current[name]);
  },

  /** Переключает настройку на следующий вариант по кругу и возвращает подпись. */
  cycle(name) {
    const list = OPTIONS[name];
    const i = list.findIndex((o) => o.value === current[name]);
    current[name] = list[(i + 1) % list.length].value;
    try { localStorage.setItem(KEY, JSON.stringify(current)); } catch {}
    return this.label(name);
  },
};

/* Какая длина забега действует СЕЙЧАС, со всеми перебивками.

   Порядок тот же, что был внутри train.js: параметр адреса сильнее всего,
   затем режим ускоренной отладки, затем родительская настройка. Ждать пять
   минут на каждую проверку экрана финиша бессмысленно, поэтому перебивки и
   существуют.

   Вынесено сюда потому, что читателей стало ДВА. С 11 октября длину видит
   ребёнок — подписью под кнопкой «Играть», — а вычислял её только забег.
   Вторая копия этой лесенки означала бы меню, которое обещает «5 минут» там,
   где отладочный режим даёт тридцать секунд: расхождение видно сразу и
   выглядит поломкой. Поймано ревью. */
export function runDurationS() {
  return Number(flag('run'))
    || (current.debug === 'fast' ? 30 : 0)
    || current.runLength
    || 300;
}

/* И подпись к ней — словами, для экрана.

   Перебивка называется перебивкой: «30 секунд (отладка)» честнее, чем
   «5 минут» над тридцатисекундным забегом, и честнее, чем просто «30 секунд»,
   из которого непонятно, почему настройка не действует. */
export function runDurationLabel() {
  const d = runDurationS();
  const known = OPTIONS.runLength.find((o) => o.value === d);
  if (known && d === current.runLength) return known.label;
  return d >= 60 ? `${Math.round(d / 60)} мин (отладка)` : `${d} с (отладка)`;
}
