// Настройки, которые крутит взрослый. Живут в localStorage, потому что
// родительское меню должно пережить перезапуск: подкручивать скорость после
// каждого включения никто не станет.
//
// Каждая настройка — список вариантов с подписью, а не число: в меню их
// переключают нажатием, а подпись сразу уходит на телевизор, и читать её будет
// взрослый с дивана. Поэтому подписи словами, а не цифрами.

const KEY = 'run-game.settings';

export const OPTIONS = {
  /* Длина забега.

     Изначально верхней границей было пять минут: для семи лет дольше — уже
     физическая нагрузка, а не игра. Границу подняли по просьбе заказчика,
     который видит ребёнка, а не рассуждает о нём. Сигнал усталости при этом
     остаётся: после трёх забегов подряд игра предлагает передохнуть. */
  runLength: [
    { value: 300, label: '5 минут' },
    { value: 480, label: '8 минут' },
    { value: 720, label: '12 минут' },
    { value: 180, label: '3 минуты' },
  ],
  // Множитель базовой скорости. Время на решение от него не зависит:
  // дистанция появления препятствия пересчитывается вместе со скоростью.
  speed: [
    { value: 0.8, label: 'медленно' },
    { value: 1.0, label: 'обычно' },
    { value: 1.2, label: 'быстрее' },
  ],
  // Приседания можно выключить целиком: ребёнку может быть тяжело, и тогда
  // игра остаётся играбельной на одном боковом смещении.
  crouch: [
    { value: true, label: 'включены' },
    { value: false, label: 'выключены' },
  ],
  // Звук — канал телеграфа, а не фон: именно он сообщает, что делать, и
  // приходит раньше картинки. Выключать его стоит только если играют поздно
  // вечером, и тогда игра становится заметно труднее.
  sound: [
    { value: 0.8, label: 'обычно' },
    { value: 1.0, label: 'громко' },
    { value: 0.5, label: 'тихо' },
    { value: 0, label: 'выключен' },
  ],
  /* Какая камера смотрит на ребёнка.

     По умолчанию фронтальная: телефон стоит на штативе экраном к ребёнку, и
     на него смотрит именно она. Основная бывает лучше по качеству и шире по
     углу, поэтому переключатель есть.

     Знак смещения от выбора камеры НЕ зависит, и это важно не перепутать:
     обе отдают кадр «как видит объектив», у человека лицом к камере левая
     рука оказывается справа в кадре. Зеркалится только предпросмотр, и то
     силами CSS. */
  camera: [
    { value: 'user', label: 'фронтальная' },
    { value: 'environment', label: 'основная' },
  ],

  /* Офлайн-кэш.

     Выключать его нужно не ребёнку, а тому, кто правит код: с включённым
     кэшем каждая выкладка проверяется через «а точно ли доехало», и половина
     времени уходит на это вместо работы. С выключенным всё берётся из сети,
     как на обычном сайте.

     Цена честная и её надо понимать: без кэша игра не работает без сети
     вовсе, а семнадцать мегабайт MediaPipe тянутся заново, как только истечёт
     обычный кэш браузера. Для телефона на штативе это не режим игры, это
     режим отладки. */
  cache: [
    { value: 'on', label: 'включён' },
    { value: 'off', label: 'выключен (для разработки)' },
  ],

  /* Отладка.

     На машине разработки камеры нет вовсе, а на телефоне проверять каждую
     правку — долго. Раньше это включалось параметрами адреса, то есть надо
     было помнить их наизусть; теперь это переключатель, и его видно.

     Видно — не формальность: с синтетическим ребёнком игра ведёт себя почти
     как настоящая, и забыть, что камера не участвует, очень легко. Поэтому
     при включённой отладке на экране забега вместо «вижу тебя» написано
     «синтетика», а источник уходит в журнал. */
  debug: [
    { value: 'off', label: 'выключена' },
    { value: 'fake', label: 'без камеры' },
    { value: 'fast', label: 'без камеры, забег 30 с' },
  ],

  // Окошко камеры со скелетом во время игры. Пока ребёнок привыкает к
  // границам игрового поля — нужно; когда привыкнет, на телевизоре это лишнее.
  preview: [
    { value: 'on', label: 'показывать' },
    { value: 'field', label: 'только полоску' },
    { value: 'off', label: 'прятать' },
  ],
};

// Умолчания заданы явно, а не «вторым вариантом списка»: у приседаний вторым
// идёт «выключены», и выведенное правило молча выключало бы половину игры.
const DEFAULTS = {
  runLength: 300,
  speed: 1.0,
  crouch: true,
  sound: 0.8,
  preview: 'on',
  debug: 'off',
  cache: 'on',
  camera: 'user',
};

function read() {
  try {
    return { ...DEFAULTS, ...JSON.parse(localStorage.getItem(KEY) || '{}') };
  } catch {
    return { ...DEFAULTS };
  }
}

let current = read();

export const settings = {
  get: (name) => current[name],

  label(name) {
    const found = OPTIONS[name].find((o) => o.value === current[name]);
    return found ? found.label : String(current[name]);
  },

  /** Переключает настройку на следующий вариант по кругу и возвращает подпись. */
  cycle(name) {
    const list = OPTIONS[name];
    const i = list.findIndex((o) => o.value === current[name]);
    current[name] = list[(i + 1) % list.length].value;
    try { localStorage.setItem(KEY, JSON.stringify(current)); } catch {}
    return this.label(name);
  },
};
