// Проверка, что MediaPipe действительно лежит на телефоне целиком.
//
// Семнадцать с половиной мегабайт по телефонной связи — самый вероятный отказ
// установки во всём проекте. Беда в том, как он проявляется: наполовину
// закэшированная модель не даёт ошибки сети, она даёт молчаливый abort внутри
// wasm при создании распознавателя. По симптому это неотличимо от дефекта
// кода, и разбираться можно долго.
//
// Поэтому перед запуском тренировки комплект проверяется явно, и при
// неполноте показывается честный экран «нужен интернет один раз» вместо
// попытки работать с тем, что есть.

import { VENDOR } from './config.js';
import { isDev } from './util.js';

/**
 * Проверяет, что каждый файл MediaPipe лежит в офлайн-кэше.
 *
 * Проверяется ровно наличие, и это не упрощение.
 *
 * Сначала здесь сверялся ещё и размер — из заголовка `content-length`
 * закэшированного ответа. Проверка была сломана по построению и не могла
 * пройти ни разу: GitHub Pages отдаёт сжатыми все файлы, включая wasm и
 * модель, то есть `content-length` — это размер в сжатом виде, а сравнивался
 * он с размером на диске. На установленном приложении это давало «нужен
 * интернет один раз» при каждом запуске тренировки, хотя скачано было всё.
 *
 * Сверять настоящий размер можно только прочитав тело, то есть распаковав
 * 17 МБ при каждом старте — ровно ту работу, которую офлайн-кэш и экономит.
 * А смысла в этом мало: `cache.addAll()` атомарен, частично закэшированного
 * комплекта из неудачной загрузки не бывает. Что бывает — во-первых, выселение
 * отдельных записей браузером; во-вторых, с разделением кэшей, обрыв сети
 * МЕЖДУ двумя addAll, когда код приложения уже лёг, а MediaPipe ещё нет. Оба
 * случая ловит именно проверка наличия.
 *
 * Размеры в `VENDOR.files` остаются: по ним `tests-shell.mjs` сверяет файлы на
 * диске с объявленными, и там сжатие ни при чём.
 */
export async function checkVendor() {
  // На localhost service worker не регистрируется вовсе, файлы берутся с
  // диска, и проверять нечего.
  if (isDev) return { ok: true, skipped: 'разработка' };
  if (!self.caches) return { ok: true, skipped: 'нет Cache API' };

  /* Спрашиваем ВСЕ кэши сразу, а не выбираем нужный по имени.

     Кэша теперь два — код приложения с номером сборки и MediaPipe с
     отпечатком содержимого, — и выбор по имени здесь был бы третьим местом,
     где это соответствие надо поддерживать. Хуже того, прежнее условие
     `startsWith('run-v')` совпадает и с `run-vendor-…`: проверка молча
     заглядывала бы то в один кэш, то в другой, в зависимости от порядка
     создания. А вопрос у этой функции ровно один — «лежит ли файл офлайн», —
     и `CacheStorage.match` отвечает на него сам, обходя все кэши.

     Расхождение двух кэшей при этом по-прежнему ловится: addAll атомарна для
     каждого, но сеть может кончиться между ними, и тогда код приложения есть,
     а MediaPipe нет. Это и есть случай, ради которого функция написана. */
  const names = await caches.keys();
  if (!names.some((k) => k.startsWith('run-'))) {
    return { ok: true, skipped: 'кэш ещё не создан' };
  }

  const missing = [];
  for (const path of Object.keys(VENDOR.files)) {
    if (!await caches.match(path)) missing.push(path);
  }

  return { ok: !missing.length, caches: names, missing };
}

/**
 * Поддерживает ли устройство WASM SIMD.
 *
 * Спрашиваем саму библиотеку, а не свою проверку: загрузчик по этому же
 * предикату решает, попросить `vision_wasm_internal.js` или
 * `vision_wasm_nosimd_internal.js`. Своя проверка могла бы разойтись с его —
 * и тогда мы бы сказали «всё хорошо», а он ушёл бы за файлом, которого у нас
 * нет, и получил 404 офлайн, на телефоне ребёнка.
 */
export async function checkSimd() {
  try {
    const { FilesetResolver } = await import(VENDOR.bundle);
    return await FilesetResolver.isSimdSupported();
  } catch {
    return null; // не смогли спросить — решает вызывающий
  }
}
