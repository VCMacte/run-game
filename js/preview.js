// Окошко камеры во время игры: что видит камера и что из этого поняла игра.
//
// Нужно не для отладки, а ребёнку. Игровое поле — это кусок комнаты, который
// видит камера, и у него есть края, которых не видно ниоткуда. Пока ребёнок к
// ним не привык, он выходит за кадр, игра встаёт на паузу, и непонятно,
// почему. Окошко со скелетом и полоса положения дают эти края увидеть.
//
// Картинка зеркалится. Камера смотрит на ребёнка спереди, и без зеркала его
// шаг влево уезжал бы на окошке вправо — то есть окошко, поставленное ради
// понимания, добавляло бы путаницы. С зеркалом оно ведёт себя как зеркало.

import { SIGNALS as S } from './config.js';

/* Кого с кем соединять, чтобы получился человечек. Руки и ноги рисуются,
   хотя игра их не использует: ребёнок должен узнать в фигурке себя, иначе
   окошко не объясняет ничего. */
const BONES = [
  [11, 12], [11, 23], [12, 24], [23, 24],       // торс
  [11, 13], [13, 15], [12, 14], [14, 16],       // руки
  [23, 25], [25, 27], [24, 26], [26, 28],       // ноги
];

const COLORS = {
  ok: '#39d98a',
  lost: '#ffb02e',
  joint: '#f2f5ff',
  // Зона-цель на калибровке: куда надо попасть. Два состояния, и различаются
  // они светлотой, а не только тоном: цветность Miracast режет сильнее.
  zone: '#2d4f8a',
  zoneHit: '#7ce0ff',
};

/**
 * Положение ребёнка на полосе игрового поля.
 *
 * Чистая функция: по горизонтальной координате в кадре отдаёт место на
 * полосе и признаки «у края» и «вышел». Зеркалит заодно — полоса читается
 * ребёнком, а не камерой.
 */
export function fieldPosition(cx, margin = S.edgeMargin) {
  if (cx == null) return { x: null, nearEdge: false, outside: true };
  const x = 1 - cx; // зеркало: право камеры — это лево ребёнка
  return {
    x,
    nearEdge: x < margin * 2 || x > 1 - margin * 2,
    outside: x < margin || x > 1 - margin,
  };
}

/**
 * Как кадр ложится в окошко при `object-fit: cover` — и, значит, куда рисовать
 * скелет.
 *
 * Окошко в вёрстке 16:9, а кадр камеры этой формы НЕ обязан быть. 8 октября
 * журнал поймал это вживую: когда полный экран сорвался и страница на миг
 * стала портретной, кадры повернулись и пришли 360×640 (`cam.aspect` 1.78 →
 * 0.56). Видео в такой ситуации `cover` обрезает — показывает серединную
 * треть по высоте, растянув её на всё окошко, — а скелет рисовался линейно во
 * всю коробку. Фигурка и картинка расходятся: ноги оказываются выше пола,
 * плечи не там, где плечи. Заказчик описал это как «меня воспринимали на
 * 10–20 см выше».
 *
 * Отдаёт перевод нормированных координат КАДРА в нормированные координаты
 * ОКОШКА: `x_окошка = x * sx + ox`. При совпадении форм — тождество, и на
 * штатном 16:9 ничего не меняется.
 */
export function coverFit(frameAspect, boxAspect) {
  if (!(frameAspect > 0) || !(boxAspect > 0)) return { sx: 1, ox: 0, sy: 1, oy: 0 };
  if (frameAspect > boxAspect) {
    // Кадр шире окошка: cover подгоняет по ВЫСОТЕ, лишнее срезает по бокам.
    const k = frameAspect / boxAspect;
    return { sx: k, ox: (1 - k) / 2, sy: 1, oy: 0 };
  }
  // Кадр выше окошка: подгоняется по ШИРИНЕ, срезается сверху и снизу.
  const k = boxAspect / frameAspect;
  return { sx: 1, ox: 0, sy: k, oy: (1 - k) / 2 };
}

/**
 * Рисует скелет поверх видео.
 *
 * `lm` — те же 132 числа, что приходят от распознавания; `ok` — считает ли
 * игра, что ребёнка видно. Цветом показано именно это: зелёный — видит,
 * жёлтый — что-то не так, и тогда понятно, что пауза будет не «ни с того ни
 * с сего».
 */
export function drawSkeleton(canvas, lm, ok, target = null, frameAspect = null) {
  /* Размер бит-мапа здесь НЕ назначается: его владелец один — `sizeSkeleton`
     в `js/app.js`, и зовётся он и при изменении окна, и при переключении
     окошка в маленький размер (`.watch`). Второй владелец разошёлся бы с ним
     на округлении, а чтение `clientWidth` из кадра отрисовки заставляло бы
     браузер пересчитывать разметку на КАЖДОМ кадре — на том самом телефоне,
     чей бюджет кадра и есть узкое место проекта. */
  const ctx = canvas.getContext('2d');
  const w = canvas.width;
  const h = canvas.height;
  ctx.clearRect(0, 0, w, h);
  // Кадр в окошко ложится так же, как его кладёт `object-fit: cover` у видео:
  // иначе фигурка расходится с картинкой — см. coverFit.
  const fit = coverFit(frameAspect, w / h);
  // Цель — под скелетом: ребёнок ищет на экране себя, и фигурка обязана
  // остаться сверху.
  if (target) drawTarget(ctx, w, h, target, fit);
  if (!lm) return;

  // Зеркало то же, что у видео, и применяется ПОСЛЕ укладки в окошко: сначала
  // координата кадра становится координатой окошка, потом отражается.
  const X = (i) => (1 - (lm[i * 4] * fit.sx + fit.ox)) * w;
  const Y = (i) => (lm[i * 4 + 1] * fit.sy + fit.oy) * h;
  const V = (i) => lm[i * 4 + 3];

  ctx.lineWidth = Math.max(2, w * 0.016);
  ctx.lineCap = 'round';
  ctx.strokeStyle = ok ? COLORS.ok : COLORS.lost;

  for (const [a, b] of BONES) {
    // Точку, в которой модель не уверена, рисовать нельзя: она улетает в
    // случайное место, и фигурка выглядит сломанной, хотя всё в порядке.
    if (V(a) < 0.4 || V(b) < 0.4) continue;
    ctx.beginPath();
    ctx.moveTo(X(a), Y(a));
    ctx.lineTo(X(b), Y(b));
    ctx.stroke();
  }

  // Плечи и бёдра — те самые четыре точки, по которым игра считает всё
  // остальное. Их видно отдельно: если пропали они, пропало управление.
  ctx.fillStyle = COLORS.joint;
  const r = Math.max(2, w * 0.014);
  for (const i of [S.LM.lShoulder, S.LM.rShoulder, S.LM.lHip, S.LM.rHip]) {
    if (V(i) < 0.4) continue;
    ctx.beginPath();
    ctx.arc(X(i), Y(i), r, 0, Math.PI * 2);
    ctx.fill();
  }
}

/**
 * Зона-цель калибровки: куда ребёнку надо переместиться.
 *
 * Существует потому, что калибровка себя не объясняла. По журналу 6 октября
 * ребёнок не прошёл её с первого раза, и причина не в нём: на каком
 * расстоянии встать, насколько шагнуть и насколько присесть — на экране не
 * было сказано нигде, а у стадии «шагни вправо» заголовок вообще оставался от
 * прошлой стадии. Словами семилетке этого и не сказать: он смотрит на
 * телевизор через комнату. Поэтому цель — зона, а не текст.
 *
 * Зеркало то же, что у скелета (`1 - x`): без него шаг влево уезжал бы на
 * окошке вправо. Зеркало складывается с `mirrorX` калибровки, и именно
 * поэтому зона, посчитанная для «шага влево», оказывается на экране слева —
 * двойное отрицание проверяется тестом, а не на глаз.
 *
 * Форма — крупная плоская заливка со светлым краем: тонкую рамку и пунктир
 * сжатие уничтожает первыми. Заливка растёт по мере выдержки — это
 * единственный указатель прогресса, который работает у того, кто не читает.
 */
function drawTarget(ctx, w, h, t, fit = { sx: 1, ox: 0, sy: 1, oy: 0 }) {
  // Рамка «куда встать» — это DOM-силуэт, канвасу здесь делать нечего.
  if (t.kind === 'stand') return;

  /* Зона едет через ту же укладку, что и скелет. Иначе на повёрнутом кадре
     она показывала бы не туда, куда шагнуть, — а это единственное, чем
     калибровка себя объясняет. */
  /* Зажим обязателен, и он не про аккуратность. На повёрнутом кадре укладка
     растягивает вертикаль втрое (sy ≈ 3.16, oy ≈ −1.08), и линия приседа при
     `t.y > 0.66` уезжает НИЖЕ окошка: `y0` становится больше `y1`, `fillRect`
     получает отрицательную высоту и заливает вверх от низа, а полоса выдержки
     вообще уходит с канваса — то есть исчезает единственный указатель
     прогресса, который работает у того, кто не читает. С боковой зоной то же:
     незажатый `mx` уводит воротца «вернись в середину» целиком за окошко, и
     стадия сгорает все три попытки, не показав ничего. */
  const зажать = (v, max) => Math.max(0, Math.min(max, v));
  let x0; let x1; let y0; let y1;
  if (t.kind === 'crouch') {
    if (!Number.isFinite(t.y)) return;
    [x0, x1, y0, y1] = [0, w, зажать((t.y * fit.sy + fit.oy) * h, h), h];
  } else {
    if (!Number.isFinite(t.x)) return;
    // то же зеркало, что у скелета
    const mx = зажать((1 - (t.x * fit.sx + fit.ox)) * w, w);
    if (t.side === 0) {
      const half = (t.half || 0) * fit.sx * w;
      [x0, x1] = [mx - half, mx + half];
    } else {
      // Боковая зона тянется до края кадра: просят уйти в сторону, а не
      // встать на черту.
      [x0, x1] = t.side < 0 ? [0, mx] : [mx, w];
    }
    [y0, y1] = [0, h];
  }

  const fill = Math.max(0, Math.min(1, t.fill || 0));
  const color = t.reached ? COLORS.zoneHit : COLORS.zone;
  ctx.globalAlpha = t.reached ? 0.55 : 0.35;
  ctx.fillStyle = color;
  ctx.fillRect(x0, y0, x1 - x0, y1 - y0);
  // Выдержка: заливка поднимается снизу вверх, то есть «постой, пока
  // наполнится».
  ctx.globalAlpha = t.reached ? 0.9 : 0.6;
  ctx.fillRect(x0, y1 - (y1 - y0) * fill, x1 - x0, (y1 - y0) * fill);
  ctx.globalAlpha = 1;

  // Край зоны — та самая линия, до которой надо дойти.
  ctx.strokeStyle = color;
  ctx.lineWidth = Math.max(2, w * 0.02);
  ctx.beginPath();
  if (t.kind === 'crouch') {
    ctx.moveTo(x0, y0); ctx.lineTo(x1, y0);
  } else if (t.side === 0) {
    ctx.moveTo(x0, y0); ctx.lineTo(x0, y1);
    ctx.moveTo(x1, y0); ctx.lineTo(x1, y1);
  } else {
    const edge = t.side < 0 ? x1 : x0;
    ctx.moveTo(edge, y0); ctx.lineTo(edge, y1);
  }
  ctx.stroke();
}

/** Двигает отметку на полосе поля и подсвечивает приближение к краю. */
export function updateField(strip, mark, cx) {
  const p = fieldPosition(cx);
  if (p.x == null) {
    strip.classList.add('lost');
    mark.hidden = true;
    return p;
  }
  mark.hidden = false;
  mark.style.left = `${(p.x * 100).toFixed(1)}%`;
  strip.classList.toggle('near', p.nearEdge && !p.outside);
  strip.classList.toggle('lost', p.outside);
  return p;
}
