// Мелкие приёмы, нужные нескольким модулям.
//
// Отдельный файл понадобился не для красоты: камера и распознавание тоже
// должны уметь не ждать вечно, а импортировать их из app.js значило бы
// замкнуть круг camera → app → train → camera.
//
// Разбор: docs/log-and-storage.md

/* Куда сообщать о несостоявшихся обещаниях.

   Журнал сюда НЕ импортируется, и это не лень. Этот файл — лист, и его тянет
   `js/signals.js`, всё достоинство которого в том, что он чистая математика
   без DOM и без хранилища. Импорт журнала протащил бы IndexedDB транзитивно в
   самый чистый модуль проекта и ради одной строки сломал бы границу, на
   которой стоит вся проверяемость из node.

   Поэтому приёмник подключает оболочка (`js/app.js`), а до подключения его
   нет вовсе: в тестах и инструментах `withTimeout` работает молча. */
let tell = null;

/** Подключить приёмник исходов. Зовётся один раз, из оболочки. */
export function reportWaits(fn) { tell = fn; }

/**
 * Не ждать обещание дольше разумного.
 *
 * Обещания полного экрана, блокировки ориентации, разрешения камеры и
 * инициализации MediaPipe умеют не завершаться никогда. В комиксе на этом
 * приложение зависало на экране загрузки, и единственное лечение — срок.
 *
 * Возвращает `undefined` по истечении срока и при ошибке: вызывающий решает,
 * что значит отсутствие результата, и это всегда понятнее, чем исключение
 * из недр браузера.
 *
 * А вот РАЗЛИЧАТЬ эти два случая обязан журнал, и в этом смысл `why`.
 * Правило проекта требует, чтобы в журнал попадала не только просьба, но и
 * исход; пока `withTimeout` возвращал `undefined` на оба случая, «не
 * успело» и «упало» были снаружи неотличимы — а чинятся они по-разному:
 * первое сроком, второе кодом. Без `why` не пишется ничего: вызывающие
 * подключаются по одному, и молчание остаётся умолчанием.
 */
export function withTimeout(promise, ms, why = null) {
  /* Один исход на вызов. Обещание вправе отказать и ПОСЛЕ срока — без этого
     флага такой случай дал бы в журнале две записи об одном ожидании. */
  let told = false;
  const say = (outcome, message) => {
    if (told || !why || !tell) return;
    told = true;
    tell(why, outcome, message);
  };

  const done = Promise.resolve(promise).then(
    (v) => { told = true; return v; },
    (e) => { say('fail', String(e?.message || e || '')); },
  );
  const late = new Promise((r) => setTimeout(() => { say('timeout'); r(); }, ms));
  return Promise.race([done, late]);
}

export const clamp = (x, lo, hi) => (x < lo ? lo : x > hi ? hi : x);

/* Проверки на `location` здесь не перестраховка: эти модули импортируются
   тестами в node, где ни location, ни URLSearchParams над адресом нет. Вся
   математика обязана оставаться запускаемой без браузера — ради этого и
   затевалось разделение на чистые модули. */
export const isDev = typeof location !== 'undefined'
  && ['localhost', '127.0.0.1'].includes(location.hostname);

/** Параметры адреса: ?fake=walk, ?pipeline=bitmap — ручки для отладки. */
export const flag = (name) => (typeof location === 'undefined'
  ? null
  : new URLSearchParams(location.search).get(name));

/** Медиана и процентиль по небольшому массиву. Нужны для сводок здоровья. */
export function quantile(xs, q) {
  if (!xs.length) return NaN;
  const a = [...xs].sort((x, y) => x - y);
  const i = (a.length - 1) * q;
  const lo = Math.floor(i);
  const hi = Math.ceil(i);
  return a[lo] + (a[hi] - a[lo]) * (i - lo);
}

/** Округление для журнала: байты там дороже последних знаков. */
export const round = (x, digits = 2) => {
  const k = 10 ** digits;
  return Math.round(x * k) / k;
};
