/* Игроки: имя, своя калибровка, свои рекорды.

   Один модуль закрывает три задачи, и они связаны сильнее, чем кажется.

   Калибровка раньше хранилась одной записью на телефон, а играют двое:
   взрослый 173 см и ребёнок 100–130 см. Каждый забег взрослого затирал
   калибровку ребёнка, и тот проходил двадцать секунд калибровки заново — при
   том что код переиспользования написан и работает. Привязать калибровку к
   игроку дешевле, чем угадывать по длине торса, кто перед камерой.

   Оттуда же берётся имя для таблицы рекордов: на финише его не надо набирать,
   оно уже выбрано перед забегом, и достаточно подтвердить.

   Хранилище — localStorage, как у настроек: записи крошечные, а IndexedDB
   здесь был бы нужен только журналу, который пишет на каждом кадре. Всё в
   try/catch, поэтому модуль импортируется в node без браузера и проверяется
   обычным скриптом.

   Разбор: docs/calibration.md, docs/log-and-storage.md,
   docs/menu-and-navigation.md, docs/trophy-and-worlds.md. */

import { STORAGE } from './config.js';

/* Потолок имени. Не произвольный: таблица и экран результата уходят на
   телевизор зеркалированием, Miracast жмёт картинку, и длинное имя там
   превращается в кашу раньше, чем кончится строка. */
export const NAME_MAX = 12;

/* Потолок записей на игрока. Вытесняется ХУДШАЯ запись, а не самая старая:
   иначе десяток рутинных забегов вытеснит собственно рекорд, ради которого
   таблица и существует. */
export const RECORDS_MAX = 50;

/* Имя в том виде, в котором оно хранится и показывается.

   Второй trim после обрезки не лишний: «Богдан Иванов» длиннее потолка, и
   обрезка по букве оставила бы «Богдан Иван » с висящим пробелом на конце —
   он невидим в поле и виден в таблице. */
export function normalizeName(raw) {
  return String(raw ?? '').replace(/\s+/g, ' ').trim().slice(0, NAME_MAX).trim();
}

/* Порядок в таблице. Сравниваются только забеги одной длины — сырые кольца
   между пятью минутами и одной несравнимы, — поэтому длина в сравнение не
   входит вовсе, её отбирает records(). */
export function rankRecords(records) {
  return [...records].sort((a, b) => (
    (b.stars - a.stars)          // больше колец
    || (a.hits - b.hits)         // при равенстве — меньше задетых
    || (b.at - a.at)             // и при полном равенстве свежее выше
  ));
}

/* Обрезка до потолка: уходит худшее по тому же правилу.

   Применять её ко ВСЕМ записям игрока разом нельзя, и это та же ошибка, от
   которой уберегает rankRecords: длина в сравнение не входит, потому что
   сравнивать забеги разной длины бессмысленно. Пятьдесят пятиминутных забегов
   по сотне колец вытеснили бы первый же трёхминутный с шестьюдесятью — молча,
   в момент записи, и таблица трёх минут осталась бы пустой навсегда. Поэтому
   потолок применяется ВНУТРИ одной длины, а записей у игрока может быть до
   max × число сыгранных длин. Это по-прежнему килобайты. */
export function capRecords(records, max = RECORDS_MAX) {
  const buckets = new Map();
  for (const r of records) {
    const key = Math.round(r.durationS);
    if (!buckets.has(key)) buckets.set(key, []);
    buckets.get(key).push(r);
  }
  const out = [];
  for (const group of buckets.values()) out.push(...rankRecords(group).slice(0, max));
  return out;
}

function fresh(name) {
  return {
    id: `p${Date.now().toString(36)}${Math.random().toString(36).slice(2, 6)}`,
    name: normalizeName(name) || 'Игрок',
    createdAt: Date.now(),
    calib: null,
    records: [],
    /* Копилка колец — всё, что игрок собрал за свою жизнь в игре.

       Это СОБСТВЕННОЕ число, а не сумма по таблице рекордов, и разница тут не
       в удобстве. В таблицу попадает только забег, который нажали «Записать»,
       а `capRecords` вытесняет из неё худшие записи — то есть сумма по ней со
       временем начала бы занижать, причём молча. Число, которое врёт, на
       экране результата хуже отсутствующего. */
    bank: 0,
    /* Выбранный мир. Второе поле, которое надо добавить в ДВА места, — см.
       комментарий в read(). Новый игрок начинает в первом мире: он открыт
       всегда и ничего не требует. */
    world: 'hills',
    /* Ступень сложности. У каждого своя — как калибровка и рекорды, и по той
       же причине: взрослый 173 см проходит забег чисто, ребёнок 7 лет учится.
       Общая ступень означала бы, что один вечер игры взрослого делает игру
       ребёнка труднее. */
    step: 0,
  };
}

/* Перенос с прошлого формата: калибровка лежала одной записью на телефон.
   Старый ключ НЕ удаляется — откат на прошлую сборку должен находить её на
   месте, а стоит она килобайт. */
function migrate() {
  let calib = null;
  try {
    const raw = JSON.parse(localStorage.getItem(STORAGE.calibration) || 'null');
    if (raw && raw.neutralX != null) calib = raw;
  } catch { /* нет так нет */ }
  const first = fresh('Игрок 1');
  first.calib = calib;
  return { v: 1, currentId: first.id, list: [first] };
}

/* Сколько очков отнимал удар до разделения колец и очков. Намеренно свой
   константой, а не OBSTACLES.starsLost: это ИСТОРИЯ, а не настройка. Поменяй
   однажды starsLost — и прошлые записи начнут пересчитываться новым числом,
   которого при них не было. */
const STARS_LOST_BEFORE_SPLIT = 2;

/**
 * Привести запись к виду «кольца и очки — разные поля».
 *
 * До правки одно поле `stars` значило очки: собранное минус отнятое за удары.
 * Число задетых лежит в той же записи, поэтому собранное восстанавливается
 * точно — `очки + задетые × starsLost`. Проверено на всех трёх дошедших до
 * финиша забегах в журналах: 102+4 = 106, 84+4 = 88, 88+2 = 90, и каждое
 * совпало с настоящим числом событий сбора кольца.
 *
 * Без этого таблица мешала бы две разные величины через границу правки: забег
 * ребёнка 7 октября навсегда остался бы «88 из 100», а точно такой же новый
 * написал бы «90 из 100» и обошёл бы его — ровно та несравнимость, ради
 * устранения которой всё и делалось.
 *
 * Чего восстановить нельзя: очки зажаты нулём снизу, и у забега, где удары
 * съели весь счёт, собранное было больше, чем говорит формула. Такой записи в
 * журналах нет, а врать числом здесь не на чем: больше нуля формула точна.
 */
export function migrateRecord(r) {
  // Поле очков есть — запись уже новая, второй раз её трогать нельзя: иначе
  // кольца накручивались бы при каждом чтении хранилища.
  if (Number.isFinite(r.score)) return r;
  const hits = Number(r.hits) || 0;
  return { ...r, score: r.stars, stars: r.stars + hits * STARS_LOST_BEFORE_SPLIT };
}

/* Пустой профиль — тот, в котором ребёнок ничего не заработал: ни колец в
   копилке, ни записей в таблице, ни калибровки. Мера объективная, а не
   эвристика, и на ней стоят оба правила ниже: заменяя пустое непустым,
   потерять нечего, а значит это и не выбор — это восстановление. */
function blank(st) {
  return st.list.every((p) => !(p.bank > 0) && p.records.length === 0 && !p.calib);
}

/* Профиль из разобранного JSON, или null, если это не профиль.

   Поля собираются ПОИМЁННО, и всё незнакомое теряется. Значит новое поле
   добавляется в два места сразу — здесь и в `fresh()`: забыть здесь — получить
   копилку, которая обнуляется при каждой перезагрузке, а заметить это можно
   только на второй сессии. */
function shape(raw) {
  if (!raw || !Array.isArray(raw.list) || raw.list.length === 0) return null;
  const list = raw.list
    .filter((p) => p && typeof p.id === 'string')
    .map((p) => ({
      id: p.id,
      name: normalizeName(p.name) || 'Игрок',
      createdAt: Number(p.createdAt) || Date.now(),
      calib: p.calib && p.calib.neutralX != null ? p.calib : null,
      records: Array.isArray(p.records)
        ? p.records.filter((r) => r && Number.isFinite(r.stars)).map(migrateRecord)
        : [],
      bank: Number.isFinite(p.bank) && p.bank > 0 ? Math.round(p.bank) : 0,
      /* Мусор здесь не чинится, а заменяется первым миром: испорченный
         профиль не вправе ни уронить кадр, ни запереть ребёнка в недоступном
         мире. Открыт ли выбранный мир — решает не хранилище, а js/awards.js:
         здесь мы не знаем ни порогов, ни копилки на момент выбора. */
      world: typeof p.world === 'string' && p.world ? p.world : 'hills',
      // Зажим по длине таблицы ступеней делает не хранилище, а js/difficulty.js:
      // здесь мы не знаем, сколько их. Нечисло — значит профиль старый, и
      // начинать ему с нуля правильно.
      step: Number.isInteger(p.step) && p.step > 0 ? p.step : 0,
    }));
  if (list.length === 0) return null;
  const currentId = list.some((p) => p.id === raw.currentId) ? raw.currentId : list[0].id;
  return { v: 1, currentId, list };
}

/* Один ключ хранилища: что в нём лежало И разобралось ли это.

   Байты возвращаются ОТДЕЛЬНО от профиля намеренно. «Ключ молчит» и «ключ
   отдал байты, которые не разбираются» — разные беды с разными ответами:
   первая решается копией, вторая запрещает запись вовсе. Слитые в одно
   `null`, они дали бы на непонятное тот же ответ, что на пустое, то есть
   запечатали бы непонятное выдумкой. */
function slot(key) {
  let bytes = null;
  try { bytes = localStorage.getItem(key); } catch { /* нет так нет */ }
  if (!bytes) return { bytes: null, state: null };
  try { return { bytes, state: shape(JSON.parse(bytes)) }; } catch { return { bytes, state: null }; }
}

/* Откуда взялся профиль этой сессии. Уходит в журнал (см. js/app.js): без
   этого слова «пропал прогресс» остаётся догадкой навсегда — «хранилище
   пришло пустым» и «мы прочитали и потеряли» в журнале неотличимы.

   'main' — прочитан основной ключ; 'backup' — его не было или он оказался
   пуст, профиль поднят из копии; 'unreadable' — байты есть, но не
   разбираются, и трогать их нельзя; 'fresh' — хранилище молчит, профиль
   действительно первый. */
let source = 'fresh';

/* Байты, в которых профиля не нашлось, — в третий ключ.

   Здесь стояла охрана на месте: нечитаемый основной ключ запрещал запись
   вовсе. Найдено ревью, и это было ХУЖЕ исходного дефекта. Запрет вечный и
   молчаливый: отказ `persist()` видит только запись рекорда, а копилка,
   калибровка, мир и ступень его игнорируют — игра важнее хранилища. То есть у
   ребёнка каждый забег терялась бы копилка и каждая сессия начиналась бы с
   двадцати секунд калибровки, и так до переустановки приложения. Тот же
   запрет вдобавок сработал бы на любой будущей смене формата профиля, заперев
   КАЖДУЮ установку сразу.

   Перенос сильнее охраны и обещание даёт более простое: байты не теряются ни
   на одном пути, включая спасение из копии. Откладываются один раз — вторая
   порция мусора уже дальше от настоящего профиля, чем первая, и затирать ею
   первую нельзя. */
let parked = false;
function park(bytes) {
  try {
    if (localStorage.getItem(STORAGE.playersBroken)) return;
    localStorage.setItem(STORAGE.playersBroken, bytes);
    parked = true;
  } catch { /* не вышло — игра всё равно важнее */ }
}

/* Профиль из двух ключей, и порядок разбора здесь — весь смысл правки.

   20 октября основной ключ не ответил, игра выдумала «Игрока 1», и первый же
   `persist()` — выбор мира или первая же собранная сотня колец — поставил
   выдумку на место профиля ребёнка. Копилка 970, девять записей и калибровка
   ушли безвозвратно, и хуже всего, что НЕВОЗВРАТНОЙ потерю сделал наш код:
   сомнительное чтение немедленно запечатывалось записью.

   Поэтому пустой профиль из основного ключа уступает непустой копии. Это не
   «доверять копии больше»: по мере `blank()` в пустом нет ничего, что можно
   потерять такой заменой. */
function read() {
  const основной = slot(STORAGE.players);
  const копия = slot(STORAGE.playersBackup);
  // Байты есть, а профиля в них нет — откладываем, прежде чем решать, чем
  // играть. Путь спасения из копии тоже сюда: там основной ключ так же
  // испорчен, и терять его байты так же нельзя.
  if (основной.bytes && !основной.state) park(основной.bytes);
  const спасать = основной.state === null || blank(основной.state);
  if (копия.state && !blank(копия.state) && спасать) {
    source = 'backup';
    return копия.state;
  }
  if (основной.state) {
    source = 'main';
    return основной.state;
  }
  // Байты есть, а профиля в них нет: они уже отложены выше, и игра пишется
  // дальше как обычно.
  source = основной.bytes ? 'unreadable' : 'fresh';
  return migrate();
}

let state = read();

/* Есть ли хранилище вообще. Спрашивается один раз за сессию и запоминается:
   сам доступ к localStorage умеет бросать исключение там, где сайту запрещены
   данные. Память сбрасывает `reload()` — ею пользуются только тесты, и без
   сброса поддельное хранилище в них не увидеть вовсе. */
let storageOk = null;
function hasStorage() {
  if (storageOk === null) {
    try { storageOk = typeof localStorage !== 'undefined' && !!localStorage; } catch { storageOk = false; }
  }
  return storageOk;
}

/* Сохранение отвечает, получилось ли. Молча оно вести себя не имеет права в
   одном-единственном месте — при записи рекорда: забег уже не повторить, и
   «Записано ✓» над потерянной записью хуже честного отказа. Везде остальное
   отказ по-прежнему игнорируется: игра важнее хранилища.

   Отсутствие хранилища отказом НЕ считается, и это не поблажка. Отказ, о
   котором стоит сообщать, — это переполнение: оно случается у работающего
   приложения, и его видно только здесь. А когда хранилища нет совсем (node с
   тестами, запрет данных в браузере), сессия живёт в памяти целиком, вместе с
   настройками и калибровкой, и жаловаться на это при каждой записи рекорда
   значит мешать играть там, где исправить всё равно нечего.

   Пишется профиль в ДВА ключа, и копия — не дубль ради надёжности вообще, а
   ответ на конкретное происшествие: 20 октября пропал один ключ из двух в
   том же origin, настройки при этом остались целы (`persisted:true` во всех
   пяти последних сессиях — вытеснение забирает origin целиком и потому
   опровергнуто). Один ключ такой потери не переживает по определению.

   Копия пишется только тогда, когда в профиле ЕСТЬ что хранить, а у пустого
   профиля она УДАЛЯЕТСЯ. Второе — находка ревью, и без неё правка отменяла
   удаление игрока: после `remove()` остаток профиля пуст, копия нет, и
   следующий `read()` предпочёл бы копию. Экран сказал бы «Матвей удалён», а
   запуск вернул бы его — то есть удалить данные игрока стало бы нельзя
   вообще.

   Удалять копию у пустого профиля безопасно ДОКАЗУЕМО, а не на честном
   слове: пустое состояние означает, что непустой копии существовать не
   может. `read()` при пустом или пропавшем основном ключе непустую копию уже
   взял бы и источником назвал её — значит всё, что здесь удаляется, пусто и
   само.

   Отказ КОПИИ отказом сохранения не считается, и это тоже находка ревью.
   Копия удваивает место под профиль, поэтому первая её запись — самый
   вероятный момент переполнения; общий `false` на это означал бы, что
   `addRecord` откатывает запись в памяти при живой записи на диске, а
   следующее сохранение возвращает откат поверх настоящего. Отвечает поэтому
   только основной ключ: он и есть хранилище, копия — страховка. */
function persist() {
  if (!hasStorage()) return true;
  let json = '';
  try {
    json = JSON.stringify(state);
    localStorage.setItem(STORAGE.players, json);
  } catch {
    return false;
  }
  try {
    if (blank(state)) localStorage.removeItem(STORAGE.playersBackup);
    else localStorage.setItem(STORAGE.playersBackup, json);
  } catch { /* страховка не легла — играем дальше, основное на диске */ }
  return true;
}

function me() {
  return state.list.find((p) => p.id === state.currentId) || null;
}

const card = (p) => ({
  id: p.id, name: p.name, hasCalib: !!p.calib, runs: p.records.length, bank: p.bank || 0,
});

export const players = {
  all: () => state.list.map(card),

  /* Откуда взялся профиль этой сессии: 'main', 'backup', 'unreadable' или
     'fresh'. Нужно журналу, а не игре — см. разбор у `source`. */
  source: () => source,

  /* Отложены ли в этой сессии нечитаемые байты. Отдельно от источника,
     потому что случиться это может и на пути спасения из копии: там источник
     'backup', а испорченные байты всё равно были и всё равно отложены.
     Журнал обязан сказать, что они лежат и что из них ещё можно достать
     копилку руками. */
  parked: () => parked,

  current: () => {
    const p = me();
    return p ? card(p) : null;
  },
  name: () => me()?.name || 'Игрок',

  select(id) {
    if (!state.list.some((p) => p.id === id)) return false;
    state.currentId = id;
    persist();
    return true;
  },

  /* Добавление по имени. Совпадение без регистра — это тот же игрок, а не
     второй: иначе «Богдан» и «богдан» разойдутся двумя таблицами рекордов и
     двумя калибровками, и выяснится это только тогда, когда рекорд пропадёт.

     `select` выключается там, где имя спрашивают только ради подписи под
     результатом. Иначе гость, которому приписали его забег, становится
     текущим игроком — и у ребёнка следующий забег начинается с двадцати
     секунд калибровки по пустому профилю гостя. Ровно то, ради устранения
     чего профили и заводились. */
  add(rawName, { select = true } = {}) {
    const name = normalizeName(rawName);
    if (!name) return null;
    const same = state.list.find((p) => p.name.toLowerCase() === name.toLowerCase());
    const p = same || fresh(name);
    if (!same) state.list.push(p);
    if (select) state.currentId = p.id;
    persist();
    return { id: p.id, name: p.name, created: !same };
  },

  /* Удаление последнего игрока запрещено: пустой список означал бы, что
     следующий же read() заново выполнит перенос и создаст «Игрок 1» с чужой
     калибровкой. */
  remove(id) {
    if (state.list.length <= 1) return false;
    const i = state.list.findIndex((p) => p.id === id);
    if (i < 0) return false;
    state.list.splice(i, 1);
    if (state.currentId === id) state.currentId = state.list[0].id;
    persist();
    return true;
  },

  // ── калибровка текущего игрока ──

  loadCalibration: () => me()?.calib || null,

  saveCalibration(cal) {
    const p = me();
    if (!p) return;
    p.calib = cal;
    persist();
  },

  clearCalibration() {
    const p = me();
    if (!p) return;
    p.calib = null;
    persist();
  },

  // ── копилка ──

  /* Сколько колец игрок собрал за всю жизнь. Растёт на КАЖДОМ доведённом до
     финиша забеге, независимо от того, нажали ли «Записать»: нажатие — это
     про таблицу рекордов, а не про то, сколько ребёнок набегал.

     Копятся КОЛЬЦА (`collected`), а не очки. Эти два числа в проекте уже
     путали однажды: «88 из 100» означало забег, в котором собрано было 90.

     Отказ хранилища молчит, как и везде, кроме записи рекорда: игра важнее.
     Потерянная сотня колец — досадно, остановленный забег — хуже. */
  bank: () => me()?.bank || 0,

  /* Хранилище мир только ХРАНИТ. Открыт ли он — дело js/awards.js, собран ли
     его арт — дело js/theme.js. Здесь нет даже списка миров: знать его этому
     файлу незачем, ровно как и длину таблицы ступеней. */
  world: () => me()?.world || 'hills',

  setWorld(id) {
    const p = me();
    if (!p || typeof id !== 'string' || !id) return p?.world || 'hills';
    p.world = id;
    persist();
    return p.world;
  },

  // ── ступень сложности ──

  /* Хранилище её только ХРАНИТ: что ступень значит, какие у неё границы и
     когда она двигается — дело js/difficulty.js. Здесь нет даже потолка:
     длина таблицы ступеней этому файлу неизвестна, и знать её ему незачем. */
  step: () => me()?.step || 0,

  setStep(n) {
    const p = me();
    if (!p || !Number.isInteger(n) || n < 0) return p?.step || 0;
    p.step = n;
    persist();
    return p.step;
  },

  addToBank(stars) {
    const p = me();
    if (!p || !Number.isFinite(stars) || stars <= 0) return p?.bank || 0;
    p.bank = (p.bank || 0) + Math.round(stars);
    persist();
    return p.bank;
  },

  // ── рекорды ──

  /* Записывается только дошедший до финиша забег. Выход через паузу сюда не
     попадает вовсе — не фильтром, а тем, что его путь этого метода не зовёт. */
  addRecord({ durationS, stars, score, starsTotal, hits, step, playerId } = {}) {
    const p = playerId ? state.list.find((x) => x.id === playerId) : me();
    if (!p || !Number.isFinite(stars) || !Number.isFinite(durationS)) return null;
    const rec = {
      at: Date.now(),
      durationS: Math.round(durationS),
      // Собранные кольца. По ним таблица и сравнивает забеги — см. rankRecords.
      stars: Math.round(stars),
      /* Очки — то же число минус отнятое за удары, то есть цифра, которую
         ребёнок видел в HUD на финише. Без неё журнал не может объяснить
         экран, а до этой правки оба числа были одним полем и «88 из 100»
         означало забег, в котором собрано было 90. У записей, сделанных до
         правки, очки и есть то, что лежит в stars: подставляем их, иначе
         прошлые рекорды выглядели бы забегами без очков вовсе. */
      score: Math.round(Number.isFinite(score) ? score : stars),
      starsTotal: Math.round(starsTotal ?? 0),
      hits: Math.round(hits ?? 0),
      /* Ступень, на которой забег шёл. Отсутствие поля — не ноль, а «запись
         сделана до тихой адаптации»: нулём это значило бы, что прошлые
         рекорды поставлены на самой лёгкой ступени, а поставлены они
         неизвестно на какой. То же правило, что у `panSpan` и у очков. */
      ...(Number.isInteger(step) ? { step } : {}),
    };
    /* Если на диск не легло — откатываем и отвечаем null.

       Иначе запись жила бы только в памяти: таблица показала бы её, кнопка
       сказала бы «Записано ✓», а после перезагрузки забега бы не было. Откат
       делает ответ честным — «ничего не записано» без строки-призрака. */
    const было = p.records;
    p.records = capRecords([...p.records, rec]);
    if (!persist()) {
      p.records = было;
      return null;
    }
    return rec;
  },

  /* Таблица одной длины: имя приклеивается здесь, а не хранится в записи —
     переименование игрока должно переименовать и его прошлые рекорды. */
  records(durationS) {
    const rows = [];
    for (const p of state.list) {
      for (const r of p.records) {
        if (Math.round(r.durationS) === Math.round(durationS)) rows.push({ ...r, name: p.name, playerId: p.id });
      }
    }
    return rankRecords(rows);
  },

  /** Длины забегов, по которым вообще есть записи. */
  lengths() {
    const set = new Set();
    for (const p of state.list) for (const r of p.records) set.add(Math.round(r.durationS));
    return [...set].sort((a, b) => a - b);
  },

  /* Только для тестов: перечитать хранилище. В игре состояние живёт на всю
     сессию, как у настроек.

     Память о наличии хранилища сбрасывается тоже: в node его нет на момент
     импорта, и без сброса поддельный диск тестов остался бы невидимым, а
     круговой ход профиля — непроверяемым. Ровно этой проверки не было, когда
     прогресс потерялся. */
  reload() { storageOk = null; state = read(); },
};
