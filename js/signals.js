const DEFAULT_CALIBRATION = {
  neutralX: null,         // центр тела по X в нейтральной позе
  neutralShoulderY: null, // высота плеч стоя
  neutralHipY: null,      // и бёдер — нужна отдельным голосом за присед
  S0: null,               // длина торса стоя: по ней ловим приближение к камере
  uEnter: S.uEnter, uExit: S.uExit, vEnter: S.vEnter, vExit: S.vExit,
};

/**
 * Состояние поверх потока поз.
 *
 * Отдаёт одну запись, в которой разделение на двух потребителей выражено
 * именами полей, а не двумя разными API:
 *
 *   u, v            — только One-Euro               → панорама (мгновенно)
 *   lane, crouch    — плюс гистерезис, дедзона и
 *                     подтверждение                 → логика (устойчиво)
 *
 * Сырые uRaw и vRaw отдаются тоже, но только для журнала и отладки: по ним
 * видно, дошёл ли сигнал до порога вообще. В игру они не идут.
 */
export function makeTracker(calibration = {}, { aspect = 1 } = {}) {
  /* Отношение сторон живое, а не раз и навсегда. Выясняется оно у первых
     кадров (js/camera.js, frameAspect), а пересоздать трекер посреди забега
     значит потерять нейтраль, защёлкнутую дорожку и присед. */
  let frameAspectRatio = aspect;
  const cal = { ...DEFAULT_CALIBRATION, ...calibration };
  /* До какого момента нейтраль, снятую с живой позы, ещё уточнять быстрым
     дрейфом. Ноль — уточнять больше не надо. См. засев нейтрали и дрейф. */
  let seedUntil = 0;

  /* Длина торса из ПРОЙДЕННОЙ калибровки, если она была. Отдельно от cal.S0,
     потому что cal.S0 ниже заполняется догадкой с первого кадра: см.
     scaleBand(). */
  const measuredS0 = Number(calibration?.S0) >= S.scaleMin ? Number(calibration.S0) : null;

  /* Длина торса СТОЯ — делитель бокового положения на время приседа.

     Отдельно от `cal.S0` и от `measuredS0` намеренно, хотя величина та же:
     `cal.S0` кормит `scaleGuardOk`, то есть определяет, что такое присед, а
     `measuredS0` задаёт границы присутствия. Третий потребитель с третьим
     сроком годности (эта дрейфует, те две нет) — именно тот случай, когда
     владелец должен быть свой. */
  let standS = measuredS0;

  const fu = makeOneEuro(S.oneEuro);
  const fv = makeOneEuro(S.oneEuro);

  /* Боковое положение, как его видит панорама. Отдельная переменная, а не
     возврат `fu.push()`, потому что в приседе путь другой: там то же значение
     ведёт медленный догоняющий фильтр. Разбор — у `lateralHeld` в push(). */
  let uOut = null;

  let tPrev = null;
  let lane = 0;
  let laneSince = 0;
  let lastLaneChange = -1e9;
  let onsetAt = null;
  let onsetDir = 0;
  let crouch = false;
  let crouchSince = 0;
  let lostSince = null;
  let okSince = null;
  let prevCx = null;
  let centeredSince = null;
  // Последний торс, которому поверили, и когда это было: по ним ловится
  // физически невозможный скачок. Подробности — в presence().
  let trustedS = null;
  let trustedSAt = 0;
  // Было ли боковое положение заморожено на последнем отсчёте. Наружу уходит
  // геттером: по нему приговор отказывается судить о том, чего не знает.
  let lateralHeld = false;
  const ring = [];

  /* Границы «слишком близко» и «слишком далеко».

     Абсолютные scaleMin/scaleMax — защита от бессмыслицы, и для взрослого
     173 см они работают: подошёл к телефону, торс дошёл до 1.07, потолок 0.80
     поймал. У ребёнка 100–130 см торс в кадре короче почти вдвое, и потолок
     0.80 становится недостижимым вовсе — ребёнок упирается в телефон, а игра
     молчит, потому что формально он «в рабочем диапазоне».

     Поэтому при наличии калибровки ВЕРХНЯЯ граница берётся от своего S0 —
     той же, что видел калибратор. До калибровки S0 ещё null, и остаётся
     абсолютная: на той стадии мерить относительно нечего.

     И только ИЗМЕРЕННАЯ S0, из пройденной калибровки. Та, что ниже
     подставляется с первой достоверной позы, когда калибровки ещё нет, — это
     догадка по одному кадру, снятому в том положении, в котором игрок
     случайно оказался. В журнале 6 октября на стадии установки штатива длина
     торса была 2.1: привязать к такому потолок значит выдать либо 0.80 (то
     есть ничего), либо, если игрок стоял далеко, 0.45 — и выгнать его на
     паузу за шаг вперёд. Поэтому догадка годится для scaleGuard (там важна
     только РАЗНИЦА) и не годится здесь.

     И только ПРАВДОПОДОБНАЯ S0, не меньше нижней абсолютной границы. Стадия
     нейтрали сдаётся после трёх попыток и всё равно доходит до finish(),
     приняв сколько успела, — так в хранилище попадает крошечная S0. Домножать
     её на 1.8 нельзя: потолок оказался бы ниже пола, presence возвращал бы
     'scale' на любой позе, и забег встал бы навсегда с «ты слишком близко к
     телефону», пока ребёнок на самом деле слишком далеко. Снять это можно
     было бы только сбросом калибровки во взрослом меню. Такая S0 — не
     измерение, а мусор, и на мусоре мы возвращаемся к абсолютным границам.

     И у самого потолка есть ПОЛ — scaleCeilMin. Относительный потолок целиком
     зависит от одного числа калибровки, и 9 октября это число вышло вдвое
     короче настоящего торса: S0 0.20 при 0.36–0.43 стоя. Потолок встал на
     0.36, то есть ниже стоящего игрока, и забега не стало — восемь пауз
     «отойди назад» за 72 секунды, отступать некуда по построению, никакая
     точка комнаты не помогла бы. Проверка «S0 правдоподобна» этого не поймала:
     0.20 больше scaleMin и на мусор не похоже. Поэтому защита стоит не на
     входе, а на выходе — на самой границе, которая решает судьбу забега.

     Медиана в js/calibrate.js, сделанная тем же коммитом, этот случай НЕ
     лечит, и путать слои нельзя: выборка стадии была однородной, а запас
     потолка почти двукратный. Забег вытащил пол, он один; медиана отвечает за
     точность `neutralX`, у которого запаса нет вовсе.

     Нижнюю границу относительной намеренно НЕ делаем. Она ловит бессмыслицу
     («в кадре вообще не человек»), срабатывать ей не положено ни разу, а длина
     торса на калибровке и в забеге расходится в ЛЮБУЮ сторону: 0.53 против
     0.40 пятого октября (возился у телефона, отошёл к старту) и 0.20 против
     0.37 девятого (калибровался дальше, чем играл). Привяжи нижнюю границу к
     S0, и это расхождение начнёт выгонять ребёнка на паузу за один лишний шаг
     назад. Ровно такой ложной паузой («отойди немного назад» посреди забега)
     уже заканчивался прогон 5 октября, второй раз этого делать не надо.

     Абсолютной она и осталась, но мерит её не торс, а ширина плеч — см.
     presence() и SIGNALS.scaleWidthRatio. Срабатывать ей по-прежнему не
     положено ни разу, а торсом она срабатывала на каждом приседе. */
  function scaleBand() {
    if (!measuredS0) return [S.scaleMin, S.scaleMax];
    // Пол применяется ПОСЛЕ абсолютного потолка, но перевесить его не может:
    // scaleCeilMin < scaleMax, и это держит тест.
    const hi = Math.max(Math.min(S.scaleMax, measuredS0 * S.scaleRelMax), S.scaleCeilMin);
    return [S.scaleMin, hi];
  }

  function presence(g, t) {
    if (g.vis < S.visMin) return 'lowvis';

    /* СНАЧАЛА «ТО ЛИ ЭТО ТЕЛО», ПОТОМ «НА ТОМ ЛИ ОНО РАССТОЯНИИ».

       Порядок здесь был обратный, и это стоило забега. 14 октября игра встала
       на 0.74 секунде с «ты слишком близко к телефону», при том что ребёнок
       стоял на месте: торс 0.25 за секунду до паузы, 1.79 в самой паузе, 0.26
       через секунду после. Объяснил это заказчик: он в тот момент нажимал
       кнопку запуска, и камера приняла за детское тело ЕГО РУКУ у объектива.

       Числа сходятся с объяснением до запятой: торс 1.79 высоты кадра и ширина
       плеч 0.76 ширины кадра — это не бессмыслица модели, а настоящее тело в
       двадцати сантиметрах от стекла. Доля принятых отсчётов в той секунде
       0.22–0.30, то есть модель металась между двумя телами.

       Причина «кто-то ещё в кадре» у проекта есть, и подсказка к ней говорит
       ровно то, что нужно взрослому: «играть должен кто-то один». Но стояла
       она ПОСЛЕДНЕЙ, после потолка расстояния, — и потолок, честно сработав на
       чужом теле, забрал приговор себе. Ребёнку было сказано отойти назад,
       хотя отходить ему было некуда и незачем.

       Поэтому опознание тела идёт первым. Расстояние и поворот — свойства
       ТОГО тела, за которым мы следим, и спрашивать о них, не убедившись, что
       тело то же самое, значит отвечать не про того.

       Второй признак того же: СКАЧОК РАЗМЕРА. Скачок места его не ловит, когда
       чужое тело оказалось там же, где было наше, — а расстояние до камеры за
       десятую секунды в разы не меняется. Замерено по сырым отсчётам всех
       журналов (243 перехода, причём из предпаузных окон, то есть из самых
       скверных мгновений): кратность изменения торса за 100 мс — медиана 1.00,
       p99 1.70, максимум 1.78. У руки у объектива вышло 7.2. Порог 3.0 лежит
       между ними с запасом в обе стороны.

       Сравнивается с последним ДОВЕРЕННЫМ торсом, а не с предыдущим кадром:
       иначе чужое тело, продержавшееся два такта, стало бы само себе точкой
       отсчёта и прошло бы как «ничего не изменилось». А спасает это именно
       потому, что отсчёты перемешаны: хорошая поза обновляет точку отсчёта, и
       весь всплеск целиком остаётся чужим — паузы же не случается вовсе, ведь
       `lostMs` считает только НЕПРЕРЫВНЫЙ отказ.

       Срок нужен на случай, когда чужое тело стоит в кадре плотно и долго:
       спорить с камерой дольше, чем пауза ждёт возвращения (`lostMs`), мы не
       вправе — за ним точка отсчёта берётся заново, и дальше судит потолок,
       как судил всегда.

       Ловится ТОЛЬКО скачок вверх, и это не экономия: подменой оборачивается
       лишь он — чужое тело попадает в кадр, когда к телефону подходят, то есть
       оказывается БЛИЖЕ ребёнка и крупнее его. Скачок вниз ведёт к «слишком
       далеко», и для вырожденного скелета это честный ответ, которого набор
       проверок требует отдельно. Заодно сюда не попадает присед: он торс
       укорачивает. */
    if (prevCx !== null && Math.abs(g.cx - prevCx) > S.jumpMax) return 'jump';
    if (trustedS !== null && g.S > trustedS * S.scaleJumpMax
        && t - trustedSAt <= S.lostMs) return 'jump';
    trustedS = g.S;
    trustedSAt = t;

    const [lo, hi] = scaleBand();
    /* «Слишком далеко» меряется шириной плеч, «слишком близко» — торсом.

       Разными мерами намеренно. Присед наклоняет ребёнка вперёд, и проекция
       торса укорачивается вдвое-втрое: по журналу 7 октября 0.30 стоя против
       0.11–0.24 в приседе, и так на всех одиннадцати приседах. Нижняя граница
       мерила торс и дважды сработала посреди забега — на ребёнке, который
       никуда не уходил и делал именно то, что от него просили. Ширину плеч
       наклон не укорачивает, а уход от камеры уменьшает наравне со всем
       остальным, поэтому «присел» и «ушёл» ею различаются, а торсом — нет.

       Верхнюю границу на ту же меру переводить нельзя: см. scaleWidthRatio. */
    /* СЛОЖЕННЫЙ ТОРС ОТМЕНЯЕТ ГЕОМЕТРИЧЕСКИЕ МЕРЫ, И ЭТО ПРОДОЛЖЕНИЕ ТОЙ ЖЕ
       МЫСЛИ, ЧТО У НИЖНЕЙ ГРАНИЦЫ.

       Заказчик 11 октября вечером: «во время приседания плечи опускались ниже
       уровня бедер и игра становилась на паузу… ещё он пытался ползти в бок во
       время препятствия сверху, на что распознавание посчитало, что он стоит
       боком». Журнал подтвердил дословно: пять пауз `profile` за 180 секунд, и
       в каждой падение плеч 2.0–3.4 длины торса, торс в проекции 0.07–0.12
       против 0.26 стоя, а ширина плеч 0.00–0.04 — то есть В НОЛЬ, плечи
       проецируются в одну точку, как и бывает, когда ложишься на бок.

       Нижнюю границу однажды уже переводили с торса на ширину плеч ровно по
       этой причине. Но у лежащего на боку НЕТ И ШИРИНЫ: ломаются обе меры
       сразу, и проверка это показывает — синтетика той позы выбивает сначала
       `scale`, а не `profile`.

       Поэтому мера, которую присед портит, в приседе не применяется. Решение
       принимается ПО ПОЗЕ, а не по защёлкнутому приседу: пока presence
       отвечает отказом, `push` возвращает управление рано, голоса не считаются
       и защёлкивать нечем — та же грабля, на которой стояла нижняя граница.

       Порог свой НЕ вводится: «поза — присед» это ровно `vEnter`, тот же
       порог, по которому присед и распознаётся. Второе число здесь означало бы
       второй ответ на один вопрос. */
    const folded = cal.neutralShoulderY !== null
      && (g.shoulderY - cal.neutralShoulderY) / Math.max(g.S, lo) > S.vEnter;

    /* «Слишком близко» мерится ТОРСОМ и действует всегда: присед его только
       укорачивает, то есть соврать в эту сторону не может по построению. А
       снимать потолок нельзя — он единственное, что ловит короткую `S0`, из-за
       которой 9 октября забег стал непроходимым. */
    if (!(g.S < hi)) return 'scale';
    if (!folded) {
      const far = Math.max(g.S, g.shoulderWidth / S.scaleWidthRatio);
      if (!(far > lo)) return 'scale';
      if (g.shoulderRatio < S.profileRatio) return 'profile';
    }
    // Положение в кадре присед не портит: это про место, а не про форму.
    if (g.cx < S.edgeMargin || g.cx > 1 - S.edgeMargin) return 'edge';
    return null;
  }

  return {
    get lane() { return lane; },
    get crouch() { return crouch; },
    /* Заморожено ли боковое положение. Наружу — ради ПРИГОВОРА, а не ради
       отладки: пока оно заморожено, игра не знает, где ребёнок, и судить
       боковое препятствие ей нечем. Разбор — у `lateralHeld` в push(). */
    get lateralHeld() { return lateralHeld; },
    /* Границы присутствия наружу — ради журнала, и это не удобство.

       Запись `pause why:"scale"` несёт длину торса, но не ту полосу, с которой
       её сравнили, — и по журналу 9 октября пришлось доставать `calib.done.S0`
       из другого события и домножать на коэффициент руками. Теперь так уже не
       получится вовсе: у потолка появился пол, то есть из S0 он одним
       умножением не выводится. Ровно эту дыру для `profile` закрыли `ratio` и
       `shW`; здесь она та же.

       Отдаётся МЕТОДОМ, а не полем записи: запись уходит 11 раз в секунду, а
       полоса нужна в момент паузы. */
    scaleBand,
    /* Кадр сказал, какой он на самом деле. Состояние при этом сохраняется —
       но ГОРИЗОНТАЛЬНОЕ приходится перевести, а не просто оставить.

       Нейтраль хранится в `cxh`, то есть x, уже умноженный на отношение
       сторон. Поменять делитель и не тронуть её — значит вычитать единицы из
       других единиц: у стоящего в середине `u` уезжает к −0.74 при пороге
       дорожки 0.34, дорожка защёлкивается и разащёлкнуться уже не может (|u|
       никогда не падает ниже `uExit`), а дрейф нейтрали её не вылечит — он сам
       разрешён только при нулевой дорожке. Снаружи это панорама, прижатая к
       стене до конца забега.

       Перевод точный, а не приближённый: всё горизонтальное линейно по
       отношению сторон, поэтому достаточно умножить на отношение нового к
       старому. Вертикальное (`neutralY`, `neutralShoulderY`, `neutralHipY`)
       от него не зависит вовсе и не трогается. */
    setAspect(a) {
      if (!(a > 0) || a === frameAspectRatio) return;
      const k = a / frameAspectRatio;
      frameAspectRatio = a;
      if (cal.neutralX !== null) cal.neutralX *= k;
    },
    /** Последние отсчёты — уходят в журнал одним событием вокруг происшествия. */
    burst(ms = 2000, now = tPrev) {
      return ring.filter((r) => now - r.t <= ms);
    },

    push({ lm, t, calibration: live }) {
      if (live) Object.assign(cal, live);
      const dt = tPrev === null ? 1 / 60 : Math.max(1e-3, (t - tPrev) / 1000);
      tPrev = t;

      if (!lm) {
        if (lostSince === null) lostSince = t;
        okSince = null;
        return { t, ok: false, why: 'none', lostMs: t - lostSince, lane, crouch };
      }

      const g = geometry(lm, frameAspectRatio);
      const why = presence(g, t);
      prevCx = g.cx;

      if (why) {
        if (lostSince === null) lostSince = t;
        okSince = null;
        return { t, ok: false, why, lostMs: t - lostSince, ...g, lane, crouch };
      }
      lostSince = null;
      if (okSince === null) okSince = t;

      const [lo] = scaleBand();

      /* Нейтраль с живой позы — УСРЕДНЁННАЯ, а не с первого кадра.

         Со СЛОЖЕННЫМ торсом её брать нельзя. Раньше такой кадр отбрасывался
         нижней границей и нейтралью стать не мог; теперь он проходит, и
         взрослый, нагнувшийся к штативу, или ребёнок, подбирающий что-то с
         пола, задали бы согнутую нейтраль — после чего `v` уже не дотянулся бы
         до `vEnter`, и присед перестал бы распознаваться до самой калибровки.
         Мерить от такой позы нечего, поэтому кадр честно считается непригодным.

         А усреднение нужно потому, что этот путь стал главным: с
         переиспользованием калибровки (`forReuse` в js/calibrate.js) им
         начинается каждый забег без повторной калибровки, и забег к этому
         моменту уже идёт. Первая достоверная поза приходит, когда взрослый
         разворачивается и идёт к телевизору, — один кадр на середине шага
         уводит нейтраль на 0.1–0.2 длины торса, то есть ровно на столько, из-за
         чего `forReuse` и появился. Поэтому первый кадр задаёт нейтраль сразу
         (игра идёт, ждать нечем), а следующую секунду её быстро уточняет
         ДРЕЙФ — тот же самый, со своими воротами «стоит на месте и ничего
         осознанного не делает». Отдельное усреднение было бы вторым таким
         механизмом без этих ворот, и первое же, что оно впитало бы, — шаг
         вбок, сделанный сразу после старта.

         `cal.S0` здесь по-прежнему догадка с первого кадра, и это не опечатка:
         границы присутствия ею не пользуются — у них своя `measuredS0`, только
         из пройденной калибровки. */
      if (cal.neutralX === null) {
        if (g.S < lo) {
          if (lostSince === null) lostSince = t;
          okSince = null;
          return { t, ok: false, why: 'scale', lostMs: t - lostSince, ...g, lane, crouch };
        }
        cal.neutralX = g.cxh;
        cal.neutralShoulderY = g.shoulderY;
        cal.neutralHipY = g.hipY;
        cal.S0 = g.S;
        /* Торс стоя: из пройденной калибровки, если она была, иначе с этого
           же кадра. Кадр здесь заведомо не согнутый — выше стоит отказ по
           `g.S < lo`, а ниже нейтраль со сложенной позы не берётся вовсе. */
        if (standS === null) standS = g.S;
        seedUntil = t + S.seedMs;
      }

      /* Делитель зажат снизу нижней границей присутствия, и это не
         перестраховка.

         Всё здесь меряется в длинах торса, а в приседе торс складывается: при
         S = 0.05 вместо 0.30 любое смещение раздувается шестикратно. Остаток
         0.02 кадра — пятая часть порога жеста — становится 0.40, проходит по
         пути «начало движения» (onsetU) и защёлкивает дорожку: панорама
         уезжает к краю, и выглядит это фантомным шагом вбок на каждом приседе.

         Раньше такого кадра здесь просто не бывало: нижняя граница по торсу
         его отбрасывала, то есть служила заодно ограничителем делителя. Теперь
         граница мерит ширину плеч и присед пропускает — значит ограничитель
         надо назвать по имени. Зажим ровно тем же числом: ниже него кадр и
         раньше не доходил до этой строки, так что в обычной игре не меняется
         ничего.

         Остаточное раздувание втрое (0.30 → 0.10) зажимом не снимается, и это
         не новость: оно было здесь всё время, при каждом приседе глубже
         половины. В журнале 7 октября фантомных шагов от него нет — на
         одиннадцать приседов один боковой жест, и тот на первом кадре забега,
         где нейтраль только что задана. Трогать вместе с этой правкой не
         стали: нормировать на ширину плеч значило бы пересчитать все пороги
         жестов на отношении, которое у каждого ребёнка своё.

         Знак инвертируется: задняя камера смотрит на ребёнка, повёрнутого к
         ней лицом, и «влево» в кадре противоположно «влево» у ребёнка. Это та
         ошибка, которая делает игру неиграбельной. */
      const unit = Math.max(g.S, lo);

      /* А У БОКОВОГО ДЕЛИТЕЛЬ СВОЙ: в приседе это торс СТОЯ.

         Абзац выше («остаточное раздувание втрое зажимом не снимается…
         трогать вместе с этой правкой не стали») отменяется здесь, и отменяет
         его не рассуждение, а третий делитель, которого тогда не назвали.
         Отвергнута была ширина плеч — отношение, своё у каждого ребёнка и
         требующее пересчёта всех порогов. Торс стоя этого изъяна не имеет: это
         ТА ЖЕ величина в тех же единицах, только измеренная тогда, когда она
         достоверна. Стоя `standS ≈ g.S`, то есть стоячая игра не меняется;
         в приседе чтение перестаёт раздуваться.

         Замерено на записанных скелетах (журнал 18 октября, 49 сложенных
         кадров): шум бокового кадр-к-кадру падает с 0.18 до 0.09 длины торса
         в секунду по медиане и с 5.81 до 2.59 по максимуму — ровно во столько,
         во сколько отличаются делители (0.282 против 0.134).

         Вертикальное остаётся на прежнем делителе, и это не недогляд: `vRaw` и
         `vHip` судят САМ присед, а менять им делитель значило бы переопределить,
         что такое присед. */
      const uUnit = crouch && standS ? standS : unit;
      const uRaw = S.mirrorX * (g.cxh - cal.neutralX) / uUnit;
      const vRaw = (g.shoulderY - cal.neutralShoulderY) / unit;
      const vHip = (g.hipY - cal.neutralHipY) / unit;

      /* БОКОВОЕ ПОЛОЖЕНИЕ В ПРИСЕДЕ ИДЁТ МЕДЛЕННО, А НЕ СТОИТ.

         ЗДЕСЬ СТОЯЛО «боковое положение в приседе не обновляется», и это
         отменено журналами 18 октября. Довод был такой: при сложенном торсе
         остаток в 0.07 длины торса раздувается до 0.4, проходит по пути
         «начало движения» (onsetU) и защёлкивает дорожку — фантомный шаг и
         тряска. Арифметика верна, но она про ДЕЛИТЕЛЬ, а не про присед:
         делитель теперь честный (см. `uUnit` выше), и раздувания нет.

         Заморозка же стоила дороже, чем защищала, и цена замерена. Фильтр за
         присед не шагал вовсе, а на первом кадре после вставания получал один
         `push` с кадровым `dt` 50–90 мс и разницей, накопленной за весь
         присед. One-Euro адаптивный ПО ПОСТРОЕНИЮ: такую разницу он пропускает
         за 2–3 отсчёта. В журналах 18 октября **29 приседов из 43** кончаются
         боковым жестом в первые 0.3 с после вставания, у восьми `|u| > 0.9`,
         максимум 2.51 — это за краем поля. Трасса `health` вокруг приседа
         3.7 с: `u` стоит ровно 0.61 все три секунды, затем −0.83, затем −1.85.
         Заказчик то же самое назвал словами: «после вставания резкий скачок в
         сторону, ребёнка дезориентирует и уводит за края поля».

         Поэтому в приседе боковое ИДЁТ, но медленно — догоняющим фильтром с
         постоянной `crouchLateralTauMs`. Разделение здесь по ЧАСТОТЕ, и только
         оно и работает: по амплитуде шум от настоящего шага не отличить
         (замерено по всем журналам — настоящие боковые скорости доходят до 13
         длин торса в секунду при p90 = 5.0, а шум в приседе до 5.8). Шум
         живёт на кадре (11 Гц), дрейф ребёнка — на секундах, и 400 мс
         разводят их начисто: на записанных сложенных кадрах остаточный шум
         падает до 0.06 по медиане и 2.59 по максимуму, то есть ниже медианного
         НАСТОЯЩЕГО шага (2.86), а дрейф за 2.5 с проходит на 99.8%.

         Накопиться за присед теперь нечему, поэтому отдельного «возврата
         после вставания» нет и заводить его не надо. Фильтр всё это время
         засевается тем же значением (`fu.seed`) — на выходе из приседа он
         продолжает с того места, где стоит панорама, с нулевой производной.

         Признак `lateralHeld` остаётся, и остаётся ровно для приговора:
         решать о боковом препятствии по чтению из приседа по-прежнему нельзя,
         защёлка дорожки по-прежнему запрещена, дрейф нейтрали по-прежнему
         стоит. Это собственная граница проекта: `u` ведёт панораму мгновенно,
         `lane` решает устойчиво. Взгляд следует за ребёнком, приговор — нет.

         Жёсткая заморозка никуда не делась, но теперь она ровно про то, про
         что и должна: `hardHold` — это «тела не видно», а не «присед». Там
         обновлять действительно нечем, и там же единственное место, где
         значение на возврате прыгает; прыгать ему разрешено, потому что игра
         в это время на паузе, а панораме положено быть там, где ребёнок.

         ЗДЕСЬ СТОЯЛО «заморозка не может накрыть два препятствия», и это
         опровергнуто журналом 14 октября. Рассуждение было такое:
         `crouchMinHoldMs` 600 мс против `minGapS` 5.5 с — значит накрыть два
         нечем. Минимум держит только нижний конец; верхнего нет вовсе, а
         ребёнок приседает надолго: медиана 3.29 с, пятнадцать приседов из 54
         длиннее пяти секунд, худший 18.4. И это настоящие приседы, а не
         залипшая защёлка — `v` в них 2.1–3.4 при пороге 0.35, торс 0.13–0.16
         против 0.31 стоя, то есть ребёнок правда лежал на полу.

         Цена названа точно, потому что случай попался: присед держался 12.3 с,
         в середину этих секунд пришёлся боковой телеграф, и исполнить его было
         НЕЧЕМ — боковое не обновлялось. Приговор за то, чего игра не дала
         сделать, — худший класс дефекта проекта.

         Приговор же починен был правильно и остаётся как был: наружу уходит
         сам признак, а `isSafe` в js/level.js ОТКАЗЫВАЕТСЯ судить боковое
         препятствие, пока он поднят. «Не знаю» не вправе обернуться ударом.
         Отпускать присед по таймеру по-прежнему нельзя: ребёнок правда
         присевший, и верхнее препятствие станет задетым незаслуженно.

         Вертикальное, наоборот, идёт как обычно: присед — это ровно оно, и
         ради него всё и затевалось. `crouch` здесь — состояние прошлого кадра,
         и это правильно: голоса этого кадра обновят его ниже. */
      /* «Тела не видно» — это короткий торс БЕЗ приседа. Приписка `!crouch`
         не украшение: глубокий присед складывает торс ниже `scaleMin` (в
         синтетике 0.05 при границе 0.10), и без неё заморозка вернулась бы
         ровно туда, откуда её убирали, — в самые глубокие приседы. Присутствие
         такой кадр пропускает намеренно (см. `folded` выше), а делитель у
         бокового в приседе свой и от длины торса в кадре не зависит. */
      const hardHold = !crouch && g.S < lo;
      lateralHeld = hardHold || crouch;

      let u;
      if (hardHold) {
        u = uOut ?? uRaw;
        fu.seed(u);
      } else if (crouch) {
        u = uOut === null ? uRaw
          : uOut + (1 - Math.exp(-(dt * 1000) / S.crouchLateralTauMs)) * (uRaw - uOut);
        fu.seed(u);
      } else {
        u = fu.push(uRaw, dt);
      }
      uOut = u;
      const v = fv.push(vRaw, dt);

      const speed = lateralHeld ? 0 : fu.velocity;

      // ── дрейф ──
      // Нейтраль подтягивается медленно, пока ребёнок не делает ничего
      // осознанного: дорожка свободна, движение небыстрое, порог не взят.
      // Ворота по величине смещения тут не годятся — интегратор отстаёт от
      // медленного ухода больше, чем любая разумная мёртвая зона, и такие
      // ворота захлопнулись бы ровно там, где впитывать и надо.
      let driftApplied = false;
      // Согнутую позу нейтраль впитывать не должна: иначе присед уедет в
      // нейтраль, `v` перестанет дотягиваться до порога, и присед растворится.
      if (!lateralHeld && lane === 0
          && Math.abs(speed) < S.driftSpeedMax && Math.abs(u) < cal.uEnter) {
        if (centeredSince === null) centeredSince = t;
        /* Пока открыто окно засева, подтягиваем быстро и начинаем раньше:
           нейтраль взята с ОДНОГО кадра и может быть снята на середине шага.
           Ворота при этом те же — впитывается только настоящее стояние на
           месте, а не шаг вбок, сделанный сразу после старта. */
        const fresh = !!seedUntil && t <= seedUntil;
        if (seedUntil && t > seedUntil) seedUntil = 0;
        if (t - centeredSince > (fresh ? S.seedCenteredMs : S.driftRequiresCenteredMs)) {
          const k = 1 - Math.exp(-(dt * 1000) / (fresh ? S.seedTauMs : S.driftTauMs));
          cal.neutralX += k * (g.cxh - cal.neutralX);
          cal.neutralShoulderY += k * (g.shoulderY - cal.neutralShoulderY);
          cal.neutralHipY += k * (g.hipY - cal.neutralHipY);
          /* Торс стоя впитывается теми же воротами и тем же темпом: ребёнок
             за забег подходит к камере и отходит, а делитель бокового,
             застывший на первом кадре, к концу забега мерил бы присед чужой
             меркой. `cal.S0` при этом не трогается намеренно — он сторожит
             «подошёл к камере» (`scaleGuardOk`), и дрейф отнял бы у него ровно
             ту разницу, которую он и ловит. */
          standS += k * (g.S - standS);
          driftApplied = true;
        }
      } else {
        centeredSince = null;
      }

      // ── дорожка: гистерезис плюс срабатывание по началу движения ──
      const canChange = t - lastLaneChange > S.laneDebounceMs && !lateralHeld;
      let laneNext = lane;

      if (lateralHeld) {
        // Решать по замороженному значению нечего: оставляем как есть.
      } else if (lane === 0) {
        const dir = Math.sign(u);
        if (Math.abs(u) > cal.uEnter) {
          laneNext = dir;
        } else if (canChange && Math.abs(u) > S.onsetU && Math.sign(speed) === dir
                   && Math.abs(speed) > S.onsetSpeed) {
          // Начало движения: срабатываем до того, как ребёнок закончил шаг.
          // Это бесплатно возвращает 150–300 мс тракту, который и так тратит
          // около 430 мс.
          laneNext = dir;
          onsetAt = t;
          onsetDir = dir;
        }
      } else if (Math.abs(u) < cal.uExit || Math.sign(u) !== lane) {
        laneNext = 0;
      }

      // Сработали по началу, а движение не состоялось — мягко вернулись.
      // Это единственная отмена, которая разрешена: во всех прочих случаях
      // решение не отыгрывается назад, иначе это читается как баг.
      if (onsetAt !== null && lane !== 0) {
        if (Math.abs(u) > cal.uEnter) onsetAt = null;
        else if (t - onsetAt > S.onsetGiveUpMs && Math.sign(u) === onsetDir) { laneNext = 0; onsetAt = null; }
      }

      let laneChanged = false;
      if (laneNext !== lane && canChange) {
        lane = laneNext;
        laneSince = t;
        lastLaneChange = t;
        laneChanged = true;
      }

      /* ── присед ──

         «Высота плеч над пятками» ломается, когда ступни уходят из кадра.
         Поэтому голоса: три независимых признака — опустились плечи,
         опустились бёдра, согнуты колени. Колени голосуют только когда их
         видно: у стоящего боком или прикрытого мебелью ребёнка их нет, и
         молчание не должно считаться «за».

         Здесь стояло «длина торса в приседе не меняется вовсе», и это
         неправда: ребёнок приседает С НАКЛОНОМ вперёд, и проекция торса
         укорачивается вдвое-втрое (журнал 7 октября: 0.30 стоя против
         0.11–0.24 в приседе). На голоса это не влияет — они и так не про
         длину торса, — но из той же неправды выросла нижняя граница
         присутствия по торсу, и она дважды остановила забег посреди приседа.

         Побочное следствие, о котором стоит знать: v делится на ТЕКУЩУЮ S, и
         при укоротившемся торсе он раздувается — в журнале на приседах v
         доходил до 2.3–5.3 при пороге 0.35. Голос «плечи опустились» поэтому
         проходит с огромным запасом, но запас этот не от уверенности в
         приседе, а от делителя. Менять нечего: одиннадцать приседов журнала
         распознаны и отпущены все одиннадцать. Но если когда-нибудь придётся
         трогать vEnter/vExit, числа читать надо с этой поправкой. */
      const votes = {
        sh: v > cal.vEnter,
        hip: vHip > cal.vEnter,
        knee: g.kneeVis > 0.5 && g.knee < S.kneeAngleMax,
      };
      const yes = (votes.sh ? 1 : 0) + (votes.hip ? 1 : 0) + (votes.knee ? 1 : 0);

      // Ребёнок, подошедший к камере, тоже опускает плечи в кадре. Настоящий
      // присед обязан уменьшить рост, не увеличив длину торса.
      const scaleGuardOk = cal.S0 ? (g.S - cal.S0) / cal.S0 < S.scaleGuard : true;

      let crouchChanged = false;
      if (!crouch) {
        if (yes >= S.votesNeeded && scaleGuardOk) { crouch = true; crouchSince = t; crouchChanged = true; }
      } else if (t - crouchSince > S.crouchMinHoldMs && v < cal.vExit) {
        crouch = false;
        crouchChanged = true;
      }

      const rec = {
        t, ok: true, why: null,
        ...g,
        uRaw, vRaw, u, v, speed,
        lane, laneAge: t - laneSince, laneChanged,
        crouch, crouchChanged, votes, scaleGuardOk,
        driftApplied,
        neutral: { x: cal.neutralX, y: cal.neutralY },
        okMs: t - okSince,
      };

      ring.push({ t, u, v, S: g.S, vis: g.vis, ok: true, why: null });
      if (ring.length > S.ringSize) ring.shift();
      return rec;
    },
  };
}

// ──────────────────── панорама между отсчётами ────────────────────

/**
 * Непрерывное слежение взгляда за телом.
 *
 * Здесь была экстраполяция по скорости: `u + скорость × возраст отсчёта`.
 * Выглядело разумно и оказалось главной ошибкой этапа. Возраст растёт от нуля
 * до 50 мс, а приход нового отсчёта сбрасывает его в ноль — то есть вид
 * уезжал вперёд и дёргался назад двадцать раз в секунду. Стоя это незаметно,
 * скорость около нуля; при смещении вбок получалась отчётливая тряска пола и
 * стен, от которой режет глаза и укачивает. Пожаловался на это ребёнок — то
 * есть цена ошибки здесь измеряется не в кадрах.
 *
 * Правильная форма — следящее сглаживание: кадр за кадром подтягиваться к
 * последнему отсчёту с постоянной времени. Оно непрерывно по построению,
 * разрывов не бывает вовсе, а отставание на больших движениях остаётся
 * небольшим и ровным.
 */
export function makeFollower(tauMs) {
  let value = null;
  return {
    get value() { return value ?? 0; },
    reset(v = 0) { value = v; },
    /** Шаг кадра: dt в секундах. */
    step(target, dt) {
      if (value === null) { value = target; return value; }
      // 1 - exp(-dt/tau): доля пути за этот кадр. Зависит от реального dt,
      // поэтому просадка частоты кадров не меняет ощущения.
      const k = 1 - Math.exp(-(dt * 1000) / Math.max(1, tauMs));
      value += (target - value) * k;
      return value;
    },
  };
}
