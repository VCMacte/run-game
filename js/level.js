// Расстановка препятствий и расписание телеграфа.
//
// Чистая арифметика без DOM и канваса: генератор проверяется прогоном тысяч
// уровней в node, и проверяется не «похоже на правду», а инварианты, которые
// обязаны держаться на любом уровне. Непроходимый уровень на глаз не заметен
// — он заметен ребёнку, который не понимает, почему проиграл.
//
// Разбор: docs/difficulty.md, docs/obstacle-looks.md, docs/obstacles.md, docs/presence-and-pause.md, docs/rings.md

import { OBSTACLES as O } from './config.js';
import { obstacleEdge } from './view.js';
import { tuneFor } from './difficulty.js';

/* Край препятствия берётся из view, а не считается заново: отрисовка и
   проверка столкновения обязаны пользоваться одним числом. Две копии
   разошлись бы, и ребёнок бился бы о то, чего не видит, — худший вид
   несправедливости, какой бывает в игре. */

/* Внешний вид препятствия — ОТДЕЛЬНО от вида препятствия как задачи.

   `kind` — это требуемое действие, и на нём стоит вся игра: по нему судит
   isSafe(), по нему выбирается звуковой мотив, по нему рисуется метка
   телеграфа. `look` не значит ничего: он меняет только то, из каких
   четырёхугольников плита собрана.

   Разделение здесь не ради чистоты. Пять минут одного и того же силуэта
   приедаются, и перекрасить хочется — а любая перекраска, дотянувшаяся до
   `kind`, означала бы препятствие, которое выглядит как одно, а судится как
   другое. Это тот самый класс дефекта, который на глаз не заметен и заметен
   только ребёнку, не понимающему, почему он проиграл. Поэтому look живёт в
   своём поле, и то, что isSafe его не читает, проверяется тестом.

   Словарь управления при этом не вырос: у ребёнка две оси — шаг в сторону и
   присед, — и шипы на потолке это всё тот же присед, а створка сбоку — всё тот
   же шаг. Новой сложности здесь нет и не предполагается. */
/* Внешность, которая есть во ВСЕХ мирах. По одной на действие: она и даёт
   ребёнку общий язык, по которому препятствие узнаётся в любом мире.

   Общей выбрана плита со зверем, а не створка, и выбор этот содержательный в
   двух смыслах. Зверь — живое существо, то есть читается одинаково и на рифе,
   и в снегу, тогда как створка с шипами это железо, и под водой она выглядела
   бы деталью не этого мира. А попутно створка — САМАЯ ДОРОГАЯ внешность игры
   (около 18 заливок против девяти у плиты), и уход её из трёх миров в один —
   тот же размен вниз, которым оплачивались семь форм обочины. */
const COMMON = { duck: 'ceiling', side: 'plate' };

/* А это своя внешность мира, и правило у них одно на все миры: ШЕВЕЛИТСЯ ИЛИ
   ДВИЖЕТСЯ — ОБХОДИ, ВИСИТ НЕПОДВИЖНО — ПРИСЕДАЙ. Ребёнок учит его один раз, а
   дальше оно работает в каждом мире; тематика меняет силуэт, а не задачу.

   У холмов «своей» оказывается то, что там и было: створка и крылан. Это не
   поблажка первому миру — это признание того, что железо и пещерный зверь и
   есть холмы, и переодевать их было бы ради самого переодевания.

   `beam` в этом списке нет и не будет: она была голая плита, четыре заливки и
   ничего на них, и заказчик 10 октября назвал её прямо — «простая и скучная
   красная стена». Имя при этом живёт в снятых журналах, и проверка требует,
   чтобы незнакомая внешность не рисовалась НИЧЕМ. */
const OWN = {
  hills: { duck: 'bat', side: 'gate' },
  ice: { duck: 'icicles', side: 'floe' },
  deep: { duck: 'ribs', side: 'jelly' },
  stars: { duck: 'comet', side: 'asteroid' },
};

/* Полный перечень внешностей — ВЫВОДИТСЯ, а не ведётся руками. Второй список
   разошёлся бы с первым, и разошёлся бы молча: внешность, забытая в перечне,
   продолжала бы выпадать в забеге, а проверка отрисовки её бы не видела. */
export const LOOKS = {
  duck: [COMMON.duck, ...Object.values(OWN).map((o) => o.duck)],
  side: [COMMON.side, ...Object.values(OWN).map((o) => o.side)],
};

/** Пара внешностей этого мира на это действие: общая плюс своя.
 *
 * Единственный владелец состава — по образцу `kindsFor` для обочины. Мир
 * неизвестный, с опечаткой или ещё не собранный отдаёт пару холмов, и отдаёт
 * МОЛЧА: генератор уровня не вправе уронить забег из-за имени мира, а пустой
 * пары не бывает по построению.
 */
export function looksFor(world, kind) {
  const own = (OWN[world] ?? OWN.hills)[kind] ?? OWN.hills[kind];
  return [COMMON[kind], own];
}

/**
 * Уровень: список препятствий с временем прихода.
 *
 * `rng` принимается снаружи, чтобы тесты могли прогнать тысячу разных
 * уровней, а не один и тот же.
 */
export function makeLevel({
  durationS = 180, crouch = true, rng = Math.random, tune = tuneFor(0), world = 'hills',
} = {}) {
  /* Числа ступени приходят СНАРУЖИ одним объектом, а не читаются отсюда из
     конфига. Так генератор остаётся чистым: тест прогоняет все ступени, не
     трогая глобального состояния, а забег читает ступень игрока один раз и
     больше её не спрашивает. */
  const edge = obstacleEdge(tune.blockFrac);
  const out = [];
  let t = O.firstAtS;
  let lastSide = 0;
  let sameSide = 0;
  /* Вид — по тем же правилам, что и сторона: подряд не больше двух одинаковых.
     Чистая случайность даёт полосы по пять-шесть штук, и перекраска, ради
     которой всё делалось, внутри такой полосы не видна вовсе. */
  const lastLook = {};
  const sameLook = {};
  /* Длина серии и сколько в ней осталось. Волна — это форма забега, и она
     живёт здесь, в расписании, а не в отрисовке: расписание строится один раз
     на забег и дальше только читается. */
  const series = () => tune.seriesMin + Math.floor(rng() * (tune.seriesMax - tune.seriesMin + 1));
  let left = series();
  /* Сколько препятствий уже выдано в текущей серии. Нужен отдельно от `left`
     ради хвоста забега: там серия продлевается по одному, и без этого счётчика
     потолок `seriesMax` переставал действовать ровно в конце. */
  let вСерии = 0;

  /* Сколько препятствий одного вида подряд уже выдано. Ручка `kindRunMax`
     ограничивает это число, и ограничивает ПАТТЕРН, а не сложность по времени:
     ни разнос, ни число препятствий от неё не меняются.

     Зачем она. Вид был независимым броском (`rng() < duckShare`), и при доле
     0.30 полосы боковых по семь-девять штук случались регулярно — ребёнок
     привыкал к одной оси и переставал ждать приседа. Самый трудный переход
     как раз обратный: присед сразу после бокового ухода. */
  let lastDuck = null;
  let sameKind = 0;

  while (t < durationS) {
    // Вид препятствия. Присед реже бокового: он утомительнее, и ребёнок
    // быстрее устаёт, если приседать приходится каждый раз.
    let wantDuck = crouch && rng() < tune.duckShare;
    /* Потолок полосы одного вида. Сменить можно только НА присед и только
       когда приседы вообще разрешены: при выключенных приседах полоса
       боковых — не дефект, а единственная возможная игра. */
    if (tune.kindRunMax && lastDuck !== null && wantDuck === lastDuck
        && sameKind >= tune.kindRunMax - 1 && (crouch || lastDuck)) {
      wantDuck = crouch ? !lastDuck : false;
    }
    sameKind = wantDuck === lastDuck ? sameKind + 1 : 0;
    lastDuck = wantDuck;

    let side = 0;
    if (!wantDuck) {
      /* Чередуем стороны: смысл игры в том, что ребёнок двигается, а три
         препятствия подряд с одной стороны означают, что он стоит. Потолок
         задан уровнем: по умолчанию 2, как было, а на верхнем 1 — то есть
         каждое боковое с другой стороны. */
      side = rng() < 0.5 ? -1 : 1;
      if (side === lastSide && sameSide >= (tune.sameSideMax ?? 2) - 1) side = -side;
      sameSide = side === lastSide ? sameSide + 1 : 0;
      lastSide = side;
    }

    const kind = wantDuck ? 'duck' : 'side';
    /* Пара берётся по МИРУ, а не по зоне, и этим снимается забота о границе
       зон: своя внешность одна на все три зоны мира, значит препятствию не
       нужно помнить, в какой зоне оно родилось. Красится оно палитрой зоны
       кадра, как и красилось. */
    const variants = looksFor(world, kind);
    let look = variants[rng() < 0.5 ? 0 : 1];
    if (look === lastLook[kind] && (sameLook[kind] || 0) >= 1) {
      look = variants[variants.indexOf(look) === 0 ? 1 : 0];
    }
    sameLook[kind] = look === lastLook[kind] ? (sameLook[kind] || 0) + 1 : 0;
    lastLook[kind] = look;

    out.push({
      at: t,                       // секунда забега, когда дойдёт до игрока
      kind,
      look,                        // только внешность: isSafe его не читает
      side,                        // какая сторона закрыта
      /* Край едет С ПРЕПЯТСТВИЕМ, а не берётся из конфига в момент вопроса.
         Иначе ступень, прочитанная на старте забега, разошлась бы с тем, по
         чему судит isSafe и что рисует view, — то есть ребёнок бился бы о то,
         чего не видит. Одно число на отрисовку и на приговор, как и было. */
      edge,
      passed: false,
      hit: false,
      verdictAt: null,             // окно прощения опоздания
    });

    /* Шаг — по фразе, а не бросок на каждое препятствие.

       Внутри серии идём по самому полу (`minGapS` плюс мелкий джиттер), на
       конце серии — передышка. Ниже пола не опускаемся никогда: там два
       телеграфа накладываются и теряются оба. Разбор — в OBSTACLES конфига.

       Остаток забега учитывается: если до конца меньше передышки, серия
       продолжается. Иначе короткий забег кончился бы пустой передышкой, а
       отладочный на двадцать секунд остался бы вовсе без препятствий. */
    вСерии++;
    left--;
    if (left > 0) {
      t += O.minGapS + rng() * O.seriesJitterS;
    } else {
      const breather = tune.breatherS + rng() * O.breatherJitterS;
      if (durationS - t > breather + O.minGapS) {
        t += breather;
        left = series();
        вСерии = 0;
      } else if (вСерии < tune.seriesMax) {
        /* На полную передышку места уже нет, но серия ещё не выбрала потолок —
           продлеваем её по одному. Укоротить передышку нельзя: промежуток
           между полосами («серия ≤ 6.1 с, передышка ≥ 8.8 с») и есть то, чем
           волна читается, и одно значение посередине сделало бы её кашей. */
        t += O.minGapS + rng() * O.seriesJitterS;
        left = 1;
      } else {
        /* Потолок серии выбран, а передышка не влезает — забег кончается
           спокойным хвостом. Именно так, а не «тянем серию до финиша»: здесь
           раньше стояло безусловное `left = 1`, и хвост вырастал до шести-семи
           препятствий подряд при заявленном потолке пять (замерено: 56 случаев
           по шесть и 12 по семь на четырёхстах посевах). Конфиг этот случай
           прямо отвергает — шесть подряд без паузы это вопрос о выносливости
           семилетки, — то есть код противоречил собственному решению. */
        break;
      }
    }
  }
  return out;
}

/**
 * Стадия телеграфа по времени до прихода.
 *
 * Отдаёт то, что нужно показать прямо сейчас. Границы — числа из config, а
 * не литералы: после первой тренировки их будут двигать.
 */
export function telegraph(timeToImpact) {
  return {
    signal: timeToImpact <= O.signalS,
    visible: timeToImpact <= O.visibleS,
    rail: timeToImpact <= O.railS,
    lastCall: timeToImpact <= O.lastCallS && timeToImpact > 0,
    arrived: timeToImpact <= 0,
  };
}

/**
 * Сколько секунд вернуть забегу, чтобы пауза не съела телеграф.
 *
 * Повод — журнал 11 октября вечером, и он читается по секундам. Телеграф на
 * присед прозвучал на 203.9; на 208.4 игра встала на паузу (ребёнок как раз
 * приседал, и поза потерялась целиком); отсчёт 3-2-1 кончился на 213.0, а
 * препятствие пришло на 213.9. То есть на исполнение осталось 0.94 с при
 * измеренном времени ответа 3.5 с — задетое было неизбежным.
 *
 * И ребёнок при этом всё сделал ПРАВИЛЬНО: в журнале на 210.1 стоит `crouchIn`
 * с голосами, то есть он присел по услышанному телеграфу — только пока шёл
 * отсчёт, и к возврату успел встать. Наказание за то, чего игра не показала,
 * здесь худший класс дефекта: ребёнок не понимает, почему проиграл.
 *
 * Поэтому долг возвращается ВРЕМЕНЕМ. Время забега и пройденный путь связаны
 * одним множителем (`travel === elapsed * speed`), так что отмотка — это шаг
 * мира назад; делать её надо в момент НАЧАЛА отсчёта, пока мир и так стоит под
 * надписью, а не на возврате.
 *
 * Отматывать больше, чем прошло, нельзя — отсюда зажим по `elapsed`. А пересечь
 * приход ПРЕДЫДУЩЕГО препятствия отмотка не может по построению: долг не
 * больше `signalS`, препятствия разнесены на `minGapS`, и инвариант
 * `minGapS > signalS` проверяется тестом. Иначе уже выданный приговор
 * выставился бы второй раз.
 *
 * Чистая функция, потому что `js/train.js` в node не исполняется, а число
 * здесь обязано проверяться числом.
 */
export function telegraphDebt(obstacles, elapsed) {
  const ob = obstacles.find((o) => !o.passed && o.at > elapsed);
  if (!ob) return 0;
  return Math.max(0, Math.min(O.signalS - (ob.at - elapsed), elapsed));
}

/**
 * Безопасно ли положение взгляда для этого препятствия.
 *
 * Для бокового — надо быть по другую сторону от края препятствия. Для
 * верхнего — приседать. Одно место на всю игру: и столкновение, и подсветка
 * «ты не там» считают отсюда, иначе подсказка и наказание разойдутся.
 */
export function isSafe(obstacle, { camX, crouching, lateralKnown = true }) {
  if (obstacle.kind === 'duck') return !!crouching;

  /* «НЕ ЗНАЮ» НЕ ВПРАВЕ ОБЕРНУТЬСЯ УДАРОМ.

     Пока ребёнок сложен или присед защёлкнут, боковое положение не
     обновляется: в такой позе оно недостоверно (разбор — у `lateralHeld` в
     js/signals.js). Судить по нему боковое препятствие значит вынести
     приговор по значению, про которое игра сама сказала «не знаю», — и
     14 октября это дало удар, которого ребёнок не мог избежать никаким
     движением: присед держался 12.3 секунды, боковой телеграф пришёлся на их
     середину, и исполнить его было нечем. Единственный такой случай за всю
     историю журналов, и он задет: 1 из 1.

     Поэтому при замороженном боковом препятствие считается пройденным. Это не
     подарок и не поблажка в сложности: когда замороженное значение говорит
     «ушёл», удара не было и так, — меняется ровно тот случай, где игра не
     знает ответа. Плата названа честно: ребёнок, пролежавший препятствие на
     полу, получит проход. Он в это время и не играет, а присед уже даёт
     бесплатный проход верхнему препятствию — так что ось симметрична.

     Умолчание `true` нарочно: препятствия, собранные руками в тестах и в
     tools/frame.html, судятся как судились. */
  if (!lateralKnown) return true;
  // Закрыта сторона `side`, уходить надо в противоположную и зайти за край
  // препятствия, а не просто качнуться в её сторону.
  // Край берётся У ПРЕПЯТСТВИЯ: он записан в него генератором вместе со
  // ступенью, на которой построен уровень. Запасной путь — для препятствий,
  // собранных руками в тестах и в tools/frame.html.
  const edge = obstacle.edge ?? obstacleEdge();
  return obstacle.side > 0 ? camX < -edge : camX > edge;
}

