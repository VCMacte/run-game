/* Громкость по типу события. Подсказки должны быть слышны поверх всего, а
   звёзды — не забивать их: за забег их собирают десятками. */
const LEVEL = {
  left: 0.26, right: 0.26, duck: 0.26,
  warn: 0.22, ready: 0.12,
  clear: 0.14, star: 0.09, hit: 0.24,
  finish: 0.28, countdown: 0.18, go: 0.24,
  /* Громкости вариантов РАВНЫ базовым: приз меняет внешность звука, а не его
     место в слышимости. Громче — значит начать спорить с телеграфом. */
  starChime: 0.09, finishFanfare: 0.28, finishGold: 0.28,
};

/* Приз подменяет мотив СОБЫТИЯ, а не добавляет новое событие. Таблица одна и
   здесь: иначе «какой приз что подменяет» разъехалось бы между звуком и
   лестницей. Разбор — docs/trophy-and-worlds.md. */
export const VARIANTS = {
  star: { chime: 'starChime' },
  /* Порядок важен: `motifNameFor` берёт ПЕРВЫЙ открытый приз, а взявший
     вершину уже взял и четвёртый уровень. Звучать должна вершина. */
  finish: { gold: 'finishGold', fanfare: 'finishFanfare' },
};

/** Какой мотив играть с этим набором призов. Чистая функция — проверяется из
    node, где Web Audio нет вовсе. Неизвестный и закрытый приз дают БАЗОВОЕ
    имя: `play` на несуществующем мотиве выходит молча, и сбор кольца потерял
    бы звук совсем — отказ, неотличимый от выключенного в меню звука. */
export function motifNameFor(name, prizes = {}) {
  const варианты = VARIANTS[name];
  if (!варианты) return name;
  for (const [приз, мотив] of Object.entries(варианты)) {
    if (prizes[приз] && MOTIFS[мотив]) return мотив;
  }
  return name;
}

export function play(name, prizes = {}) {
  /* Выключенный звук проверяется ПЕРВЫМ, до отбора варианта: приз не вправе
     обойти настройку взрослого. Порядок сторожит тест в группе «звук». */
  const vol = settings.get('sound') ?? 0.8;
  if (!vol) return;                 // «выключен» в родительском меню
  const c = wake();
  if (!c || c.state !== 'running') return;

  const имя = motifNameFor(name, prizes);
  const motif = MOTIFS[имя];
  if (!motif) return;
  const gain = vol * (LEVEL[имя] ?? 0.2);
  const t0 = c.currentTime + 0.005;
  const shape = имя === 'hit' ? 'sawtooth' : 'triangle';
  for (const [freq, offset, dur] of motif) note(t0 + offset, freq, dur, gain, shape);
}

/** Мотив для препятствия: что именно надо сделать. */
export const motifFor = (obstacle) =>
  (obstacle.kind === 'duck' ? 'duck' : obstacle.side > 0 ? 'left' : 'right');

/** Для проверок: сами мотивы. Не число нот — его мало, чтобы сравнить два. */
export const describe = () =>
  Object.fromEntries(Object.entries(MOTIFS).map(([k, v]) => [k, v.map((n) => [...n])]));
